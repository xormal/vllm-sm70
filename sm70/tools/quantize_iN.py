"""КВАНТОВАТЕЛЬ ВЕСОВ В int-N (умолчание 12) -- ГОТОВЫЕ ВЕСА, КОТОРЫЕ ГРУЗЯТСЯ КАК ЕСТЬ.

ЗАЧЕМ ИМЕННО ЭТИ СЛОИ. Опись слепка по индексу safetensors показала: у 16 слоёв полного внимания
`q_proj` ([12288,5120]), `k_proj`, `v_proj` и у ОДНОГО слоя MLP веса НЕ КВАНТОВАНЫ -- лежат в BF16.
Это 3.17 ГБ, из них 1.58 ГБ на карту ЧИТАЕТСЯ КАЖДЫЙ ШАГ ДЕКОДА.

ПОЧЕМУ int12 ЗДЕСЬ -- НЕ ПОТЕРЯ, А УТОЧНЕНИЕ. Замерено на этих самых тензорах (tools/attn_ent.py):

    ширина  ошибка к хранимому BF16   байт от bf16
    int14        1.1e-04                 0.875
    int12        4.2e-04                 0.750
    int10        1.7e-03                 0.625
    int8         6.8e-03                 0.500
    собственная зернистость BF16 (8 разрядов мантиссы) = 1.95e-03

Точка равенства -- **int10**. Всё выше неё ТОЧНЕЕ того, что лежит в слепке сейчас: int12 впятеро,
int14 в восемнадцать раз. Причина не в хитрости, а в устранении дублирования: BF16 тратит восемь
разрядов на экспоненту, а динамический диапазон уже вынесен в масштаб группы. Поэтому int-путь
даёт И точность, И экономию -- размена здесь нет.
Энтропия кода замерена 0.950-0.954 от ширины, макс/скз ~2.9: диапазон занят почти полностью,
то есть ширину нельзя резать «на глаз» -- отсюда и выбор верхней части шкалы.

ГРУППА ИДЁТ ПО ОСИ СВЁРТКИ, и это не вкусовщина. У веса [выход, вход] произведение суммируется по
`вход`; масштаб на (выход, группа входа) выносится из ЧАСТИЧНОЙ суммы группы -- то есть умножение
остаётся целочисленным внутри группы, а масштаб применяется один раз на группу. Группировка по
выходу потребовала бы масштабировать каждый выход отдельно уже ПОСЛЕ свёртки, что ломает накопление.

РАСКЛАДКА ПОДЧИНЕНА ЧИТАТЕЛЮ, А НЕ ПИСАТЕЛЮ -- И ЭТО ИСПРАВЛЕНИЕ.
Первая редакция клала веса в ТОТ ЖЕ формат, что обмен (fa2_sm70/csrc/exch_i12.cu), «чтобы разбор был
один». Это ошибка выбора единицы: у провода и у веса РАЗНЫЕ читатели с разными шаблонами обращения.
Обмену безразличен порядок -- он везёт сплошной кусок. Весу нет: у проверенного GEMV (w8a16_gemv.cu)
ОДНА КОЛОНКА НА НИТЬ, и вся его коалесценция держится на k-мажорном слове `[K/4, N]` -- варп берёт
32 подряд идущих слова = 128 байт. В формате `[N, K/4*3]` соседние нити разъезжаются на K*1.5 байт,
то есть каждое чтение варпа = 32 отдельные транзакции вместо одной.

Поэтому вес кладётся так: **`[K/8, 3, N]` int32**. Восемь подряд идущих k ОДНОГО столбца = 96 разрядов
= РОВНО три слова, разложенные по трём плоскостям; варп читает 32 подряд идущих int32 = 128 байт,
три раза на восемь ключей. Масштабы -- `[K/G, N]` fp16, тоже коалесцированно по n.

    w0 = v0 | v1<<12 | (v2&0xFF)<<24            (12+12+8  = 32)
    w1 = v2>>8 | v3<<4 | v4<<16 | (v5&0xF)<<28  ( 4+12+12+4 = 32)
    w2 = v5>>4 | v6<<8 | v7<<20                 ( 8+12+12  = 32)

КВАНТОВАНИЕ СИММЕТРИЧНОЕ, БЕЗ НУЛЕВОЙ ТОЧКИ -- и это не мелочь: у GPTQ эпилог группы обязан считать
сумму x по группе (чтобы свернуть z), а здесь эпилог = один множитель. Целая фаза ядра исчезает.

    python tools/quantize_iN.py <слепок> <куда> [--бит 12] [--что attn|all] [--проверить]

Пишет sidecar-файл и опись; ИСХОДНЫЙ СЛЕПОК НЕ ТРОГАЕТ.
"""
import argparse
import json
import os
import struct
import sys

import torch


def выбрать(индекс, что):
    """Какие тензоры берём. По умолчанию -- ровно неквантованные веса слоёв языковой модели."""
    цели = []
    for имя in индекс:
        if имя.startswith("mtp") or "visual" in имя or "vision" in имя:
            continue                      # MTP не читается (спекуляция выкл), зрение -- не на тексте
        if "embed" in имя or "lm_head" in имя:
            continue                      # отдельная статья, свой разговор
        if имя.endswith(("qweight", "qzeros", "scales", "g_idx")):
            continue                      # уже квантовано
        if not имя.endswith(".weight"):
            continue                      # нормы, смещения -- мелочь, не трогаем
        if что == "attn" and ".self_attn." not in имя:
            continue
        цели.append(имя)
    return sorted(цели)


def упаковать(q, бит):
    """q: [N, K] целые в [-lvl,lvl] -> [K/8, 3, N] int32 (раскладка читателя, см. шапку).

    ВАЖНО: смещение на 2048 делает значение БЕЗЗНАКОВЫМ 12-разрядным. Знак -- полноценный
    двенадцатый разряд, отдельного бита ему не нужно (см. запись про лестницу разрядности).
    Считаем в int64: сдвиг на 28 в int32 залезает в знаковый разряд и torch даёт переполнение.
    """
    assert бит == 12, "пока упакован формат 12 разрядов (8 значений -> 3 int32)"
    N, K = q.shape
    assert K % 128 == 0, "ось свёртки обязана делиться на 128 (группа масштаба)"
    u = (q.to(torch.int64) + 2048) & 0xFFF
    v = u.view(N, K // 8, 8)
    w0 = v[..., 0] | (v[..., 1] << 12) | ((v[..., 2] & 0xFF) << 24)
    w1 = (v[..., 2] >> 8) | (v[..., 3] << 4) | (v[..., 4] << 16) | ((v[..., 5] & 0xF) << 28)
    w2 = (v[..., 5] >> 4) | (v[..., 6] << 8) | (v[..., 7] << 20)
    пак = torch.stack([w0, w1, w2], dim=2).permute(1, 2, 0).contiguous()   # [K/8, 3, N]
    пак = torch.where(пак >= (1 << 31), пак - (1 << 32), пак)              # в знаковый диапазон
    return пак.to(torch.int32)


def разобрать(пак, бит):
    """Обратное преобразование -- для проверки ТОЖДЕСТВА упаковки, а не для боя. -> [N, K]."""
    Kd8, три, N = пак.shape
    assert три == 3
    п = пак.permute(2, 0, 1).to(torch.int64) & 0xFFFFFFFF                  # [N, K/8, 3]
    w0, w1, w2 = п[..., 0], п[..., 1], п[..., 2]
    v = torch.stack([
        w0 & 0xFFF,
        (w0 >> 12) & 0xFFF,
        ((w0 >> 24) & 0xFF) | ((w1 & 0xF) << 8),
        (w1 >> 4) & 0xFFF,
        (w1 >> 16) & 0xFFF,
        ((w1 >> 28) & 0xF) | ((w2 & 0xFF) << 4),
        (w2 >> 8) & 0xFFF,
        (w2 >> 20) & 0xFFF,
    ], dim=2)                                                              # [N, K/8, 8]
    return (v.reshape(N, Kd8 * 8) - 2048).to(torch.int32)


def квантовать(w, бит, G=128):
    """w: [выход, вход] fp32 -> (упакованное, масштабы fp16, ошибка, целые q).

    КВАНТУЕМ ПО ТОМУ МНОЖИТЕЛЮ, КОТОРЫЙ РЕАЛЬНО ПРИМЕНИТСЯ. Первая редакция делила на ТОЧНЫЙ
    максимум, а масштаб клала в fp16 -- то есть на исполнении делитель был ДРУГОЙ, и хранимое q
    оказывалось оптимальным для несуществующего масштаба. Поймано собственной проверкой
    обратимости (она сравнивала два способа получить q и разошлась). Порядок обязан быть такой:
    сперва округлить МАСШТАБ до формата хранения, потом по нему квантовать.
    """
    lvl = (1 << (бит - 1)) - 1
    строк, K = w.shape
    г = w.view(строк, K // G, G)
    m = г.abs().amax(dim=2, keepdim=True).clamp_min(1e-12)
    масш = (m / lvl).to(torch.float16)                 # готовый множитель: значение = q * масштаб
    mf = масш.float().clamp_min(1e-20)                 # ровно он и будет делителем
    q = torch.round(г / mf).clamp(-lvl, lvl)
    ош = ((q * mf - г).norm() / г.norm()).item()
    qi = q.view(строк, K).to(torch.int32)
    # масштабы отдаются как [K/G, N]: у читателя n -- быстрая ось, так же как у веса.
    return упаковать(qi, бит), масш.squeeze(2).t().contiguous(), ош, qi


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("слепок")
    ap.add_argument("куда")
    ap.add_argument("--бит", type=int, default=12)
    ap.add_argument("--что", default="attn", choices=("attn", "all"))
    ap.add_argument("--предел", type=float, default=1.95e-3,
                    help="порог относительной ошибки; умолчание = собственная зернистость BF16")
    a = ap.parse_args()

    import glob
    from safetensors import safe_open
    from safetensors.torch import save_file

    инд = json.load(open(glob.glob(os.path.join(a.слепок, "*.index.json"))[0]))["weight_map"]
    цели = выбрать(инд, a.что)
    if not цели:
        print("нечего квантовать"); return 1
    print(f"тензоров к обработке: {len(цели)}, ширина {a.бит}, порог ошибки {a.предел:.2e}\n")
    print(f"{'тензор':<52} {'форма':>15} {'ошибка':>9} {'байт было':>10} {'стало':>9}")

    вых, опись = {}, {}
    было = стало = 0
    худшая = 0.0
    for имя in цели:
        with safe_open(os.path.join(a.слепок, инд[имя]), framework="pt") as f:
            w = f.get_tensor(имя)
        исх_байт = w.numel() * w.element_size()
        wf = w.float()
        if wf.dim() != 2 or wf.shape[1] % 128 != 0:
            print(f"  ПРОПУСК {имя}: форма {tuple(wf.shape)} не годится под группу 128")
            continue
        пак, масш, ош, qi = квантовать(wf, a.бит)
        # ТОЖДЕСТВО УПАКОВКИ проверяется ВСЕГДА, а не под флагом: ошибка здесь тихая и полная.
        # Сверяется РОВНО упаковка (разобрать(упаковать(q)) == q), без повторного вывода q --
        # иначе проверялась бы арифметика квантования, а не то, что она должна проверять.
        assert torch.equal(разобрать(пак, a.бит), qi), f"упаковка НЕ обратима на {имя}"
        # РАЗМЕР БЕРЁТСЯ У ТЕНЗОРА, А НЕ ИЗ КОНСТАНТЫ. Здесь стояло *2 от прежней раскладки
        # (uint16); после перехода на int32 опись отрапортовала x2.612 -- невозможное для 12
        # разрядов из 16 число, и поймала себя именно арифметикой, а не проверкой.
        нов_байт = пак.numel() * пак.element_size() + масш.numel() * масш.element_size()
        было += исх_байт; стало += нов_байт; худшая = max(худшая, ош)
        вых[имя + ".i12"] = пак
        вых[имя + ".i12_scale"] = масш
        опись[имя] = {"бит": a.бит, "группа": 128, "форма": list(w.shape),
                      "ошибка": ош, "байт_было": исх_байт, "байт_стало": нов_байт}
        print(f"{имя.replace('model.language_model.layers.','сл.'):<52} "
              f"{str(tuple(w.shape)):>15} {ош:>9.2e} {исх_байт/1e6:>9.1f}М {нов_байт/1e6:>8.1f}М")
        del w, wf, пак, масш, qi

    if худшая > a.предел:
        print(f"\nОТКАЗ: худшая ошибка {худшая:.2e} выше порога {a.предел:.2e}. Ничего не записано.")
        return 2
    os.makedirs(a.куда, exist_ok=True)
    save_file(вых, os.path.join(a.куда, f"weights_i{a.бит}.safetensors"))
    json.dump({"бит": a.бит, "группа": 128, "раскладка": "три плоскости по 32 в группе 128",
               "тензоры": опись}, open(os.path.join(a.куда, f"manifest_i{a.бит}.json"), "w"),
              ensure_ascii=False, indent=1)
    print(f"\nИТОГО: {было/1e9:.3f} -> {стало/1e9:.3f} ГБ  (x{было/стало:.3f} меньше), "
          f"худшая ошибка {худшая:.2e} при зернистости BF16 1.95e-03")
    print(f"записано -> {a.куда}/weights_i{a.бит}.safetensors + manifest_i{a.бит}.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
