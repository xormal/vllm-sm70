# -*- coding: utf-8 -*-
"""ПЛАН ОБМЕНА ПО ТОПОЛОГИИ: два пути и смешанный режим.

Задача. Обмен между картами в декоде -- 23 % шага при 0.006 % байт (см. EV_decode_phase_falsifier.md):
платим за РАНДЕВУ, а не за перевозку. Значит план выбирается по числу переходов через МЕДЛЕННЫЙ
канал и по числу рандеву, а не по полосе.

Что взято из чужой реализации (`csrc/custom_all_reduce.cuh` форка) и что добавлено:

* у них при `world_size == 2` топология не спрашивается вовсе -- всегда одношаговый. Берём;
* у них при `world_size > 2 && !fully_connected` быстрый путь ВЫКЛЮЧАЕТСЯ целиком (и в
  `REDUCE_CASE` у этой ветки даже нет `else`). То есть четыре карты, где мостом связаны лишь две,
  у них падают в NCCL полностью. Вот эту клетку и занимаем СМЕШАННЫМ планом;
* барьер поблочный (блок i с блоком i соседа), кооперативный запуск не нужен. Берём.

ПОЧЕМУ ПЛАН СЧИТАЕТСЯ ЗДЕСЬ, А НЕ НА ШАГЕ. Ветвь обязана совпасть на ВСЕХ картах: если одна карта
вошла в обмен, а другая нет, ядро виснет на ожидании (это уже случилось). Лечение структурное --
план выводится ТОЛЬКО из величин, одинаковых на всех картах по построению: матрица топологии
(один и тот же вывод `nvidia-smi topo -m` на всей машине) и размер посылки (геометрия сети).
Ни состояние планировщика, ни номер шага, ни что-либо локальное в решение не входит.
"""

from __future__ import annotations

import os
import re
import subprocess
from dataclasses import dataclass, field

# Классы канала от быстрого к медленному. Значение -- ЦЕНА, порядок важен, величины -- нет.
КЛАССЫ = {"NV": 0, "PIX": 1, "PXB": 2, "PHB": 3, "NODE": 4, "SYS": 5, "X": -1}

# Порог, ниже которого свой обмен имеет смысл. У vLLM для sm_70 при TP=2 стоит 40 КБ
# (`kSm70Tp2SmallAllreduceBytes`), общий потолок быстрого пути -- 8 МБ. У нас посылка декода
# 10 КБ, то есть на два порядка ниже любого их порога.
ПОТОЛОК_БАЙТ = int(os.environ.get("FA2SM70_EXCH_MAX_BYTES", 8 * 1024 * 1024))

# Размер, с которого смешанный (двухъярусный) план начинает выигрывать у плоского. Плоский платит
# ОДНИМ рандеву, но тащит через медленный канал (R-1) посылок; смешанный платит ДВУМЯ рандеву, но
# тащит через медленный ОДНУ. Значение по умолчанию -- ЗАГЛУШКА до замера перелома, и оно
# намеренно велико: на 10 КБ декода выбирается плоский.
ПЕРЕЛОМ_БАЙТ = int(os.environ.get("FA2SM70_EXCH_TIER_BYTES", 256 * 1024))


@dataclass
class План:
    путь: str                      # "свой" | "nccl" | "нет"
    ярусы: list[list[int]] = field(default_factory=list)   # для КАЖДОГО яруса: у кого тянуть
    почему: str = ""
    матрица: list[list[str]] = field(default_factory=list)

    @property
    def рандеву(self) -> int:
        return len(self.ярусы)

    def описание(self, тянуть: list[int] | None = None) -> str:
        # НАПРАВЛЕНИЕ НАЗЫВАТЬ ЧЕСТНО. Раньше здесь всегда стояло «тяну у», хотя перенос
        # толкающий: журнал сообщал не то, что исполняется, и при разборе отказа это уводит.
        def как(i):
            т = (тянуть[i] if тянуть and i < len(тянуть) else 0)
            return "тяну у" if т else "толкаю в"
        я = "; ".join(f"ярус {i}: {как(i)} {p}" for i, p in enumerate(self.ярусы)) or "-"
        return f"путь={self.путь}, рандеву={self.рандеву}, {я}. {self.почему}"


def _топология(карты: list[int]) -> list[list[str]] | None:
    """Матрица классов канала между УКАЗАННЫМИ физическими картами.

    Читается `nvidia-smi topo -m`. Вывод одинаков на всей машине, поэтому все ранги получают
    одну матрицу -- это и есть условие совпадения ветви.
    """
    try:
        сырое = subprocess.run(["nvidia-smi", "topo", "-m"], capture_output=True,
                               text=True, timeout=20).stdout
    except Exception:
        return None
    строки = {}
    for ln in сырое.splitlines():
        m = re.match(r"^\s*GPU(\d+)\s+(.*)$", ln)
        if not m:
            continue
        поля = m.group(2).split()
        клетки = [x for x in поля if x in КЛАССЫ or x.startswith("NV")]
        if клетки:
            строки[int(m.group(1))] = клетки
    if not строки:
        return None
    m = []
    for i in карты:
        if i not in строки:
            return None
        ряд = []
        for j in карты:
            if j >= len(строки[i]):
                return None
            c = строки[i][j]
            ряд.append("NV" if c.startswith("NV") and c != "X" else c)
        m.append(ряд)
    return m


def _цена(c: str) -> int:
    return КЛАССЫ.get("NV" if c.startswith("NV") and c != "X" else c, 9)


def _группы(м: list[list[str]]) -> list[list[int]] | None:
    """Разбиение рангов на группы по СВОЕМУ САМОМУ БЫСТРОМУ каналу.

    ПЕРВАЯ ПОПЫТКА БЫЛА НЕВЕРНА и это поймал фальсификатор: компоненты связности по ГЛОБАЛЬНО
    минимальному классу дают группу только там, где стоит NVLink ({2,3}), а карты 0 и 1 остаются
    одиночками -- и план РАСХОДИТСЯ по рангам (у одного два яруса, у другого один). Расхождение
    ветви между картами и есть причина зависания: одна вошла в обмен, другая нет.

    Верное правило -- ВЗАИМНО ЛУЧШИЙ сосед: группа образуется, если i считает j своим лучшим и j
    считает i своим лучшим. На нашей машине это даёт {0,1} (обе лучшие друг другу через PHB) и
    {2,3} (через NV2) -- то самое смешанное разбиение.

    Возвращает None, если ровного разбиения нет: тогда план плоский У ВСЕХ, и ветвь снова одна.
    """
    R = len(м)
    лучший = {}
    for i in range(R):
        прочие = [j for j in range(R) if j != i]
        if not прочие:
            return None
        # min по (цена, номер) -- порядок детерминирован, иначе ранги разойдутся на равных ценах.
        лучший[i] = min(прочие, key=lambda j: (_цена(м[i][j]), j))
    группы = []
    занят = set()
    for i in range(R):
        if i in занят:
            continue
        j = лучший[i]
        if лучший.get(j) != i or j in занят:
            return None                     # не взаимные -- ровного разбиения нет
        группы.append(sorted((i, j)))
        занят.update((i, j))
    if len(группы) < 2 or len({len(g) for g in группы}) != 1:
        return None                         # одна группа либо разные размеры -- ярусы не строятся
    # Каждому рангу внутригрупповой канал обязан быть СТРОГО быстрее любого межгруппового,
    # иначе ярусы не экономят ничего.
    for g in группы:
        for i in g:
            свой = max(_цена(м[i][j]) for j in g if j != i)
            чужой = min(_цена(м[i][j]) for h in группы if h is not g for j in h)
            if свой >= чужой:
                return None
    return sorted(группы, key=lambda g: g[0])


def построить(ранг: int, мир: int, карты: list[int] | None = None,
              байт: int = 0, p2p_есть: bool = True) -> План:
    """Единственная точка выбора. Возвращает план, одинаковый на всех рангах."""
    if мир <= 1:
        return План("нет", [], "одна карта, обмен не нужен")
    if not p2p_есть:
        return План("nccl", [], "P2P между картами недоступен")
    if мир > 4:
        return План("nccl", [], f"мир {мир} > 4: свой путь не собран для такого числа карт")
    if байт > ПОТОЛОК_БАЙТ:
        return План("nccl", [], f"посылка {байт} Б выше потолка {ПОТОЛОК_БАЙТ} Б")

    карты = карты if карты is not None else list(range(мир))
    м = _топология(карты)
    if м is None:
        # Топология не прочиталась -- НЕ гадаем. Плоский план верен всегда, он лишь не оптимален.
        м = [["NODE"] * мир for _ in range(мир)]
        плоско_потому = "топология не прочитана, беру плоский план (верен, но не оптимален)"
    else:
        плоско_потому = ""

    прочие = [r for r in range(мир) if r != ранг]

    if мир == 2:
        # Как у них: на двух картах топология не спрашивается.
        return План("свой", [прочие], "две карты: одношаговый независимо от канала", м)

    группы = _группы(м)
    однороден = len({_цена(м[i][j]) for i in range(мир) for j in range(мир) if i != j}) == 1

    if плоско_потому or однороден or группы is None or байт < ПЕРЕЛОМ_БАЙТ:
        почему = плоско_потому or (
            "канал однороден: ярусы не дали бы выигрыша" if однороден else
            "ровного разбиения на группы нет" if группы is None else
            f"посылка {байт} Б ниже перелома {ПЕРЕЛОМ_БАЙТ} Б: одно рандеву дешевле одного перехода")
        return План("свой", [прочие], почему, м)

    # СМЕШАННЫЙ ПЛАН. Ярус 1 -- внутри своей группы (быстрый канал), ярус 2 -- между группами
    # по ОДНОМУ переходу: ранг с тем же местом в своей группе.
    моя = next(g for g in группы if ранг in g)
    место = моя.index(ранг)
    свои = [r for r in моя if r != ранг]
    чужие = [g[место] for g in группы if g is not моя]
    порог_свой = max(_цена(м[ранг][r]) for r in свои)
    медленных_плоско = sum(1 for r in прочие if _цена(м[ранг][r]) > порог_свой)
    return План("свой", [свои, чужие],
                f"смешанный: переходов по медленному {len(чужие)} вместо {медленных_плоско}, "
                f"ценой второго рандеву", м)


def согласован(мир: int, карты: list[int] | None = None, байт: int = 0,
               p2p_есть: bool = True) -> tuple[bool, str]:
    """ФАЛЬСИФИКАТОР ПЛАНА, встроенный в код.

    Проверяет то, нарушение чего вешает ядро намертво: (1) все ранги выбрали ОДИН путь;
    (2) у всех ОДИНАКОВОЕ число ярусов; (3) отношение «тяну у» СИММЕТРИЧНО на каждом ярусе --
    если ранг r тянет у s, то s обязан тянуть у r на том же ярусе, иначе один ждёт другого вечно.
    """
    планы = [построить(r, мир, карты, байт, p2p_есть) for r in range(мир)]
    пути = {p.путь for p in планы}
    if len(пути) != 1:
        return False, f"ранги выбрали РАЗНЫЕ пути: {пути}"
    if планы[0].путь != "свой":
        return True, f"путь {планы[0].путь} у всех: проверять нечего"
    ярусов = {p.рандеву for p in планы}
    if len(ярусов) != 1:
        return False, f"разное число ярусов по рангам: {[p.рандеву for p in планы]}"
    for k in range(планы[0].рандеву):
        for r in range(мир):
            for s in планы[r].ярусы[k]:
                if r not in планы[s].ярусы[k]:
                    return False, f"ярус {k}: ранг {r} тянет у {s}, а {s} у {r} -- нет"
    return True, f"согласован: путь свой, ярусов {планы[0].рандеву}"


