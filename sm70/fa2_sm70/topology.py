    # Имена переменных окружения -- ASCII: оболочка не принимает иные.
    мир = int(os.environ.get("FA2SM70_WORLD", "4"))
    байт = int(os.environ.get("FA2SM70_BYTES", str(5120 * 2)))
    for r in range(мир):
        p = построить(r, мир, байт=байт)
        print(f"ранг {r}: {p.описание()}")
