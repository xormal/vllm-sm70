// ==================================================================================================
// W12A16 НА ТЕНЗОРНЫХ ЯДРАХ VOLTA: вес в 12 разрядах, потребляемый упакованным.
// ==================================================================================================
//
// ЗАЧЕМ ЭТО ТЕЛО. Разбор чужого движка (docs/SPEC_TURBOMIND.md) дал карту по M на форме словарной
// проекции (N=124160, K=5120), отношения к turbomind:
//     M= 1  наш скалярный GEMV 1.898   наше прежнее тензорное 0.653
//     M= 4  1.449                       0.673
//     M= 8  0.908                       0.688
//     M=16  0.624                       0.679      <- пол по полосе для int8 = 0.74 мс против 1.674
// Скалярный GEMV связан СЧЁТОМ на fp32-трубе выше M=4. Прежнее тензорное тело (`w8a16_hmma`)
// считает верно, но проигрывает чужому ВЕЗДЕ, ЧИТАЯ ВДВОЕ МЕНЬШЕ БАЙТ -- значит его стена не
// полоса, а ФОРМА: плитка 64 по N, свод группы целиком в разделяемой, барьеры. При M=16 не взято
// x2.25, и это ровно то, что здесь берётся.
//
// ================= ИТОГ 16.08.2026: ЧУЖОЕ ТЕЛО ПРОЙДЕНО ПРИ M>=8 =================
// Боевая форма словарной проекции (N=124160, K=5120), отношения к turbomind:
//
//     проход                                            M=1     M=8    M=16
//     первая редакция (по образцу, не по плейбуку)      0.714   0.694   0.631
//     проход 1: LDG.128 на вес, STS.64, вынос суммы x   0.938   0.992   1.028
//     проход 2a: широкая подача активации               0.984   1.038   1.079
//
// ТРИ ПОТЕРИ ПРОХОДА 1 -- ВСЕ ТРИ БЫЛИ УЖЕ ЗАПИСАНЫ В НАШИХ ЖЕ ДОКАХ, И Я ИХ ПОВТОРИЛ:
//   1. вес читался тремя LDG.32 вместо трёх LDG.128 (ровно потеря, закрытая в `w8a16_gemv`);
//   2. в общую память писалось 64 STS.U16 вместо 16 STS.64 (плейбук §3, вариант 1);
//   3. сумма x по группе считалась в КАЖДОМ из 970 блоков, хотя от n не зависит вовсе.
// Машинный код: 12 LDG.E -> 3 LDG.E.128, 64 STS.U16 -> 16 STS.64, регистров 168 -> 104.
// Проход 2a добавил широкую подачу активации (uint2 вместо четырёх полуслов): 18 STS.64, 1 LDG.64.
//
// ЧТО СВЯЗЫВАЕТ ТЕПЕРЬ (фальсификаторы, геометрия BN=128 WN=4 BK=32 без конвейера, M=16):
//     полное                                   1.531 мс   (чужое 1.662)
//     минус вторая плоскость (= цена int10)     1.374     -10.3 %
//     минус подача B из разделяемой              1.460      -4.6 %
//     минус тензорное умножение                  1.372     -10.4 %
// Тензорная работа стала 10 % периода вместо 86: тело СВЯЗАНО ПАМЯТЬЮ, 702 ГБ/с из 878 (80 %).
// Это и есть правильное состояние для M<=16, где вес читается один раз на 16 строк.
//
// ОСТАВШИЙСЯ ЗАПАС: 1.372 против пола по полосе 1.097 = 25 %. Он в ПАМЯТИ, а не в счёте, и
// следующий проход обязан идти туда, а не в тензорную часть.
//
// ПРОВЕРЕНО И НЕ ДАЛО (чтобы не переделывать третий раз):
//   * конвейер (двойная буферизация): проигрывает без него почти везде -- удвоение плиты режет
//     блоки на SM, и потеря занятости дороже выигранной тени;
//   * принуждённая занятость MINB: 0.8 %;
//   * предзагрузка фрагментов A (`accumulate_pre`, §13 про адресную арифметику): ПОБАЙТОВО ТОТ ЖЕ
//     машинный код -- адреса в `WarpMma::a_base/b_base` уже подняты, загрузки компилятор выносит сам.
//
// ГЕОМЕТРИЯ ВЗЯТА У turbomind (разобрана из искажённого имени ядра, §5 спецификации):
//   MMA_Map<8..16, 128, 64>, БЛОК 128 НИТЕЙ = 4 варпа, накопитель fp32, вывод fp16,
//   операнд B предпакован при загрузке, конвейер глубины 2.
// Здесь: BN столбцов на блок (128 по умолчанию), WN=4 варпов, подплитка BK ключей.
//
// ---------------------------------------------------------------------------------------------
// ГЛАВНОЕ: ПОЧЕМУ int12 ВООБЩЕ ЛОЖИТСЯ НА HMMA, И ПОЧЕМУ ТРЮК int8 СЮДА НЕ ПЕРЕНОСИТСЯ
// ---------------------------------------------------------------------------------------------
// У int8 разворот стоит ОДНУ команду: `0x6400 | q` даёт fp16-число РОВНО 1024+q, потому что низкие
// 10 бит кодировки -- это мантисса. ЗАМЕРЕНО (не вспомнено): целые представимы в fp16 точно только
// на [0, 2048); на [2048, 4096) шаг уже 2. Значит для 12 разрядов тот же OR ЛОМАЕТСЯ -- старшие два
// бита теряются, и проверка это подтверждает на всех 3072 значениях.
//
// ХОД: РАЗЛОЖИТЬ 12 РАЗРЯДОВ НА ДВЕ ШЕСТЁРКИ И ПРОДУБЛИРОВАТЬ АКТИВАЦИЮ.
//     u = q + 2048 in [0,4096),  hi = u >> 6,  lo = u & 63,  оба < 64  ->  u = 64*hi + lo
// Плоскости кладутся ЧЕРЕДУЯСЬ по оси свёртки, а активация дублируется как [x, 64x]:
//     sA[.., 2j] = x_j        sB[2j,   n] = 1024 + lo
//     sA[.., 2j+1] = 64*x_j   sB[2j+1, n] = 1024 + hi
// Тогда ОДНО обычное умножение по удвоенному K даёт
//     H = sum_j ( x_j*(1024+lo_j) + 64*x_j*(1024+hi_j) ) = 66560*Sx + sum_j x_j*u_j,
// откуда  sum_j x_j*q_j = H - 68608*Sx,  где Sx -- сумма x по группе (она и так нужна).
//
// ПОЧЕМУ ЭТО ТОЧНО, А НЕ ПРИБЛИЗИТЕЛЬНО:
//   * оба операнда 1024+hi и 1024+lo лежат в [1024, 1088) -- зона ТОЧНЫХ целых fp16;
//   * умножение на 64 -- сдвиг двоичного порядка, округления нет вовсе (проверено равенством);
//   * накопитель HMMA -- fp32, точный до 2^24, а самый крупный член ~7e5.
// ЗАМЕРЕНО на модели схемы: relL2 к точному развороту int12 = 9.15e-06, то есть в 53 раза ниже
// собственной ошибки квантования int12 (4.87e-04). Сходимость здесь ДОКАЗАНА, а не желательна.
//
// ЦЕНА: тензорной работы вдвое (удвоенный K). Она не связывает: при M=16 на форме словаря это
// 0.43 мс тензорной трубы против пола по полосе 1.10 мс -- то есть уходит в тень чтения веса.
//
// КВАНТОВАНИЕ int12 СИММЕТРИЧНОЕ, нулевой точки нет вовсе: эпилог группы -- ОДИН множитель, и
// целая фаза чужого формата (свод нуля) отсутствует. Вычитание 68608*Sx -- это не нулевая точка,
// а разворот СМЕЩЕНИЯ КОДИРОВКИ, и оно одинаково для всех столбцов.
#pragma once
#include <cuda_fp16.h>
#include <cstdint>
#include "gemm/volta_warp_mma.h"

namespace fa2_sm70 {
namespace w12a16 {

using fa2_sm70::WarpMma;
using fa2_sm70::BLayout;

// Смещение кодировки, снимаемое в эпилоге: 64*1024 (плоскость hi) + 1024 (плоскость lo) + 2048.
constexpr float kBias12 = 68608.0f;

// Суммы x по группам: [M][K/G]. Отдельный пуск законен ровно потому, что незаконен для веса --
// его цена делится на ВСЕ блоки сетки (970 на этой форме), а не платится каждым.
__global__ void w12_sx_kernel(const __half* __restrict__ x, float* __restrict__ sxg,
                              int M, int K, int G) {
  const int r = blockIdx.y, g = blockIdx.x * blockDim.x + threadIdx.x;
  if (r >= M || g >= K / G) return;
  float s = 0.f;
  for (int c = 0; c < G; ++c) s += __half2float(x[(long)r * K + (long)g * G + c]);
  sxg[(long)r * (K / G) + g] = s;
}

// BN -- столбцов выхода на блок; WN -- варпов по N; G -- группа масштаба; BK -- ключей в подплитке.
// DIAG -- ФАЛЬСИФИКАТОР СНЯТИЕМ ФАЗЫ. Ответ при DIAG!=0 ЗАВЕДОМО НЕВЕРЕН, читается ТОЛЬКО время:
//   1 -- снята распаковка и запись веса в разделяемую (чтение из глобальной остаётся);
//   2 -- снято чтение веса из глобальной (распаковка и запись остаются);
//   3 -- снято тензорное умножение.
// Разность даёт ДОЛЮ фазы, а не догадку. Счёт команд предсказанием не является -- четыре правки
// по нему уже роняли счёт и не роняли время.
// PIPE -- ОСЬ, А НЕ РЕШЕНИЕ. Двухстадийный конвейер (выдача загрузок следующей плитки ДО
// умножения текущей) стоит УДВОЕНИЯ плиты в общей памяти, а та режет число блоков на SM. Что
// перевесит -- тень или занятость -- решается ЗАМЕРОМ на каждой геометрии, а не выбором автора:
// первый же прогон показал, что на BN=128/BK=32 конвейер ХУЖЕ (3.75 против 2.63).
// MINB -- НИЖНЯЯ ГРАНИЦА БЛОКОВ НА SM, наш обычный обход компилятора. Без неё ptxas берёт 172
// регистра и кладёт 2 блока на SM = 8 варпов = 12.5 % занятости, а тело связано ЗАДЕРЖКОЙ.
// Вторым параметром `__launch_bounds__` компилятор ОБЯЗАН уложиться в 65536/(MINB*WN*32) регистров
// -- ровно тот рычаг, что уже применён в ядре внимания. Он тоже ОСЬ, а не решение: где регистров
// не хватит, ptxas разольёт в локальную, и это надо не предполагать, а ЧИТАТЬ (гейт по разливу
// гоняет `-Xptxas -v` по ВСЕЙ таблице и отсеивает воплощения с ненулевым кадром стека).
template <int BN, int WN, int G, int BK, int PIPE = 1, int MINB = 1, int DIAG = 0>
__global__ __launch_bounds__(WN * 32, MINB) void w12a16_hmma(
    const __half* __restrict__ x, const int* __restrict__ qw,
    const __half* __restrict__ scales, const float* __restrict__ sxg,
    __half* __restrict__ y, int M, int N, int K) {
  constexpr int MT = 16;                       // одна плитка HMMA по M
  constexpr int NBw = (BN / WN) / 16;          // блоков по 16 столбцов на варп
  // [ФАЛЬСИФИКАТОР DIAG=4: ОДНА ПЛОСКОСТЬ ВМЕСТО ДВУХ]
  // Ответ ЗАВЕДОМО НЕВЕРЕН (берутся только младшие 6 разрядов), но ВРЕМЯ -- это ровно то, во что
  // обошёлся бы int10: тот же поток байт, но БЕЗ удвоения тензорной работы, потому что 10 разрядов
  // ложатся в мантиссу fp16 ОДНИМ OR. Без этого замера выбор «строить ли int10» был бы догадкой.
  constexpr int PL = (DIAG == 4) ? 1 : 2;
  constexpr int KD = PL * BK;                  // ось свёртки: [lo, hi] чередуясь либо только lo
  // Дополнения -- по тем же двум законам, что выведены для w8a16_hmma и ядер GDN:
  //   sA (k-мажорный): «DK+4»  -> LDA = KD+4 полуслов;
  //   sB (n-мажорный): (LD/2) mod 32 == 8 -> при BN=128 это LDB=144 (144/2=72, 72 mod 32 = 8).
  constexpr int PADA = 4, PADB = 16;
  constexpr int LDA = KD + PADA, LDB = BN + PADB;
  static_assert(BN % (WN * 16) == 0, "BN кратно WN*16");
  static_assert(BK % 8 == 0, "подплитка кратна 8: упаковка int12 идёт тройками на 8 ключей");
  static_assert(G % BK == 0, "группа масштаба обязана делиться на подплитку");

  constexpr int NBUF = PIPE ? 2 : 1;
  __shared__ __half sA[NBUF * MT * LDA];              // [MT][KD]  k-мажорный, чередование [x, 64x]
  __shared__ __half sB[NBUF * KD * LDB];              // [KD][BN]  n-мажорный, чередование [lo, hi]
  __shared__ float sSx[MT];                    // сумма x по ГРУППЕ, на строку
  __shared__ float sS[BN];                     // масштаб группы -- один раз на столбец

  const int tid = threadIdx.x, lane = tid & 31, warp = tid >> 5;
  const int n0 = blockIdx.x * BN;
  const int m0 = blockIdx.y * MT;
  const int mrows = min(MT, M - m0);
  const __half k64 = __float2half(64.0f);

  // Двойная буферизация ОБОИХ операндов: пока идёт умножение по буферу cur, загрузки следующей
  // плитки уже выданы и летят.
  // [ШИРИНА И ЗДЕСЬ] Активация грузилась ПО ПОЛУСЛОВУ (40 LDG.E.U16 в машинном коде) и клалась
  // по полуслову же. Четыре подряд идущих ключа одной строки -- это ровно uint2: одна LDG.64
  // вместо четырёх, и две STS.64 вместо восьми STS.U16 (плейбук §3, вар. 1).
  static_assert(BK % 4 == 0, "четыре ключа на нить");
  constexpr int NX = (MT * (BK / 4) + WN * 32 - 1) / (WN * 32);   // четвёрок ключей на нить
  // [ШИРИНА ОБРАЩЕНИЯ -- ЗАПИСАННАЯ И ЗАКРЫТАЯ ПОТЕРЯ, ПОВТОРЁННАЯ ЗДЕСЬ ЗАНОВО]
  // Раскладка `qw [K/8, 3, N]` по n НЕПРЕРЫВНА, значит одна нить берёт ЧЕТЫРЕ соседних столбца
  // одним `uint4`: три LDG.128 на восемь ключей вместо двенадцати LDG.32. Ровно тот ход, что уже
  // дал -8.9 % в `w8a16_gemv` (машинный код там назвал отсутствие LDG.128 прямой причиной).
  // Даром достаётся вторая половина: четыре развёрнутых полуслова одного ключа лежат в общей
  // памяти ПОДРЯД, поэтому запись идёт одной STS.64 вместо четырёх STS.U16 (плейбук §3, вар. 1).
  static_assert(BN % 4 == 0, "четыре столбца на нить");
  constexpr int NW = ((BK / 8) * (BN / 4) + WN * 32 - 1) / (WN * 32);   // четвёрок столбцов на нить

  WarpMma<1, NBw, BLayout::kNMajor> o;
  float acc[NBw][8];
#pragma unroll
  for (int j = 0; j < NBw; ++j)
#pragma unroll
    for (int r = 0; r < 8; ++r) acc[j][r] = 0.f;

  uint2 rx[NX];         // четыре полуслова активации на элемент
  uint4 rw[NW][3];      // три плоскости упаковки x четыре столбца

  // --- ВЫДАЧА ЗАГРУЗОК ПЛИТКИ В РЕГИСТРЫ (без записи в общую -- она отдельной фазой) -----------
  auto подать = [&](int k0) {
#pragma unroll
    for (int t = 0; t < NX; ++t) {
      const int i = tid + t * WN * 32;
      if (i < MT * (BK / 4)) {
        const int r = i / (BK / 4), c4 = i - r * (BK / 4);
        rx[t] = ((r < mrows) && (k0 + 4 * c4 + 3 < K))
                    ? *reinterpret_cast<const uint2*>(x + (long)(m0 + r) * K + k0 + 4 * c4)
                    : make_uint2(0u, 0u);
      }
    }
#pragma unroll
    for (int t = 0; t < NW; ++t) {
      const int i = tid + t * WN * 32;
      if (i < (BK / 8) * (BN / 4)) {
        const int kq = i / (BN / 4), n4 = i - kq * (BN / 4);
        const int nn = n0 + 4 * n4;
        const long base = (long)((k0 >> 3) + kq) * 3 * N + nn;
        if (DIAG != 2 && nn + 3 < N) {
          rw[t][0] = *reinterpret_cast<const uint4*>(qw + base);
          rw[t][1] = *reinterpret_cast<const uint4*>(qw + base + N);
          rw[t][2] = *reinterpret_cast<const uint4*>(qw + base + 2 * N);
        } else {
          const uint4 z = make_uint4(0u, 0u, 0u, 0u);
          rw[t][0] = z; rw[t][1] = z; rw[t][2] = z;
        }
      }
    }
  };

  // --- РАСКЛАДКА ПРИНЯТОГО В ОБЩУЮ ПАМЯТЬ (эта фаза стоит В ТЕНИ следующего умножения) --------
  auto разложить = [&](int buf) {
    __half* pA = sA + buf * (MT * LDA);
    __half* pB = sB + buf * (KD * LDB);
#pragma unroll
    for (int t = 0; t < NX; ++t) {
      const int i = tid + t * WN * 32;
      if (i < MT * (BK / 4)) {
        const int r = i / (BK / 4), c4 = i - r * (BK / 4);
        const __half* h = reinterpret_cast<const __half*>(&rx[t]);
        __half* q = &pA[r * LDA + PL * 4 * c4];
        if constexpr (PL == 2) {
          // чередование [x, 64x] собирается В РЕГИСТРАХ и уходит двумя STS.64
          uint2 a, b;
          reinterpret_cast<__half*>(&a)[0] = h[0];
          reinterpret_cast<__half*>(&a)[1] = __hmul(h[0], k64);
          reinterpret_cast<__half*>(&a)[2] = h[1];
          reinterpret_cast<__half*>(&a)[3] = __hmul(h[1], k64);
          reinterpret_cast<__half*>(&b)[0] = h[2];
          reinterpret_cast<__half*>(&b)[1] = __hmul(h[2], k64);
          reinterpret_cast<__half*>(&b)[2] = h[3];
          reinterpret_cast<__half*>(&b)[3] = __hmul(h[3], k64);
          *reinterpret_cast<uint2*>(q) = a;
          *reinterpret_cast<uint2*>(q + 4) = b;
        } else {
          *reinterpret_cast<uint2*>(q) = rx[t];
        }
      }
    }
    if (DIAG == 1) return;                    // фаза распаковки+записи веса снята
#pragma unroll
    for (int t = 0; t < NW; ++t) {
      const int i = tid + t * WN * 32;
      if (i < (BK / 8) * (BN / 4)) {
        const int kq = i / (BN / 4), n4 = i - kq * (BN / 4);
        // Четыре столбца идут ВМЕСТЕ: развёрнутая четвёрка одного ключа -- это ровно uint2,
        // то есть одна STS.64 на (ключ, плоскость) вместо четырёх STS.U16.
        unsigned v[4][8];
#pragma unroll
        for (int c = 0; c < 4; ++c) {
          const unsigned w0 = (&rw[t][0].x)[c], w1 = (&rw[t][1].x)[c], w2 = (&rw[t][2].x)[c];
          v[c][0] = w0 & 0xFFFu;
          v[c][1] = (w0 >> 12) & 0xFFFu;
          v[c][2] = ((w0 >> 24) & 0xFFu) | ((w1 & 0xFu) << 8);
          v[c][3] = (w1 >> 4) & 0xFFFu;
          v[c][4] = (w1 >> 16) & 0xFFFu;
          v[c][5] = ((w1 >> 28) & 0xFu) | ((w2 & 0xFFu) << 4);
          v[c][6] = (w2 >> 8) & 0xFFFu;
          v[c][7] = (w2 >> 20) & 0xFFFu;
        }
        __half* q8 = &pB[(kq * 8) * PL * LDB + 4 * n4];
#pragma unroll
        for (int b = 0; b < 8; ++b) {
          uint2 lo, hi;
          lo.x = (0x6400u | (v[0][b] & 63u)) | ((0x6400u | (v[1][b] & 63u)) << 16);
          lo.y = (0x6400u | (v[2][b] & 63u)) | ((0x6400u | (v[3][b] & 63u)) << 16);
          *reinterpret_cast<uint2*>(&q8[(PL * b) * LDB]) = lo;
          if constexpr (PL == 2) {
            hi.x = (0x6400u | (v[0][b] >> 6)) | ((0x6400u | (v[1][b] >> 6)) << 16);
            hi.y = (0x6400u | (v[2][b] >> 6)) | ((0x6400u | (v[3][b] >> 6)) << 16);
            *reinterpret_cast<uint2*>(&q8[(PL * b + 1) * LDB]) = hi;
          }
        }
      }
    }
  };

  // [ФАЛЬСИФИКАТОР DIAG=5: ТЕНЗОРНАЯ РАБОТА БЕЗ ПОДАЧИ B ИЗ РАЗДЕЛЯЕМОЙ]
  // Ответ ЗАВЕДОМО НЕВЕРЕН. Тензорных команд РОВНО столько же, A по-прежнему из разделяемой, но
  // фрагмент веса берётся из РЕГИСТРА -- то есть это ядро, у которого вес предварительно уложен в
  // порядок дорожек инструкции и читается из глобальной ПРЯМО В РЕГИСТРЫ, минуя общую память
  // (`Operand_B_Pack` у turbomind). Разность с полным телом = цена подачи B, и она решает, стоит
  // ли строить предукладку.
  uint32_t fb_reg[NBw][2];
#pragma unroll
  for (int j = 0; j < NBw; ++j) { fb_reg[j][0] = 0x64006400u; fb_reg[j][1] = 0x64006400u; }
  auto мма_без_B = [&](const __half* pA, const __half* pB) {
    // СТОК, БЕЗ КОТОРОГО ПРИБОР ВРЁТ В ПОЛЬЗУ УСПЕХА. Если sB не читается ВООБЩЕ, ptxas выносит
    // всю цепочку веса (загрузка из глобальной, разбор, запись в общую) как мёртвую, и замер даёт
    // 0.801 мс -- НИЖЕ пола по полосе 1.097. Одно чтение на плитку держит цепочку живой, а его
    // собственная цена ничтожна против NBw*2 чтений на КАЖДЫЙ шаг k, которые мы и снимаем.
    uint32_t fa[1][2];
    uint32_t fb[NBw][2];
#pragma unroll
    for (int j = 0; j < NBw; ++j) { fb[j][0] = fb_reg[j][0]; fb[j][1] = fb_reg[j][1]; }
    fb[0][0] ^= (uint32_t)__half_as_ushort(pB[lane]) & 0xFFFFu;
#pragma unroll
    for (int k = 0; k < KD; k += 4) { o.load_a(fa, pA, LDA, 0, lane, k); o.mma(fa, fb); }
  };

  if constexpr (PIPE) { подать(0); разложить(0); }
  int cur = 0;

  for (int g0 = 0; g0 < K; g0 += G) {
    o.clear();
    // Сумма x по ГРУППЕ берётся ИЗ ГЛОБАЛЬНОЙ, а не из sA: зависимость от общей памяти вносила
    // лишний барьер внутрь плиточного цикла, а это ровно то, что мы отсюда и убираем. x мал и
    // живёт в L2, поэтому цена -- обращение к кэшу, а не к HBM.
    // [ИНВАРИАНТ ВЫНЕСЕН ИЗ СЕТКИ БЛОКОВ] Сумма x по группе от n НЕ ЗАВИСИТ, а считалась в
    // КАЖДОМ из 970 блоков: 128 полусловных чтений на нить на группу, 970-кратно избыточно.
    // Теперь она считается ОДИН раз отдельным пуском (M*K/G чисел, доли микросекунды) и здесь
    // только читается -- одно обращение вместо ста двадцати восьми.
    if (tid < MT) sSx[tid] = (tid < mrows) ? sxg[(long)(m0 + tid) * (K / G) + g0 / G] : 0.f;
    for (int c = tid; c < BN; c += WN * 32) {
      const int nn = n0 + c;
      sS[c] = (nn < N) ? __half2float(scales[(long)(g0 / G) * N + nn]) : 0.f;
    }
    for (int k0 = g0; k0 < g0 + G; k0 += BK) {
      if constexpr (PIPE) {
        __syncthreads();                        // буфер cur готов; sSx и sS видны
        const int nxt = k0 + BK;
        if (nxt < K) подать(nxt);               // ВЫДАЧА ДО УМНОЖЕНИЯ -- задержка в его тени
        if (DIAG == 5) { мма_без_B(sA + cur * (MT * LDA), sB + cur * (KD * LDB)); }
        else if (DIAG != 3)
          o.template accumulate<KD>(sA + cur * (MT * LDA), LDA, 0, sB + cur * (KD * LDB), LDB,
                                    warp * (BN / WN), lane);
        if (nxt < K) разложить(cur ^ 1);        // пишем ДРУГОЙ буфер: барьер не нужен
        cur ^= 1;
      } else {
        __syncthreads();                        // прежняя плитка дочитана
        подать(k0);
        разложить(0);
        __syncthreads();
        if (DIAG == 5) { мма_без_B(sA, sB); }
        else if (DIAG != 3)
          o.template accumulate<KD>(sA, LDA, 0, sB, LDB, warp * (BN / WN), lane);
      }
    }
    // --- эпилог группы: s * (H - 68608*Sx). Нулевой точки НЕТ: квантование симметричное. -------
#pragma unroll
    for (int j = 0; j < NBw; ++j)
#pragma unroll
      for (int r = 0; r < 8; ++r) {
        const int row = ((lane & 1) | ((lane & 16) >> 2) | (lane & 8)) + 2 * ((r >> 1) & 1);
        const int col = ((lane & 2) | ((lane & 4) << 1)) + (r & 1) + 4 * ((r >> 2) & 1) + j * 16
                        + warp * (BN / WN);
        if (n0 + col < N && row < mrows)
          acc[j][r] += sS[col] * (o.acc[0][j][r] - kBias12 * sSx[row]);
      }
    __syncthreads();   // sS/sSx следующей группы пишутся ПОСЛЕ того, как все дочитали текущие
  }
#pragma unroll
  for (int j = 0; j < NBw; ++j)
#pragma unroll
    for (int r = 0; r < 8; ++r) {
      const int row = ((lane & 1) | ((lane & 16) >> 2) | (lane & 8)) + 2 * ((r >> 1) & 1);
      const int col = ((lane & 2) | ((lane & 4) << 1)) + (r & 1) + 4 * ((r >> 2) & 1) + j * 16
                      + warp * (BN / WN);
      const int nn = n0 + col;
      if (nn < N && row < mrows) y[(long)(m0 + row) * N + nn] = __float2half(acc[j][r]);
    }
}

