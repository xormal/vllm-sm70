// Профилировщик недоступен (ERR_NVGPUCTRPERM), поэтому раскладка снята абляцией. Обычная абляция
// "закомментировать STG" НЕГОДНА: она убивает заодно G3, эпилог и подачу V как мёртвый код, и цена
// записи выходит завышенной. Здесь запись отменяется ПРЕДИКАТОМ НА РАНТАЙМНЫЙ АРГУМЕНТ
// (scale > 1e30f) -- свернуть его компилятор не может, вся цепочка зависимостей остаётся живой:
//     всё как есть .................. 0.1429 мс   96.34 МБ
//     запись отменена предикатом .... 0.1040 мс   80.28 МБ чтения -> 772 ГБ/с = 94% от 819
//     пишется каждая 4-я строка ..... 0.1257 мс   84.29 МБ
// ЗАПИСЬ СТОИТ 0.0389 мс на 16.06 МБ = 413 ГБ/с, то есть идёт ВДВОЕ ХУЖЕ ЧТЕНИЯ. ЭТО И ЕСТЬ ВЕСЬ
// ОСТАВШИЙСЯ ЗАПАС. И это же доказывает, что АРИФМЕТИКА СПРЯТАНА ПОЛНОСТЬЮ: если бы она стояла на
