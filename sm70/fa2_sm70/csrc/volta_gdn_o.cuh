// РАСКЛАДКИ ОПЕРАНДА B В НАШЕМ API -- ПРОТИВОПОЛОЖНЫ ИНТУИЦИИ ИМЕНИ, и на этом уже ошибались:
//   kKMajor: B это [N][K], непрерывен K  -> инструкция .row.col, это случай Q*K^T
//   kNMajor: B это [K][N], непрерывен N  -> инструкция .row.row, это случай P*V
// Отсюда: G1 (h лежит [V][K]) и G2 (k лежит [t][K]) -- ОБА kKMajor; G3 (v лежит [t][V]) -- kNMajor.

// РАЗМЕР РАЗДЕЛЯЕМОЙ ПАМЯТИ ДЛЯ ЗАПУСКА (Б). Считать ТОЛЬКО по этой функции: окно объединено, и
// наивная сумма буферов даёт 77 КБ вместо 44 -- то есть молча теряет второй блок на SM.
template <int BT, int DK, int DV>
__host__ __device__ constexpr size_t gdn_smem_bytes() {
  constexpr int PAD = 8;
  constexpr int win_k = BT * (DK + PAD);        // sK во время G2
  constexpr int win_h = DV * (DK / 2 + PAD);    // половина sH во время G1
  constexpr int win_v = BT * (DV + PAD);        // sV во время G3
  constexpr int win = win_k > win_h ? (win_k > win_v ? win_k : win_v)
                                    : (win_h > win_v ? win_h : win_v);
  return (size_t)(BT * (DK + PAD) + BT * (BT + PAD) + win) * sizeof(__half);
}

// [ВЫХОД БЕЗ ОТДЕЛЬНОЙ КОНВЕРСИИ] Тип выхода -- ПАРАМЕТР ШАБЛОНА, а не жёстко __half.
// Модель идёт в bfloat16, а тензорные ядра Volta bf16 не умеют, поэтому счёт обязан быть fp16.
// Наивная развязка -- отдельный проход .to(bfloat16) над [T][H][DV]; замерено 0.378 мс на слой,
// то есть 10% всего скана, потраченные РОВНО на перекладку 2-байтовых слов.
// Здесь конверсия -- НАЕЗДНИК на эпилоге: накопитель и так лежит в fp32 в регистрах, и упаковка
// пары в __half2 либо в __nv_bfloat162 стоит ОДНУ инструкцию в обоих случаях (CVT с разным
// суффиксом). Байтов пишется столько же, шаг строки тот же, вся укладка через разделяемую
// не меняется -- значит выигрыш 0.378 мс достаётся ДАРОМ. Именно так и надо забирать
// структурные конверсии: не отдельным ядром, а сменой типа у уже существующей записи.
// Ошибка от этого НЕ растёт: у bf16 меньше мантисса, но выход всё равно немедленно уходит
// в bf16-путь модели, то есть округление лишь ПЕРЕЕЗЖАЕТ из отдельного ядра сюда.
template <typename OT>
struct gdn_o2;
template <>
struct gdn_o2<__half> {
  using v2 = __half2;
  static __device__ __forceinline__ v2 pack(float a, float b) { return __floats2half2_rn(a, b); }
};
#if defined(__CUDA_ARCH__) || 1
template <>
struct gdn_o2<__nv_bfloat16> {
  using v2 = __nv_bfloat162;
  // Volta (sm_70) НЕ ИМЕЕТ инструкции cvt.rn.bf16x2.f32 -- __floats2bfloat162_rn там раскрывается
  // в пару вызовов, а на старых тулкитах и вовсе в round-trip через fp32-битовые операции.
  // Пишем округление к ближайшему-чётному ЯВНО битовой арифметикой (§4m примитивов: сдвиг и
  // сложение дешевле любой эмулированной конверсии). NaN сохраняется, denormal bf16 не нужен.
  static __device__ __forceinline__ unsigned short one(float x) {
    unsigned int u = __float_as_uint(x);
    if ((u & 0x7fffffffu) > 0x7f800000u) return (unsigned short)((u >> 16) | 0x0040u);  // NaN
    u += 0x7fffu + ((u >> 16) & 1u);
    return (unsigned short)(u >> 16);
  }
  static __device__ __forceinline__ v2 pack(float a, float b) {
    v2 r;
    unsigned int w = (unsigned int)one(a) | ((unsigned int)one(b) << 16);
    r = *reinterpret_cast<const v2*>(&w);
    return r;
  }
};
#endif

// BT -- размер чанка (64), DK/DV -- размерности головы, WM x WN -- сетка варпов по выходу.
// Отгружаемая конфигурация: <64,128,128,2,4> -- 8 варпов, плитка варпа 32x32, 44.0 КБ, 124 регистра,
// разлив 0, ДВА блока на SM.
//
// [VARLEN] chunk_indices/cu_seqlens -- ровно контракт fla (index.py): chunk_indices[i] = (номер
// последовательности, ЛОКАЛЬНЫЙ номер чанка), а blockIdx.x -- СКВОЗНОЙ номер чанка по всей партии,
// он же индекс в h (у Triton это i_tg, см. chunk_o.py: `h += (i_tg*H + i_h)*V*K`). Оба указателя
// nullptr = одна последовательность длины T, поведение прежнее ДОСЛОВНО.
// Без этого ядро нельзя поставить в боевой путь: чанкованный префилл vLLM подаёт cu_seqlens всегда.
template <int BT, int DK, int DV, int WM, int WN, typename OT = __half>
__global__ __launch_bounds__(WM * WN * 32, 2) void volta_gdn_chunk_o(
    const __half* __restrict__ q,      // [T, Hg, DK]
    const __half* __restrict__ k,      // [T, Hg, DK]
    const __half* __restrict__ v,      // [T, H,  DV]
    const __half* __restrict__ h,      // [NT, H, DV, DK]   состояние на начало чанка
    const float*  __restrict__ g,      // [T, H]            накопленный логарифм гейта
    OT* __restrict__ o,                // [T, H, DV]
    const int* __restrict__ chunk_indices,   // [NT][2] или nullptr
    const int* __restrict__ cu_seqlens,      // [N+1]   или nullptr
    int T, int H, int Hg, float scale) {
  constexpr int PAD = 8;                             // 8 полуслов = 16 Б: держит uint4 выровненным
  constexpr int LDQ = DK + PAD, LDV = DV + PAD, LDA = BT + PAD;
  constexpr int DKH = DK / 2, LDH = DKH + PAD;       // половина k у операнда h
  constexpr int SM = BT / WM, SN = DV / WN, SNA = BT / WN;
  constexpr int MB = SM / 16, NB = SN / 16, NBA = SNA / 16;
  constexpr int nthr = WM * WN * 32;
  static_assert(SM % 16 == 0 && SN % 16 == 0 && SNA % 16 == 0, "плитки кратны шагу фрагмента");
  static_assert(DK == DV, "буфер выхода переиспользует sQ");
  static_assert(DKH % 8 == 0, "половина k кратна ширине uint4");
  // §4b: шаг строки, по которой пишут uint4, кратен 16 Б = 8 полусловам. Нарушение даёт ОТКАЗ
  // ЖЕЛЕЗА (misaligned address), а не замедление, и портит контекст всем следующим замерам.
  static_assert(PAD % 8 == 0, "PAD кратен 8: широкая (uint4) подача строк");

  extern __shared__ __half smem[];
  __half* sQ = smem;                                 // [BT][LDQ]  -- он же sO в эпилоге
  __half* sA = sQ + BT * LDQ;                        // [BT][LDA]
  __half* sU = sA + BT * LDA;                        // ОКНО: sK -> половина sH -> sV
  __half* sK = sU;                                   // [BT][LDQ]
  __half* sHh = sU;                                  // [DV][LDH]
  __half* sV = sU;                                   // [BT][LDV]
  __shared__ float sG[BT];

  // itg -- СКВОЗНОЙ номер чанка (индекс в h), it -- локальный внутри своей последовательности.
  const int itg = blockIdx.x, ih = blockIdx.y;
  int it = itg, i_n = 0;
  if (chunk_indices) { i_n = chunk_indices[2 * itg]; it = chunk_indices[2 * itg + 1]; }
  long bos = 0;
  int Tn = T;
  if (cu_seqlens) { bos = cu_seqlens[i_n]; Tn = (int)(cu_seqlens[i_n + 1] - bos); }
  const int NT = (Tn + BT - 1) / BT;
  if (it >= NT) return;
  const int t0 = it * BT, rows = min(BT, Tn - t0), rlast = rows - 1;
  if (rows <= 0) return;
  // База последовательности сдвигает ВСЕ поточные тензоры разом; h адресуется сквозным itg.
  q += bos * Hg * DK;
  k += bos * Hg * DK;
  v += bos * H * DV;
  o += bos * H * DV;
  g += bos * H;
  const int ihg = ih / (H / Hg);                     // голова ключа для GQA-подобного отображения
  const int tid = threadIdx.x;
  const int lane = tid & 31, warp = tid >> 5;
  const int wm = warp / WN, wn = warp % WN;
  const int ro = wm * SM, co = wn * SN, ca = wn * SNA;
  const int rb = (lane & 1) | ((lane & 16) >> 2) | (lane & 8);   // wmma_acc_row, база полосы
  const int cb = (lane & 2) | ((lane & 4) << 1);                 // wmma_acc_col, база полосы

  constexpr int kQK = BT * (DK / 8) / nthr;          // uint4 на нить: 4
  constexpr int kHH = DV * (DKH / 8) / nthr;         // 4 -- ПОЛОВИНА h
  constexpr int kVR = BT * (DV / 8) / nthr;          // 4
  static_assert(kQK * nthr == BT * (DK / 8) && kHH * nthr == DV * (DKH / 8) &&
                    kVR * nthr == BT * (DV / 8), "плитки делятся на нити нацело");
  const long hbase = ((long)itg * H + ih) * DV;   // h нумеруется СКВОЗНЫМ чанком (i_tg у Triton)

  auto ldg_h = [&](uint4 (&dst)[kHH], int half) {
#pragma unroll
    for (int t = 0; t < kHH; ++t) {
      const int i = tid + t * nthr, r = i / (DKH / 8), c = (i % (DKH / 8)) * 8;
      dst[t] = *reinterpret_cast<const uint4*>(&h[(hbase + r) * DK + half * DKH + c]);
    }
  };
  auto sts_h = [&](const uint4 (&src)[kHH]) {
#pragma unroll
    for (int t = 0; t < kHH; ++t) {
      const int i = tid + t * nthr, r = i / (DKH / 8), c = (i % (DKH / 8)) * 8;
      *reinterpret_cast<uint4*>(&sHh[r * LDH + c]) = src[t];
    }
  };

  // --- ПРОЛОГ. ХВОСТ ЧАНКА -- ЗАЖИМОМ СТРОКИ, А НЕ ПРЕДИКАТОМ: предикат вносит ветвь в каждую
  // итерацию и мешает ptxas собрать загрузки в пачку. Зажатая строка даёт КОНЕЧНЫЙ мусор, а он
  // гасится ровно там же, где и раньше: A[t][s] обнуляется при t >= rows или s >= rows, строки
  // выхода при r >= rows не пишутся, а V умножается на уже обнулённые элементы A.
  uint4 qr[kQK], kr[kQK], h0[kHH], h1[kHH], vr[kVR];
#pragma unroll
  for (int t = 0; t < kQK; ++t) {
    const int i = tid + t * nthr, r = min(i / (DK / 8), rlast), c = (i % (DK / 8)) * 8;
    qr[t] = *reinterpret_cast<const uint4*>(&q[((long)(t0 + r) * Hg + ihg) * DK + c]);
    kr[t] = *reinterpret_cast<const uint4*>(&k[((long)(t0 + r) * Hg + ihg) * DK + c]);
  }
  ldg_h(h0, 0);
  if (tid < BT) sG[tid] = g[(long)(t0 + min(tid, rlast)) * H + ih];
#pragma unroll
  for (int t = 0; t < kQK; ++t) {
    const int i = tid + t * nthr, r = i / (DK / 8), c = (i % (DK / 8)) * 8;
    *reinterpret_cast<uint4*>(&sQ[r * LDQ + c]) = qr[t];
    *reinterpret_cast<uint4*>(&sK[r * LDQ + c]) = kr[t];
  }
  __syncthreads();

  // --- G2 (окно = sK). Вторая половина h запрашивается ЗДЕСЬ: её задержка уйдёт под G2 и под первую
  // половину G1, а живой диапазон её регистров не пересечётся с первой половиной.
  ldg_h(h1, 1);
  WarpMma<MB, NBA, BLayout::kKMajor> ma;
  ma.clear();
  ma.template accumulate<DK>(sQ, LDQ, ro, sK, LDQ, ca, lane);

  // --- гейты и причинная маска ВНУТРИ чанка: b_A[t][s] *= e^{g_t-g_s}, ноль при s > t.
  // Поэлементная поправка по накопителю -- свободный слот FP32 под HMMA (§4p). Перебор (i,j,reg)
  // ЯВНЫЙ, а не через visit: индексы обязаны быть константами компиляции, иначе массивы состояния
  // уезжают в локальную память (§43 плейбука), и это не лечится освобождением регистров.
  // Экспонента берётся по ЧЕТЫРЁМ строкам нити, а не по всем 16 ячейкам: EX2 идёт на четверти темпа.
  // Разложение e^{g_t-g_s} = e^{g_t} * e^{-g_s} (8 вызовов SFU вместо 16) ЗАМЕРЕНО И ОТВЕРГНУТО:
  // 0.1435 против 0.1430 -- ноль, потому что арифметика здесь уже спрятана. Оно ещё и сужает
  // числовой диапазон (e^{-g_s} растёт по чанку), так что отказ двойной.
  {
    float gt[MB][2];
#pragma unroll
    for (int i = 0; i < MB; ++i)
#pragma unroll
      for (int s = 0; s < 2; ++s) gt[i][s] = sG[ro + i * 16 + rb + 2 * s];
#pragma unroll
    for (int i = 0; i < MB; ++i)
#pragma unroll
      for (int j = 0; j < NBA; ++j)
#pragma unroll
        for (int rg = 0; rg < 8; rg += 2) {          // пара (rg,rg+1) -- СОСЕДНИЕ столбцы одной строки
          const int sub = (rg >> 1) & 1;
          const int tt = ro + i * 16 + rb + 2 * sub;
          const int s0 = ca + j * 16 + cb + 4 * ((rg >> 2) & 1);
          const float e0 = ma.acc[i][j][rg] * __expf(gt[i][sub] - sG[s0]);
          const float e1 = ma.acc[i][j][rg + 1] * __expf(gt[i][sub] - sG[s0 + 1]);
          const bool ok = tt < rows;
          *reinterpret_cast<__half2*>(&sA[(long)tt * LDA + s0]) = __floats2half2_rn(
              (ok && s0 <= tt && s0 < rows) ? e0 : 0.f,
              (ok && s0 + 1 <= tt && s0 + 1 < rows) ? e1 : 0.f);
        }
  }
  __syncthreads();                                   // sA видна; окно свободно

  // --- G1 ПОЛОВИНАМИ ПО k. Смещение по k у операнда A -- это просто сдвиг базы (sQ + DKH), потому
  // что A k-мажорный: a_base = sQ + (row0 + a_row(lane))*LDQ, и прибавка к указателю двигает k.
  sts_h(h0);
  __syncthreads();
  WarpMma<MB, NB, BLayout::kKMajor> mo;
  mo.clear();
  mo.template accumulate<DKH>(sQ, LDQ, ro, sHh, LDH, co, lane);
  __syncthreads();                                   // окно свободно
  sts_h(h1);
#pragma unroll
  for (int t = 0; t < kVR; ++t) {                    // V запрашивается под вторую половину G1
    const int i = tid + t * nthr, r = min(i / (DV / 8), rlast), c = (i % (DV / 8)) * 8;
    vr[t] = *reinterpret_cast<const uint4*>(&v[((long)(t0 + r) * H + ih) * DV + c]);
  }
  __syncthreads();
  mo.template accumulate<DKH>(sQ + DKH, LDQ, ro, sHh, LDH, co, lane);
  __syncthreads();                                   // окно свободно
#pragma unroll
  for (int t = 0; t < kVR; ++t) {
    const int i = tid + t * nthr, r = i / (DV / 8), c = (i % (DV / 8)) * 8;
    *reinterpret_cast<uint4*>(&sV[r * LDV + c]) = vr[t];
  }

  // --- G3: += tril(A) x V. Накопитель G3 ЗАСЕВАЕТСЯ гейтованным результатом G1 (§2a: операнд C
  // бесплатен), поэтому отдельного накопителя и цикла слияния нет -- это 32 регистра и 32 сложения
  // даром. Раскладка аккумулятора у всех четырёх вариантов инструкции ОДНА И ТА ЖЕ (замерено, см.
  // шапку volta_warp_mma.h), поэтому пересыпать значения между объектами законно.
  WarpMma<MB, NB, BLayout::kNMajor> mv;
  {
    float eg[MB][2];
#pragma unroll
    for (int i = 0; i < MB; ++i)
#pragma unroll
      for (int s = 0; s < 2; ++s) eg[i][s] = __expf(sG[ro + i * 16 + rb + 2 * s]);
#pragma unroll
    for (int i = 0; i < MB; ++i)
#pragma unroll
      for (int j = 0; j < NB; ++j)
#pragma unroll
        for (int rg = 0; rg < 8; ++rg) mv.acc[i][j][rg] = mo.acc[i][j][rg] * eg[i][(rg >> 1) & 1];
  }
  __syncthreads();                                   // sV видна
  mv.template accumulate<BT>(sA, LDA, ro, sV, LDV, co, lane);

  // --- ЗАПИСЬ ЧЕРЕЗ РАЗДЕЛЯЕМУЮ (см. §4 шапки). Пары регистров (0,1) (2,3) (4,5) (6,7) -- СОСЕДНИЕ
  // СТОЛБЦЫ одной строки (карта wmma_acc_col), поэтому в разделяемую кладём __half2: 16 STS вместо 32.
  // Тип элемента -- OT: пара упаковывается ОДНОЙ инструкцией и в fp16, и в bf16, а размер слова
  // одинаков (2 Б), поэтому ни шаг LDQ, ни широкая выгрузка ниже не меняются.
  OT* sO = reinterpret_cast<OT*>(sQ);                // sQ МЕРТВА: последнее чтение -- в G1
  using O2 = typename gdn_o2<OT>::v2;
#pragma unroll
  for (int i = 0; i < MB; ++i)
#pragma unroll
    for (int j = 0; j < NB; ++j)
#pragma unroll
      for (int rg = 0; rg < 8; rg += 2) {
        const int r = i * 16 + rb + 2 * ((rg >> 1) & 1);
        const int c = j * 16 + cb + 4 * ((rg >> 2) & 1);
        *reinterpret_cast<O2*>(&sO[(long)(ro + r) * LDQ + co + c]) =
            gdn_o2<OT>::pack(mv.acc[i][j][rg] * scale, mv.acc[i][j][rg + 1] * scale);
      }
  __syncthreads();
  for (int i = tid; i < BT * (DV / 8); i += nthr) {
    const int r = i / (DV / 8), c = (i % (DV / 8)) * 8;
    if (r < rows)
      *reinterpret_cast<uint4*>(&o[((long)(t0 + r) * H + ih) * DV + c]) =
          *reinterpret_cast<const uint4*>(&sO[(long)r * LDQ + c]);
  }
}

