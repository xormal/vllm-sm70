// 4. ПОЧЕМУ ДВА БЛОКА НА SM И ЧЕМ ВЗЯТ ПОРОГ
// =================================================================================================
// У ядра НЕТ мейнлупа: оно грузит ~96 КБ, ставит барьер, считает три умножения и выходит. При ОДНОМ
// блоке подача и счёт СТРОГО ПОСЛЕДОВАТЕЛЬНЫ и прятать задержку нечем (VOLTA_SM70 §4). Второй блок --
// единственное, что даёт перекрытие, и порог у него ДВОЙНОЙ: <= 48 КБ разделяемой И <= 128 регистров.
// СНЯТИЕ ОДНОГО НЕ ДАЁТ НИЧЕГО, и это замерено с ОБЕИХ сторон (стратегия ЗАНЯТОСТЬ):
//     45 КБ, 148 рег -> 1 блок (упор в регистры) ... 0.1804 мс
//     77 КБ, 103 рег -> 1 блок (упор в память) ..... 0.1669 мс
//     45 КБ, 126 рег -> 2 БЛОКА ..................... 0.1524 мс   <- только когда взяты ОБА
//
// КАК ВЗЯТ ПОРОГ 48 КБ -- ОКНОМ. Три буфера кладутся в ОДНО место, потому что живут в непересекающиеся
// моменты:  окно = sK (во время G2) -> ПОЛОВИНА sH (во время G1) -> sV (во время G3).
// Одного объединения мало (дало бы 61 КБ). Решает то, что h подаётся ПОЛОВИНАМИ ПО k: G1 -- сумма по
// k=0..127, её можно разбить на две по 64 БЕЗ ЕДИНОГО лишнего умножения и без смены плитки варпа,
// то есть загрузок-на-mma остаётся 1.0. Тогда окно = max(17408, 18432, 17408) = 18432 Б:
//     sQ 17408 + sA 9216 + окно 18432 = 45056 Б = 44.0 КБ  ->  ДВА блока в 96 КБ
// Ценой четырёх лишних барьеров (33 такта каждый против ~18000 тактов на блок -- 0.7%).
//
// ПОРЯДОК ФАЗ ЗАДАН ЗАВИСИМОСТЯМИ, А НЕ ФОРМУЛОЙ:
//   1. G2 идёт ПЕРВЫМ: A -- единственная величина, которой нужен круг через разделяемую (её строит
//      один варп, а читают четыре), значит она должна быть готова как можно раньше;
//   2. каждая пачка LDG выдаётся за одну-две фазы до своего STS (h1 -- под G2, V -- под вторую
//      половину G1), потому что на Volta нет cp.async, но сама LDG неблокирующая: платит потребитель;
//   3. вся подача читается в РЕГИСТРЫ пачкой и только потом кладётся в разделяемую -- §13 каталога
//      сокрытия: весь выигрыш даёт РАЗНЕСЕНИЕ LDG и STS, а не равномерность выдачи.
//
// ВЫНОС ВЫХОДА ЧЕРЕЗ РАЗДЕЛЯЕМУЮ -- самый крупный ОТДЕЛЬНЫЙ приём (его независимо нашли ТРИ
// стратегии из четырёх, x1.16..x1.23). Раскладка накопителя даёт полосе 8 РАЗНЫХ СТРОК по 4
// НЕСМЕЖНЫХ столбца, поэтому каждая из 32 команд STG.E.U16 трогала 8 секторов ради 64 полезных байт
// -- умножение трафика 4-8x. Плитка собирается в sQ (он мёртв с конца G1, доплата памятью НОЛЬ) и
// выносится наружу командами STG.128 по строкам. В SASS видно прямо: STG 32 -> 5.
// Это тот же класс дефекта, что "FRAGMENT-ORDER emit" в backward: не ОБЪЁМ, а ФОРМА обращения.
//
// РЕСУРСЫ (ptxas -v и cudaOccupancyMaxActiveBlocksPerMultiprocessor -- ДРАЙВЕР, а не счёт на бумаге):
//     124 регистра/нить   разлив 0 Б   кадр стека 0 Б   локальной 0 Б
//     разделяемой 44.0 КБ динамической + 256 Б статической
//     2 БЛОКА НА SM, 16 варпов из 64 = занятость 25% (было 1 блок, 8 варпов, 12.5%)
// SASS (cuobjdump -sass): всего 2096 инструкций, HMMA 1024, LDL 0, STL 0, BAR 8,
//     LDG.E.128 x20 + LDG.E x1 (скаляр g), STG.E.128 x5 -- узких .U16 не осталось ни одной,
//     все обращения в глобальную 128-битные.
//
// =================================================================================================
// 5. ЧТО ПРОВЕРЕНО И ДАЛО НОЛЬ ИЛИ ХУЖЕ -- НЕ ПОВТОРЯТЬ (сводно по всем четырём стратегиям)
