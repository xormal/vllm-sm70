//    Режим сменился, вывод не изменился.
//  * ПОСТОЯННЫЕ БЛОКИ С ПРЕДПОДАЧЕЙ СЛЕДУЮЩЕГО ЧАНКА В РЕГИСТРЫ: механизм работает (0.193 -> 0.172
//    внутри своей сборки), но плитка следующего задания -- 20 uint4 = 80 регистров, ЖИВЫХ ЧЕРЕЗ
//    ЗАДНЮЮ ДУГУ, отчего ptxas берёт 218 регистров вместо 104, и итог ХУЖЕ (0.169 против 0.163).
//    ВЫВОД: на Volta межчанковый конвейер ЧЕРЕЗ РЕГИСТРЫ не окупается; ту же работу бесплатно делает
//    второй резидентный блок, потому что его подача -- это ЧУЖИЕ регистры, а не наши.
//  * ВЫНОС ВЫХОДА ПО ВАРПАМ (__syncwarp вместо барьера): 0.146 против 0.144 -- ХУЖЕ. Барьер в 33
//    такта дешевле потери сплошности: при поблочном обходе полоса варпа кроет 2 строки по 256 Б, при
//    поварповом -- 8 строк по 64 Б.
//  * ПРЯМАЯ ЗАПИСЬ ПАРАМИ __half2 в глобальную вместо круга через разделяемую: 0.151 против 0.144.
//  * ПОРЯДОК БЛОКОВ голова-по-быстрой-оси: 0.143 против 0.143 -- НОЛЬ (L2 в 6 МБ сглаживает).
//  * A ИЗ РЕГИСТРОВ вместо круга через разделяемую (перекладка накопителя G2 в операнд G3 ДВУМЯ
//    ступенями бабочки, 24 SHFL -- нижняя граница достигнута): работает и точна, но x0.77. Причина
//    НЕ в цене обмена: регистровая передача требует, чтобы варп держал ВСЕ 64 столбца A для своих
//    строк (межварповых обменов на Volta нет), то есть плитку 16 строк вместо 32x32, а это само по
//    себе x0.87 по закону геометрии плитки. При РАВНОЙ геометрии (4x1) обмен и круг сходятся:
//    0.2887 против 0.2850 -- обмен на 1.3% ХУЖЕ. ПОПРАВКА К §4h: ступеней бабочки ДВЕ, а не одна
//    (столбец накопителя несёт ДВА бита полосы), и вердикт решается НЕ на уровне полосы, а на уровне
//    БЛОКА: прежде чем считать ступени, проверь, лежит ли ВЕСЬ индекс свёртки второго умножения
//    внутри одного варпа.
//  * УДЕШЕВЛЕНИЕ КРУГА (STS.32 вместо двух STS.16, LDS.128 вместо двух LDS.64 -- вдвое меньше
//    обращений): РОВНО НОЛЬ (0.2178 против 0.2184). Круг НЕ на критическом пути -- и это же
//    объясняет, почему его полное снятие ничего не даёт.
//  * sV ОТДЕЛЬНО от sK, чтобы убрать барьер (77 -> 94 КБ): x0.94, хуже.
//  * ШИРОКАЯ ПОДАЧА ГЛОБАЛЬНОГО ОПЕРАНДА (LDG.128 вместо двух LDG.64, обращений вдвое меньше): по
//    §4n/§1c обязана была выиграть -- ЗАМЕРЕНО 1.105 -> 1.001 при тех же регистрах. ПРИЧИНА: закон
//    "MIO считает инструкции" выведен для РАЗДЕЛЯЕМОЙ памяти. У ГЛОБАЛЬНОЙ ресурс -- СЕКТОР: 16
//    строк фрагмента лежат через 256 Б, вдвое более широкое чтение накрывает ТЕ ЖЕ 16 секторов,
//    ничего не экономя, зато вдвое укорачивает цикл и лишает планировщик половины независимых
//    обращений в полёте. Переносить §1c на глобальную с разрывной раскладкой НЕЛЬЗЯ.
//  * ДОПОЛНЕНИЕ PAD=0: x0.70 (шаг 128 полуслов = 64 слова, 64%32==0 -> все 16 строк фрагмента в
//    ОДИН банк). PAD=16: шум. PAD=4 и PAD=12 ВООБЩЕ НЕЗАКОННЫ -- отказ железа (misaligned address),
//    а не замедление; ловится static_assert ниже. Это важно: упавшее ядро портит контекст, и ВСЕ
//    последующие замеры в том же процессе врут.
//  * СЕТКИ 8x1 и 8x2 по выходу НЕВЫРАЗИМЫ: сторона плитки варпа кратна 16 (шаг фрагмента
//    mma.m8n8k4), значит WM <= BT/16 = 4. Это раскладка инструкции, а не ограничение кода.
//
// ЛОВУШКИ ЗАМЕРА, СТОИВШИЕ ВРЕМЕНИ ТРЁМ СТРАТЕГИЯМ ИЗ ЧЕТЫРЁХ (записать и не повторять):
//  * Карта без режима постоянства уходит в низкое состояние между процессами: короткий прогрев дал
//    0.47 вместо 0.217 -- ошибка ВДВОЕ. Прогрев по ЧАСАМ, не по числу итераций.
//  * Соседние агенты грузят карты 0/1 и ЗАТИРАЮТ одноимённые бинарники в /tmp. Собирать в свой
//    каталог; мерить все варианты В ОДНОМ ПРОЦЕССЕ вперемешку и брать МИНИМУМ (tools/gdn_syn).
//  * Если синтетика мелкая, произведения выходят ПОДДЁННОРМАЛЬНЫМИ в fp16, и ТО ЖЕ САМОЕ ядро идёт
//    ВДВОЕ медленнее (0.253 против 0.497 мс). Пробник обязан давать нормальный диапазон fp16.
//
// =================================================================================================
// 6. ЧТО ОСТАЛОСЬ. Оставшийся запас x1.22 весь в ЗАПИСИ (423 ГБ/с против 765 у чтения), а все
// известные механизмы для неё выше помечены мёртвыми (.cs, .wt, поварповый вынос, прямая парная
// запись, порядок блоков). Единственный рычаг, который двигает не расписание, а ЧИСЛИТЕЛЬ, --
// BT=128: состояние h читается по 32 КБ на чанк и это ТРЕТЬ трафика, а удвоение чанка его ополовинит
// (96.3 -> 80.3 МБ, потолок 0.1176 -> 0.0980 мс). Цена -- вчетверо больший внутричанковый
// треугольник (работа на токен 65536 -> 98304 ФЛОП, x1.5) и полная перекройка раскладки: sQ и sA
// становятся по 34.8 КБ, то есть два блока на SM в нынешнем виде НЕ ВЫЖИВАЮТ. И это НЕ правка ядра:
// BT -- размер чанка ВСЕГО скана, его меняют вместе с chunk_fwd_h/kkt/wu, иначе ядро перестаёт быть
// подстановочной заменой.
