// ВНУТРИЧАНКОВАЯ МАТРИЦА beta*K*K^T НА ТЕНЗОРНЫХ ЯДРАХ VOLTA. Замена chunk_scaled_dot_kkt_fwd из fla.
//
// ЗАЧЕМ. Замерено (volta_prims.h §4qq): Triton при цели sm_70 НЕ ЭМИТИТ тензорных инструкций вообще --
// в PTX mma.sync 0, wmma 0, hmma 0 и 1024 fma.rn.f32, то есть tl.dot разворачивается в цикл FP32-FMA на
// обычных ядрах. Потолок 3.5 TFLOP/s против 83 у cuBLAS. Этот шаг идёт на 2.62 TFLOP/s -- ровно на том
// потолке -- и составляет 11.1% скана.
//
// ЧТО СЧИТАЕТСЯ (дословно chunk_scaled_dot_kkt_fwd_kernel, чанк BT=64, строго нижний треугольник):
//     A[t_i, h, j] = beta[t_i,h] * exp(g[t_i,h] - g[t_j,h]) * SUM_c k[t_i,hk,c]*k[t_j,hk,c],  i > j
//     A[t_i, h, j] = 0                                                                        иначе
// hk = h/(H/Hg) -- голова ключа; диагональ РАВНА НУЛЮ (маска строгая: o_t[:,None] > o_t[None,:]);
// beta умножает СТРОКУ i, а не столбец; знак гейта именно (g_i - g_j), и в нижнем треугольнике он <= 0.
//
// ГЛАВНЫЙ СТРУКТУРНЫЙ РЫЧАГ -- ОДНА ГРАМ-МАТРИЦА НА ГРУППУ ГОЛОВ. tl.dot зависит ТОЛЬКО от k, а beta и
// g входят поэлементно по строке/столбцу. Значит G = K_hk K_hk^T одинакова для всех H/Hg = GQ голов
// значения группы: блок = пара (чанк, голова КЛЮЧА), считает G один раз и выдаёт GQ выходов тремя
// эпилогами. Умножений втрое меньше (3.083 -> 1.028 GMAC), чтений k -- тоже втрое. Условие: beta
// вынесен из операнда в эпилог, что заодно СТРОГО ТОЧНЕЕ Triton (там b_k*b_beta округляется до fp16).
//
// И ВТОРОЙ, НЕ МЕНЕЕ ВАЖНЫЙ: у выхода A[t][h][j] голова -- СРЕДНЯЯ ось, поэтому GQ голов одной группы
// лежат в памяти ПОДРЯД. Строка блока -- сплошной кусок GQ*BT = 192 float = 768 Б, то есть ровно 6
// секторов по 128 Б. Эпилог поэтому пишет float4 подряд, а не собирает разбросанные куски.
//
// ЧЕМ ЭТО ОГРАНИЧЕНО. На боевой форме (T=15680, Hg=8, H=24) счёт после свёртки групп -- 2.055 GFLOP,
// то есть 68 мкс на наших 30 TFLOP/s; трафик -- 96.3 МБ записи A плюс 32.1 МБ чтения k, то есть 158 мкс
// при достижимых 841 ГБ/с. ЯДРО УПИРАЕТСЯ В ЗАПИСЬ, и всё остальное подчинено ей: симметрия G (нужно
// 10 фрагментов из 16) и урезание записи до 10 блоков 16x16 -- рычаги ВТОРОГО порядка, первым идёт
// форма записи.
//
// ЗАМЕРЕНО (V100 @1530, боевая форма T=15680 H=24 Hg=8, tools/volta_gdn_kkt_test.cu):
//     Triton (тот же вход)        2.308 мс    2.67 TFLOP/s    58 ГБ/с
//     это ядро                    0.220 мс   28.1 TFLOP/s*   606 ГБ/с      x10.5
//     пол ПО ТРАФИКУ этой же
//     раскладки (без счёта)       0.192 мс                    694 ГБ/с
//   (* в мерке Triton, то есть на плотный квадрат каждой головы значения; собственная работа ядра
//    после свёртки групп -- 9.4 TFLOP/s.)
// Ошибка против эталона fp64 по определению -- 7.0e-07 (у самого Triton на том же входе 4.1e-05:
// он теряет разряды на округлении beta*k до fp16, которого у нас нет). 61 регистр, разлив 0,
// 4 блока/SM, 32 варпа/SM.
//
// ЧТО ЭТИ ТРИ СТРОКИ ГОВОРЯТ: ядро идёт на 89% ПОЛА СВОЕЙ ЖЕ раскладки памяти, то есть весь остаток
// внутри ядра ограничен x1.15, а сам пол (694 из 841 ГБ/с) задан формой выхода [T][H][BT] -- запись
// идёт кусками по GQ*BT*4 = 768 Б с шагом H*BT*4 = 6144 Б, и это не наш выбор, а контракт solve_tril.
// Геометрия сетки варпов при этом БЕЗРАЗЛИЧНА (2x4, 4x2, 4x4, 2x2, 1x4 сходятся в пределах 2%, при
// занятости от 31% до 50%) -- подпись ядра, ограниченного памятью, а не расписанием.
//
// ЗАМЕРЕНО ОТРИЦАТЕЛЬНОЕ: подсказка st.global.cs на записи A -- 0.2202 против 0.2205, то есть НОЛЬ.
// Ожидаемо по volta_prims.h §4l/§4v: подсказка потока помогает на ЧТЕНИИ без переиспользования, а
// здесь запись в 96 МБ и так не помещается в L2 (6 МБ), вытеснять ей нечего.
#pragma once
#include <cuda_fp16.h>
#include <cuda_runtime.h>
#include "volta_warp_mma.h"

namespace fa2_sm70 {
namespace gdn {

// Чистая MUFU.EX2 -- ровно то, во что раскрывается __expf после домножения на log2(e). Гейт умножен
// на log2(e) ОДИН раз при укладке в разделяемую, поэтому здесь не остаётся ни одного FMUL.
__device__ __forceinline__ float kkt_ex2(float x) {
  float r;
  asm("ex2.approx.f32 %0, %1;" : "=f"(r) : "f"(x));
  return r;
}

// РАСКЛАДКА ОПЕРАНДА B -- ПРОТИВОПОЛОЖНА ИНТУИЦИИ ИМЕНИ, сверено по enum в volta_warp_mma.h:
//   kKMajor: B это [N][K], непрерывен K -> инструкция .row.col, случай Q*K^T
//   kNMajor: B это [K][N], непрерывен N -> инструкция .row.row, случай P*V
// Здесь K K^T: операнд B -- та же матрица k, лежащая [строка][канал] с непрерывным каналом, то есть
// [N][K] -> kKMajor. Операнд A -- она же, [M][K] -> ALayout::kKMajor (по умолчанию). ОДИН буфер на оба.

// BT -- размер чанка (64), DK -- размер головы ключа, GQ = H/Hg -- голов значения на голову ключа,
// WM x WN -- сетка варпов по грам-матрице. SKIP_UPPER -- не писать шесть СТРОГО ВЕРХНИХ блоков 16x16
// (их единственный потребитель solve_tril не читает никогда; диагональные блоки читает ЦЕЛИКОМ, там
// нули обязаны лежать явно). По умолчанию выключено: это меняет контракт выхода.
// AT -- тип выходной Araw (задача 131). Ядро УПИРАЕТСЯ В ЗАПИСЬ A (96.3 МБ из 128), поэтому
// AT=__half режет главный трафик вдвое. Точность: |Araw| <= 1 (строки k нормированы, beta<1,
// e^{g_i-g_j} <= 1 в нижнем треугольнике), а ошибку ПУТИ задаёт округление Ai (fp16 на выходе
// solve_tril) -- это уже замерено в его шапке («чтение в fp32 ради точности не даёт ничего»).
template <int BT, int DK, int GQ, int WM, int WN, bool SKIP_UPPER = false, typename AT = float>
__global__ __launch_bounds__(WM * WN * 32, 1) void volta_gdn_kkt(
    const __half* __restrict__ k,      // [T, Hg, DK]      fp16, строки единичной нормы
    const __half* __restrict__ beta,   // [T, H]           fp16, sigmoid -> (0,1)
    const float* __restrict__ g,       // [T, H]           fp32, накопленный ВНУТРИ чанка лог-гейт
    AT* __restrict__ A,                // [T, H, BT]       fp32 или fp16, выход
    const int* __restrict__ cu_seqlens,      // [N+1] или nullptr (одна последовательность с bos=0)
    const int* __restrict__ chunk_indices,   // [NT][2] или nullptr (чанк = blockIdx.x)
    int T, int H, int Hg) {
  // ДОПОЛНЕНИЕ +4 ПОЛУСЛОВА, А НЕ +8. Шаг строки 132 полуслова = 66 слов, и 66 % 32 = 2, поэтому
  // шестнадцать строк фрагмента ложатся на банки 0,2,4,...,30 -- по два подряд на LDS.64, все 32 банка
  // ровно по разу, БЕЗ КОНФЛИКТА (плейбук §3: нужно LD = 4t с НЕЧЁТНЫМ t; 132 = 4*33). Дополнение +8
  // дало бы 68 слов, 68 % 32 = 4, то есть строки r и r+8 в одном банке -- двукратный конфликт.
  // Плата -- запись в sK идёт двумя STS.64 вместо одной STS.128 (264 Б не кратно 16); замерено в
  // плейбуке §46.1, что бесконфликтность здесь важнее ширины.
  constexpr int LDK = DK + 4;
  // У выгрузки грам-матрицы ограничение ДРУГОЕ: читают её сплошными float4 по строке, и при ЛЮБОМ
  // шаге, кратном 4 словам, восемь нитей четверти варпа кроют все 32 банка. Значит шаг выбирается по
  // ЗАПИСИ из накопителя (пары соседних столбцов, восемь различных строк на варп): 68 слов даёт
  // r*68 % 32 = r*4, то есть четыре различных базы -- двукратный конфликт против восьмикратного при 64.
  constexpr int LDG = BT + 4;
  constexpr int SM = BT / WM, SN = BT / WN;
  static_assert(SM % 16 == 0 && SN % 16 == 0, "плитки варпа кратны шагу фрагмента 16");
  static_assert(BT % 4 == 0 && DK % 8 == 0, "широкие обращения");
  constexpr int nthr = WM * WN * 32;
  constexpr int MB = SM / 16, NB = SN / 16;

  // Выравнивание объявлено ЯВНО: по этому же адресу лежат и fp16-операнды, и fp32-грам-матрица,
  // которую эпилог читает по 16 Б. Объявление через __half дало бы компилятору право считать базу
  // выровненной лишь на 2 Б.
  extern __shared__ __align__(16) char smem_raw[];
  __half* sK = reinterpret_cast<__half*>(smem_raw);   // [BT][LDK] -- операнд ОБОИХ множителей
  float* sG = reinterpret_cast<float*>(smem_raw);     // [BT][LDG] -- ТО ЖЕ МЕСТО: G живёт после K
  // [ДОПОЛНЕНИЕ ШАГА ГОЛОВЫ: 64 -> 68 СЛОВ] Шаг головы BT = 64 слова кратен 32, поэтому строки
  // РАЗНЫХ голов, читаемые одной командой варпа, садятся в те же банки: конфликтность 3.00 по
  // замкнутой форме |R| / |{r*S mod 32}| (docs/SM70_KERNEL_PLAYBOOK.md, «диагональ по строкам»).
  // +4 слова разводят их в 1.00, стоят 2*GQ*4*4 = 96 Б на блок и НЕ МЕНЯЮТ ОТВЕТ: это только
  // размещение. Кривая проверена целиком -- одностороннее «дополнить» неверно в общем случае, но
  // здесь минимум и выбор совпадают (следующий бесконфликтный шаг стоил бы вчетверо дороже).
  __shared__ float sBeta[GQ][BT + 4];
  __shared__ float sGate[GQ][BT + 4];                 // g * log2(e): экспонента считается через exp2

  int it = blockIdx.x;
  int i_n = 0;
  if (chunk_indices) { i_n = chunk_indices[2 * it]; it = chunk_indices[2 * it + 1]; }
  int bos = 0, Tn = T;
  if (cu_seqlens) { bos = cu_seqlens[i_n]; Tn = cu_seqlens[i_n + 1] - bos; }
  const int ihg = blockIdx.y;                          // голова КЛЮЧА
  const int h0 = ihg * GQ;                             // первая голова значения группы
  const int t0 = it * BT;
  const int rows = min(BT, Tn - t0);                   // фактическая длина чанка
  if (rows <= 0) return;

  const int tid = threadIdx.x, lane = tid & 31, warp = tid >> 5;
  const int wm = warp / WN, wn = warp % WN;

  // --- подача k. Строка головы -- DK полуслов подряд, читаем ЦЕЛИКОМ по 16 Б (§4n: MIO считает
  // ИНСТРУКЦИИ), кладём двумя по 8 Б, потому что шаг 264 Б не кратен 16. Строки за пределом
  // последовательности обнуляются -- это повторяет boundary_check у Triton и делает лишние строки и
  // столбцы грам-матрицы нулевыми ещё до маски.
  for (int i = tid; i < BT * (DK / 8); i += nthr) {
    const int r = i / (DK / 8), c = (i % (DK / 8)) * 8;
    uint4 v = make_uint4(0, 0, 0, 0);
    if (r < rows) v = *reinterpret_cast<const uint4*>(&k[((long)(bos + t0 + r) * Hg + ihg) * DK + c]);
    *reinterpret_cast<uint2*>(&sK[r * LDK + c]) = make_uint2(v.x, v.y);
    *reinterpret_cast<uint2*>(&sK[r * LDK + c + 4]) = make_uint2(v.z, v.w);
  }
  // beta и гейт -- по одному значению на (голова, строка), GQ*BT = 192 штуки на блок. Гейт сразу
  // умножается на log2(e), чтобы в эпилоге остался ОДИН exp2 без домножения (§4e: EX2 -- четверть темпа,
  // экономить надо сами вызовы, а не то, что вокруг).
  for (int i = tid; i < GQ * BT; i += nthr) {
    const int hq = i / BT, r = i % BT;
    const bool ok = r < rows;
    const long off = (long)(bos + t0 + r) * H + h0 + hq;
    sBeta[hq][r] = ok ? __half2float(beta[off]) : 0.f;
    sGate[hq][r] = ok ? g[off] * 1.4426950408889634f : 0.f;
  }
  __syncthreads();

  // --- G = K K^T. Оба операнда -- ОДИН буфер sK; второй не нужен именно потому, что beta вынесен.
  WarpMma<MB, NB, BLayout::kKMajor> m;
  m.clear();
  m.template accumulate<DK>(sK, LDK, wm * SM, sK, LDK, wn * SN, lane);
  __syncthreads();                       // sK больше не нужен -> его место занимает sG

  // --- выгрузка накопителя. Регистры 2p и 2p+1 -- СОСЕДНИЕ СТОЛБЦЫ одной строки
  // (acc_col = base + (reg&1) + 4*((reg>>2)&1)), поэтому пишем парами: одна STS.64 вместо двух STS.32.
  {
    const int arow = (lane & 1) | ((lane & 16) >> 2) | (lane & 8);
    const int acol = (lane & 2) | ((lane & 4) << 1);
#pragma unroll
    for (int i = 0; i < MB; ++i)
#pragma unroll
      for (int j = 0; j < NB; ++j)
#pragma unroll
        for (int p = 0; p < 4; ++p) {
          const int r = wm * SM + i * 16 + arow + 2 * (p & 1);
          const int c = wn * SN + j * 16 + acol + 4 * ((p >> 1) & 1);
          *reinterpret_cast<float2*>(&sG[r * LDG + c]) =
              make_float2(m.acc[i][j][2 * p], m.acc[i][j][2 * p + 1]);
        }
  }
  __syncthreads();

  // --- эпилоги. Плоский обход по float4: строка выхода для ВСЕЙ группы голов -- сплошные GQ*BT float,
  // поэтому соседние нити пишут соседние 16 Б и варп кроет 512 Б подряд.
  //
  // МАСКА -- ТЕРНАРНИК, А НЕ УМНОЖЕНИЕ НА 0/1. В верхнем треугольнике g_i - g_j > 0 и exp2 может дать
  // +inf; 0*inf = NaN. tl.where у Triton -- селект, и здесь обязан быть селект.
  constexpr int NQ = BT / 4;                 // float4 в строке одной головы
  constexpr int RQ = GQ * NQ;                // float4 в строке всей группы
  for (int i = tid; i < BT * RQ; i += nthr) {
    const int r = i / RQ, kk = i % RQ;
    if (r >= rows) continue;                 // строка чужой последовательности -- НЕ ТРОГАТЬ
    const int hq = kk / NQ, c0 = (kk % NQ) * 4;
    if (SKIP_UPPER && (c0 >> 4) > (r >> 4)) continue;
    const float4 v = *reinterpret_cast<const float4*>(&sG[r * LDG + c0]);
    const float rb = sBeta[hq][r], gi = sGate[hq][r];
    const float* gc = &sGate[hq][c0];
    float4 o;
    o.x = (r > c0 + 0 && c0 + 0 < rows) ? v.x * rb * kkt_ex2(gi - gc[0]) : 0.f;
    o.y = (r > c0 + 1 && c0 + 1 < rows) ? v.y * rb * kkt_ex2(gi - gc[1]) : 0.f;
    o.z = (r > c0 + 2 && c0 + 2 < rows) ? v.z * rb * kkt_ex2(gi - gc[2]) : 0.f;
    o.w = (r > c0 + 3 && c0 + 3 < rows) ? v.w * rb * kkt_ex2(gi - gc[3]) : 0.f;
    if constexpr (sizeof(AT) == 2) {
      // fp16-выход: та же четвёрка столбцов уезжает одной записью 8 Б -- строка группы остаётся
      // сплошной (GQ*BT*2 = 384 Б = 3 сектора), трафик записи вдвое меньше.
      const __half2 lo = __floats2half2_rn(o.x, o.y), hi = __floats2half2_rn(o.z, o.w);
      const uint2 pk = {*reinterpret_cast<const uint32_t*>(&lo),
                        *reinterpret_cast<const uint32_t*>(&hi)};
      *reinterpret_cast<uint2*>(&A[((long)(bos + t0 + r) * H + h0 + hq) * BT + c0]) = pk;
    } else {
      *reinterpret_cast<float4*>(&A[((long)(bos + t0 + r) * H + h0 + hq) * BT + c0]) = o;
    }
  }
}

// Разделяемая память ядра: sK и sG ДЕЛЯТ одно место (K мертва к моменту выгрузки G).
template <int BT, int DK>
constexpr size_t volta_gdn_kkt_smem() {
  return sizeof(__half) * BT * (DK + 4) > sizeof(float) * BT * (BT + 4)
             ? sizeof(__half) * BT * (DK + 4)
             : sizeof(float) * BT * (BT + 4);
}

