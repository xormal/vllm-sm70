// РАСПИСАНИЕ, КОТОРОЕ ЗДЕСЬ СТРОИТСЯ (цель, поставленная Алексом):
//   такт    группа A (везёт)     группа B (считает)
//     0     LDS                  ALU
//     1     LDS                  ALU
//     2     HMMA                 LDS
//     3     HMMA                 LDS
//     4     HMMA                 HMMA
//     ...
// Ткань разделяемой памяти ОДНА и с конечной пропускной способностью; когда обе группы просят её
// одновременно, обращения СЕРИАЛИЗУЮТСЯ (конфликтов банков между ними нет -- массив делится по
// времени, §4jj). Значит выигрыш даёт не разведение по банкам, а разведение ПО ФАЗЕ.
//
// ПОЧЕМУ ИМЕННО ВАРПЫ, А НЕ БЛОКИ. Всё это уже пробовано на двух РЕЗИДЕНТНЫХ БЛОКАХ и закрыто
// замером: начальный зазор не удерживается (§4gg), точная шахматка по %smid удерживает, но只 как
// чистая потеря (§4hh), поворот обхода по TPC -- ноль (§4ii), сдвиг банковой базы -- ноль (§4jj).
// Причина одна: У БЛОКОВ НЕТ СВЯЗИ, а bar.sync/bar.arrive на Volta -- инструкции области CTA.
// ВНУТРИ блока связь есть, и её цена замерена (§4q): сигнал bar.arrive 2.76 такта против 33.4 у
// ожидания. Фаза, заданная защёлкой, НЕ РАССЫПАЕТСЯ при дрейфе -- в этом всё отличие.
//
// УСТРОЙСТВО. 16 варпов = 512 нитей, ОДИН блок на SM:
//   варпы  0..7  ВЕЗУТ  : перекладывают K/V/Q плитки N+1 в теневой буфер, bar.arrive "готово" и
//                         сразу идут за следующей; ждут только если потребитель отстал на буфер.
//   варпы  8..15 СЧИТАЮТ: bar.sync "готово", оба умножения и софтмакс, bar.arrive "буфер свободен".
// Двойной буфер обязателен: иначе везущим негде готовить N+1, пока читают N.
// У ОДНОГО блока нет порога 48 КБ -- доступны все 96, и двойной буфер туда влезает.
//
// ================================================================================================
// СОСТОЯНИЕ: КАРКАС, В СБОРКУ НЕ ПОДКЛЮЧЁН. Что сделано и что осталось -- честно.
// ================================================================================================
// СДЕЛАНО: роли варпов (первая половина везёт, вторая считает), сетка считающих, двойной буфер,
// именованные барьеры объявлены, бюджет посчитан РУКАМИ и сходится:
//   K полная 17408 Б/буфер + V полная 17408 Б/буфер, двойной буфер -> 69632 Б
//   + Q полная 16640 + P 4352  =  90624 Б = 88.5 КБ при пределе ОДНОГО блока 96 КБ (запас 7.5 КБ)
//   512 нитей, один блок на SM -> 128 регистров на нить; накопитель O у считающих 32 регистра;
//   занятость 25% против 22.4% у двух блоков по 8 варпов.
//
// ОСТАЛОСЬ, и это не мелочи:
//  1. K и Q подаются ЦЕЛИКОМ на плитку, а не кусками по d. Сейчас в теле K стоит внутри цикла по d
//     (DC=64), а везущая группа обязана готовить плитку ЦЕЛИКОМ -- иначе она снова сцеплена со
//     считающей ВНУТРИ плитки, и вся расфазировка теряется. Это меняет и раскладку sK, и адресацию
//     в accumulate_bi8 (шаг строки LDK8 становится D+16, а не DC+16).
//  2. Развести тело на две ветки: везущая крутит [перекладка в буфер t&1; bar.arrive READY;
//     bar.sync FREE], считающая -- [bar.sync READY; два умножения и софтмакс; bar.arrive FREE].
//     ЧИСЛО НИТЕЙ В ЗАЩЁЛКЕ -- 512 (обе группы), иначе она не парная и одна сторона проскочит.
//  3. Пролог: везущая готовит плитку 0 ДО входа в цикл, иначе считающая ждёт на первой же итерации
//     и расфазировки не возникает вовсе.
//  4. Хвост: на последней плитке везущей нечего готовить -- она должна дойти до bar.arrive, иначе
//     считающая зависнет на bar.sync. Это классическое место отказа у producer/consumer.
//  5. Редукции софтмакса идут по ВСЕМ варпам через sRedM/sRedS -- их надо сузить до СЧИТАЮЩИХ,
//     иначе везущие внесут нули и максимум/сумма будут неверны. ТИХАЯ порча, если пропустить.
//
// ПОЧЕМУ ЭТО ВООБЩЕ СТОИТ СТРОИТЬ: карта простоев (§4ff) даёт первым not_selected = 1.02 -- варпы
// готовы, но выдают не их, потому что в одной фазе все просят ОДИН конвейер. Разведение по фазе
// целится ровно туда. А все более дешёвые способы получить ту же расфазировку МЕЖДУ БЛОКАМИ
// проверены и закрыты замером (§4gg зазор, §4hh шахматка, §4ii поворот, §4jj банки).
//
// ================================================================================================
// СОСТОЯНИЕ: СОБИРАЕТСЯ (124 регистра, 0 разлива, 4 барьера в SASS), НО ЗАВИСАЕТ. В сборку НЕ
// подключён. Ниже -- что проверено и где искать причину, чтобы не начинать с нуля.
// ================================================================================================
// РАБОТАЕТ: компиляция чистая; бюджет сходится (88.5 КБ при пределе 96 у одного блока; 512 нитей ->
// 128 регистров на нить, взято 124, разлив ноль); именованные барьеры ПОПАЛИ в SASS -- ptxas пишет
// "used 4 barriers", то есть защёлки реальны, а не выброшены оптимизатором.
//
// НЕ РАБОТАЕТ: ядро НЕ ВОЗВРАЩАЕТСЯ (снято по таймауту 60 с на форме 256x256). Это отказ номер 4 из
// списка, составленного ДО постройки. Три подозреваемых по убыванию вероятности:
//   1. ВЕЗУЩИЕ ВАРПЫ ПАДАЮТ В ЭПИЛОГ. После своего цикла они не выходят, а идут в общий эпилог, где
//      у них wm=wn=0 и они ПИШУТ В O -- то есть не только зависают, но и портят результат. Эпилог
//      обязан быть под if (!isProd), а везущим нужен ранний выход после последнего bar.arrive.
//   2. СЧЁТ ЗАЩЁЛОК. bar.sync 1 требует kAllThr приходов: 256 от bar.arrive везущих плюс 256 от
//      bar.sync считающих. Если хоть одна группа выходит из цикла раньше, счёт не наберётся НИКОГДА.
//      Проверять надо не "логику", а РАВЕНСТВО ЧИСЛА ПРИХОДОВ на каждом барьере.
//   3. Редукции софтмакса переведены на барьер 3 с kConsThr, но sRedM/sRedS всё ещё индексируются
//      по всем варпам -- при 8 считающих это надо пересчитать.
//
// СЛЕДУЮЩИЙ ШАГ: сперва развести ЭПИЛОГ по ролям и дать везущим ранний выход; затем на форме с ОДНОЙ
// плиткой ключей убедиться, что ядро возвращается ВООБЩЕ; и только потом сверять числа. Отлаживать
// защёлки на многоплиточной форме бессмысленно -- зависание не локализуется.
