  // ОДНО вычитание на элемент S вместо поэлементной конверсии всей плитки K, а сумма строки Q
  // считается ОДИН раз на блок. Пропустить эту поправку = получить тихо неверный ответ, который
  // при малых значениях выглядит правдоподобно: смещение общее для всей строки, и softmax его
  // частично съедает, оставляя ошибку только там, где строка Q несимметрична.
  __shared__ float sQsum[BQ];
  // [ПЕРЕКЛАДКА Q -- В ПРОЛОГ, ЦЕЛИКОМ] В исходном ядре Q клалась ВНУТРИ цикла по d (подача
  // кусками), а здесь этот цикл свёрнут в одно умножение по всему D -- значит перекладка обязана
  // переехать сюда, иначе sQ не заполняется ВООБЩЕ. Именно это и давало relL2 0.16 при уже
  // работающих защёлках: ядро возвращалось, но считало по мусору.
  // Кладут ВСЕ 512 нитей: пролог общий для обеих ролей, до разделения.
#pragma unroll
  for (int i = tid; i < BQ * D / 8; i += kAllThr) {
    const int r = i / (D / 8), c = (i % (D / 8)) * 8;
    uint4 g = make_uint4(0, 0, 0, 0);
    if (q0 + r < Sq) g = *reinterpret_cast<const uint4*>(&Q[(long)(q0 + r) * q_sM + c]);
    __half* dq = &sQ[r * LDQ + c];
    *reinterpret_cast<uint2*>(dq)     = make_uint2(g.x, g.y);
    *reinterpret_cast<uint2*>(dq + 4) = make_uint2(g.z, g.w);
  }
  __syncthreads();
  // [СУММЫ СТРОК Q -- ИЗ РАЗДЕЛЯЕМОЙ, А НЕ ИЗ ГЛОБАЛЬНОЙ] Разбор SASS нашёл в потоке множество
  // LDG.E.U16 -- ДВУХБАЙТОВЫХ глобальных чтений: это был отдельный проход по Q ради сумм строк, по
  // одному __half за инструкцию. В int8-ядре он был оправдан (Q подавалась кусками), здесь Q уже
  // ЦЕЛИКОМ лежит в разделяемой -- читаем оттуда.
  // Атомики в разделяемой ЗДЕСЬ НЕ ГОДЯТСЯ: замерено ранее, что контенция дороже отдельного прохода
  // (485 -> 1046 мкс). Пробовал -- 0.2782 -> 0.2913, то есть повторил свою же записанную ошибку.
  // Верная форма -- кооперативная редукция варпом с бабочкой, как было, но по РАЗДЕЛЯЕМОЙ памяти.
  // [ШИРИНА, А НЕ ТОЛЬКО ПРОСТРАНСТВО] Перенести сумму из глобальной в разделяемую было мало:
  // доступ оставался СКАЛЯРНЫМ, и разбор SASS показал LDS.U.U16 -- чтения по одному __half за
  // инструкцию. MIO считает ИНСТРУКЦИИ (§4n), поэтому читаем по ВОСЕМЬ: одна LDS.128 вместо восьми
  // LDS.U16. Шаг строки LDQ = D + 4 = 260 полуслов = 520 Б, не кратно 16, поэтому читаем uint2
  // (8 Б = 4 значения) -- он требует лишь 8-байтового выравнивания, которое здесь есть.
  for (int r = warp; r < BQ; r += kWarps) {
    float acc = 0.f;
    const __half* pr = &sQ[r * LDQ];
    // ШИРИНА, А НЕ ТОЛЬКО ПРОСТРАНСТВО: перенести сумму из глобальной в разделяемую было мало --
    // доступ оставался СКАЛЯРНЫМ, и разбор SASS показал LDS.U.U16, то есть чтения по одному __half.
    // MIO считает ИНСТРУКЦИИ (§4n), поэтому берём по ЧЕТЫРЕ значения за раз. Шаг строки
    // LDQ = D + 4 = 260 полуслов = 520 Б -- не кратен 16, но кратен 8, поэтому uint2 законен, а
    // uint4 нет: проверять надо ВЫРАВНИВАНИЕ ШАГА, а не только желание читать шире.
    for (int d = lane * 4; d < D; d += 128) {
      const uint2 v = *reinterpret_cast<const uint2*>(pr + d);
      const __half2* h = reinterpret_cast<const __half2*>(&v);
      acc += __half2float(__low2half(h[0])) + __half2float(__high2half(h[0]))
           + __half2float(__low2half(h[1])) + __half2float(__high2half(h[1]));
    }
#pragma unroll
    for (int off = 16; off; off >>= 1) acc += __shfl_xor_sync(0xffffffffu, acc, off);
    if (lane == 0) sQsum[r] = acc;
  }
  __syncthreads();

  // ============================ ГЛАВНЫЙ ЦИКЛ, РАЗВЕДЁННЫЙ ПО РОЛЯМ ============================
  // Защёлки на kAllThr нитей: в каждой участвуют ОБЕ группы (везущие приходят bar.arrive, считающие
  // ждут bar.sync -- вместе это полный счёт). Внутренние синхронизации считающих идут по барьеру 3
  // на kConsThr: обычный __syncthreads там ПОВЕСИТ блок, потому что требует все kAllThr нитей.
  // [ОТОБРАЖЕНИЕ ПЛИТКИ] Плотный путь: kb = t * BK. Разреженный: t-я ОТОБРАННАЯ плитка.
  // Блок индекса крупнее плитки ядра в selSub раз, поэтому один отобранный блок разворачивается
  // в selSub подряд идущих плиток -- деления на рантайме нет, только сдвиг и маска.
  const int* _selI = nullptr; int _selN = 0;
  if (selIdx != nullptr) {
    // [ПЛИТКА СЧЁТА БЕРЁТСЯ ИЗ q0, А НЕ ИЗ blockIdx.x] При REV=1 (а постраничный путь идёт
    // именно так) порядок блоков ОБРАТНЫЙ: q0 = (gridDim.x-1-blockIdx.x)*BQ. Строка индекса,
    // взятая по blockIdx.x, достаётся ЗЕРКАЛЬНОЙ плитке. Дефект тихий: при равномерном индексе
    // (все счётчики равны) он не виден вовсе, а при поплиточном роняет ровно ту половину плиток,
    // которой зеркало отдаёт МЕНЬШЕЕ покрытие. Так и было поймано -- сравнением равномерного
    // индекса с поплиточным при ОДНОМ И ТОМ ЖЕ счётчике.
    const int _st = q0 / (BQ * selGroup), _hk = (kv_ratio > 0) ? (blockIdx.y / kv_ratio) : 0;
    const int _hkv = (pageHkv > 0) ? pageHkv : 1;
    _selI = selIdx + ((size_t)_st * _hkv + _hk) * (size_t)selStride;
    _selN = selCnt[(size_t)_st * _hkv + _hk];
  }
  const int nTiles = (_selI != nullptr) ? (_selN << selSub) : ((kEnd + BK - 1) / BK);
  // [СРЕЗ ДИАПАЗОНА ПЛИТОК] Абсолютные индексы плиток СОХРАНЯЮТСЯ -- от них зависит чётность
  // двойного буфера (`tw & 1` у везущих и `tIdx & 1` у считающих), и разъехаться им нельзя.
  // Меняются только границы обхода; счёт встреч у обеих ролей остаётся равным (tEnd - tBeg).
  // [РАЗДАЧА С ОСТАТКОМ, А НЕ ПОТОЛКОМ] Первая редакция брала perT = ceil(nTiles/kSplit) --
  // и при kSplit, НЕ делящем nTiles, хвостовые срезы оставались ПУСТЫМИ (tBeg >= nTiles).
  // Пустой срез не пишет свою площадку, а Lpart -- torch::empty: сводящее ядро читало мусор,
  // случайно конечный, и брало пустой срез за активный. Замер: relL2 к нерасщеплённому шёл
  // 1.0e+00 при 64 пустых из 192, 5.0e-01 при 21, 2.0e-01 при 5 -- ровно ДОЛЯ пустых.
  // Дефект НЕВИДИМ на лестнице из степеней двойки: они делят nTiles нацело, пустых нет.
  // Здесь остаток раздаётся первым (nTiles % kSplit) срезам: пустых не бывает по построению,
  // и заодно снимается перекос последнего среза.
  const int _spl  = (kSplit > 1) ? ((int)blockIdx.z % kSplit) : 0;
  const int _base = (kSplit > 1) ? (nTiles / kSplit) : nTiles;
  const int _rem  = (kSplit > 1) ? (nTiles % kSplit) : 0;
  const int tBeg  = (kSplit > 1) ? (_spl * _base + (_spl < _rem ? _spl : _rem)) : 0;
  const int tEnd  = (kSplit > 1) ? (tBeg + _base + (_spl < _rem ? 1 : 0)) : nTiles;
  // Базы площадок среза: раскладка [срез, B, H, Sq, D] и [срез, B, H, Sq] -- ровно та, которую
  // ждёт `fwd_combine_splits_kernel` (строка row = bh*Sq + q, o_base = row*D).
  float* __restrict__ Op = nullptr;
  float* __restrict__ Lp = nullptr;
  if (Opart != nullptr) {
    // b/h выше объявлены В ЧУЖОЙ области видимости -- пересчитываем здесь, тем же выражением.
    const long nH = (long)gridDim.y / kSlices;
    const long nB = (long)gridDim.z / (kSplit > 0 ? kSplit : 1);
    const long _hh = (long)blockIdx.y / kSlices;
    const long _bb = (kSplit > 1) ? ((long)blockIdx.z / kSplit) : (long)blockIdx.z;
    const long bh = _bb * nH + _hh;
    Op = Opart  + (long)_spl * nB * nH * (long)Sq * D + bh * (long)Sq * D;
    Lp = LSEpart + (long)_spl * nB * nH * (long)Sq     + bh * (long)Sq;
  }
  // [СДВИГ, А НЕ ДЕЛЕНИЕ]  selSub -- это log2 отношения (блок индекса / плитка ключей), и хост
  // проверяет, что отношение -- степень двойки. Прежде здесь стояли `/ selSub` и `% selSub`
  // с РАНТАЙМОВЫМ делителем: два целочисленных деления (~20 команд каждое) на КАЖДУЮ плитку,
  // причём в цепи адреса подачи. Замер цены обвязки: при полном индексе (98.5 % блоков)
  // разреженный путь шёл x0.93 к плотному -- то есть механика стоила 7-8 % НИ ЗА ЧТО.
#define FA2_KB_OF(t) ((_selI != nullptr) \
    ? (((_selI[(t) >> selSub] << selSub) | ((t) & ((1 << selSub) - 1))) * BK) : ((t) * BK))
  if (isProd) {
    // ХВОСТ: цикл идёт на ДВЕ итерации дольше. На последних двух готовить нечего, но дойти до
    // bar.arrive обязательно -- иначе считающие зависнут на bar.sync READY. Классическое место
    // отказа у producer/consumer, и молчаливое: ядро просто не возвращается.
    // [ОДНА ВСТРЕЧА НА ПЛИТКУ ВМЕСТО ДВУХ]
    // Было: "плитка готова" (везущие -> считающие) и "буфер свободен" (обратно) -- ДВЕ встречи по
    // 33.4 такта ожидания на каждую плитку, и замер долей показал, что обе группы ждут больше, чем
    // работают (53.4% против 39.1%). При ДВОЙНОМ буфере обе встречи сводятся в ОДНУ: на общем
    // рандеву обе группы одновременно узнают, что буфер t полон, а буфер t+1 свободен. Дальше
    // везущие наполняют ОДИН, считающие читают ДРУГОЙ -- они не пересекаются ПО ПОСТРОЕНИЮ, и
    // второе подтверждение не нужно.
    // Пролог: плитка 0 готовится ДО первого рандеву, иначе считающим нечего брать.
    for (int t = tBeg - 1; t < tEnd; ++t) {
      if (t >= tBeg) { PH(1); asm volatile("bar.sync 1, %0;" :: "r"(kAllThr)); PH(0); }
      const int tw = t + 1;                      // готовим СЛЕДУЮЩУЮ плитку
      if (tw < tEnd) {
        const int kb = FA2_KB_OF(tw);
        int8_t* dK = sBuf + (tw & 1) * kBuf;
        int8_t* dV = dK + BK * LDK8;
        // [ПЛИТКА ЗА КОНЦОМ КОНТЕКСТА] Плотный путь до неё не доходит (nTiles считается по kEnd),
        // а РАЗРЕЖЕННЫЙ может: последний блок индекса крупнее плитки и способен выйти за Sk.
        // Тогда (Sk - kb) ОТРИЦАТЕЛЕН -- лечится зажимом в ноль, плитка просто пуста.
        const int rv = (kb + BK <= Sk) ? BK : ((Sk > kb) ? (Sk - kb) : 0);
        // [ФАЗА: обращение за масштабами УХОДИТ ПЕРВЫМ] Его задержка прячется под перекладкой
        // байтов, которая идёт следом; укладка в разделяемую -- уже после неё.
        float2 scPre = make_float2(0.f, 0.f);
        if constexpr (kPre) {
          static_assert(BK <= kProdThr, "ранняя подача масштабов рассчитана на одну строку на нить");
          if (tid < BK && kb + tid < Sk) scPre = reinterpret_cast<const float2*>(Ks)[kb + tid];
        }
        // K и V ЦЕЛИКОМ на плитку: везущая не должна быть сцеплена со считающей ВНУТРИ плитки,
        // иначе расфазировка теряется. Прямая адресация -- шаг между итерациями постоянен (§4bb).
        // ПРЯМАЯ АДРЕСАЦИЯ, а не шаговый цикл. Шаговый допускает ЛЮБОЕ число везущих (в том числе
        // нечётное), но возвращает адресную арифметику на КАЖДУЮ итерацию -- замерено: те же восемь
        // везущих дают 0.3150 против 0.2849, то есть способ сам по себе стоит 10%. Это больше, чем
        // может дать любая нечётность. Поэтому число везущих ограничено делителями 128
        // (1,2,4,8,16), и это ограничение ДЕШЕВЛЕ его снятия.
        // [ДЕЛЕНИЕ, ДОШЕДШЕЕ ДО НУЛЯ] При ОДНОМ везущем варпе kProdThr = 32, а D/4 = 64, и шаг
        // строки становится НУЛЁМ: указатель не сдвигается, перекладка читает одну строку, ответ
        // тихо неверен. Компилятор молчит. Ровно та ловушка, что записана про стены cutlass.
        static_assert(kProdThr >= D / 4, "везущих слишком мало: шаг строки выродится в ноль");
        static_assert((BK * D / 4) % kProdThr == 0, "перекладка должна делиться на нити нацело");
        constexpr int kW = WIDE ? 16 : 4;                 // байт на одну ПОЗИЦИЮ нити (не на выдачу)
        constexpr int kRowK = kProdThr / (D / kW);
        const int r0 = tid / (D / kW), c0 = (tid % (D / kW)) * kW;
        // [ПЕРЕСТАНОВКА -- ПО СТОЛБЦУ, А НЕ ПО АДРЕСУ] XOR полного адреса на 16 НЕВЕРЕН:
        // LDK8 = 272 несёт бит 4 (272 = 256+16), поэтому у НЕЧЁТНЫХ строк тот же XOR уводит
        // на -16 вместо +16 -- запись попадает в чужой кусок, и ответ тихо расходится
        // (замерено relL2 8.8e-2 при верной на вид алгебре). Сдвиг считается по СТОЛБЦУ.
        // [АУДИТ БАНКОВ] АМПЛИТУДА 64, А НЕ 16 (замер: 16 -- мёртвая, даёт -1.25 % времени; 64 --
        // конфликты 19.4 % -> 5.8 % и +3.4 % времени). Парная правка в volta_warp_mma.h (swj):
        // запись и чтение обязаны переставлять ОДИНАКОВО, иначе ответ тихо разойдётся.
        const int kcd = (c0 ^ 64) - c0;   // +-64, один раз на плитку
        const int8_t* pk = Kq + (long)(kb + r0) * k_sM + c0;
        const int8_t* pv = Vq + (long)(kb + r0) * k_sM + c0;
        // [АДРЕСА РАЗДЕЛЯЕМОЙ -- 32 БИТА] Разбор SASS: у везущих 249 целочисленных инструкций на
        // 156 обращений к памяти. Причина считаемая: в цикле ЧЕТЫРЕ указателя, и каждый сдвиг
        // 64-битный, то есть ДВА IADD3 (младшая часть плюс перенос) -- восемь на итерацию.
        // Но два из четырёх ведут в РАЗДЕЛЯЕМУЮ память, а её адресное пространство 32-битное:
        // __cvta_generic_to_shared даёт оконный адрес, и сдвиг по нему -- ОДИН IADD3 вместо двух.
        // Минус четыре инструкции на итерацию при том же числе обращений.
        unsigned qk = (unsigned)__cvta_generic_to_shared(dK + r0 * LDK8 + c0);
        unsigned qv = (unsigned)__cvta_generic_to_shared(dV + r0 * LDV + c0);
        int rr = r0;
        if constexpr (PAGED) {
          // [ЗАДАЧА 163] Строка токена t плитки лежит в странице pageBt[(kb+t)/16] со смещением
          // ((t%16)*Hkv + hkv)*D -- 256 непрерывных байт, как и в плите; коалесцинг тот же.
          // [АДРЕС -- ОДИН РАЗ НА ПЛИТКУ, кукбук §П1] Первая редакция читала таблицу страниц на
          // КАЖДОЙ итерации, сажая задержку L1 в ЦЕПЬ адреса данных, -- x3.5 замером. Здесь базы
          // четырёх страниц плитки считаются ДО цикла, а в развёрнутом цикле смещение -- константа
          // компилятора: та же арифметика, что у линейной плиты, плюс 4 чтения таблицы на плитку.
          static_assert(BK % 16 == 0, "PAGED: плитка кратна странице");
          // [ИНДЕКС СТРАНИЦЫ -- КОМПИЛЯТОРНАЯ КОНСТАНТА, А НЕ ДИНАМИКА] pgBase[rr>>4] с
          // переменным индексом отправлял массив в локальную память (LDL/STL в цикле подачи).
          // Но r0 < kRowK и бит 0..3 не меняют >>4 при kRowK | 16: индекс страницы = (kRowK*u)>>4
          // -- чистая константа развёрнутого цикла, массив остаётся в регистрах.
          static_assert(kRowK <= 16 && 16 % kRowK == 0, "PAGED: строки волны внутри страницы");
          long pgBase[BK / 16];
#pragma unroll
          for (int pi = 0; pi < BK / 16; ++pi)
            pgBase[pi] = (kb + pi * 16 < Sk) ? __ldg(pageOff + (kb >> 4) + pi) : 0;
          const long pgOff = ((long)pgHead) * D + c0;
          const long pgRow = (long)pageHkv * D;
#pragma unroll
          for (int u = 0; u < (BK * D / 4) / kProdThr; ++u) {
            uint32_t wk = 0, wv = 0;
            if (rr < rv) {
              const long src = pgBase[(kRowK * u) >> 4]
                             + (long)((r0 + kRowK * u) & 15) * pgRow + pgOff;
              wk = *reinterpret_cast<const uint32_t*>(Kq + src);
              wv = *reinterpret_cast<const uint32_t*>(Vq + src);
            }
            asm volatile("st.shared.u32 [%0], %1;" :: "r"(qk), "r"(wk));
            asm volatile("st.shared.u32 [%0], %1;" :: "r"(qv), "r"(wv));
            qk += kRowK * LDK8; qv += kRowK * LDV; rr += kRowK;
          }
        } else {
#if FA2_SPLITLS
        // [ПЕРЕСТАНОВКА БЕЗ ЕДИНОЙ ИНСТРУКЦИИ] Было: LDG, LDG, STS, STS на каждой итерации -- каждый
        // STS ЖДЁТ свой LDG (это long_scoreboard). Стало: СНАЧАЛА все чтения из глобальной в
        // регистры, ПОТОМ все записи в разделяемую. Тех же инструкций столько же, изменён ПОРЯДОК:
        // ожидание собирается в одно место, а поток STS в MIO идёт сплошняком и не перемежается
        // ожиданием. Цена -- регистры под задержанные значения, но у везущих запас есть (они ждут
        // 30.7% времени, §4kk-четв).
        constexpr int kIt = (BK * D / 4) / kProdThr;
        uint32_t bk[kIt], bv[kIt];
#pragma unroll
        for (int u = 0; u < kIt; ++u) {
          bk[u] = 0; bv[u] = 0;
          if (rr < rv) { bk[u] = *reinterpret_cast<const uint32_t*>(pk);
                         bv[u] = *reinterpret_cast<const uint32_t*>(pv); }
          pk += (long)kRowK * k_sM; pv += (long)kRowK * k_sM; rr += kRowK;
        }
#pragma unroll
        for (int u = 0; u < kIt; ++u) {
          // [ФАЛЬСИФИКАТОР KVFMT=3] Та же лишняя команда, что у KVFMT=2, но посаженная на ВЕЗУЩИЙ
          // варп вместо считающего. Маска нулевая -- значение не меняется. Сравнение 2 против 3 при
          // равном числе команд измеряет не КОЛИЧЕСТВО работы, а РОЛЬ, на которую она села.
          if constexpr (KVFMT == 3) { bk[u] ^= fa2_sm70::prims::kFakeXorMask;
                                      bv[u] ^= fa2_sm70::prims::kFakeXorMask; }
          asm volatile("st.shared.u32 [%0], %1;" :: "r"(qk), "r"(bk[u]));
          asm volatile("st.shared.u32 [%0], %1;" :: "r"(qv), "r"(bv[u]));
          qk += kRowK * LDK8; qv += kRowK * LDV;
        }
#else
        if constexpr (DIAG == 4) { /* ФАЛЬСИФИКАТОР: подача снята, рандеву оставлено */ } else {
        // [ПЕРЕСТАНОВКА НА ПИШУЩЕЙ СТОРОНЕ] Бит 4 адреса разделяемой == бит 4 столбца, потому что
        // младшие 4 бита у r*LDK8 нулевые (LDK8 кратно 16) и переноса в бит 4 нет, а база плитки
        // кратна 32. Значит XOR адреса на 16 -- это ровно перестановка кусков ВНУТРИ строки.
        // Бит перестановки -- КОМПИЛЯТОРНАЯ величина: при широкой перекладке rr = r0 + 8u и r0 < 8,
        // поэтому (rr>>3)&1 == u&1; при узкой rr = r0 + 2u и r0 < 2, поэтому == (u>>2)&1.
        if constexpr (WIDE == 1) {
          // [ШИРИНА = СОКРАЩЕНИЕ ЧИСЛА ВЫДАЧ, А НЕ ТРАФИКА] Байты те же самые: 2 x BK x D на плитку.
          // Меняется только то, сколько выдач их несёт: 32 итерации -> 8. Кратность 16 у ОБОИХ
          // адресов обязательна: у разделяемого её даёт LDK8 % 16 == 0 и LDV % 16 == 0 (проверено
          // static_assert), у глобального -- шаг строки k_sM и сам указатель (проверяет ХОСТ).
          static_assert(LDK8 % 16 == 0 && LDV % 16 == 0, "широкая укладка: шаги разделяемой кратны 16");
          static_assert((BK * D / 16) % kProdThr == 0, "широкая перекладка должна делиться нацело");
#pragma unroll
          for (int u = 0; u < (BK * D / 16) / kProdThr; ++u) {
            uint4 wk = make_uint4(0, 0, 0, 0), wv = make_uint4(0, 0, 0, 0);
            if (rr < rv) { wk = *reinterpret_cast<const uint4*>(pk);
                           wv = *reinterpret_cast<const uint4*>(pv); }
            const unsigned qks = (SWZ && (u & 1)) ? (unsigned)((int)qk + kcd) : qk;
            asm volatile("st.shared.v4.u32 [%0], {%1,%2,%3,%4};"
                         :: "r"(qks), "r"(wk.x), "r"(wk.y), "r"(wk.z), "r"(wk.w));
            asm volatile("st.shared.v4.u32 [%0], {%1,%2,%3,%4};"
                         :: "r"(qv), "r"(wv.x), "r"(wv.y), "r"(wv.z), "r"(wv.w));
            pk += (long)kRowK * k_sM; pv += (long)kRowK * k_sM;
            qk += kRowK * LDK8; qv += kRowK * LDV; rr += kRowK;
          }
        } else if constexpr (WIDE == 4) {
          // [ШИРОКАЯ + РАЗВЕДЁННЫЕ ЗАГРУЗКА И УКЛАДКА] Проверка догадки о том, ПОЧЕМУ широкая
          // перекладка проиграла: при восьми итерациях компилятору некуда прятать задержку, и
          // каждая STS ждёт СВОЮ LDG (long_scoreboard). Здесь сперва ВСЕ загрузки в регистры
          // (16 uint4 = 64 регистра), потом все укладки: ожидание собирается в одно место.
          constexpr int kIt = (BK * D / 16) / kProdThr;
          uint4 bk[kIt], bv[kIt];
#pragma unroll
          for (int u = 0; u < kIt; ++u) {
            bk[u] = make_uint4(0, 0, 0, 0); bv[u] = make_uint4(0, 0, 0, 0);
            if (rr < rv) { bk[u] = *reinterpret_cast<const uint4*>(pk);
                           bv[u] = *reinterpret_cast<const uint4*>(pv); }
            pk += (long)kRowK * k_sM; pv += (long)kRowK * k_sM; rr += kRowK;
          }
#pragma unroll
          for (int u = 0; u < kIt; ++u) {
            const unsigned qks = (SWZ && (u & 1)) ? (unsigned)((int)qk + kcd) : qk;
            asm volatile("st.shared.v4.u32 [%0], {%1,%2,%3,%4};"
                         :: "r"(qks), "r"(bk[u].x), "r"(bk[u].y), "r"(bk[u].z), "r"(bk[u].w));
            asm volatile("st.shared.v4.u32 [%0], {%1,%2,%3,%4};"
                         :: "r"(qv), "r"(bv[u].x), "r"(bv[u].y), "r"(bv[u].z), "r"(bv[u].w));
            qk += kRowK * LDK8; qv += kRowK * LDV;
          }
        } else if constexpr (WIDE == 2) {
          // ШИРОКАЯ ЗАГРУЗКА, УЗКАЯ УКЛАДКА: 16 Б приезжают одной выдачей, уезжают четырьмя.
#pragma unroll
          for (int u = 0; u < (BK * D / 16) / kProdThr; ++u) {
            uint4 wk = make_uint4(0, 0, 0, 0), wv = make_uint4(0, 0, 0, 0);
            if (rr < rv) { wk = *reinterpret_cast<const uint4*>(pk);
                           wv = *reinterpret_cast<const uint4*>(pv); }
            const unsigned qks = (SWZ && (u & 1)) ? (unsigned)((int)qk + kcd) : qk;
            const uint32_t kk[4] = {wk.x, wk.y, wk.z, wk.w}, vv[4] = {wv.x, wv.y, wv.z, wv.w};
#pragma unroll
            for (int e = 0; e < 4; ++e) {
              asm volatile("st.shared.u32 [%0], %1;" :: "r"(qks + 4u * e), "r"(kk[e]));
              asm volatile("st.shared.u32 [%0], %1;" :: "r"(qv + 4u * e), "r"(vv[e]));
            }
            pk += (long)kRowK * k_sM; pv += (long)kRowK * k_sM;
            qk += kRowK * LDK8; qv += kRowK * LDV; rr += kRowK;
          }
        } else if constexpr (WIDE == 3) {
          // УЗКАЯ ЗАГРУЗКА, ШИРОКАЯ УКЛАДКА: четыре смежных слова приезжают четырьмя выдачами,
          // уезжают одной. Раскладка нитей -- как у широкой (16 Б на нить на строку).
#pragma unroll
          for (int u = 0; u < (BK * D / 16) / kProdThr; ++u) {
            uint4 wk = make_uint4(0, 0, 0, 0), wv = make_uint4(0, 0, 0, 0);
            if (rr < rv) {
              wk.x = reinterpret_cast<const uint32_t*>(pk)[0]; wk.y = reinterpret_cast<const uint32_t*>(pk)[1];
              wk.z = reinterpret_cast<const uint32_t*>(pk)[2]; wk.w = reinterpret_cast<const uint32_t*>(pk)[3];
              wv.x = reinterpret_cast<const uint32_t*>(pv)[0]; wv.y = reinterpret_cast<const uint32_t*>(pv)[1];
              wv.z = reinterpret_cast<const uint32_t*>(pv)[2]; wv.w = reinterpret_cast<const uint32_t*>(pv)[3];
            }
            const unsigned qks = (SWZ && (u & 1)) ? (unsigned)((int)qk + kcd) : qk;
            asm volatile("st.shared.v4.u32 [%0], {%1,%2,%3,%4};"
                         :: "r"(qks), "r"(wk.x), "r"(wk.y), "r"(wk.z), "r"(wk.w));
            asm volatile("st.shared.v4.u32 [%0], {%1,%2,%3,%4};"
                         :: "r"(qv), "r"(wv.x), "r"(wv.y), "r"(wv.z), "r"(wv.w));
            pk += (long)kRowK * k_sM; pv += (long)kRowK * k_sM;
            qk += kRowK * LDK8; qv += kRowK * LDV; rr += kRowK;
          }
        } else {
#pragma unroll
        for (int u = 0; u < (BK * D / 4) / kProdThr; ++u) {
          uint32_t wk = 0, wv = 0;
          if (rr < rv) { wk = *reinterpret_cast<const uint32_t*>(pk);
                         wv = *reinterpret_cast<const uint32_t*>(pv); }
          if constexpr (KVFMT == 3) { wk ^= fa2_sm70::prims::kFakeXorMask;
                                      wv ^= fa2_sm70::prims::kFakeXorMask; }
          const unsigned qk_ = (SWZ && ((u >> 2) & 1)) ? (unsigned)((int)qk + kcd) : qk;
          asm volatile("st.shared.u32 [%0], %1;" :: "r"(qk_), "r"(wk));
          asm volatile("st.shared.u32 [%0], %1;" :: "r"(qv), "r"(wv));
          pk += (long)kRowK * k_sM; pv += (long)kRowK * k_sM;
          qk += kRowK * LDK8; qv += kRowK * LDV; rr += kRowK;
        }
        }
#endif
        }   // конец else (не PAGED)
        }
        if constexpr (kPre) {
          if (tid < BK) { sKs[(tw & 1) * BK + tid] = scPre.x; sVs[(tw & 1) * BK + tid] = scPre.y; }
        } else if constexpr (kPack2) {
          const float2* __restrict__ Ks2 = reinterpret_cast<const float2*>(Ks) + kb;   // адрес плитки -- ОДИН РАЗ
          for (int j = tid; j < BK; j += kProdThr) {
            const float2 s2 = (kb + j < Sk) ? Ks2[j] : make_float2(0.f, 0.f);          // ОДНА .64 на обе таблицы
            sKs[(tw & 1) * BK + j] = s2.x;
            sVs[(tw & 1) * BK + j] = s2.y;
          }
        } else if constexpr (kPackH) {
          const __half2* __restrict__ Ksh = reinterpret_cast<const __half2*>(Ks) + kb;  // запись = 4 Б = один float
          for (int j = tid; j < BK; j += kProdThr) {
            const __half2 h2 = (kb + j < Sk) ? Ksh[j] : __half2(__float2half(0.f), __float2half(0.f));
            sKs[(tw & 1) * BK + j] = __low2float(h2);
            sVs[(tw & 1) * BK + j] = __high2float(h2);
          }
        } else if constexpr (!kNoScale) {
          for (int j = tid; j < BK; j += kProdThr) {     // масштабы плитки
            const int p = kb + j;
            if constexpr (PAGED) {
              // Таблицы масштабов пула: [(страница*16 + позиция) * Hkv + голова]. Чтение таблицы
              // страниц ПОД гвардом p < Sk -- за концом последовательности страницы может не быть.
              float ks = 0.f, vs = 0.f;
              if (p < Sk) {
                const long si = __ldg(pageScl + (p >> 4)) + (long)(p & 15) * pageHkv + pgHead;
                ks = Ks[si]; vs = Vs[si];
              }
              sKs[(tw & 1) * BK + j] = ks;
              sVs[(tw & 1) * BK + j] = vs;
            } else {
              sKs[(tw & 1) * BK + j] = (p < Sk) ? (kIsI8 ? Ks[p] : 1.f) : 0.f;
              sVs[(tw & 1) * BK + j] = (p < Sk) ? (kIsI8 ? Vs[p] : 1.f) : 0.f;
            }
          }
        }
      }
      // (разведение по чётности больше не нужно: встреча ОДНА на плитку, и производитель не может
      // уйти вперёд на два прихода -- он ждёт на том же рандеву)
    }
    // [НАКОПИТЕЛИ РАЗВЕДЕНЫ ПО РОЛЯМ] Везущие пишут в СВОЮ половину буфера (смещение 8).
    // Без этого PH(3) у везущих (ожидание рандеву) складывается с PH(3) у считающих (маска и
    // максимум) в один счётчик -- и читается как «маска стоит 27.7 %», хотя это сумма ОЖИДАНИЯ
    // одной группы и РАБОТЫ другой. Ровно та ошибка, от которой предупреждает шапка ядра
    // («фазы разнесены по варпам»), и я на неё уже наступил.
    PH_OUT(phase_acc ? phase_acc + 8 : phase_acc);
    return;   // [ПОДОЗРЕВАЕМЫЙ 1 СНЯТ] Везущие ОБЯЗАНЫ выйти здесь. Иначе они падают в общий
              // эпилог, где у них wm=wn=0, и не только зависают, но и ПИШУТ В O поверх счёта.
  } else {
    for (int tIdx = tBeg; tIdx < tEnd; ++tIdx) {
      PH(3);
      asm volatile("bar.sync 1, %0;" :: "r"(kAllThr));   // ОДНА встреча: плитка готова И буфер свободен
      // [РАСКОС ВАРПОВ ПО ТАКТУ] Все считающие проходят рандеву РАЗОМ и разом бьют в MIO чтениями
      // фрагментов (по карте участков -- 84-86 LDS на участок). Очередь получает пик, хотя работа
      // та же. Разводим варпы по ОДНОМУ такту: варп cw ждёт cw тактов, и его LDS попадают в свой
      // такт, а не в общий. NOP выбран намеренно -- он не трогает НИ РЕГИСТРОВ, ни флагов, ни
      // памяти, то есть добавляет ровно задержку выдачи и ничего больше.
#if FA2_SKEW
#pragma unroll
      // PTX НЕ ЗНАЕТ "nop" -- такой инструкции в нём нет (ptxas: Not a name of any known
      // instruction). Годится pmevent: она даёт в SASS PMTRIG, занимает слот выдачи и НЕ ТРОГАЕТ
      // ни регистров, ни флагов, ни памяти -- то есть ровно чистая задержка выдачи.
      for (int _s = 0; _s < FA2_SKEW * 8; ++_s) if (_s < cw * FA2_SKEW) asm volatile("pmevent 0;");
#endif
      PH(2);
      const int kb = FA2_KB_OF(tIdx);
      // [БАРЬЕР УБРАН] Здесь стоял bar.sync 3 -- остаток исходного цикла. Он ИЗБЫТОЧЕН: барьер
      // готовности плитки (1 или 4) прямо над ним уже синхронизировал ВСЕ нити блока, включая
      // считающих. Два барьера подряд -- это чистая цена без смысла.
    const int8_t* sK = sBuf + (tIdx & 1) * kBuf;
    const int8_t* sV = sK + BK * LDK8;
    PH(0);   // ФАЗА 0: барьер входа
    // --- масштабы плитки: варп-однородны по строке, читаются один раз (мимо поэлементного пути)
    if constexpr (kPack2 || kPre) {
      const float2* __restrict__ Ks2 = reinterpret_cast<const float2*>(Ks) + kb;
      for (int j = tid; j < BK; j += kWarps * 32) {
        const float2 s2 = (kb + j < Sk) ? Ks2[j] : make_float2(0.f, 0.f);
        sKs[(tIdx & 1) * BK + j] = s2.x;
        sVs[(tIdx & 1) * BK + j] = s2.y;
      }
    } else if constexpr (kPackH) {
      const __half2* __restrict__ Ksh = reinterpret_cast<const __half2*>(Ks) + kb;
      for (int j = tid; j < BK; j += kWarps * 32) {
        const __half2 h2 = (kb + j < Sk) ? Ksh[j] : __half2(__float2half(0.f), __float2half(0.f));
        sKs[(tIdx & 1) * BK + j] = __low2float(h2);
        sVs[(tIdx & 1) * BK + j] = __high2float(h2);
      }
    } else if constexpr (!kNoScale) {
      for (int j = tid; j < BK; j += kWarps * 32) {
        const int p = kb + j;
        if constexpr (PAGED) {
          float ks = 0.f, vs = 0.f;
          if (p < Sk) {
            const long si = __ldg(pageScl + (p >> 4)) + (long)(p & 15) * pageHkv + pgHead;
            ks = Ks[si]; vs = Vs[si];
          }
          sKs[(tIdx & 1) * BK + j] = ks;
          sVs[(tIdx & 1) * BK + j] = vs;
        } else {
          sKs[(tIdx & 1) * BK + j] = (p < Sk) ? (kIsI8 ? Ks[p] : 1.f) : 0.f;
          sVs[(tIdx & 1) * BK + j] = (p < Sk) ? (kIsI8 ? Vs[p] : 1.f) : 0.f;
        }
      }
    }
    // [СМЕЩЕНИЕ K -- В ОПЕРАНД C, ЦЕНА НОЛЬ (§4m, пункт 1)]
    // Инструкция считает D = A*B + C, и слагаемое в C бесплатно. Поправка -1152*sum(q) аддитивна и
    // НЕ зависит от столбца, поэтому её место -- ЗАТРАВКА аккумулятора, а не вычитание после MMA.
    // Прежняя редакция тратила на неё FFMA на КАЖДЫЙ элемент S и, что важнее, ставила его В ЦЕПЬ
    // между двумя умножениями, где сдвигать фазу некуда. Здесь она исчезает как инструкция:
    // s.clear() мы вызываем всё равно, меняется лишь то, ЧЕМ засеяно.
    // [РАЗВОРАЧИВАНИЕ -- НАШ ВЫБОР, А НЕ КОМПИЛЯТОРА]
    // Разбор живости SASS: из 204 задействованных регистров лишь 62 живут через весь мейнлуп, и это
    // РОВНО накопитель O. Регистров, которые держатся долго и почти не читаются, НОЛЬ -- то есть
    // компилятор ничего не "крадёт". Остальные ~142 это КОРОТКОЖИВУЩИЕ временные, и их столько
    // потому, что развёрнуты все циклы разом: по d (4 шага), по SMB/SNB и конвейер внутри
    // accumulate_bi8. Диапазоны жизни перекрываются, и пик растёт.
    // FA2_DUNROLL задаёт разворот цикла по d ЯВНО: 1 = не разворачивать (минимум временных,
    // максимум накладных на цикл), 4 = как было. Это размен, и его решает замер.
    PH(1);   // ФАЗА 1: перекладка масштабов и V (LSU + запись в разделяемую)
    const int dcRot = 0;
    WarpMma<SMB, SNB, BLayout::kKMajor> s;
    {   // §2a: суммы строк этого потока -- подряд, чтобы примитив читал их одним шагом
      const int rb = (lane & 1) | ((lane & 16) >> 2) | (lane & 8);
      float qs[SMB * 2];
#pragma unroll
      for (int i = 0; i < SMB; ++i)
#pragma unroll
        for (int t = 0; t < 2; ++t) qs[i * 2 + t] = sQsum[wm * SM + i * 16 + rb + 2 * t];
      seed_rank1<float, SMB, SNB>(s.acc, kI8Bias, qs, 2);
    }
    // SWZ идёт ТОЛЬКО сюда: перестановка касается плитки K (k-мажорный операнд, LDS.128).
    // У второго умножения операнд V n-мажорный, читается по 4 Б и конфликта не даёт.
    // DIAG=6 -- ОБА умножения сняты сразу. Заведён под проверку АДДИТИВНОСТИ фаз: снятие двух
    // фаз по отдельности даёт в сумме 57.4 %, и вопрос в том, даст ли снятие обеих столько же.
    // Одним скалярным равенством обе не снять (DIAG!=5 и DIAG!=3 -- разные значения), поэтому 6.
    if constexpr (DIAG != 5 && DIAG != 6) s.template accumulate_bi8<D, KVFMT, SWZ, KSP>(sQ, LDQ, wm * SM, sK, LDK8, wn * SN, lane);

    PH(2);   // ФАЗА 2: подача Q/K кусками + ПЕРВОЕ умножение (Tensor + MIO вперемешку)
    const int r0 = wm * SM, c0 = wn * SN;
    const int rowbase = (lane & 1) | ((lane & 16) >> 2) | (lane & 8);
    // [МАСШТАБЫ -- В РЕГИСТРЫ, А НЕ ИЗ РАЗДЕЛЯЕМОЙ НА КАЖДЫЙ ЭЛЕМЕНТ]
    // Первая редакция читала sKs[(tIdx & 1) * BK + c0+c] на каждый элемент S и sVs[(tIdx & 1) * BK + cc] дважды на каждую пару P --
    // около 8192 лишних обращений на плитку К ТОМУ САМОМУ ОГРАНИЧИТЕЛЮ, ради значений, которые
    // у нити ПОСТОЯННЫ: колонки аккумулятора заданы полосой. Это ровно та ошибка, что в §4v --
    // рычаг прикладывался к 4% трафика, а лишняя работа клалась в 96%.
    // МАСШТАБЫ ОСТАВЛЕНЫ В РАЗДЕЛЯЕМОЙ. Подъём их в регистры замерен как НОЛЬ (1.477 -> 1.473),
    // а стоил 8*SNB регистров на нить -- в ядре, где регистры и есть предел занятости, это чистый
    // убыток. Правило: рычаг, давший ноль, надо ОТКАТЫВАТЬ, а не оставлять "пусть будет".
    float mloc[SMB][2], lloc[SMB][2], vloc[SMB][2];
#pragma unroll
    for (int i = 0; i < SMB; ++i) { mloc[i][0] = mloc[i][1] = -CUDART_INF_F;
                                    lloc[i][0] = lloc[i][1] = 0.f; vloc[i][0] = vloc[i][1] = 0.f; }

    // МАСШТАБ КЛЮЧА поэлементно: s_k[j] НЕ выносится из софтмакса, потому что softmax идёт по j.
    // Это поэлементное плавающее -- свободный слот FP32 под HMMA (§4p).
    if constexpr (DIAG == 1) {
      // фальсификатор: максимум не считается вовсе, но ЗАВИСИМОСТЬ от накопителя сохранена
      // (константа нулевая, но лежит в постоянной памяти -- свернуть её компилятор не вправе)
      const float z = (float)fa2_sm70::prims::kFakeXorMask;
      s.visit(lane, [&](float& v, int r, int c) { v = v * z; });
    } else
    s.visit(lane, [&](float& v, int r, int c) {
      const int kk = kb + c0 + c;
      // ПОРЯДОК ОБЯЗАТЕЛЕН: сперва снять смещение разворота (ранг-1 по строке), и только потом
      // масштабировать. Обратный порядок даёт неверный ответ, проходящий проверку на малых числах.
      // смещение уже снято ЗАТРАВКОЙ аккумулятора -- здесь только масштаб
      // qkm = qk_scale * kFmtMul -- инвариант цикла, компилятор поднимает его из тела (проверено
      // по SASS: у KVFMT=11 в мейнлупе НЕТ лишнего FMUL против KVFMT=1).
      if constexpr (kNoScale) v *= qkm;                            // масштаб K свёрнут в Q до запуска
      else                    v *= qkm * sKs[(tIdx & 1) * BK + c0 + c];
      // [ОПРОВЕРГНУТО 15.08.2026: СНЯТИЕ МАСКИ НА ВИДИМЫХ ПЛИТКАХ ДАЁТ НОЛЬ]
      // Довод был счётный и выглядел неотразимо: при Sq=4096 плитка ключей лежит ЦЕЛИКОМ под
      // диагональю в 87.3 % случаев при Sk=16384, 95.4 % при 46002 и 99.1 % при 250000 -- то есть
      // это сравнение почти всегда тождественно ложно. Быстрый путь (варп-однородная ветка, без
      // маски) СОБРАН, ПРОВЕРЕН и даёт ПОБИТОВО ТОЖДЕСТВЕННЫЙ ответ -- и x1.001 / x0.997 по
      // времени, то есть НОЛЬ.
      // ВЫВОД: два целочисленных сравнения на элемент УЖЕ ЛЕЖАТ В ТЕНИ тензорной трубы. Счёт
      // операций снова оказался не связан со временем -- ровно тот случай, ради которого в
      // CLAUDE.md записано «единица анализа -- ФАЗА, а не команда». Не возвращать без ЗАМЕРА фазы.
      if ((CAUSAL && (q0 + r0 + r + causal_off) < kk) || kk >= Sk) v = -CUDART_INF_F;
      const int mb = r >> 4, sub = ((r & 15) - rowbase) >> 1;
      if (v > mloc[mb][sub]) mloc[mb][sub] = v;
    });
#pragma unroll
    for (int i = 0; i < SMB; ++i)
#pragma unroll
      for (int t = 0; t < 2; ++t) {
        if constexpr (DIAG == 1) break;
        // ВНУТРИВАРПОВЫЙ свод нужен И ПРИ KSPL: столбцы одной строки разложены по полосам
        // lane&2 и lane&4, то есть без этих двух перестановок максимум неполон даже по СВОЕМУ
        // срезу ключей. Расщепление снимает только МЕЖВАРПОВУЮ часть (запись в sRedM, барьер,
        // сбор по w) -- ровно те 38.9 % тактов считающих, что дал замер фаз.
        float x = mloc[i][t];
        float y = __shfl_xor_sync(0xffffffffu, x, 2); x = x > y ? x : y;
        y = __shfl_xor_sync(0xffffffffu, x, 4);       x = x > y ? x : y;
        mloc[i][t] = x;
        if constexpr (!KSPL)
          if ((lane & 6) == 0) sRedM[(wm * SM + i * 16 + rowbase + 2 * t) * WN + wn] = x;
      }
    if constexpr (DIAG != 2 && !KSPL) {
      if constexpr (PHSPLIT) asm volatile("bar.sync %0, %1;" :: "r"(4 + wm), "r"(kConsThr / WM));
      else                   asm volatile("bar.sync 3, %0;" :: "r"(kConsThr));
    }
    if constexpr (!KSPL)
#pragma unroll
    for (int i = 0; i < SMB; ++i)
#pragma unroll
      for (int t = 0; t < 2; ++t) {
        float x = -CUDART_INF_F;
#pragma unroll
        for (int w = 0; w < WN; ++w) { float y = sRedM[(wm * SM + i * 16 + rowbase + 2 * t) * WN + w]; x = x > y ? x : y; }
        mloc[i][t] = x;
      }
    PH(3);   // ФАЗА 3: маска, максимум, редукция максимума по варпам (ALU + барьер)
    float corr2[SMB][2], cnew[SMB][2];
#pragma unroll
    for (int i = 0; i < SMB; ++i)
#pragma unroll
      for (int t = 0; t < 2; ++t) {
        const float mo = m_run[i][t], mn = (mo > mloc[i][t]) ? mo : mloc[i][t];
        corr2[i][t] = (mo == -CUDART_INF_F) ? 0.f : exp2f(mo - mn);
        cnew[i][t]  = (mloc[i][t] == -CUDART_INF_F) ? 0.f : exp2f(mloc[i][t] - mn);
      }
    {
      const int cbase = (lane & 2) | ((lane & 4) << 1);
#pragma unroll
      for (int i = 0; i < SMB; ++i)
#pragma unroll
        for (int j = 0; j < SNB; ++j)
#pragma unroll
          for (int pr = 0; pr < 4; ++pr) {
            const int rg = (pr & 1) ? (4 + ((pr >> 1) << 1)) : ((pr >> 1) << 1);
            const int reg0 = rg, reg1 = rg + 1;
            const int row = i * 16 + rowbase + 2 * ((reg0 >> 1) & 1);
            const int col = j * 16 + cbase + 4 * ((reg0 >> 2) & 1);
            const int mb = i, sub = (reg0 >> 1) & 1;
            const float mm = mloc[mb][sub];
            const float v0 = s.acc[i][j][reg0], v1 = s.acc[i][j][reg1];
            // DIAG=1: exp2 и сравнения сняты, зависимость от накопителя S оставлена
            const float p0 = (DIAG == 1) ? (0.5f + v0)
                           : ((v0 == -CUDART_INF_F || mm == -CUDART_INF_F) ? 0.f : exp2f(v0 - mm));
            const float p1 = (DIAG == 1) ? (0.5f + v1)
                           : ((v1 == -CUDART_INF_F || mm == -CUDART_INF_F) ? 0.f : exp2f(v1 - mm));
            lloc[mb][sub] += p0 + p1;
            // МАСШТАБ V СВЁРНУТ В УЖЕ СУЩЕСТВУЮЩЕЕ ДОМНОЖЕНИЕ -- цена НОЛЬ (§4m, пункт 4).
            // Операнд P всё равно строится и всё равно умножается на cnew; s_v[j] входит в тот же
            // множитель. Отдельного прохода по P для деквантования V НЕ СУЩЕСТВУЕТ.
            const float sc2 = cnew[mb][sub];
            const int cc = c0 + col;
            // масштаб V при kNoScale свёрнут в ЭПИЛОГ (столбцовый -> ранг-1 по выходу)
            const float w0 = kNoScale ? (p0 * sc2) : (p0 * sc2 * sVs[(tIdx & 1) * BK + cc]);
            const float w1 = kNoScale ? (p1 * sc2) : (p1 * sc2 * sVs[(tIdx & 1) * BK + cc + 1]);
            // [ПОПРАВКА СЧИТАЕТСЯ ПО ОКРУГЛЁННОМУ ОПЕРАНДУ, А НЕ ПО ИСХОДНОМУ ЗНАЧЕНИЮ]
            // Умножение видит P' УЖЕ округлённым до fp16. Разница округления сама по себе ~5e-4,
            // но в накопителе она умножается на смещение 1152 и потому НЕ сокращается при
            // вычитании поправки. Первый прогон с fp32-значениями дал relL2 3.5e-3 при верной
            // алгебре -- ошибка была целиком в этом рассогласовании.
            const __half2 ph = __floats2half2_rn(w0, w1);
            vloc[mb][sub] += __half2float(__low2half(ph)) + __half2float(__high2half(ph));
            *reinterpret_cast<__half2*>(&sP[(r0 + row) * LDP + cc]) = ph;
          }
    }
    PH(4);   // ФАЗА 4: exp2 и запись P (SFU + разделяемая)
    float sloc[SMB][2], vsum[SMB][2];   // при KSPL свод остаётся В РЕГИСТРАХ, мимо разделяемой
#pragma unroll
    for (int i = 0; i < SMB; ++i)
#pragma unroll
      for (int t = 0; t < 2; ++t) {
        if constexpr (DIAG == 1) break;      // фальсификатор: редукция сумм снята
        float x = lloc[i][t], y = vloc[i][t];
        x += __shfl_xor_sync(0xffffffffu, x, 2); y += __shfl_xor_sync(0xffffffffu, y, 2);
        x += __shfl_xor_sync(0xffffffffu, x, 4); y += __shfl_xor_sync(0xffffffffu, y, 4);
        if constexpr (KSPL) { sloc[i][t] = x; vsum[i][t] = y; }
        else if ((lane & 6) == 0) {
          const int idx = (wm * SM + i * 16 + rowbase + 2 * t) * WN + wn;
          sRedS[idx] = x; sRedS[BQ * WN + idx] = y;
        }
      }
    if constexpr (KSPL) {
      // Барьер здесь стоял РАДИ ДВУХ вещей: свода сумм по варпам и видимости sP для второго
      // умножения. Свода больше нет, а sP каждый варп читает ТОЛЬКО СВОЙ срез столбцов
      // [wn*SN, (wn+1)*SN) -- тот же, в который сам писал. Остаётся согласовать полосы ВНУТРИ
      // варпа (раскладка записи по (row,col) и раскладка чтения фрагмента A -- разные), и это
      // ровно __syncwarp: на Volta с независимым планированием нитей он обязателен.
      __syncwarp();
    } else if constexpr (DIAG != 2) {
      if constexpr (PHSPLIT) asm volatile("bar.sync %0, %1;" :: "r"(4 + wm), "r"(kConsThr / WM));
      else                   asm volatile("bar.sync 3, %0;" :: "r"(kConsThr));
    }
#pragma unroll
    for (int i = 0; i < SMB; ++i)
#pragma unroll
      for (int t = 0; t < 2; ++t) {
        float ss = 0.f, vv = 0.f;
        if constexpr (DIAG == 1) { l_run[i][t] = 1.f; vb_run[i][t] = 0.f; corr2[i][t] = 1.f; break; }
        if constexpr (KSPL) { ss = sloc[i][t]; vv = vsum[i][t]; }
        else
#pragma unroll
        for (int w = 0; w < WN; ++w) {
          const int idx = (wm * SM + i * 16 + rowbase + 2 * t) * WN + w;
          ss += sRedS[idx]; vv += sRedS[BQ * WN + idx];
        }
        const float mo = m_run[i][t], mn = (mo > mloc[i][t]) ? mo : mloc[i][t];
        l_run[i][t] = l_run[i][t] * corr2[i][t] + ss * cnew[i][t];
        // vv УЖЕ содержит множитель cnew (он вложен в записанный операнд), поэтому здесь его нет.
        vb_run[i][t] = vv;                  // вклад ТОЛЬКО этой плитки: снимается сразу, см. ниже
        m_run[i][t] = mn;
      }
      // [БАРЬЕР УБРАН] Он гарантировал видимость sP для второго умножения. Но sP пишется РАНЬШЕ
      // редукции сумм, а барьер этой редукции уже прошёл выше -- видимость обеспечена им.
      // Порядок: запись sP -> редукция сумм -> bar.sync 3 -> чтение сумм -> ЗДЕСЬ -> чтение sP.
    // [СМЕЩЕНИЕ V -- ПРЕДВЫЧЕСТЬ, А НЕ СНИМАТЬ ПОСЛЕ]
    // sum(P') известна ДО второго умножения (она пришла из редукции), поэтому вместо
    //     o = o*corr;  o += P'*(1152+V);  o -= 1152*sum(P')
    // пишем
    //     o = o*corr - 1152*sum(P');  o += P'*(1152+V)
    // Подстановка даёт то же самое, но вычитание СЛИВАЕТСЯ с домножением на corr в ОДИН FFMA:
    // минус восемь инструкций на блок 16x16 и, главное, минус звено в ЦЕПИ между умножениями.
        // corr2 передаётся НАПРЯМУЮ: отдельный массив corr был его побайтовой копией и стоил 4 регистра
    // на нить. vv тоже идёт напрямую -- vb_run хранил вклад ОДНОЙ плитки, который тут же и тратится.
    PH(5);   // ФАЗА 5: редукция сумм по варпам (барьер)
    // [ФАЛЬСИФИКАТОР KSPL=2 -- ЦЕНА ПЕРЕМАСШТАБИРОВАНИЯ НАКОПИТЕЛЯ] Ответ НЕВЕРЕН, читается время.
    // При расщеплении накопитель на варп вырос с ON=64 до DV=256 столбцов, то есть эта строка
    // трогает 128 регистров на плитку вместо 32 -- и стоит она В ЦЕПИ между двумя умножениями.
    // Разность 1 и 2 даёт ДОЛЮ этой фазы, а не догадку о ней.
    // DIAG=7 -- ТОТ ЖЕ фальсификатор на БАЗЕ: без пары «сколько это стоит там» цифра «сколько
    // здесь» ничего не ранжирует, потому что накопители разного размера.
    if constexpr (KSPL != 2 && DIAG != 7)
    rescale_fold<float, OM / 16, ONo / 16>(o.acc, corr2, kI8Bias, vb_run);   // §2b
    if constexpr (DIAG != 3 && DIAG != 6) {
      if constexpr (KSPL)
        // Смещения выражаются УКАЗАТЕЛЕМ: у A (sP) полоса ключей -- это сдвиг по столбцам,
        // у B (sV) -- по строкам. Примитив MMA трогать не пришлось.
        o.template accumulate_bi8<SN, KVFMT>(sP + wn * SN, LDP, wm * OM,
                                             sV + (long)wn * SN * LDV, LDV, 0, lane);
      else
        o.template accumulate_bi8<BK, KVFMT>(sP, LDP, wm * OM, sV, LDV, wn * ON, lane);
    }
    /* снято предвычитанием выше -- блок оставлен выключенным как след разбора
    // [СНИМАТЬ СМЕЩЕНИЕ НА КАЖДОЙ ПЛИТКЕ, А НЕ КОПИТЬ ДО ЭПИЛОГА]
    // Копить нельзя: накопитель тогда держит величину ~1152*sum(P), то есть на порядок больше
    // истинного O, и остаточная ошибка равна расхождению ПОРЯДКОВ СУММИРОВАНИЯ, умноженному на
    // 1152. При длинном контексте sum(P) растёт, и с ним растёт ошибка -- замерено: 6e-4 на
    // квадратных формах против 4.4e-4 при |эталон| 0.049, то есть до 0.9% относительной.
    // Снимая вклад КАЖДОЙ плитки сразу, держим накопитель в масштабе истинного O, и сокращение
    // идёт на малых числах. Цена -- OMB*ONB*8 вычитаний fp32 на плитку, ровно как у соседней
    // строки с corr, и они уезжают в свободный слот FP32 под HMMA (§4p).
    {
      constexpr int OMB = OM / 16, ONB = ON / 16;
#pragma unroll
      for (int i = 0; i < OMB; ++i)
#pragma unroll
        for (int j = 0; j < ONB; ++j)
#pragma unroll
          for (int rg = 0; rg < 8; ++rg) o.acc[i][j][rg] -= kI8Bias * vb_run[i][(rg >> 1) & 1];
    } */
    }
  }
  PH_OUT(phase_acc);
  if constexpr (KSPL) {
    // ==================== СВОД РАСЩЕПЛЕНИЯ ПО КЛЮЧАМ (ОДИН РАЗ НА БЛОК) ====================
    // Каждый из WN варпов вёл СВОЙ срез ключей и потому свою тройку (O, m, l) на ОДНИ И ТЕ ЖЕ
    // строки. Склейка -- та же, что у флеш-внимания между плитками, только между варпами:
    //     m = max_w m_w;   l = sum_w l_w * 2^(m_w - m);   O = sum_w O_w * 2^(m_w - m).
    // Цена -- WN проходов по площадке подачи ОДИН РАЗ на блок; снято -- два межварповых свода
    // НА КАЖДУЮ плитку ключей (их у боевой формы 256..719).
    const int r0 = wm * OM;
    const int rowbase = (lane & 1) | ((lane & 16) >> 2) | (lane & 8);
    float mycorr[SMB][2];
#pragma unroll
    for (int i = 0; i < SMB; ++i)
#pragma unroll
      for (int t = 0; t < 2; ++t)
        if ((lane & 6) == 0) {
          const int idx = (wm * SM + i * 16 + rowbase + 2 * t) * WN + wn;
          sRedM[idx] = m_run[i][t]; sRedS[idx] = l_run[i][t];
        }
    asm volatile("bar.sync 3, %0;" :: "r"(kConsThr));
#pragma unroll
    for (int i = 0; i < SMB; ++i)
#pragma unroll
      for (int t = 0; t < 2; ++t) {
        const int idx0 = (wm * SM + i * 16 + rowbase + 2 * t) * WN;
        float m = -CUDART_INF_F;
#pragma unroll
        for (int w = 0; w < WN; ++w) { const float y = sRedM[idx0 + w]; m = m > y ? m : y; }
        float l = 0.f;
#pragma unroll
        for (int w = 0; w < WN; ++w) {
          const float mw = sRedM[idx0 + w];
          // Срез мог не увидеть НИ ОДНОГО ключа (причинная маска режет по столбцам): у него
          // m = -inf и l = 0. exp2(-inf - m) даёт 0, но при m = -inf это -inf минус -inf = NaN,
          // поэтому ветка, а не арифметика.
          if (mw != -CUDART_INF_F) l += sRedS[idx0 + w] * exp2f(mw - m);
        }
        mycorr[i][t] = (m_run[i][t] == -CUDART_INF_F) ? 0.f : exp2f(m_run[i][t] - m);
        m_run[i][t] = m; l_run[i][t] = l;
      }
    // Нормировка строки кладётся в sQsum: после мейнлупа он свободен, а новой разделяемой стоил бы
    // занятости. Барьер -- чтобы никто не переписал sRedM/sRedS до того, как их дочитали выше.
    asm volatile("bar.sync 3, %0;" :: "r"(kConsThr));
    if (wn == 0 && (lane & 6) == 0)
#pragma unroll
      for (int i = 0; i < SMB; ++i)
#pragma unroll
        for (int t = 0; t < 2; ++t) {
          const int row = r0 + i * 16 + rowbase + 2 * t;
          sQsum[row] = (l_run[i][t] > 0.f) ? (kFmtMul * __frcp_rn(l_run[i][t])) : 0.f;
          if (vslice == 0 && q0 + row < Sq)
            Lse[q0 + row] = (l_run[i][t] > 0.f)
                ? (m_run[i][t] * 0.6931471805599453f + __logf(l_run[i][t])) : -CUDART_INF_F;
        }
    // Свод O идёт ПОЛОСАМИ ПО ON СТОЛБЦОВ, а не всей шириной: площадка на WM*WN частиц полной
    // ширины d -- это 128 КБ, а на полосу -- 32 КБ, и они влезают в буфер подачи (69.7 КБ),
    // который освободился, когда везущие вышли. Полоса c принадлежит варпу wn==c, поэтому итог
    // ложится в глобальную ровно тем же куском, что и у базового ядра.
    float* sMrg = reinterpret_cast<float*>(sBuf);
    constexpr int kPart = OM * ON;                     // частица одного варпа: строки x полоса
    static_assert((long)WM * WN * kPart * sizeof(float) <= (long)2 * kBuf,
                  "площадка свода не влезает в буфер подачи");
    const int cbase0 = (lane & 2) | ((lane & 4) << 1);
    const int tg = wn * 32 + lane;                     // 0..WN*32-1 внутри группы строк
    float* my  = sMrg + (long)(wm * WN + wn) * kPart;
    float* grp = sMrg + (long)(wm * WN) * kPart;
#pragma unroll
    for (int c = 0; c < WN; ++c) {                     // РАЗВЁРНУТ: индекс в o.acc обязан быть
      asm volatile("bar.sync 3, %0;" :: "r"(kConsThr));  // константой, иначе накопитель уедет в LOCAL
#pragma unroll
      for (int i = 0; i < OM / 16; ++i)
#pragma unroll
        for (int jb = 0; jb < ON / 16; ++jb)
#pragma unroll
          for (int rg = 0; rg < 8; ++rg) {
            const int sub = (rg >> 1) & 1;
            const int row = i * 16 + rowbase + 2 * sub;
            const int col = jb * 16 + cbase0 + (rg & 1) + 4 * ((rg >> 2) & 1);
            my[row * ON + col] = o.acc[i][c * (ON / 16) + jb][rg] * mycorr[i][sub];
          }
      asm volatile("bar.sync 3, %0;" :: "r"(kConsThr));
      // Сложение ведут ВСЕ WN варпов группы: соседние нити читают соседние слова (шаг между
      // частицами kPart слов кратен 32), конфликта банков нет, и ни один варп не простаивает.
      static_assert(kPart % (WN * 32) == 0, "полоса свода обязана делиться на нити группы");
#pragma unroll
      for (int it = 0; it < kPart / (WN * 32); ++it) {
        const int e = tg + it * WN * 32;
        float s = 0.f;
#pragma unroll
        for (int w = 0; w < WN; ++w) s += grp[w * kPart + e];
        const int row = e / ON, col = e - row * ON;
        if (q0 + r0 + row < Sq)
          O[(long)(q0 + r0 + row) * o_sM + voff + c * ON + col] = __float2half(s * sQsum[r0 + row]);
      }
    }
  } else {                                             // эпилог: O = acc / l, LSE = m + log(l)
    const int r0 = wm * OM;
    const int rowbase = (lane & 1) | ((lane & 16) >> 2) | (lane & 8);
    float inv[SMB][2];
#pragma unroll
    for (int i = 0; i < SMB; ++i)
#pragma unroll
      // [МНОЖИТЕЛЬ ФОРМАТА У V -- СЮДА] Накопитель O собран по значениям V/256 (разворот e4m3),
      // поэтому итог домножается на 256 РОВНО ЗДЕСЬ, в уже существующем умножении на 1/l.
      // Точность не страдает: 256 -- степень двойки, kFmtMul * __frcp_rn(l) точно, и итоговое
      // округление одно и то же, что у эталона (256*acc)*(1/l).
      for (int t = 0; t < 2; ++t) inv[i][t] = (l_run[i][t] > 0.f) ? (kFmtMul * __frcp_rn(l_run[i][t])) : 0.f;
    constexpr int OMB = OM / 16, ONB = ONo / 16;
    const int cbase0 = (lane & 2) | ((lane & 4) << 1);
#pragma unroll
    for (int i = 0; i < OMB; ++i)
#pragma unroll
      for (int j = 0; j < ONB; ++j)
#pragma unroll
        for (int rg = 0; rg < 8; ++rg) {
          const int sub = (rg >> 1) & 1;
          const int row = i * 16 + rowbase + 2 * sub;
          const int col = j * 16 + cbase0 + (rg & 1) + 4 * ((rg >> 2) & 1);
          if (q0 + r0 + row < Sq) {  // смещение уже снято поплиточно -- здесь только нормировка
            const float _v = o.acc[i][j][rg] * inv[i][sub];
            // При расщеплении пишем СВОЙ (уже нормированный на свой l) выход среза в fp32 --
            // ровно то, что ждёт `fwd_combine_splits_kernel`: он переваживает срезы по их LSE.
            if (Op != nullptr) Op[(long)(q0 + r0 + row) * D + voff + wn * ON + col] = _v;
            else O[(long)(q0 + r0 + row) * o_sM + voff + wn * ON + col] = __float2half(_v);
          }
        }
    if ((lane & 6) == 0 && wn == 0 && vslice == 0) {   // LSE пишет только первый срез
#pragma unroll
      for (int i = 0; i < SMB; ++i)
#pragma unroll
        for (int t = 0; t < 2; ++t) {
          const int row = r0 + i * 16 + rowbase + 2 * t;
          if (q0 + row < Sq) {
            const float _lse = (l_run[i][t] > 0.f)
                ? (m_run[i][t] * 0.6931471805599453f + __logf(l_run[i][t])) : -CUDART_INF_F;
            // LSE среза ОБЯЗАН быть записан даже у пустого среза: сводящее ядро читает его у
            // ВСЕХ срезов и отбирает активные по isfinite. Незаписанная площадка -- мусор.
            if (Lp != nullptr) Lp[q0 + row] = _lse;
            else Lse[q0 + row] = _lse;
          }
        }
    }
  }
}


