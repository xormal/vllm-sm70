// ПЕРЕСЧЁТ w И u ЧАНКОВОГО GATED-DELTA-NET НА ТЕНЗОРНЫХ ЯДРАХ VOLTA.
// Замена recompute_w_u_fwd из fla/Triton (wy_fast.py) -- 8.5% скана.
//
// ЗАЧЕМ. Замерено (§4qq библиотеки примитивов): Triton при цели sm_70 НЕ ЭМИТИТ тензорных инструкций
// вообще -- в PTX mma.sync 0, wmma 0, hmma 0 и 1024 fma.rn.f32, то есть tl.dot компилируется в цикл
// FP32-FMA на обычных ядрах.
//
// ЧТО СЧИТАЕТСЯ (чанк BT=64, A уже ОБРАЩЕНА предыдущим шагом solve_tril и унитреугольна снизу):
//     u[i][d] = SUM_j A[i][j] * ( beta_j * v[j][d] )
//     w[i][e] = SUM_j A[i][j] * ( beta_j * e^{g_j} * k[j][e] )
// Два умножения матриц [64,64] x [64,128] на пару (чанк, голова значения). Ни софтмакса, ни маски --
// причинность уже зашита в треугольность A.
//
// ГЛАВНОЕ ПРО ЭТОТ ШАГ, И ЭТО РЕШАЕТ ВСЮ ЕГО КОМПОНОВКУ: ОН ПАМЯТИ-ОГРАНИЧЕННЫЙ.
// На боевых формах (T=15680, H=24, Hg=8) счёта 12.3 ГФЛОП, а трафика 436 МБ; при достижимых 841 ГБ/с
// пол по памяти 0.52 мс, а пол по счёту при наших замеренных 37-44 ТФЛОП/с -- 0.3 мс. Разложение
// ядра по частям (то же ядро без записи выхода / поток без счёта) это подтвердило буквально:
//     полное ядро .............. 0.751 мс      без ЗАПИСИ выхода ........ 0.375 мс
//     без счёта (свёртка K=4) .. 0.761 мс      поток без счёта .......... 0.682 мс
// Счёт стоит НОЛЬ (0.751 против 0.761), запись -- ПОЛОВИНУ. Поэтому все три хода ниже -- про
// РАСКЛАДКУ ОБРАЩЕНИЙ, а не про тензорный конвейер.
//
// ХОД 1. МАСШТАБ ПЕРЕЕЗЖАЕТ ИЗ ПРАВОГО ОПЕРАНДА В ЛЕВЫЙ.
// Triton масштабирует ПРАВЫЕ операнды: b_vb = fp16(v*beta), b_kb = fp16(fp16(k*beta)*e^g) -- это
// 16384 элемента на пару (чанк, голова), причём вторая ветка требует пары конверсий fp16<->fp32 на
// элемент, а конверсия -- самая дорогая инструкция машины (7.3 IPC против 57 у PRMT, §4e). Но
// множители beta_j и e^{g_j} зависят ТОЛЬКО от индекса свёртки j, то есть от СТОЛБЦА левого операнда:
//     SUM_j A[i][j] * (s_j * B[j][d])  ==  SUM_j (A[i][j] * s_j) * B[j][d].
// Значит их место -- в A, которой вчетверо меньше, и она масштабируется ПАРАМИ fp16 (__hmul2, полный
// темп, §4e п.5). Правые операнды (K и V) кладутся в разделяемую память ЧИСТЫМ копированием uint4 --
// ни одной арифметической инструкции. Это §2/§2a примитивов (вынести поправку из внутреннего цикла),
// только для мультипликативной поправки.
// Точность НЕ страдает: у Triton на пути w тоже ДВА округления в fp16 (k*beta, затем *e^g), у нас
// тоже два (beta*e^g -> fp16, затем A*s -> fp16). Класс ошибки один.
//
// ХОД 2 (САМЫЙ КРУПНЫЙ, x1.76 ПО ЗАМЕРУ): ПЕРЕСТАНОВКА СТОЛБЦОВ ПРАВОГО ОПЕРАНДА.
// Карта аккумулятора Volta даёт столбец = 8*L2 + 4*R2 + 2*L1 + R0 (L -- биты полосы, R -- биты номера
// регистра). Поэтому четыре полосы одной строки пишут по 4 Б в РАЗРЫВЫ 32-байтового сектора, и каждый
// сектор дописывается ВТОРОЙ инструкцией: вдвое больше транзакций, все частичные. Замер потока с
// такой записью -- 2.6-7.3 мс против 0.68 мс у сплошной.
// Лечение бесплатное: раскладку правого операнда в разделяемой памяти выбираем МЫ. Кладём глобальный
// столбец d в столбец sigma(d), где sigma меняет местами биты 1 и 2. Тогда выходной столбец полосы
// равен 8*L2 + 4*L1 + 2*R2 + R0, то есть ЧЕТЫРЕ регистра (0,1,4,5) одной строки ложатся на ЧЕТЫРЕ
// СМЕЖНЫХ столбца -- одна запись по 8 Б, и четыре полосы кроют сектор ЦЕЛИКОМ.
// А сама sigma при укладке -- перестановка двух 32-битных слов внутри uint4 ({x,z,y,w}), то есть
// ПЕРЕИМЕНОВАНИЕ РЕГИСТРОВ: ноль инструкций. Ровно случай "перестановка, выразимая адресом" из §4m
// примитивов -- граница проходит между "вписывается в адрес" (ноль) и "не вписывается".
// ИЗМЕРЕНО: 1.276 -> 0.726 мс при побайтово том же ответе.
//
// ХОД 3: ПЛИТКА КЛЮЧА ОБЩАЯ НА ГРУППУ ГОЛОВ ЗНАЧЕНИЯ (HPB).
// k индексируется головой КЛЮЧА (Hg=8), а всё остальное -- головой ЗНАЧЕНИЯ (H=24). При блоке
// "чанк x одна голова значения" плитка k читается ТРИЖДЫ. Абляция (ядро, которому запрещено читать k)
// дала 0.751 -> 0.635 мс, то есть весь трафик k стоит 15%; общая плитка снимает две трети этого.
// Тем же ходом чинится и мелочь: beta и g лежат как [T][H], поэтому три соседние головы значения
// сидят в ОДНОМ секторе -- при обходе голов внутри блока их чтения попадают в L1 (сами по себе они
// стоили 4.7%: 4 КБ секторов на 384 Б полезных).
//
// ХОД 4: ТРЕУГОЛЬНОСТЬ A -- ЭТО ДЛИНА СВЁРТКИ, А НЕ МАСКА.
// A[i][j] = 0 при j > i ТОЧНЫМ нулём (solve_tril выделяет zeros_like и наддиагональ не пишет).
// Значит варпу, владеющему строками [ro, ro+SM), достаточно свёртки длиной ro+SM, а не BT. Работы
// становится (SM+2SM+...+BT)/(WM*BT): при WM=2 это 75%, при WM=4 -- 62.5%. Это не маскирование
// (маска стоила бы инструкций), а более короткий цикл -- цена ноль.
//
// РАСКЛАДКА. Блок = (чанк, группа из HPB голов значения при одной голове ключа). Восемь варпов,
// сетка WM x WN по выходу [64][128]. Разделяемая: sA [64][68], sV [64][144], sK [64][144] = 44.5 КБ
// -> два блока на SM. Дополнения выведены из арифметики банков, см. ниже.
#pragma once
#include <cuda_fp16.h>
#include <cuda_runtime.h>
#include "volta_warp_mma.h"

namespace fa2_sm70 {
namespace gdn {

// РАСКЛАДКИ ОПЕРАНДА B В НАШЕМ API ПРОТИВОПОЛОЖНЫ ИНТУИЦИИ ИМЕНИ (см. enum в volta_warp_mma.h:47):
//   kKMajor: B это [N][K], непрерывен K  -> инструкция .row.col, это случай Q*K^T
//   kNMajor: B это [K][N], непрерывен N  -> инструкция .row.row, это случай P*V
// Здесь свёртка идёт по j, а правый операнд лежит как [j][d] с непрерывным d = N. То есть [K][N] с
// непрерывным N -> kNMajor. Левый операнд A лежит [i][j] с непрерывным j = K -> ALayout::kKMajor.
//
// HPB  -- голов значения на блок; обязано делить H/Hg (иначе группа задела бы две головы ключа).
//         HPB=1 возвращает прежнюю компоновку "блок = одна голова".
// TRI  -- укорачивать свёртку по треугольности A (ход 4).
// MINB -- цель по блокам на SM. Второй аргумент __launch_bounds__ НЕ украшение: без него компилятор
//         сам решает, сколько регистров оставить, и меняет решение от правки к правке (§34.2).
// DBUF -- ОСЬ ПО КАРТЕ СОЛВЕРА (задача 192, research/19 §П): факт T1=2387 против плана 1736
//         (−27%), и карта требует STS фазы w ПОЗЖЕ (+248, в тень умножения u), а LDS -- РАНЬШЕ.
//         В однобуферной компоновке этому мешает БАРЬЕР между store u и укладкой sA фазы w:
//         фаза w перезаписывает ту же sA, которую ещё читает gemm(sV) других варпов. При DBUF=1
//         фаза w пишет ВТОРУЮ копию sA -- барьер уходит, и ptxas получает ПРАВО тянуть её STS
//         под хвост первого умножения. Цена: +BT*LDA*2 Б разделяемой (8.7 КБ) -- блок перестаёт
//         влезать по двое на SM, поэтому ось решается СЕКУНДОМЕРОМ, а не рассуждением.
template <int BT, int DK, int DV, int WM, int WN, int HPB, int MINB, bool TRI, typename IdxT,
          int DBUF = 0>
__global__ __launch_bounds__(WM * WN * 32, MINB) void volta_gdn_chunk_wu(
    const __half* __restrict__ kk,     // [B, T, Hg, DK]
    const __half* __restrict__ vv,     // [B, T, H,  DV]
    const __half* __restrict__ bb,     // [B, T, H]        beta, fp16
    const float*  __restrict__ gg,     // [B, T, H]        ВНУТРИЧАНКОВЫЙ включающий кумсум, fp32
    const __half* __restrict__ aa,     // [B, T, H, BT]    (I + Araw)^{-1}, унитреугольная нижняя
    __half* __restrict__ ww,           // [B, T, H, DK]    ВНИМАНИЕ: шаг строки H*DK, а не Hg*DK
    __half* __restrict__ uu,           // [B, T, H, DV]
    const IdxT* __restrict__ cu_seqlens,     // [N+1] или nullptr (одна последовательность на партию)
    const IdxT* __restrict__ chunk_indices,  // [NT_total][2] = (номер посл-ти, локальный чанк)
    int T, int H, int Hg) {
  static_assert(DK == DV, "правый операнд общей ширины: k и v одной размерности головы");
  constexpr int nthr = WM * WN * 32;

  // --- ДОПОЛНЕНИЯ ВЫВЕДЕНЫ ИЗ АРИФМЕТИКИ БАНКОВ, а не взяты круглыми.
  // Банк = адрес в 4-байтовых словах по модулю 32; шаг строки в словах = LD/2 (LD в half).
  //
  // sA читается как ОПЕРАНД A (k-мажорный): полоса берёт строку wmma_a_row(lane) в 0..15 и восемь
  // байт подряд. Нужно, чтобы 16 строк легли на 32 банка -> шаг строки в словах должен быть чётным,
  // но НЕ кратным 4: LDA=68 даёт 34 слова, 34 % 32 = 2, строки садятся на банки 0,2,...,30, а
  // 8-байтовый доступ кроет пару {2r, 2r+1} -> ровно 32 банка, ноль конфликтов.
  // Цена известна и принята (§3 плейбука): 68*2 = 136 Б не кратно 16, поэтому УКЛАДКА A идёт по 8 Б.
  // Это дешевле конфликта: A пишется один раз, а читается 32 раза на варп за умножение.
  constexpr int LDA = BT + 4;
  // sV/sK читаются как ОПЕРАНД B (n-мажорный): адрес полосы = (lane&3)*LDB/2 + nbase/2, где nbase из
  // wmma_b_nbase пробегает {0,4,8,12}, то есть nbase/2 = {0,2,4,6}. Чтобы слагаемые НЕ накладывались
  // (именно это §4c примитивов диагностировал как источник 22.4% конфликтов на отгруженном forward),
  // шаг строки в словах должен быть ровно 8 по модулю 32: LDB=144 -> 72 слова, 72 % 32 = 8, суммы
  // (lane&3)*8 + {0,2,4,6} все различны. Заодно 144*2 = 288 Б кратно 16 -> укладка одной STS.128.
  constexpr int LDB = DK + 16;
  constexpr int SM = BT / WM, SN = DV / WN;
  constexpr int MB = SM / 16, NB = SN / 16;
  static_assert(SM % 16 == 0 && SN % 16 == 0, "плитки варпа кратны шагу фрагмента");
  static_assert(WM == 1 || WM == 2 || WM == 4, "разбор укороченной свёртки написан на эти три случая");
  constexpr int kAV = (BT * BT / 8) / nthr;   // uint4 операнда A на поток
  constexpr int kBV = (BT * DV / 8) / nthr;   // uint4 правого операнда на поток
  static_assert(kAV * nthr * 8 == BT * BT, "укладка A обязана делиться нацело по потокам");
  static_assert(kBV * nthr * 8 == BT * DV, "укладка B обязана делиться нацело по потокам");

  extern __shared__ __half smem[];
  __half* sA = smem;                  // [BT][LDA]  левый операнд, масштабированный по столбцам
  // При DBUF=1 фаза w пишет ВТОРУЮ копию A: барьер между store u и её укладкой не нужен.
  __half* sAw = smem + DBUF * (BT * LDA);
  __half* sV = smem + (1 + DBUF) * (BT * LDA);   // [BT][LDB]  V текущей головы значения
  __half* sK = sV + BT * LDB;         // [BT][LDB]  K головы ключа -- ОДИН на всю группу голов
  // Два готовых столбцовых масштаба. __align__(16) обязателен: читаем их по 8 half одной LDS.128,
  // а массив __half по умолчанию выровнен на 2 байта.
  __shared__ __align__(16) __half sSc[2][BT];

  // --- какой чанк какой последовательности и какая группа голов достались блоку
  int it = blockIdx.x;
  const int ibh = blockIdx.y, ihb = ibh % (H / HPB), ib = ibh / (H / HPB);
  long bos;
  int Tn;
  if (chunk_indices != nullptr) {                       // varlen: сетка плоская по всем чанкам
    const int in = (int)chunk_indices[2 * (long)it];
    it = (int)chunk_indices[2 * (long)it + 1];
    bos = (long)cu_seqlens[in];
    Tn = (int)cu_seqlens[in + 1] - (int)bos;
  } else {
    bos = (long)ib * T;
    Tn = T;
  }
  const int t0 = it * BT;
  const int rows = (Tn - t0) < BT ? (Tn - t0) : BT;     // хвостовой чанк короче
  if (rows <= 0) return;
  const int ih0 = ihb * HPB;                            // первая голова значения группы
  const int ihg = ih0 / (H / Hg);                       // голова КЛЮЧА: группировка блочная, не по модулю

  const int tid = threadIdx.x, lane = tid & 31, warp = tid >> 5;
  const int wm = warp / WN, wn = warp % WN;
  const int ro = wm * SM, co = wn * SN;

  // --- ПЛИТКА КЛЮЧА: читается ОДИН раз на группу голов значения.
  // Выигрыш даёт именно ДИСТАНЦИЯ между выдачей и потреблением, а не равномерность потока запросов
  // (§13 каталога: разнесение LDG/STS +20..46%, размазывание выдачи -- 0.4-1.9%, шум).
  {
    uint4 rk[kBV];
#pragma unroll
    for (int s = 0; s < kBV; ++s) {
      const int q = tid + s * nthr, r = q / (DK / 8), c = (q % (DK / 8)) * 8;
      rk[s] = (r < rows) ? *reinterpret_cast<const uint4*>(&kk[((bos + t0 + r) * Hg + ihg) * DK + c])
                         : uint4{0, 0, 0, 0};
    }
#pragma unroll
    for (int s = 0; s < kBV; ++s) {
      const int q = tid + s * nthr, r = q / (DK / 8), c = (q % (DK / 8)) * 8;
      // sigma: столбцы группы восьмёрки идут в порядке 0,1,4,5,2,3,6,7, то есть средние два слова
      // uint4 меняются местами. Инструкций это не стоит вовсе -- только имена регистров.
      *reinterpret_cast<uint4*>(&sK[r * LDB + c]) = make_uint4(rk[s].x, rk[s].z, rk[s].y, rk[s].w);
    }
  }

  WarpMma<MB, NB, BLayout::kNMajor> mm;

  // Длина свёртки: строки варпа [ro, ro+SM), а A[i][j] = 0 при j > i -> хватает ro+SM.
  // Ветвление ПО ВАРПАМ, а не по полосам: расхождения внутри варпа нет, стоимость нулевая.
#define FA2_WU_GEMM(SA, SB, KK) mm.template accumulate<(KK)>((SA), LDA, ro, (SB), LDB, co, lane)
  auto gemm = [&](const __half* sL, const __half* sB) {
    if constexpr (!TRI || WM == 1) {
      FA2_WU_GEMM(sL, sB, BT);
    } else if constexpr (WM == 2) {
      if (wm == 0) { FA2_WU_GEMM(sL, sB, SM); } else { FA2_WU_GEMM(sL, sB, 2 * SM); }
    } else {
      if (wm == 0)      { FA2_WU_GEMM(sL, sB, SM); }
      else if (wm == 1) { FA2_WU_GEMM(sL, sB, 2 * SM); }
      else if (wm == 2) { FA2_WU_GEMM(sL, sB, 3 * SM); }
      else              { FA2_WU_GEMM(sL, sB, 4 * SM); }
    }
  };

  // Эпилог. ПОСЛЕ перестановки столбцов (ход 2) регистры (0,1,4,5) держат ЧЕТЫРЕ СМЕЖНЫХ столбца
  // строки r, а (2,3,6,7) -- те же столбцы строки r+2:
  //     столбец = 8*L2 + 4*L1 + 2*R2 + R0,  R2 = (reg>>2)&1, R0 = reg&1, L -- биты полосы 2 и 1.
  // Значит одна запись по 8 Б на строку, и четыре полосы одной строки кроют 32-байтовый сектор
  // ЦЕЛИКОМ. Перебор (i, j, reg) ЯВНЫЙ, не через visit: visit отдаёт (r, c) во время выполнения, и
  // любой регистровый массив с таким индексом уезжает в локальную память (§43 плейбука, §4d примитивов).
  auto store_out = [&](__half* base, int ldrow) {
    const int cbase = co + ((lane & 6) << 1);          // 8*L2 + 4*L1
#pragma unroll
    for (int i = 0; i < MB; ++i)
#pragma unroll
      for (int j = 0; j < NB; ++j)
#pragma unroll
        for (int hh = 0; hh < 2; ++hh) {
          const int rg = hh * 2;                        // 0 -> строка r, 2 -> строка r+2
          const int r = ro + i * 16 + wmma_acc_row(lane, rg);
          if (r < rows) {
            const __half2 pay[2] = {__floats2half2_rn(mm.acc[i][j][rg], mm.acc[i][j][rg + 1]),
                                    __floats2half2_rn(mm.acc[i][j][rg + 4], mm.acc[i][j][rg + 5])};
            *reinterpret_cast<uint2*>(&base[(bos + t0 + r) * (long)ldrow + cbase + j * 16]) =
                *reinterpret_cast<const uint2*>(pay);
          }
        }
  };

  // --- обход голов значения группы. Глобальные загрузки головы hv выдаются ДО барьера, поэтому они
  // летят под хвостом умножения предыдущей головы -- конвейер получается без единой лишней строки.
  for (int hv = 0; hv < HPB; ++hv) {
    const int ih = ih0 + hv;
    uint4 ra[kAV], rv[kBV];
#pragma unroll
    for (int s = 0; s < kAV; ++s) {
      const int q = tid + s * nthr, r = q / (BT / 8), c = (q % (BT / 8)) * 8;
      ra[s] = (r < rows) ? *reinterpret_cast<const uint4*>(&aa[((bos + t0 + r) * H + ih) * BT + c])
                         : uint4{0, 0, 0, 0};
    }
#pragma unroll
    for (int s = 0; s < kBV; ++s) {
      const int q = tid + s * nthr, r = q / (DV / 8), c = (q % (DV / 8)) * 8;
      rv[s] = (r < rows) ? *reinterpret_cast<const uint4*>(&vv[((bos + t0 + r) * H + ih) * DV + c])
                         : uint4{0, 0, 0, 0};
    }
    // Столбцовые масштабы: 64 значения на голову. e^{g_j} считается ОДИН раз (у Triton -- тоже, до
    // циклов). g <= 0 внутри чанка, поэтому e^g в (0,1], переполнения нет; недобор до нуля ведёт себя
    // как у Triton (там правый операнд всё равно округляется в fp16 после умножения на e^g).
    // Соседние головы значения лежат в ОДНОМ секторе [T][H], поэтому со второй итерации это L1.
    float bsc = 0.f, gsc = 0.f;
    if (tid < BT && tid < rows) {
      bsc = __half2float(bb[(bos + t0 + tid) * H + ih]);
      gsc = __expf(gg[(bos + t0 + tid) * H + ih]);
    }
    __syncthreads();                     // sA/sV предыдущей головы отработали; sK готов
    if (tid < BT) {
      sSc[0][tid] = __float2half(bsc);            // beta ровно как лежит (обратное преобразование точно)
      sSc[1][tid] = __float2half(bsc * gsc);      // beta * e^g -- одно округление, дальше только fp16
    }
    __syncthreads();

    // --- ФАЗА u: sA = A * beta (по столбцам), sV = V как есть (с перестановкой sigma).
#pragma unroll
    for (int s = 0; s < kAV; ++s) {
      const int q = tid + s * nthr, r = q / (BT / 8), c = (q % (BT / 8)) * 8;
      uint4 a = ra[s];
      const uint4 sc = *reinterpret_cast<const uint4*>(&sSc[0][c]);   // 8 масштабов одной LDS.128
      __half2* ah = reinterpret_cast<__half2*>(&a);
      const __half2* sh = reinterpret_cast<const __half2*>(&sc);
#pragma unroll
      for (int m = 0; m < 4; ++m) ah[m] = __hmul2(ah[m], sh[m]);
      *reinterpret_cast<uint2*>(&sA[r * LDA + c]) = make_uint2(a.x, a.y);
      *reinterpret_cast<uint2*>(&sA[r * LDA + c + 4]) = make_uint2(a.z, a.w);
    }
#pragma unroll
    for (int s = 0; s < kBV; ++s) {
      const int q = tid + s * nthr, r = q / (DV / 8), c = (q % (DV / 8)) * 8;
      *reinterpret_cast<uint4*>(&sV[r * LDB + c]) = make_uint4(rv[s].x, rv[s].z, rv[s].y, rv[s].w);
    }
    __syncthreads();

    mm.clear();
    gemm(sA, sV);
    store_out(uu + (long)ih * DV, H * DV);

    // --- ФАЗА w: A * beta * e^g. Пересчитывается из ИСХОДНЫХ регистров, а не домножением уже
    // округлённой sA -- иначе округлений стало бы три вместо двух. sV и sK не трогаем.
    // При DBUF=1 запись идёт во ВТОРУЮ копию (sAw != sA): WAR-конфликта с чужими чтениями sA нет,
    // барьер перед укладкой не нужен -- ptxas получает право тянуть эти STS в тень gemm(sV).
    if constexpr (!DBUF) __syncthreads();
#pragma unroll
    for (int s = 0; s < kAV; ++s) {
      const int q = tid + s * nthr, r = q / (BT / 8), c = (q % (BT / 8)) * 8;
      uint4 a = ra[s];
      const uint4 sc = *reinterpret_cast<const uint4*>(&sSc[1][c]);
      __half2* ah = reinterpret_cast<__half2*>(&a);
      const __half2* sh = reinterpret_cast<const __half2*>(&sc);
#pragma unroll
      for (int m = 0; m < 4; ++m) ah[m] = __hmul2(ah[m], sh[m]);
      *reinterpret_cast<uint2*>(&sAw[r * LDA + c]) = make_uint2(a.x, a.y);
      *reinterpret_cast<uint2*>(&sAw[r * LDA + c + 4]) = make_uint2(a.z, a.w);
    }
    __syncthreads();

    mm.clear();
    gemm(sAw, sK);
    store_out(ww + (long)ih * DK, H * DK);   // ЛОВУШКА: у w шаг строки H*DK, у входного k -- Hg*DK
  }
#undef FA2_WU_GEMM
}

// Разделяемая память ядра, В ОДНОМ МЕСТЕ с самим ядром. Хост обязан считать её ИМЕННО отсюда:
// дополнения LDA/LDB выведены из арифметики банков (см. выше) и повторять их на стороне вызова --
// это ровно тот класс расхождения, который даёт не отказ, а тихо неверный ответ.
template <int BT, int DK, int DV, int DBUF = 0>
__host__ __device__ constexpr size_t volta_gdn_wu_smem() {
  constexpr int LDA = BT + 4;
  constexpr int LDB = DK + 16;
  return (size_t)((1 + DBUF) * BT * LDA + 2 * BT * LDB) * sizeof(__half);
}

