// ПЛОТНЫЙ fp16-GEMM НА НАШЕМ ВАРП-ОПЕРАТОРЕ (задача 197).
//
// ЗАЧЕМ ОН ВООБЩЕ. В пути w12 (веса внимания в int12) при больших M стояло
// «наш деквант -> torch.matmul». Замер 20.08 на боевых формах: деквант 0.14-0.26 мс, а
// torch.matmul 1.4-13.5 мс -- то есть ВСЯ цена в чужом матмуле, и он даёт лишь 50-70 % пика
// карты. Поправка владельца: torch в пути -- антипаттерн, его надо убрать, а не мерить им.
//
// ПОЧЕМУ НЕ СЛИТОЕ int12-ТЕЛО. Наша упаковка int12 кладётся в тензорные ядра ДВУМЯ
// плоскостями (lo 6 бит + hi 6 бит, кодировка 0x6400|v), то есть тензорной работы ВДВОЕ
// больше, чем у fp16-GEMM. Арифметика формы qkv (M=8192, K=5120, N=7168): 601 GFLOP, при
// пике 125 TFLOPS это 4.8 мс для fp16 и ~9.6 мс при удвоении -- слитое тело на больших M
// проигрывает В ПРИНЦИПЕ (torch там 6.9 мс). Поэтому деквант оставлен отдельной фазой (он
// дёшев и упирается в полосу), а заменяется ровно то, что дорого: САМ МАТМУЛ.
//
// ПОЧЕМУ ПЛИТКА КРУПНАЯ. Существующее тело w12a16_hmma -- GEMV-класса: MT=16, то есть при
// M=8192 вес перечитывается 512 раз. Трафик веса = (M/BM) * K*N*2 байт; при BM=16 это 28 ГБ
// на форму (замер подтвердил: 35 мс = ровно полоса), при BM=128 -- 3.5 ГБ. Плитка по M --
// не «настройка», а то, что определяет ПОРЯДОК цены.
//
// ГЕОМЕТРИЯ ПО УМОЛЧАНИЮ: BM=128, BN=128, BK=32, 8 варпов сеткой 2x4. Варп считает 64x32,
// то есть MB=4, NB=2 -> acc[4][2][8] = 64 регистра накопителя (бюджет при 256 нитях и
// MINB=1 -- 256 регистров на нить, разлива быть не должно; проверяется -Xptxas -v).
#pragma once

#include <cuda_fp16.h>
#include <cstdint>
#include "gemm/volta_warp_mma.h"

namespace fa2_sm70 {
namespace gemm_f16 {

using fa2_sm70::WarpMma;
using fa2_sm70::BLayout;

// A -- k-мажорный [BM][BK], дополнение +4 полуслова (закон из w8a16/GDN: «DK+4»).
// B -- n-мажорный [BK][BN], дополнение +16 (при BN=128 даёт LDB=144: 144/2=72, 72 mod 32 = 8).
// DIAG -- ФАЛЬСИФИКАТОР СНЯТИЕМ ФАЗЫ (ответ заведомо неверен, читается ТОЛЬКО время):
//   0 -- полное тело;
//   1 -- подача из ГЛОБАЛЬНОЙ снята (в разделяемой мусор): разность с 0 = цена канала памяти;
//   2 -- снято УМНОЖЕНИЕ (подача и раскладка на месте): разность = цена тензорной трубы;
//   3 -- снята РАСКЛАДКА в разделяемую (пишет только нить 0 -- сток, чтобы подача не умерла
//        как мёртвый код): разность = цена записи STS;
//   4 -- сняты БАРЬЕРЫ (__syncthreads): разность = цена синхронизации;
//   5 -- снято ЧТЕНИЕ из разделяемой в тензорную трубу (фрагменты берутся из регистров, число
//        HMMA то же): разность = цена подачи операндов LDS.
// СТОК ОБЯЗАТЕЛЕН. Если снятая фаза делает предыдущую мёртвой, ptxas выбросит и её, и прибор
// покажет время НИЖЕ физического пола -- уже пойманная в этом проекте ловушка (w12a16, DIAG=5).
// Без этого «связывает полоса» остаётся догадкой: интенсивность плитки её только допускает.
// PERSIST -- СЛИЯНИЕ БЛОКОВ (ход владельца 20.08). Блок не завершается после одной плитки,
// а забирает следующие ЗАДАЧИ подряд. Смысл не в накладных запуска (они малы), а в том, что
// соседние задачи идут по N при ТОМ ЖЕ m0: операнд A между ними остаётся горячим, и его
// трафик падает во столько раз, сколько плиток N блок обошёл. Плюс исчезает хвостовая волна
// (1792 блока на 80 SM -- это 22.4 волны, последняя неполная).
template <int BM, int BN, int BK, int WM, int WNw, int MINB = 1, int DIAG = 0, int PERSIST = 0>
__global__ __launch_bounds__(WM * WNw * 32, MINB) void volta_gemm_f16(
    const __half* __restrict__ x, const __half* __restrict__ w, __half* __restrict__ y,
    int M, int N, int K) {
  constexpr int WARPS = WM * WNw;
  constexpr int THREADS = WARPS * 32;
  constexpr int TM = BM / WM;                 // строк на варп
  constexpr int TN = BN / WNw;                // столбцов на варп
  constexpr int MB = TM / 16, NB = TN / 16;
  static_assert(TM % 16 == 0 && TN % 16 == 0, "плитка варпа кратна 16");
  static_assert(BK % 8 == 0, "шаг по K кратен 8: грузим uint4");
  constexpr int PADA = 4, PADB = 16;
  constexpr int LDA = BK + PADA, LDB = BN + PADB;

  __shared__ __half sA[2 * BM * LDA];
  __shared__ __half sB[2 * BK * LDB];

  const int tid = threadIdx.x, lane = tid & 31, warp = tid >> 5;
  const int wm = warp / WNw, wn = warp % WNw;
  const int всего_m = (M + BM - 1) / BM, всего_n = (N + BN - 1) / BN;
  const int всего_задач = всего_m * всего_n;
  for (int задача = (PERSIST ? (int)blockIdx.x : -1);
       PERSIST ? (задача < всего_задач) : (задача < 0);
       задача += (PERSIST ? (int)gridDim.x : 1)) {
  // РАСТР ПОД L2, А НЕ ЛИНЕЙНЫЙ ПОРЯДОК. Плитка 128x128x32 читает 16 КиБ и делает 524 288
  // MAC -- это 32 MAC/байт, а чтобы держать тензорный пик при полосе 878 ГБ/с нужно 71.
  // Тело связано ПОЛОСОЙ ровно вдвое (замер: 50 % пика против 71 % у cuBLAS), и лечится это
  // не укладкой (комбинатор: T1=566 при поле 512, зазор 9.6 %), а ПЕРЕИСПОЛЬЗОВАНИЕМ через
  // L2: блоки, идущие одновременно, должны накрывать КОМПАКТНЫЙ прямоугольник, а не строку.
  // Группируем по SWZ плиток вдоль M -- тогда одна плитка веса обслуживает SWZ плиток x.
  // ПЕРЕСТАНОВКА ОБЯЗАНА БЫТЬ БИЕКТИВНОЙ. Первый заход этого не обеспечил: часть блоков
  // считалась дважды, часть не считалась вовсе, и гейт точности поймал это на малой форме
  // (8.03e+01 и nan вместо 2.07e-04) -- ровно то, ради чего точность меряется ПЕРВОЙ.
  // Здесь канонический вид: сетка режется на группы по SWZ строк M, внутри группы блоки
  // идут по M быстрее, чем по N, поэтому одна плитка веса обслуживает SWZ плиток x.
  constexpr int SWZ = 8;
  const int nb_m = PERSIST ? всего_m : (int)gridDim.y;
  const int nb_n = PERSIST ? всего_n : (int)gridDim.x;
  // При PERSIST номер задачи идёт по N БЫСТРЕЕ: соседние задачи блока делят одну плитку A.
  const int lin = PERSIST ? задача : ((int)blockIdx.y * nb_n + (int)blockIdx.x);
  const int в_группе = SWZ * nb_n;
  const int группа = lin / в_группе;
  const int первая_m = группа * SWZ;
  const int высота = (nb_m - первая_m) < SWZ ? (nb_m - первая_m) : SWZ;   // хвост короче
  const int внутри = lin - группа * в_группе;
  const int by = первая_m + (внутри % высота);
  const int bx = внутри / высота;
  const int m0 = by * BM, n0 = bx * BN;
  if (PERSIST && (m0 >= M || n0 >= N)) continue;
  const int row0 = wm * TM, col0 = wn * TN;

  // Сколько uint4 (по 8 полуслов) на нить в каждой фазе подачи.
  constexpr int AX = (BM * (BK / 8) + THREADS - 1) / THREADS;
  constexpr int BX = (BK * (BN / 8) + THREADS - 1) / THREADS;
  uint4 ra[AX], rb[BX];

  // ---- П1: АДРЕСА СЧИТАЮТСЯ ОДИН РАЗ В ПРОЛОГЕ -----------------------------------------
  // SASS-аудит (20.08) сказал прямо: 21.3 % команд -- IADD/IMAD/LEA, то есть 34.6 команды
  // адресной арифметики НА ОДНУ загрузку, плюс 16 % ветвлений; HMMA при этом 25.4 %. При
  // этом загрузки УЖЕ в тени (медиана расстояния LDG->потребитель 353, коротких нет), то
  // есть память не связывает -- связывают ИЗДЕРЖКИ ВЫДАЧИ. Разложения i/(BK/8) и остаток
  // от него КОНСТАНТНЫ по k0, а считались на каждой итерации K. Здесь они вычисляются один
  // раз, а в цикле остаётся инкремент указателя. Это П1 из плейбука (там дал -92 такта).
  const __half* pga[AX];        // указатель в x для этой нити, двигается на BK за итерацию
  const __half* pgb[BX];        // указатель в w, двигается на BK*N
  int oa[AX], ob[BX];           // смещения в разделяемой -- тоже константы
  // ---- УКАЗАТЕЛИ ЗАЖАТЫ, ПРЕДИКАТОВ НЕТ ------------------------------------------------
  // SASS-аудит лучшего воплощения: branch/pred 20.8 % против HMMA 21.9 %. Половина этого --
  // проверка годности строки/столбца НА КАЖДУЮ загрузку В КАЖДОЙ итерации, хотя годность от
  // k не зависит. Здесь она снята иначе: указатель невалидной строки ЗАЖАТ в последнюю
  // валидную, загрузка идёт всегда. Прочитанный мусор попадёт в свою ячейку накопителя и
  // умрёт там: эпилог этих строк/столбцов НЕ ПИШЕТ, а HMMA считает ячейки независимо.
  // Обмена «правильность на скорость» тут нет -- вывод побитово тот же (гейт точности).
#pragma unroll
  for (int t = 0; t < AX; ++t) {
    const int i = tid + t * THREADS;
    const int r = i / (BK / 8), c8 = i - r * (BK / 8);
    const bool есть = (i < BM * (BK / 8));
    const int rr = есть ? r : 0;
    const int mm = (m0 + rr < M) ? (m0 + rr) : (M - 1);      // зажим по строкам
    oa[t] = есть ? (r * LDA + 8 * c8) : 0;
    pga[t] = x + (long)mm * K + 8 * c8;
  }
#pragma unroll
  for (int t = 0; t < BX; ++t) {
    const int i = tid + t * THREADS;
    const int r = i / (BN / 8), c8 = i - r * (BN / 8);
    const bool есть = (i < BK * (BN / 8));
    const int nn0 = n0 + 8 * c8;
    const int nn = (nn0 + 7 < N) ? nn0 : (N >= 8 ? N - 8 : 0);   // зажим по столбцам
    ob[t] = есть ? (r * LDB + 8 * c8) : 0;
    pgb[t] = w + (long)(есть ? r : 0) * N + nn;
  }

  // ВЫДАЧА ЗАГРУЗОК ОТДЕЛЕНА ОТ ЗАПИСИ В ОБЩУЮ: пока идёт умножение по буферу cur, загрузки
  // следующей плитки уже летят (тот же приём, что в w12a16_hmma и в ядрах внимания).
  // В ЦИКЛЕ -- ТОЛЬКО СМЕЩЕНИЕ ОТ ГОТОВОГО УКАЗАТЕЛЯ. Ни делений, ни остатков, ни
  // пересчёта границ: всё это уже в прологе. `сдвиг` -- номер итерации по K.
  auto подать = [&](int сдвиг) {
#pragma unroll
    for (int t = 0; t < AX; ++t)
      ra[t] = (DIAG == 1) ? make_uint4(0u, 0u, 0u, 0u)
                          : *reinterpret_cast<const uint4*>(pga[t] + (long)сдвиг * BK);
#pragma unroll
    for (int t = 0; t < BX; ++t)
      rb[t] = (DIAG == 1) ? make_uint4(0u, 0u, 0u, 0u)
                          : *reinterpret_cast<const uint4*>(pgb[t] + (long)сдвиг * BK * N);
  };

  auto разложить = [&](int buf) {
    __half* pA = sA + buf * (BM * LDA);
    __half* pB = sB + buf * (BK * LDB);
#pragma unroll
    for (int t = 0; t < AX; ++t) {
      const int i = tid + t * THREADS;
      if (i < BM * (BK / 8) && (DIAG != 3 || tid == 0)) {
        // ДВЕ STS.64, А НЕ ОДНА STS.128: строка sA идёт с дополнением LDA = BK+4 полуслов,
        // то есть 72 байта при BK=32 -- НЕ кратно 16, и запись uint4 даёт misaligned address
        // (поймано сборкой 20.08). Дополнение +4 менять нельзя: это закон против конфликта
        // банков («DK+4», w8a16/GDN). Поэтому ширину записи снижаем до 8 байт -- ровно то же
        // решение, что уже принято в w12a16_hmma.
        __half* q = &pA[oa[t]];
        *reinterpret_cast<uint2*>(q)     = make_uint2(ra[t].x, ra[t].y);
        *reinterpret_cast<uint2*>(q + 4) = make_uint2(ra[t].z, ra[t].w);
      }
    }
#pragma unroll
    for (int t = 0; t < BX; ++t) {
      const int i = tid + t * THREADS;
      if (i < BK * (BN / 8) && (DIAG != 3 || tid == 0))
        *reinterpret_cast<uint4*>(&pB[ob[t]]) = rb[t];
    }
  };

  WarpMma<MB, NB, BLayout::kNMajor> o;
  o.clear();

  // ---- ТЕНЬ ГЛУБИНОЙ В ЦЕЛУЮ ИТЕРАЦИЮ -------------------------------------------------
  // SASS-аудит после выноса адресов: половина загрузок стоит на расстоянии 17-64 команд от
  // потребителя, а промах в HBM стоит 400-800 тактов. Двухстадийный конвейер прячет загрузку
  // за ОДНУ фазу раскладки; трёхстадийный прячет её за ЦЕЛУЮ итерацию, то есть за 256 HMMA.
  // Цена -- второй комплект регистров подачи (AX+BX штук uint4), разлива не даёт.
  uint4 ra2[AX], rb2[BX];
  auto подать2 = [&](int сдвиг) {
#pragma unroll
    for (int t = 0; t < AX; ++t)
      ra2[t] = (DIAG == 1) ? make_uint4(0u, 0u, 0u, 0u)
                           : *reinterpret_cast<const uint4*>(pga[t] + (long)сдвиг * BK);
#pragma unroll
    for (int t = 0; t < BX; ++t)
      rb2[t] = (DIAG == 1) ? make_uint4(0u, 0u, 0u, 0u)
                           : *reinterpret_cast<const uint4*>(pgb[t] + (long)сдвиг * BK * N);
  };
  auto перенять = [&]() {
#pragma unroll
    for (int t = 0; t < AX; ++t) ra[t] = ra2[t];
#pragma unroll
    for (int t = 0; t < BX; ++t) rb[t] = rb2[t];
  };

  const int шагов = (K + BK - 1) / BK;
  подать(0);
  разложить(0);
  if (шагов > 1) подать(1);        // плитка 1 -- в регистрах уже сейчас
  int cur = 0;
  // DIAG=5: фрагменты из РЕГИСТРОВ. Один элемент берётся из разделяемой -- это сток, без
  // которого вся цепочка подачи и раскладки уходит в мёртвый код.
  uint32_t fa5[MB][2], fb5[NB][2];
#pragma unroll
  for (int i = 0; i < MB; ++i) { fa5[i][0] = 0x3C003C00u; fa5[i][1] = 0x3C003C00u; }
#pragma unroll
  for (int j = 0; j < NB; ++j) { fb5[j][0] = 0x3C003C00u; fb5[j][1] = 0x3C003C00u; }

  for (int ш = 0; ш < шагов; ++ш) {
    if (DIAG != 4) __syncthreads();        // буфер cur разложен и виден всем
    const bool есть_ещё = (ш + 1 < шагов);
    // Выдача на ДВА шага вперёд: её потребитель -- раскладка СЛЕДУЮЩЕЙ итерации, а между
    // ними стоит целый accumulate. Это и есть тень длиной в итерацию.
    if (ш + 2 < шагов) подать2(ш + 2);
    if (DIAG == 5) {
      fa5[0][0] ^= (uint32_t)__half_as_ushort(sA[cur * (BM * LDA) + lane]) & 0xFFFFu;
#pragma unroll
      for (int k = 0; k < BK; k += 4) o.mma(fa5, fb5);
    } else if (DIAG != 2)
      o.template accumulate<BK>(sA + cur * (BM * LDA), LDA, row0,
                                sB + cur * (BK * LDB), LDB, col0, lane);
    if (есть_ещё) {
      разложить(cur ^ 1);                  // пишем ДРУГОЙ буфер: второй барьер не нужен
      if (ш + 2 < шагов) перенять();       // плитка ш+2 переезжает в рабочий комплект
    }
    cur ^= 1;
  }

  // ---- ЭПИЛОГ: ПАРАМИ ЧЕРЕЗ half2, А НЕ ПО ОДНОМУ -------------------------------------
  // SASS-аудит лучшего воплощения: HMMA 21.9 %, а branch/pred 20.8 %, F2F 11.3 %, STG 11.0 %
  // -- то есть ЭПИЛОГ стоит дороже мейнлупа по слотам выдачи. Причина видна в раскладке
  // HMMA.884: соседние r дают СОСЕДНИЕ столбцы одной строки
  //   r=0,1 -> col base+0, base+1;  r=2,3 -> те же столбцы строкой ниже;  r=4,5 / r=6,7 -> +4.
  // Значит пара накопителей -- это одно 32-битное слово: одна команда упаковки
  // (__floats2half2_rn) вместо двух F2F и одна запись вместо двух. Плюс общий случай, когда
  // плитка целиком внутри матрицы, идёт БЕЗ проверок границ -- один вопрос на блок вместо
  // 128. Это ровно размен «узкое и много» на «широкое и мало» из плейбука §3.
  const bool плитка_целиком = (m0 + BM <= M) && (n0 + BN <= N);
  const int rb0 = ((lane & 1) | ((lane & 16) >> 2) | (lane & 8));
  const int cb0 = ((lane & 2) | ((lane & 4) << 1));
#pragma unroll
  for (int i = 0; i < MB; ++i)
#pragma unroll
    for (int j = 0; j < NB; ++j)
#pragma unroll
      for (int пара = 0; пара < 4; ++пара) {
        const int r = (пара & 1) * 2 + (пара >> 1) * 4;   // 0, 2, 4, 6
        const int row = rb0 + 2 * ((r >> 1) & 1) + i * 16 + row0;
        const int col = cb0 + 4 * ((r >> 2) & 1) + j * 16 + col0;
        const int mm = m0 + row, nn = n0 + col;
        const __half2 v = __floats2half2_rn(o.acc[i][j][r], o.acc[i][j][r + 1]);
        // ВОПРОС О ГРАНИЦАХ ЗАДАН ОДИН РАЗ НА БЛОК (переменная выше), а не внутри цикла:
        // в общем случае здесь остаётся ровно одна запись без единого ветвления.
        if (плитка_целиком) *reinterpret_cast<__half2*>(&y[(long)mm * N + nn]) = v;
        else if (mm < M) {
          if (nn + 1 < N) *reinterpret_cast<__half2*>(&y[(long)mm * N + nn]) = v;
          else if (nn < N) y[(long)mm * N + nn] = __low2half(v);
        }
      }
  if (!PERSIST) break;
  __syncthreads();          // следующая задача перепишет разделяемую -- все обязаны дочитать
  }
}

