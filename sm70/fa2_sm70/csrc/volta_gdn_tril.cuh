// Выгрузка накопителя в разделяемую ПАРАМИ. Регистры (0,1),(2,3),(4,5),(6,7) карты накопителя лежат
// в ОДНОЙ строке и в СОСЕДНИХ столбцах, а базовый столбец чётен -- значит пара пишется одним
// __half2. Вдвое меньше инструкций MIO, чем у поэлементного visit(): §4kk-девятое ровно про то, что
// узкий доступ к разделяемой -- это дефект, который не виден ни одному счётчику простоя.
// sgn -- множитель (-1 для блоков вида -Y*T), addI -- прибавить единичную матрицу (для сомножителей
// вида I + M^k, которые иначе пришлось бы формировать отдельным проходом).
template <int MB, int NB, BLayout BL>
__device__ __forceinline__ void tril_store(const WarpMma<MB, NB, BL>& m, __half* dst, int ld,
                                           int row0, int col0, int lane, float sgn, bool addI) {
#pragma unroll
  for (int i = 0; i < MB; ++i)
#pragma unroll
    for (int j = 0; j < NB; ++j)
#pragma unroll
      for (int p = 0; p < 4; ++p) {
        const int r = i * 16 + wmma_acc_row(lane, 2 * p);
        const int c = j * 16 + wmma_acc_col(lane, 2 * p);
        float v0 = sgn * m.acc[i][j][2 * p];
        float v1 = sgn * m.acc[i][j][2 * p + 1];
        if (addI) {
          v0 += (r == c) ? 1.f : 0.f;
          v1 += (r == c + 1) ? 1.f : 0.f;
        }
        *reinterpret_cast<__half2*>(&dst[(long)(row0 + r) * ld + col0 + c]) = __floats2half2_rn(v0, v1);
      }
}

// ---------------------------------------------------------------------------------------------
// Диагональный блок 16x16 на HMMA: (I+A_dd)^{-1} = (I+M)(I+M^2)(I+M^4)(I+M^8), M = -A_dd.
// Четыре буфера 16x16, расписание подобрано так, чтобы каждый освобождался ровно к моменту, когда
// нужен следующий результат (иначе буферов требуется пять и разделяемой не хватает на 4 блока/SM):
//   b0=M  b1=I+M | G1: M^2 -> b2,b3=I+M^2 | G2: M^4 -> b0,b2=I+M^4 | G3: B2=b1*b3 -> b1
//   | G4: M^8 -> b3=I+M^8 | G5: B4=b1*b2 -> b1 | G6: B8=b1*b3 -> результат.
// Критический путь -- 4 умножения (G1->G3->G5->G6 и G1->G2->G4->G6), а не 6.
// ---------------------------------------------------------------------------------------------
template <int LDM, int LD16>
__device__ __forceinline__ void tril_diag_mma(__half* sM, int d, __half* b, int lane) {
  __half* b0 = b;
  __half* b1 = b + 16 * LD16;
  __half* b2 = b + 32 * LD16;
  __half* b3 = b + 48 * LD16;
  const int o = 16 * d;

  // M = -tril_strict(A_dd) и I+M за один проход. Маска строго-нижнего повторяет
  // "-tl.where(m_A, ...)" из Triton: ядро не полагается на чистоту верхнего треугольника входа.
  for (int i = lane; i < 64; i += 32) {
    const int r = i >> 2, c = (i & 3) * 4;
    const uint2 raw = *reinterpret_cast<const uint2*>(&sM[(long)(o + r) * LDM + o + c]);
    __half hv[4];
    *reinterpret_cast<uint2*>(hv) = raw;
    __half hw[4];
#pragma unroll
    for (int j = 0; j < 4; ++j) hw[j] = __float2half((c + j < r) ? -__half2float(hv[j]) : 0.f);
    *reinterpret_cast<uint2*>(&b0[r * LD16 + c]) = *reinterpret_cast<uint2*>(hw);
    if (r >= c && r < c + 4) hw[r - c] = __float2half(1.f);
    *reinterpret_cast<uint2*>(&b1[r * LD16 + c]) = *reinterpret_cast<uint2*>(hw);
  }
  __syncwarp();

  WarpMma<1, 1, BLayout::kNMajor> m;
  m.clear(); m.template accumulate<16>(b0, LD16, 0, b0, LD16, 0, lane);   // M^2
  __syncwarp();
  tril_store(m, b2, LD16, 0, 0, lane, 1.f, false);
  tril_store(m, b3, LD16, 0, 0, lane, 1.f, true);
  __syncwarp();
  m.clear(); m.template accumulate<16>(b2, LD16, 0, b2, LD16, 0, lane);   // M^4
  __syncwarp();
  tril_store(m, b0, LD16, 0, 0, lane, 1.f, false);
  tril_store(m, b2, LD16, 0, 0, lane, 1.f, true);
  __syncwarp();
  m.clear(); m.template accumulate<16>(b1, LD16, 0, b3, LD16, 0, lane);   // B2 = (I+M)(I+M^2)
  __syncwarp();
  tril_store(m, b1, LD16, 0, 0, lane, 1.f, false);
  __syncwarp();
  m.clear(); m.template accumulate<16>(b0, LD16, 0, b0, LD16, 0, lane);   // M^8
  __syncwarp();
  tril_store(m, b3, LD16, 0, 0, lane, 1.f, true);
  __syncwarp();
  m.clear(); m.template accumulate<16>(b1, LD16, 0, b2, LD16, 0, lane);   // B4 = B2 (I+M^4)
  __syncwarp();
  tril_store(m, b1, LD16, 0, 0, lane, 1.f, false);
  __syncwarp();
  m.clear(); m.template accumulate<16>(b1, LD16, 0, b3, LD16, 0, lane);   // B8 = B4 (I+M^8)
  __syncwarp();
  tril_store(m, sM, LDM, o, o, lane, 1.f, false);
}

// ---------------------------------------------------------------------------------------------
// Тот же диагональный блок строчной рекурсией в fp32 (как в Triton), полоса l держит столбец l.
//     X[i][:] = -A[i][:] + sum_{k<i} (-A[i][k]) * X[k][:]
// Значение -A[i][k] лежит у полосы k -- берётся ОДНИМ __shfl, без разделяемой памяти вовсе.
// SRC_GLOBAL=true читает вход ИЗ ГЛОБАЛЬНОЙ в fp32 -- задумывалось как "точный" путь. ЗАМЕР ЭТО
// ОПРОВЕРГ: ошибка та же 1.22e-04, что и при чтении округлённого до fp16 входа из sM, зато второй
// проход по глобальной стоит 18% времени. Округление ВХОДА здесь не видно вообще: погрешность
// задаёт округление ВЫХОДА в fp16, и до него ещё далеко. Ветка оставлена как зафиксированный
// отрицательный результат -- в бою берите SRC_GLOBAL=false.
// Полосы 16..31 дублируют 0..15 (col = lane & 15): так адрес заведомо внутри строки чанка, а обмен
// с полосой k<16 даёт всем одно и то же значение.
// ---------------------------------------------------------------------------------------------
template <int LDM, bool SRC_GLOBAL, typename AT = float>
__device__ __forceinline__ void tril_diag_fp32(const AT* __restrict__ Ag, long strideR, int rows,
                                               __half* sM, int d, int lane) {
  const int col = lane & 15, o = 16 * d;
  float X[16];
#pragma unroll
  for (int i = 0; i < 16; ++i) {
    const int r = o + i;
    float a;
    if constexpr (SRC_GLOBAL) a = (r < rows) ? (float)Ag[(long)r * strideR + o + col] : 0.f;
    else                      a = __half2float(sM[(long)r * LDM + o + col]);
    X[i] = (col < i) ? -a : 0.f;                 // строго нижний + смена знака
  }
#pragma unroll
  for (int i = 2; i < 16; ++i) {                 // строки 0 и 1 верны из затравки (см. Triton)
    const float b = X[i];
    float s = b;
#pragma unroll
    for (int k = 1; k < i; ++k) s += __shfl_sync(0xffffffffu, b, k, 32) * X[k];
    X[i] = s;
  }
  if (lane < 16) {
#pragma unroll
    for (int i = 0; i < 16; ++i)
      sM[(long)(o + i) * LDM + o + col] = __float2half(X[i] + ((col == i) ? 1.f : 0.f));
  }
}

// Способ обращения диагональных блоков 16x16 (см. замер в шапке файла).
enum : int { kDiagMma = 0, kDiagRowGmem = 1, kDiagRowSmem = 2 };

// ---------------------------------------------------------------------------------------------
// Ядро. Один блок = одна пара (чанк, голова), 4 варпа. Сетка (NT, B*H).
// DIAG -- см. enum выше; по умолчанию берите kDiagRowSmem, он замеренно быстрейший.
// varlen: chunk_indices[i] = (номер последовательности, локальный номер чанка), как у Triton;
// при nullptr считается одна последовательность длины T.
// ---------------------------------------------------------------------------------------------
// AT -- тип входной Araw (задача 131, парно с volta_gdn_kkt): при fp16 чтение A вдвое легче, а
// конверсий на подаче становится НОЛЬ (sM и так fp16). Точность пути задаёт округление ВЫХОДА Ai
// (замерено в шапке: fp32-чтение диагонали «не даёт ничего»), вход fp16 добавляет тот же класс.
template <int BT, int DIAG, typename AT = float>
__global__ __launch_bounds__(128) void volta_gdn_solve_tril(
    const AT* __restrict__ A,             // [B, T, H, BT] fp32 или fp16, строго нижнетреугольная
    __half* __restrict__ Ai,              // [B, T, H, BT] fp16, пишется ЦЕЛИКОМ (нули верха тоже)
    const int* __restrict__ chunk_indices,
    const int* __restrict__ cu_seqlens,
    int T, int H) {
  static_assert(BT == 64, "ядро рассчитано на чанк 64 (единственный живой размер у Qwen3.5)");
  constexpr int kThreads = 128, kWarps = 4;
  constexpr int PAD = 8;
  constexpr int LDM = BT + PAD;          // 72 полуслова = 144 Б: кратно 16 -> законен uint4
  constexpr int LD16 = 16 + PAD;         // 24
  constexpr int LD32 = 32 + PAD;         // 40
  // Временная область: у тензорного пути -- по 4 буфера 16x16 на варп; у fp32-пути её хватает
  // только под уровень 2. Уровни не пересекаются во времени, поэтому область общая.
  constexpr int SCR = (DIAG == kDiagMma) ? (kWarps * 4 * 16 * LD16) : (32 * LD32);
  static_assert(SCR >= 32 * LD32 && SCR >= 3 * 16 * LD16, "временной области не хватает");

  extern __shared__ __half smem[];
  __half* sM = smem;                     // [BT][LDM] -- сперва A, затем Ai на том же месте
  __half* sS = sM + BT * LDM;

  const int tid = threadIdx.x, lane = tid & 31, warp = tid >> 5;

  int i_n = 0, i_t = blockIdx.x, bos = 0, eos = T;
  if (chunk_indices) { i_n = chunk_indices[2 * blockIdx.x]; i_t = chunk_indices[2 * blockIdx.x + 1]; }
  if (cu_seqlens) { bos = cu_seqlens[i_n]; eos = cu_seqlens[i_n + 1]; }
  const int t0 = i_t * BT;
  const int rows = min(BT, eos - bos - t0);
  if (rows <= 0) return;

  const int ih = blockIdx.y;
  const long strideR = (long)H * BT;
  const long base = ((long)(bos + t0) * H + ih) * BT;
  const AT* Ag = A + base;
  __half* Aig = Ai + base;

  // --- ПОДАЧА. Обходим все 16 четвёрок строки, но ЧИТАЕМ только нижние блоки: строка r берёт
  // 4*(r/16+1) четвёрок, остальное пишется нулём. Так и обнуление верха, и экономия 6 КБ чтения на
  // пару делаются одним проходом без лишнего барьера. Отрезки 64/128/192/256 Б выровнены на 64 Б,
  // то есть каждый запрос кратен сектору -- потерь на гранулярности нет ни в одной из четырёх зон.
  for (int i = tid; i < BT * (BT / 4); i += kThreads) {
    const int r = i >> 4, q = i & 15;
    uint2 v = make_uint2(0u, 0u);
    if (r < rows && q < 4 * ((r >> 4) + 1)) {
      if constexpr (sizeof(AT) == 2) {
        // fp16-вход: та же четвёрка -- одна LDG.64, и ни одной конверсии (sM тоже fp16)
        v = *reinterpret_cast<const uint2*>(&Ag[(long)r * strideR + 4 * q]);
      } else {
        const float4 f = *reinterpret_cast<const float4*>(&Ag[(long)r * strideR + 4 * q]);
        const __half2 lo = __floats2half2_rn(f.x, f.y);
        const __half2 hi = __floats2half2_rn(f.z, f.w);
        v.x = *reinterpret_cast<const uint32_t*>(&lo);
        v.y = *reinterpret_cast<const uint32_t*>(&hi);
      }
    }
    *reinterpret_cast<uint2*>(&sM[r * LDM + 4 * q]) = v;
  }
  __syncthreads();

  // --- УРОВЕНЬ 0: четыре диагональных блока, по одному на варп.
  if constexpr (DIAG == kDiagMma) tril_diag_mma<LDM, LD16>(sM, warp, sS + warp * (4 * 16 * LD16), lane);
  else tril_diag_fp32<LDM, DIAG == kDiagRowGmem>(Ag, strideR, rows, sM, warp, lane);
  __syncthreads();

  // --- УРОВЕНЬ 1: слияние пар (0,1) и (2,3). X_hl = -(X_hh * A_hl) * X_ll.
  // Ассоциация взята как у Triton (-dot(dot(Ai_22, A_21), Ai_11)) -- то же значение, тот же порядок
  // округлений, чтобы расхождение с эталоном нельзя было списать на скобки.
  if ((warp & 1) == 0) {
    const int oh = 16 * (warp + 1), ol = 16 * warp;
    __half* G = sS + warp * (16 * LD16);
    WarpMma<1, 1, BLayout::kNMajor> m;
    m.clear();
    m.template accumulate<16>(sM + oh, LDM, oh, sM + (long)oh * LDM, LDM, ol, lane);
    __syncwarp();
    tril_store(m, G, LD16, 0, 0, lane, 1.f, false);
    __syncwarp();
    m.clear();
    m.template accumulate<16>(G, LD16, 0, sM + (long)ol * LDM, LDM, ol, lane);
    __syncwarp();
    tril_store(m, sM, LDM, oh, ol, lane, -1.f, false);
  }
  __syncthreads();

  // --- УРОВЕНЬ 2: нижний левый блок 32x32. X_ll = -(Y_b * A_ll) * Y_a, оба умножения 32x32x32,
  // выход разбит на четыре плитки 16x16 -- по плитке на варп, ни один не простаивает.
  {
    __half* sG = sS;                               // 32x32, поверх буферов уровня 0
    const int wr = 16 * (warp >> 1), wc = 16 * (warp & 1);
    WarpMma<1, 1, BLayout::kNMajor> m;
    m.clear();
    m.template accumulate<32>(sM + 32, LDM, 32 + wr, sM + 32L * LDM, LDM, wc, lane);
    __syncwarp();
    tril_store(m, sG, LD32, wr, wc, lane, 1.f, false);
    __syncthreads();                               // sG собран целиком; A_ll больше не нужен
    m.clear();
    m.template accumulate<32>(sG, LD32, wr, sM, LDM, wc, lane);
    __syncwarp();
    // Второе умножение читает ТОЛЬКО строки 0..31 (Y_a), а пишем мы в строки 32..63 -- пересечения
    // нет по построению, поэтому лишний барьер перед записью не нужен.
    tril_store(m, sM, LDM, 32 + wr, wc, lane, -1.f, false);
  }
  __syncthreads();

  // --- ВЫГРУЗКА. Весь тайл 64x64 одним проходом uint4: строка -- 128 Б, ровно одна линия, а нули
  // верхнего треугольника едут вместе с данными и снимают отдельный torch.zeros_like (8.2% шага).
  for (int i = tid; i < BT * (BT / 8); i += kThreads) {
    const int r = i >> 3, q = i & 7;
    if (r < rows)
      *reinterpret_cast<uint4*>(&Aig[(long)r * strideR + 8 * q]) =
          *reinterpret_cast<const uint4*>(&sM[r * LDM + 8 * q]);
  }
}

// Размер разделяемой памяти на блок (байты) -- вызывающий обязан задать его в cudaFuncSetAttribute.
template <int BT, int DIAG>
constexpr size_t volta_gdn_solve_tril_smem() {
  return (size_t)(BT * (BT + 8) + ((DIAG == kDiagMma) ? (4 * 4 * 16 * 24) : (32 * 40))) * sizeof(__half);
}

