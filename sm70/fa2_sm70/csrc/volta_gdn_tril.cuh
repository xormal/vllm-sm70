// (ветка merge_16x16_to_64x64_inverse_kernel, единственная живая при BT=64).
//
// ЧТО СЧИТАЕТСЯ. На каждую пару (чанк, голова) дана СТРОГО нижнетреугольная A[64][64] (fp32), нужна
//     Ai = (I + A)^{-1},   выход fp16, весь тайл 64x64 (строго верхний треугольник -- точные нули).
// Диагональ у I+A равна единице ПО ПОСТРОЕНИЮ, поэтому обращение не содержит НИ ОДНОГО ДЕЛЕНИЯ, а
// деление -- самая дорогая операция машины (§4g: 7.3 IPC против 57 у prmt). Структурное избегание
// деления ценнее любого быстрого деления.
//
// ЗАЧЕМ ПЕРЕПИСЫВАТЬ. Замерено (§4qq): Triton при цели sm_70 НЕ ЭМИТИТ тензорных инструкций вообще
// (mma.sync 0, wmma 0, hmma 0, 1024 fma.rn.f32), потолок 3.5 TFLOP/s. Но ЗДЕСЬ это не главный рычаг,
// и это надо сказать честно до постройки: шаг мелкий (79 872 MAC на пару) и упирается в ТРАФИК, а не
// в счёт. Пол по железу: 10 240 Б чтения (только нижние блоки) + 8 192 Б записи = 18 432 Б на пару,
// 108 МБ на боевую форму -> ~0.13 мс при 819 ГБ/с. Triton делает 0.558 мс + 0.067 мс на zeros_like.
// Значит ЦЕЛЬ -- пол по трафику, а тензорные ядра нужны лишь чтобы счёт не стал новым ограничителем.
// Отсюда три решения, и все три -- про трафик, а не про арифметику:
//   1. читаем ТОЛЬКО нижние блоки (10 240 Б вместо полных 16 384: строка r берёт 64*(r/16+1) байт);
//   2. пишем ВЕСЬ тайл, включая нули верхнего треугольника -- это убирает отдельный проход
//      torch.zeros_like (8.2% шага) и позволяет вызывающему брать empty_like;
//   3. одна пара (чанк, голова) = один блок из 4 варпов, а не 8: разделяемой уходит вдвое меньше,
//      блоков на SM вдвое больше, и это ровно то, чем прячется задержка глобальной памяти.
//
// АЛГОРИТМ -- РЕКУРСИВНОЕ БЛОЧНОЕ ОБРАЩЕНИЕ 2x2, а не прямая подстановка Triton.
//     [L11  0 ]^-1   [    Y11      0  ]
//     [L21 L22]    = [ -Y22 L21 Y11  Y22 ]
// Уровень 0: четыре независимых 16x16 (4 варпа параллельно). Уровень 1: две независимые пары.
// Уровень 2: один блок 32x32, разложенный на 4 плитки 16x16 -- снова все четыре варпа.
// У Triton вместо этого прямая подстановка: 16 умножений и цепочка Ai_21 -> Ai_31 -> Ai_41 длиной 3.
// У нас 20 умножений (на 25% больше работы), зато глубина после уровня 0 равна ДВУМ, и на каждом
// уровне заняты все варпы. Мы меняем лишнюю работу на короткую цепь -- правильный размен там, где
// ограничитель это ЗАДЕРЖКА, а не счёт (тензорная доля здесь ~10% от пола по трафику).
//
// ДИАГОНАЛЬНЫЙ БЛОК 16x16 -- ТРИ ПУТИ СОБРАНЫ И ЗАМЕРЕНЫ. ТЕНЗОРНЫЙ ПРОИГРАЛ, И ЭТО РЕЗУЛЬТАТ.
// (V100 GPU0 @1530, T=15680 H=24, усечённое среднее по 50 запускам; отн.ошибка у всех трёх ОДНА
//  И ТА ЖЕ -- 1.22e-04, то есть половина ulp fp16 выхода: арифметика ни у одного не является
//  источником погрешности, её задаёт формат выхода.)
//   kDiagMma=0     квадрирование на HMMA ...... 0.2471 мс  439 ГБ/с  46 рег, 21.0 КБ, 16 варп/SM
//   kDiagRowGmem=1 рекурсия fp32, вход из гло... 0.2102 мс  516 ГБ/с  32 рег, 11.5 КБ, 32 варп/SM
//   kDiagRowSmem=2 рекурсия fp32, вход из sM ... 0.1784 мс  608 ГБ/с  32 рег, 11.5 КБ, 32 варп/SM <-
// ПОЧЕМУ ТЕНЗОРНЫЙ ПУТЬ ХУЖЕ НА 38%, хотя вся его работа идёт по конвейеру в 30 раз быстрее:
//   * полезной работы в блоке 16x16 всего 1904 MAC, а возведение в квадрат тратит 24 576 -- в 13 раз
//     больше. Там, где счёт не является ограничителем, лишний счёт нельзя разменять ни на что;
//   * ему нужно 4 буфера 16x16 на ВАРП = 12 КБ разделяемой на блок сверх тайла. Это роняет число
//     блоков на SM с 8 до 4, то есть ВДВОЕ режет ровно тот ресурс, которым прячется задержка
//     глобальной памяти -- единственный настоящий ограничитель шага.
// Это тот самый случай из §4u: тензор дёшев для МЕЖПОЛОСНОЙ работы и не окупается на мелкой.
// Второй замер того же рода: чтение диагонали из ГЛОБАЛЬНОЙ в fp32 ради точности стоит 18% и НЕ
// ДАЁТ НИЧЕГО -- ошибка та же 1.22e-04, потому что её задаёт округление выхода, а не входа.
// Тензорные ядра остались там, где они и правда дёшевы: уровни 1 и 2 (20 умножений 16^3 из 24).
//
// РАСКЛАДКА ОПЕРАНДОВ -- ПРОТИВОПОЛОЖНА ИНТУИЦИИ ИМЕНИ, сверено с enum в volta_warp_mma.h:
//   kKMajor: B это [N][K], непрерывен K  -> инструкция .row.col  (случай Q*K^T)
//   kNMajor: B это [K][N], непрерывен N  -> инструкция .row.row  (случай P*V)
// У нас ВСЕ матрицы лежат построчно (row-major), а свёртка всегда идёт по "столбцу A / строке B" --
// значит A всегда kKMajor, B всегда kNMajor. Ни одной перекладки не требуется ни на одном уровне;
// это и есть причина, по которой рекурсия 2x2 ложится на готовый оператор без единой транспозиции.
//
// ДОПОЛНЕНИЕ СТРОКИ. LDM = 64 + 8 полуслов = 144 Б: кратно 16, значит законны uint4 и на чтении из
// разделяемой в эпилоге, и на записи в глобальную (§4a/§4b). Банки при этом двухпутевые с обеих
// сторон -- дополнение +4 дало бы бесконфликтный операнд A, но конфликт 4x у операнда B и запретило
// бы uint4; выбран симметричный компромисс, потому что ядро упирается в глобальную, а не в MIO.
//
// ИТОГ ЗАМЕРА (V100 GPU0, T=15680 H=24 BT=64, сетка 5880 блоков по 128 нитей, занятость 50%:
// 8 блоков на SM по 4 варпа, 32 регистра, 11.5 КБ разделяемой):
//   triton solve_tril целиком ......... 0.6254 мс  (из них torch.zeros_like 0.0673)
//   triton, только ядро ............... 0.5580 мс
//   НАШЕ (kDiagRowSmem) ............... 0.1733 мс  ->  x3.61 к полному вызову, x3.22 к ядру
//   пол ЭТОГО ЖЕ шаблона доступа ...... 0.1692 мс  (то же ядро без счёта: только загрузки/выгрузки)
// То есть ВСЯ арифметика обращения стоит 5.4% сверх транспорта: ядро стоит НА СВОЁМ ПОЛУ, и дальше
// двигать можно только сам шаблон доступа (640 ГБ/с против 819 потоковых -- цена того, что строки
// чанка разнесены в памяти на 6144 Б, а нужные отрезки в них по 64..256 Б).
// Ошибка 1.22e-04 -- ровно та же, что у Triton на тех же данных против fp64-эталона.
#pragma once
#include <cuda_fp16.h>
#include <cuda_runtime.h>
#include "volta_warp_mma.h"

