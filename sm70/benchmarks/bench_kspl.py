НАЗВАНИЕ = {7: "расщ", 5: "WN=2"}
ЗАПАС = 256              # запас ЗА видом -- ядро читает плитками за конец Sk


def кв(x, T, d):
    """[1, T, Hkv, d] fp16 -> (int8 головно-мажорно [Hkv,T,d], масштаб на позицию [Hkv,T])."""
    y = x[0].permute(1, 0, 2).contiguous()               # [Hkv, T, d]
    Hkv = y.size(0)
    a = y.abs().amax(-1, keepdim=True).float() / 127.
    q = torch.clamp(torch.round(y.float() / a), -127, 127).to(torch.int8)
    пл = torch.zeros(Hkv * (T + ЗАПАС) * d, dtype=torch.int8, device=x.device)
    плс = torch.zeros(Hkv * (T + ЗАПАС), dtype=torch.float32, device=x.device)
    kq = пл[:Hkv * T * d].view(Hkv, T, d)
    ks = плс[:Hkv * T].view(Hkv, T)
    kq.copy_(q); ks.copy_(a.squeeze(-1))
    return kq, ks, пл, плс


def таблица_масштабов(fmt, Ks, Vs, T):
    """РАСКЛАДКУ ТАБЛИЦЫ ЗАДАЁТ ФОРМАТ, А НЕ УДОБСТВО ВЫЗЫВАЮЩЕГО.

    [НАЙДЕНО ЗАМЕРОМ 16.08.2026] Формат 0 читает ДВА раздельных массива [Hkv, T]. Формат 8 читает
    ОДИН ЧЕРЕДУЮЩИЙСЯ (`float2` на позицию: k-масштаб, v-масштаб), и хост потому удваивает шаги
    ks_sH/ks_sB. Прежний стенд (`bench_ws_boevaya.py`) подавал формату 8 раздельные массивы -- то
    есть ядро брало масштабы из чужих слов и читало за конец головы. По ВРЕМЕНИ это не видно (та же
    работа, те же обращения), поэтому дефект прожил весь цикл замеров; вылез он первой же СВЕРКОЙ
    ОТВЕТА, где известно-верная база разошлась с fp32-эталоном на 880 %.
    """
    if fmt != 8:
        return Ks, Vs
    Hkv, _ = Ks.shape
    пл = torch.zeros(Hkv * (T + ЗАПАС) * 2, dtype=torch.float32, device=Ks.device)
    в = пл[:Hkv * T * 2].view(Hkv, T, 2)
    в[..., 0] = Ks; в[..., 1] = Vs
    return пл, пл


def эталон(Kq, Ks, Vq, Vs, Q, scale, causal, h_od_raz=True):
    """fp32-внимание ПО РАЗВЁРНУТЫМ int8 -- независимый путь, голова за головой.

    Считается по головам, потому что на боевой форме матрица S это 4096x46002 на голову: держать
    все H сразу негде, а по одной -- 0.75 ГБ, и они переиспользуют один буфер.
    """
    B, Sq, H, D = Q.shape
    Hkv, Sk, _ = Kq.shape
    kv_ratio = H // Hkv
    off = (Sk - Sq) if causal else 0
    O = torch.empty(B, Sq, H, D, dtype=torch.float16, device=Q.device)
    L = torch.empty(B, H, Sq, dtype=torch.float32, device=Q.device)
    строки = torch.arange(Sq, device=Q.device).unsqueeze(1)
    столбцы = torch.arange(Sk, device=Q.device).unsqueeze(0)
    маска = (столбцы > строки + off) if causal else None
    for h in range(H):
        hkv = h // kv_ratio
        k = Kq[hkv].float() * Ks[hkv].unsqueeze(-1)
        v = Vq[hkv].float() * Vs[hkv].unsqueeze(-1)
        q = Q[0, :, h, :].float()
        s = (q @ k.t()) * scale
        if маска is not None:
            s = s.masked_fill(маска, float("-inf"))
        m = s.amax(-1, keepdim=True)
        m = torch.where(torch.isinf(m), torch.zeros_like(m), m)
        p = torch.exp(s - m)
        l = p.sum(-1, keepdim=True)
        O[0, :, h, :] = ((p @ v) / l).half()
        L[0, h] = (m.squeeze(-1) + torch.log(l.squeeze(-1)))
        del k, v, q, s, p
    return O, L


def relL2(a, b):
    a = a.float(); b = b.float()
    return ((a - b).norm() / b.norm().clamp_min(1e-30)).item()


def замер(f, n=9):
    for _ in range(4):
        f()
    torch.cuda.synchronize()
    т = []
    for _ in range(n):
        t0 = time.perf_counter(); f(); torch.cuda.synchronize()
        т.append(time.perf_counter() - t0)
    т.sort()
    return sum(т[2:-2]) / len(т[2:-2]) * 1e3


def прогон(ext, форма, эталонить, мерить, fmt=0, вариант=7, имя_в="расщ"):
    Sq, Sk, H, Hkv, D, causal = форма
    torch.manual_seed(0)
    # ДАННЫЕ ПОРОЖДАЮТСЯ ОДИН РАЗ НА ФОРМУ. Сравнивать два варианта на разных случайных числах
    # (генератор ушёл вперёд) -- уже стоило нам недействительного вердикта о корректности.
    # РАЗМАХ ЛОГИТОВ ВЫБРАН, А НЕ УНАСЛЕДОВАН: при Q~0.5 и K~0.5 станд.откл. логита 0.25, софтмакс
    # почти равномерен, O = среднее нулевых по среднему V, то есть |O| ~ 0.03|V| -- ОТНОСИТЕЛЬНАЯ
    # мера на таких данных вырождена. Берём q=4.0: |s| ~ 2 (боевой замер даёт до 56), софтмакс
    # ПИКОВЫЙ, и |O| становится сравним с |V|.
    Q = (torch.randn(1, Sq, H, D, device="cuda") * 4.0).half()
    K = (torch.randn(1, Sk, Hkv, D, device="cuda") * 0.5).half()
    V = (torch.randn(1, Sk, Hkv, D, device="cuda") * 0.5).half()
    Kq, Ks, _kb, _sb = кв(K, Sk, D)
    Vq, Vs, _vb, _vsb = кв(V, Sk, D)
    del K, V
    масштаб = 1.0 / (D ** 0.5)
    Kt, Vt = таблица_масштабов(fmt, Ks, Vs, Sk)
    зов = lambda n: ext.attn_fwd_volta_i8(Q, Kq.unsqueeze(0), Kt.unsqueeze(0),          # noqa: E731
                                          Vq.unsqueeze(0), Vt.unsqueeze(0),
                                          масштаб, causal, n)
    БАЗА, РАСЩ = fmt, вариант * 100 + fmt
    имя = f"ф{fmt}/в{вариант} Sq={Sq} Sk={Sk} H={H} Hkv={Hkv}{' прич.' if causal else ''}"
    Ob, Lb = зов(БАЗА)
    Ok, Lk = зов(РАСЩ)
    равно = torch.equal(Ob, Ok)
    d_bk = relL2(Ok, Ob)
    # ПОБИТОВОЕ РАВЕНСТВО ЗДЕСЬ -- НЕ УСПЕХ, А ТРЕВОГА. Расщепление меняет порядок суммирования
    # fp32 И аргумент exp2 (максимум берётся по СВОЕЙ полосе, а не по плитке), поэтому совпасть
    # бит в бит оно не может. Совпало -- значит собрался не тот шаблон и зонд НЕ В ПУТИ.
    стр = f"{имя:<36s} база<->{имя_в} relL2 {d_bk:.2e}" + (
        "  <<< ТРЕВОГА: ПОБИТОВО РАВНО, зонд вне пути" if равно else "")
    if эталонить:
        Oe, Le = эталон(Kq, Ks, Vq, Vs, Q, масштаб, causal)
        rb, rk = relL2(Ob, Oe), relL2(Ok, Oe)
        lb, lk = relL2(Lb, Le), relL2(Lk, Le)
        # ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ ПРИБОРА: `база` -- известно-верное отгруженное ядро. Если ОНА
        # разошлась с эталоном, сломан ЭТАЛОН, и вердикт по расщеплению недействителен целиком.
        # Именно так и вскрылась подмена раскладки таблицы масштабов у формата 8.
        приговор = ("ПРИБОР СЛОМАН (база сама мимо)" if rb > 5e-2
                    else "ВЕРНО" if rk < max(3 * rb, rb + 2e-3) else "НЕВЕРНО")
        стр += f"\n{'':<36s} к fp32-эталону: база {rb:.2e}  {имя_в} {rk:.2e}  -> {приговор}"
        стр += f"   | LSE: база {lb:.2e} расщ {lk:.2e}"
    print(стр)
    if мерить:
        видно = ((Sk - Sq) * Sq + Sq * (Sq + 1) / 2) if causal else (Sq * Sk)
        флоп = 2 * 2 * видно * H * D
        # ПАРНЫЕ ОТНОШЕНИЯ С ЧЕРЕДОВАНИЕМ ВНУТРИ РАУНДА, медиана ОТНОШЕНИЙ, а не отношение медиан.
        отн = []
        for _ in range(5):
            tb = замер(lambda: зов(БАЗА), 5)
            tk = замер(lambda: зов(РАСЩ), 5)
            отн.append(tb / tk)
        отн.sort()
        tb = замер(lambda: зов(БАЗА)); tk = замер(lambda: зов(РАСЩ))
        print(f"{'':<36s} база {tb:7.2f} мс ({флоп/(tb/1e3)/1e12:5.1f} ТФЛОП/с, {флоп/(tb/1e3)/1e12/93.6:5.1%} пика)"
              f"   {имя_в} {tk:7.2f} мс ({флоп/(tk/1e3)/1e12:5.1f})"
              f"   ОТНОШЕНИЕ {отн[len(отн)//2]:.4f} (размах {отн[0]:.4f}..{отн[-1]:.4f})")
        # ФАЛЬСИФИКАТОР ПЕРЕМАСШТАБИРОВАНИЯ, ПАРНЫЙ. Ответ НЕВЕРЕН, читается только доля фазы.
        # Он и решает, куда переехало ожидание: при расщеплении накопитель на варп вчетверо шире,
        # и та же строка трогает 128 регистров вместо 32 -- В ЦЕПИ между двумя умножениями.
        try:
            if вариант != 7:
                raise RuntimeError("фальсификатор перемасштабирования заведён только для варианта 7")
            tbn = замер(lambda: зов(900 + fmt)); tkn = замер(lambda: зов(800 + fmt))
            print(f"{'':<36s} БЕЗ перемасштабирования (ответ неверен): база {tbn:7.2f} "
                  f"(доля {1 - tbn/tb:5.1%})   расщ {tkn:7.2f} (доля {1 - tkn/tk:5.1%})")
        except Exception as e:  # noqa: BLE001
            print(f"{'':<36s} фальсификатор не собран: {str(e)[:60]}")
    del Q, Kq, Ks, Vq, Vs, _kb, _sb, _vb, _vsb
    torch.cuda.empty_cache()


ФОРМЫ_СВЕРКИ = [
    (256,  1024,  4, 2, 256, True),    # короткая, диагональ весит много
    (512,  2048,  4, 1, 256, True),    # MQA
    (512,  2048,  4, 4, 256, False),   # без маски
    (1024, 1024,  2, 2, 256, True),    # квадрат: первая плитка ключей у части варпов ПУСТА
    (4096, 16384, 2, 1, 256, True),    # боевая пропорция, H урезано ради памяти эталона
]
ФОРМЫ_ВРЕМЕНИ = [
    (4096, 4096,  24, 4, 256, True),
    (4096, 16384, 24, 4, 256, True),
    (4096, 46002, 24, 4, 256, True),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tolko-svera", action="store_true")
    ap.add_argument("--fmt", default="0,8", help="0 -- ОТГРУЖЕННЫЙ формат, 8 -- чередующаяся таблица")
    ap.add_argument("--variant", type=int, default=7, help="7 -- расщепление по ключам, 5 -- WN=2")
    a = ap.parse_args()
    ext = fa2_sm70._ext.prefill_ext()
    форматы = [int(x) for x in a.fmt.split(",")]
    print("=== СВЕРКА ОТВЕТА (эталон -- torch fp32 по развёрнутым int8, ДРУГОЙ путь) ===")
    for fmt in форматы:
        for ф in ФОРМЫ_СВЕРКИ:
            прогон(ext, ф, эталонить=True, мерить=False, fmt=fmt, вариант=a.variant,
                   имя_в=НАЗВАНИЕ.get(a.variant, f"в{a.variant}"))
    if a.tolko_svera:
        return 0
    print("\n=== ВРЕМЯ НА БОЕВОЙ ФОРМЕ (Sq=4096 фиксировано, ключи копятся) ===")
    for fmt in форматы:
        for ф in ФОРМЫ_ВРЕМЕНИ:
            прогон(ext, ф, эталонить=False, мерить=True, fmt=fmt, вариант=a.variant,
                   имя_в=НАЗВАНИЕ.get(a.variant, f"в{a.variant}"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
