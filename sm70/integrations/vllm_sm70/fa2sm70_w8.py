def _tm8_podgotovit_sloy(layer, v2: bool) -> bool:
    """Строит tm8-pack для слоя и вешает НА СЛОЙ (идентичность по владению, урок 137).
    Возвращает True при успехе; бюджет памяти уважается молча."""
    qw, qz, sc = layer.qweight, layer.qzeros, layer.scales
    k = qw.shape[0] * 4
    n = qw.shape[1]
    g = k // 128
    if g * 128 != k or sc.shape[0] != g or n % 4 != 0:
        return False                       # плитки собраны под g=128
    nbytes = k * n + g * n * 4
    # [ОТБОР ПО ПРИЗУ НА БАЙТ 25.08] Упаковка tm8 -- ВТОРАЯ копия веса, и бюджет конечен.
    # Замер при M=8 (см. _tm8_mm): широкий выход даёт x1.86 (gate_up) и x1.36 (in_proj_qkv),
    # узкий -- x1.08..1.10 (down, out_proj), то есть почти ничего за те же байты. Порог по N
    # тратит бюджет туда, где он окупается. FA2SM70_TM8_NMIN=0 снимает отбор.
    #
    # [31.08] ПОРОГ ДЕРЖИТ НЕ ТОЛЬКО БЮДЖЕТ, НО И КОРРЕКТНОСТЬ -- ПРОВЕРЕНО ПОДЪЁМОМ.
    # С подобранными splits/log_tile tm8 обгоняет gemv и на узких формах (M=4: down 153/122,
    # out_proj 41/32), поэтому порог выглядел устаревшим. Но:
    #   NMIN=0    -> подъём падает: `CUDA error: an illegal memory access` (и с включённым
    #                подбором, и с выключенным -- значит виновата САМА упаковка узких форм);
    #   NMIN=5120 -> подъём проходит, но tm8 не используется НИ РАЗУ (ноль строк в журнале),
    #                и сквозняк падает до 24.6 мс/ток против 21.9-23.7 у базы;
    #   NMIN=7168 -> работает как 8192: qkv (N=7168) всё равно не наш слой, он идёт чужим
    #                torch.mm в fp16 на 87 % тензорного пика.
    # Значит 8192 остаётся. Чтобы опустить порог, надо сперва починить упаковку узких форм.
    #
    # [31.08, ПОЗЖЕ] ОПРОВЕРЖЕНИЕ ВЫВОДА ВЫШЕ -- УПАКОВКА НЕ ВИНОВАТА, И УЗКИХ ФОРМ НЕТ.
    # Журнал упаковки (FA2SM70_TM8_PACKLOG=1) показал: при NMIN=0 пакуются РОВНО ЧЕТЫРЕ формы,
    # и самая узкая -- N=5120. Никаких «узких форм» в модели нет вовсе, чинить было нечего.
    # Настоящая причина падения -- КЭШ КОМПИЛЯЦИИ vLLM: его ключ не включает наши рычаги, а
    # inductor запекает число измерений аргументов (упакованному слою -- двумерный tm_w,
    # непокрытому -- одномерная пустышка). Смена NMIN меняет, кому достанется пустышка, и
    # старый граф получает аргумент другой структуры. Лечение -- в пускаче (отпечаток рычагов
    # в VLLM_CACHE_ROOT), доказано положительным контролем: последовательность NMIN=0 -> база,
    # ронявшая подъём, проходит, гейт 391 пройден.
    # Отдельно ЗАМЕРЕНО, что порог опускать НЕ НАДО: сквозной декод при NMIN=0 хуже базы на
    # 24 % (62.6 против ~50 мс/ток, ABBA с возвратом к базе на дрейфе +11.7 %). Причина видна
    # в замере ниже: при M=4 tm8 на down/out_proj медленнее нашего gemv (153 против 122),
    # а `_TM8_ONLY` освобождает исходную раскладку и запирает эти формы на tm8 навсегда.
    if n < _TM8_NMIN:
        return False
    if _TM8_BUDGET[0] - nbytes < 0:
        return False
    ext = _расш_tm8()
    # [ДИАГНОСТИКА УПАКОВКИ] Печатаем форму ДО работы: при NMIN=0 подъём падает с illegal
    # memory access, и надо знать, на какой именно форме -- а не гадать по последней строке.
    if os.environ.get("FA2SM70_TM8_PACKLOG", "0") == "1":
        print(f"[fa2_sm70 TM8 pack] K={k} N={n} g={g} nbytes={nbytes}", file=sys.stderr, flush=True)
    w_u8 = torch.stack([(qw >> (8 * j)) & 0xFF for j in range(4)], dim=1)         .reshape(k, n).to(torch.uint8)
    w_u16 = w_u8.t().contiguous().to(torch.int16)
    del w_u8
    z_i = torch.stack([(qz >> (8 * j)) & 0xFF for j in range(4)], dim=2).reshape(g, n)
    z = (z_i + (0 if v2 else 1)).to(torch.float16)    # условность нуля -- у СЛОЯ
    tm_w, tm_s, meta = ext.prepare(w_u16, sc.contiguous(), z.contiguous(), 128)
    del w_u16, z_i, z
    layer.fa2sm70_tm8 = (tm_w, tm_s, int(meta[0]), int(meta[1]))
    # [ПРОГРЕВ ПОДБОРА -- ВНЕ ГОРЯЧЕГО ПУТИ] Подбор (splits, log_tile) сам по себе дёшев
    # (28 проб на форму), но делать его в первом боевом запросе -- значит платить задержкой
    # там, где её видит клиент. Здесь форма уже упакована, буферы под рукой, и кэш ключуется
    # по (K, N, M): четыре уникальные формы x четыре боевых M -- десятки миллисекунд на весь
    # подъём. Ошибка прогрева не должна ронять загрузку: подбор -- ускорение, а не условие.
    if not _ТЮН_ВЫКЛ and os.environ.get("FA2SM70_TM8_TUNE_WARM", "1") == "1":
        try:
            for _m in (1, 2, 4, 8, 16, 32, 64):
                _кл = (k, n, _m)
                if _кл in _ТЮН:
                    continue
                _x = torch.zeros((_m, k), dtype=torch.float16, device=tm_w.device)
                _y = torch.empty((_m, n), dtype=torch.float16, device=tm_w.device)
                _подобрать(_y, _x, tm_w, tm_s, 128, int(meta[0]), int(meta[1]),
                           6 if _m <= 16 else 2, _кл)
                del _x, _y
        except Exception as _ex:                      # noqa: BLE001
            print(f"[fa2_sm70 TM8] прогрев подбора пропущен: {type(_ex).__name__}",
                  file=sys.stderr, flush=True)
    if _TM8_ONLY:
        # Исходная раскладка больше не нужна: все зоны M закрыты tm8. Освобождаем СРАЗУ,
        # чтобы пик держался на одной упаковке, а не на всей модели.
        #
        # [ВОЗВРАТ ДРАЙВЕРУ, А НЕ В КЭШ -- ИНАЧЕ ПЛАТИТ KV-ПУЛ]
        # `del` отдаёт блок КЭШИРУЮЩЕМУ РАСПРЕДЕЛИТЕЛЮ торча, а движок считает свободную память
        # драйвером (`mem_get_info`) -- освобождённое, но закэшированное, для него ЗАНЯТО. При
        # замене всей модели это 4.3 ГиБ на ранг, и ровно на столько сжимается пул KV. Признак
        # был читаем: профилировщик отдавал 98 304 токена там, где модель занимает лишь половину
        # карты. Чистка стоит миллисекунды на слой и делается ОДИН РАЗ на подъёме.
        # `qweight` -- nn.Parameter, присвоить голый тензор нельзя: только Parameter или None.
        layer.qweight = torch.nn.Parameter(
            torch.empty(0, qw.shape[1], dtype=qw.dtype, device=qw.device), requires_grad=False)
        del qw
        torch.cuda.empty_cache()          # вернуть ДРАЙВЕРУ, а не оставить в кэше торча
        _TM8_BUDGET[0] += nbytes          # байты вернулись: замена, а не добавка
    _TM8_BUDGET[0] -= nbytes
    _TM8_ПОКРЫТО[0] += 1
    _TM8_ПОКРЫТО[1] += nbytes
    return True


def _perestanovka_tozhdestvennaya() -> bool:
    """ПРОВЕРЯЕМ ИСПОЛНЯЕМО, А НЕ ВЕРИМ ЗАМЕРУ ПРОШЛОЙ НЕДЕЛИ.

    Помечаем каждый байт номером его строки k, прогоняем через `gptq_shuffle` и смотрим, сдвинулось
    ли что-нибудь. Стоит один раз на подъём. Если движок сменит раскладку, подмена молча выключится
    вместо того, чтобы молча считать мусор -- это разница между «медленнее» и «неверно».
    """
    try:
        from vllm import _custom_ops as ops
        K, N = 32, 4
        qw = torch.zeros(K // 4, N, dtype=torch.int32, device="cuda")
        for w in range(K // 4):
            for b in range(4):
                qw[w, :] |= ((4 * w + b) & 0xFF) << (8 * b)
        до = qw.clone()
        ops.gptq_shuffle(qw, torch.empty(0, dtype=torch.int32, device="cuda"), 8)
        return bool(torch.equal(до, qw))
    except Exception:  # noqa: BLE001
        return False


