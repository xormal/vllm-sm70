    # [TM8] Трёхзонная операция для слоёв с pack'ом: gemv | tm8 | чужое. Ветвление по M --
    # внутри тела (форма здесь конкретна). Выбор плитки по замеру 18.08: M<=32 -> v4 (32x128),
    # выше -> v2 (64x256).
    def _tm8_mm(x: torch.Tensor, qw: torch.Tensor, qz: torch.Tensor, sc: torch.Tensor,
                gi: torch.Tensor, tm_w: torch.Tensor, tm_s: torch.Tensor, group: int,
                v2: bool, mmax: int, k_ld: int, q_ld: int, tm8_mmax: int) -> torch.Tensor:
        m = x.shape[0]
        # [ВАРИАНТ 4 ПЕРЕБОРА 14.09] большой M: reconstruct+cuBLAS вместо плитки tm8 (см. _recon_mm)
        if _RECON_MMIN and m >= _RECON_MMIN and tm_w.numel() > 0 and qz.numel() > 0 and sc.numel() > 0:
            y = _recon_mm(x, tm_w, qz, sc, v2, int(tm_s.shape[1]))
            if y is not None:
                return y
        # [ЗОНА СПЕКУЛЯЦИИ 25.08] M = k+1 -- НЕ ЗОНА gemv.
        # Наше gemv-тело стоит на крыше ЧТЕНИЯ только при M=1, дальше оно уходит на скалярный
        # конвейер: замер (одни и те же веса, чистая карта, мкс)
        #     gate_up 5120x17408   M=1/2/4/8:  119 / 125 / 199 / 274   при крыше чтения 114
        #     tm8 v6                           124 / 122 / 123 / 123   -- ПЛОСКОЕ, 93 % крыши
        #     gdn_in  5120x5120    gemv 44/50/60/103   tm8 72/72/72/72
        #     down    8704x5120    gemv 64/71/83/145   tm8 118 (плоское)
        # Причина структурная и записана в шапке w8a16_hmma.cuh: при M>1 счёт FFMA (8*K*N на
        # скалярном конвейере 15.7 TFLOPS) перестаёт прятаться под чтение, а tm8 считает на
        # ТЕНЗОРНЫХ (93.6 TFLOPS) и остаётся связан чтением. Спекулятивный декод идёт ИМЕННО
        # при M=k+1, поэтому эта зона -- главная статья шага, а не редкий край.
        # Точность сверена на одних весах: relL2 4.6e-4..4.8e-4 (тот же порядок, что записан у tm8).
        # ПРАВИЛО ЗОНЫ ПО ЗАМЕРУ (чистая карта, боевые формы, мкс; ЧУЖОЕ / tm8 v6):
        #   gate_up 5120x17408  M=1 117/126  M=4 166/123  M=8 231/124  M=16 422/157
        #   gdn_in  5120x8192   M=1  59/81   M=4  80/80   M=8 109/80   M=16 202/99
        #   down    8704x5120   M=1  77/122  M=4  89/119  M=8 128/119  M=16 222/158
        #   out_proj 3072x5120  M=1  31/47   M=4  35/45   M=8  50/45   M=16  97/58
        # tm8 ПЛОСКОЕ по M (тензорные ядра, связано чтением), чужое растёт линейно. Отсюда:
        # с M=8 tm8 выигрывает везде; с M=4 -- только на широком выходе (N>=16384).
        _только = qw.numel() == 0                      # исходной раскладки нет -- только tm8
        # [29.08] ПРАВИЛО ЗОНЫ M=4 ПЕРЕСМОТРЕНО: сравнивать надо было НАШ gemv с tm8, а не
        # ЧУЖОЕ тело с tm8. Прежнее правило («tm8 при M=4 только если N>=16384») выведено из
        # таблицы «чужое / tm8», где при N<16384 был паритет -- но в бою при M=4 работает НЕ
        # чужое, а наш gemv, и он ТАМ ХУЖЕ. Замер 29.08 (чистая карта, мкс, gemv / tm8):
        #     qkv     5120x7168   M=4  101.7 / 82.0   -> tm8 быстрее в 1.24
        #     gdn_in  5120x8192   M=4  106.6 / 84.0   -> tm8 быстрее в 1.27
        #     gate+up 5120x17408  M=4  204.9 / 127.3  -> tm8 быстрее в 1.61  (и раньше брался)
        #     down   17408x5120   M=4  240.9 / 252.3  -> gemv быстрее, tm8 НЕ брать
        #     out_proj 3072x5120  M=4   42.1 /  48.9  -> gemv быстрее, tm8 НЕ брать
        # Разделитель по замеру: tm8 выигрывает там, где выход ШИРЕ входа и не узок.
        #
        # [30.08] ПОРОГ ПОДНЯТ 7168 -> 10240, ПОТОМУ ЧТО ПРАВИЛО ПЕРЕЖИЛО СВОЮ ПРИЧИНУ.
        # Прежний порог выведен 29.08, ДО того как gemv при M=4 ускорился шириной колонок.
        # Свежий замер (K=5120, M=4, чистая карта, мкс, gemv / tm8):
        #     N= 7168   75.0 /  82.1  -> gemv     N=12288  152.1 / 114.7  -> tm8
        #     N= 8192   79.5 /  84.2  -> gemv     N=14336  189.8 / 118.1  -> tm8
        #     N=10240  143.3 /  89.6  -> tm8      N=17408  215.0 / 124.7  -> tm8
        # Граница между 8192 и 10240 -- берём 10240. При старом пороге qkv (N=7168) и
        # gdn_in (N=8192) уходили в tm8, где они на 6-9 % МЕДЛЕННЕЕ нашего gemv.
        # Лестница вариантов при этом проверена целиком (v=1..14 на пяти боевых формах):
        # v=6 оптимален и при M=1, и при M=4, следующий лучший хуже на 55-70 %.
        # K берём ИЗ ВХОДА, а не из формы упакованного веса: у части слоёв исходной раскладки
        # нет вовсе, и `qw.shape[0]` там роняет воркер (IndexError: tuple index out of range --
        # поймано подъёмом 29.08). Вход есть всегда.
        _tm8_zona4 = (tm_s.dim() > 1 and tm_s.shape[1] >= _TM8_N4
                      and x.shape[-1] <= tm_s.shape[1])
        # [31.08] ЗОНА ПЕРЕСЧИТАНА ПОСЛЕ ПОДБОРА splits/log_tile -- ПРЕЖНЯЯ ОПИРАЛАСЬ НА
        # ЯДРО, КОТОРОЕ РАБОТАЛО ВПОЛСИЛЫ. Старое правило выводилось при splits=1, где tm8
        # проигрывал gemv на узких формах. С подобранными осями (замер, M=4, мкс, gemv / tm8):
        #     qkv  76 / 60     gdn_in 79 / 65    gate_up 194 / 121
        #     down 153 / 122   out_proj 41 / 32
        # то есть tm8 быстрее ВЕЗДЕ при M>=4, от x1.22 до x1.60. При M=1 картина смешанная
        # (gate_up 169/121 за tm8, qkv 56/59 и gdn_in 62/67 за gemv), поэтому там зона по
        # ширине выхода сохраняется.
        _зона = (m >= _TM8_MMIN) if m >= _TM8_MMIN else _tm8_zona4
        # [31.08] ПОЧЕМУ ПРИ NMIN=0 ПАДАЛ ПОДЪЁМ -- ЭТО НЕ УПАКОВКА, А МАРШРУТ.
        # `_TM8_ONLY` ОСВОБОЖДАЕТ исходный `qweight` («все зоны M закрыты tm8»), но правило
        # зоны закрывает их только для ШИРОКОГО выхода: у узкой формы при M=1 путь уходил на
        # `w8a16_gemv(x, qw, ...)` с УЖЕ ПУСТЫМ qw -- отсюда `illegal memory access` на подъёме,
        # причём одинаково с включённым и выключенным подбором (что и сбило меня на диагнозе
        # «виновата упаковка узких форм»). Проверено в изоляции: сами формы и варианты живы.
        # Лечение: если вес освобождён (`_только`), в tm8 обязаны идти ВСЕ M, а не только зона.
        # Замер разрешает это делать лишь ВМЕСТЕ с подбором: при M=1 без подбора tm8 вдвое
        # хуже gemv (down 280 против 123), с подбором -- паритет (121 против 123).
        if tm_w.numel() > 0 and (_только or (m <= mmax
                and (m >= 8 or (m >= _TM8_MMIN and _зона) or _tm8_zona4))):
            y = torch.empty((m, tm_s.shape[1]), dtype=x.dtype, device=x.device)
            # Лестница вариантов по замеру 25.08 (gate_up 5120x17408, мкс):
            #   M<=16 -> v6 (124/124/157); M<=32 -> v4; M<=64 -> v12 (203); выше -> v2.
            # [ЛЕСТНИЦА ПЕРЕМЕРЕНА 31.08 -- ОНА НЕ ЗАВИСЕЛА ОТ ФОРМЫ, А ДОЛЖНА]
            # Прежняя лестница ставила v6 до M<=16 и v4 до M<=32 ДЛЯ ВСЕХ форм. Замер на
            # боевых формах (мкс, чистая карта, 150 повторов) показал, что на ШИРОКОМ выходе
            # это неверно уже при M=8:
            #     gate_up 5120x17408  M=8:  v4=162  v6=182   -> v4 быстрее на 12 %
            #                         M=16: v4=163  v6=200   -> на 23 %
            #                         M=32: v12=195 v4=315   -> на 62 %
            #     down    8704x5120   M=8:  v6=118  v4=197   -> v6 верен
            #                         M=32: v4=198  v12=219  -> v4 верен
