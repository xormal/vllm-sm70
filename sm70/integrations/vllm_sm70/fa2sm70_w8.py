# [ПАМЯТЬ 17.09] ПРЕДОХРАНИТЕЛЬ НА ЧУЖОМ ТЕЛЕ.
# `ops.gptq_gemm` заводит буфер деквантизации размером с весь вес (K*N*2 байт). При
# util 0.96 свободного на карте 109 МиБ, и на широкой форме (170 МиБ) отказ памяти
# роняет ЗАПРОС, а в бою 15.09 уронил и движок. Между тем у распределителя торча в этот
