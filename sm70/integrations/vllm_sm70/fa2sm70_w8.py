def _корзина_M(m: int) -> int:
    """Округление M вверх до степени двойки -- КЛЮЧ подбора.

    ЗАЧЕМ. Подбор ленив по ключу (K, N, M), а прогрев на старте покрывал только
    M из (1,2,4,8,16). Бой же просит 13, 15, 19, 20, 25 -- и эти формы тюнились
    ПРЯМО В ГОРЯЧЕМ ПУТИ: 17 вариантов x 7 splits x 4 log_tile прямо посреди запроса.
    Замерено 07.09: в установившемся режиме подбор даёт -10.6 % шага, а со своими
    пробами в пути роняет сквозняк вдвое на смене промпта.
    Корзина делает число ключей конечным: любой M попадает в прогретую степень
    двойки, и в горячем пути не остаётся ни одной пробы. Конфигурация соседней
    степени практически оптимальна -- шаг по M пологий (замер §168: M=1 и M=8
    дают 56.0 и 56.1 мкс на одной форме).
    """
    if m <= 1:
        return 1
    b = 1
    while b < m and b < 4096:
        b <<= 1
    return b


def _подобрать(y, x, tm_w, tm_s, group, k_ld, q_ld, v0, ключ):
    """Разовый подбор (variant, splits, log_tile) прямым замером на РЕАЛЬНЫХ буферах.

    Возвращает и запоминает лучшее. При любой неожиданности отдаёт базовое (v0, 1, 0):
    подбор -- это ускорение, а не условие работы, и права падать он не имеет.
    Цена -- 28 проб по три запуска, единицы миллисекунд НА ФОРМУ и только один раз.
    """
    баз = (v0, 1, 0)
    if _ТЮН_ВЫКЛ:
        _ТЮН[ключ] = баз
        return баз
    # [ПОДБОР ТОЛЬКО ДЛЯ ДЕКОДНЫХ M -- СУЖЕНИЕ ПОВЕРХНОСТИ, А НЕ ЛЕЧЕНИЕ ПАДЕНИЯ]
    # Свип splits/log_tile я делал при M=1..16 и при M=1022, а комбинацию «большой M и
    # splits>1 / log_tile>0» не проверял НИ РАЗУ, и подъём боевого падал ровно после строки
    # «подбор (5120, 8192, 4096)». ГИПОТЕЗА ОПРОВЕРГНУТА ДВАЖДЫ: перебор 1008 комбинаций
    # (6 боевых форм x M=1..4096 x 28) прошёл без единого отказа, а положительный контроль на
    # стенде -- боевая конфигурация со СНЯТЫМ этим ограничением -- поднялся. Виноват был кэш
    # компиляции (см. разбор у порога NMIN выше). Ограничение оставлено как сужение поверхности
    # риска: приза при больших M нет (там всегда побеждает splits=1, log_tile=0), а 140 лишних
    # запусков на форму в profile_run -- чистая трата пикового буфера.
    if ключ[2] > _ТЮН_MMAX:
        _ТЮН[ключ] = баз
        return баз
    import time as _t
    _ОТКАЗЫ = []
    ядро = _расш_tm8().gemm
    # [03.09] ВЫБОРКА ПОДБОРА УВЕЛИЧЕНА 3 -> 20 (прогрев 2 -> 5).
    # Замер на РЕАЛЬНЫХ тензорах боевого слоя (K=5120 N=8192 M=4, снято дампом): подбор выбрал
    # (6,1,0) = 83.7 мкс, тогда как проверенный эталоном (6,2,2) даёт 68.1 мкс -- x1.23, и
    # разница устойчива в четырёх кругах чередования (разброс 0.3 мкс). При трёх пробах весь
    # замер длится ~250 мкс, и разница в 16 мкс тонет в накладных запуска: подбор выбирал
    # шумом. Цена лечения -- 28 комбинаций x 25 запусков на форму ОДИН раз за подъём.
    def _сек(v, sp, lt, повт=20):
        try:
            for _ in range(5):
                ядро(y, x, tm_w, tm_s, group, k_ld, q_ld, v, sp, lt)
            torch.cuda.synchronize()
            t0 = _t.perf_counter()
            for _ in range(повт):
                ядро(y, x, tm_w, tm_s, group, k_ld, q_ld, v, sp, lt)
            torch.cuda.synchronize()
            return (_t.perf_counter() - t0) / повт
        except Exception as e:
            # [31.08] МОЛЧАНИЕ ЗДЕСЬ СТОИЛО ЧАСА ДИАГНОСТИКИ. Пробу роняет ЛИБО негодная
            # комбинация, ЛИБО уже мёртвый контекст CUDA -- и во втором случае все следующие
            # пробы тоже «бесконечны», подбор возвращает базу, а падение всплывает СТРОКОЙ
            # НИЖЕ, на настоящем вызове. В журнале это выглядело как «подобрана база» плюс
            # необъяснимый illegal access. Печатаем первую же неудачу: она и есть диагноз.
            if not _ОТКАЗЫ:
                _ОТКАЗЫ.append(1)
                print(f"[fa2_sm70 TM8] проба v={v} splits={sp} log_tile={lt} на {ключ} "
                      f"ОТКАЗАЛА: {type(e).__name__}: {str(e)[:120]}",
                      file=sys.stderr, flush=True)
            return float("inf")
    try:
        ядро(y, x, tm_w, tm_s, group, k_ld, q_ld, *баз)
        torch.cuda.synchronize()
        эт = y.detach().clone().float()
    except Exception:
        _ТЮН[ключ] = баз
        return баз
    лучшее, лучт = баз, _сек(*баз)
    _варианты = range(_расш_tm8().num_variants) if _ТЮН_ВАРИАНТЫ else (v0,)
    for _v in _варианты:
      for sp in (1, 2, 3, 4, 6, 8, 12):
        for lt in (0, 1, 2, 3):
            if (_v, sp, lt) == баз:
                continue
            t = _сек(_v, sp, lt)
            if t >= лучт:
                continue
            # ГЕЙТ ТОЧНОСТИ ВНУТРИ ПОДБОРА. Расщепление по K меняет порядок сложения, и
            # принимать вариант по одному секундомеру -- значит принять неверный ответ, если
            # он окажется быстрым. Порог 2e-3 -- на два порядка выше наблюдаемых 3e-5.
            try:
                ядро(y, x, tm_w, tm_s, group, k_ld, q_ld, _v, sp, lt)
                torch.cuda.synchronize()
                d = float((y.detach().float() - эт).norm() / (эт.norm() + 1e-30))
            except Exception:
                continue
            if d < 2e-3:
                лучшее, лучт = (_v, sp, lt), t
    # [СОГЛАСИЕ РАНГОВ, 07.09] При TP ранги идут В ТАКТ, и шаг гейтит МЕДЛЕННЫЙ.
    # Замерено: на одной и той же форме (5120,8192,4) ранг 0 выбрал (6,3,0), а ранг 1
    # -- (7,6,3). Значит половина выигрыша съедалась рассогласованием. Выбор сводится
    # к общему: берём тот, что медленнее у СЕБЯ, -- он заведомо годен у обоих (гейт
    # точности пройден локально у каждого), а согласие важнее последнего процента.
    try:
        import torch.distributed as _рд
        if _рд.is_available() and _рд.is_initialized() and _рд.get_world_size() > 1:
            _код = torch.tensor([лучшее[0] * 1000 + лучшее[1] * 10 + лучшее[2]],
                                dtype=torch.int64, device="cuda")
            _рд.broadcast(_код, src=0)
            _з = int(_код.item())
            лучшее = (_з // 1000, (_з // 10) % 100, _з % 10)
    except Exception:
        pass
    _ТЮН[ключ] = лучшее
    # Печатаем ВСЕ подборы: при четырёх формах и четырёх боевых M записей 16, и прежний
    # предел в 12 строк прятал ровно те формы, которые подбирались последними -- узкие.
    # Я по этой отсечке решил, что они «не попадают в подбор», хотя они попадали.
    if len(_ТЮН) <= 64:
        print(f"[fa2_sm70 TM8] подбор {ключ}: variant={лучшее[0]} splits={лучшее[1]} "
              f"log_tile={лучшее[2]}", file=sys.stderr, flush=True)
    return лучшее
