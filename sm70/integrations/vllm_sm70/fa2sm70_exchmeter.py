# ИЗМЕРИТЕЛЬ ОБМЕНА TP: РАЗДЕЛИТЬ ПЕРЕВОЗКУ И ОЖИДАНИЕ.
#
# Снятие фазы уже показало, что обмен -- 58% префилла (97.8 -> 41.1 с). Но 58% чего именно? Тот же
# размер в автономном бенче идёт 28.9 мс, а в сервере выходит ~86 мс. Разница может быть двух
# РАЗНЫХ природ, и рычаги у них противоположные:
#   * ПЕРЕВОЗКА  -> лечится транспортом (свой проталкивающий обмен, NVLink, int8-свёртка);
#   * ОЖИДАНИЕ ОТСТАВШЕГО РАНГА -> транспорт не поможет вообще, лечится перекрытием и расписанием.
# Отличить можно только замером: ПЕРЕД свёрткой ставится выравнивающий барьер, и его время -- это
# и есть перекос рангов; остаток -- перевозка.
#
# ЗАЧЕМ БАРЬЕР ДО, А НЕ ТОЛЬКО ПОСЛЕ. Без него всё ожидание отставшего попадает внутрь замера
# свёртки и читается как "медленная перевозка" -- ровно та ошибка, из-за которой автономный бенч
# занизил цену втрое.
#
# Включается FA2SM70_GATES='FA2SM70_ЗАМЕР_ОБМЕНА=1'. Ответы ВЕРНЫ (ничего не снимается), но сам
# барьер добавляет работу -- это ПРИБОР, МЕНЯЮЩИЙ ИЗМЕРЯЕМОЕ, и суммарное время вырастет.
# Читать надо ОТНОШЕНИЕ перекоса к перевозке, а не абсолют.
import os
import sys

if os.environ.get("FA2SM70_ЗАМЕР_ОБМЕНА", "0") == "1":
    import torch
    import torch.distributed as dist

    С = {"n": 0, "перекос": 0.0, "перевозка": 0.0, "байт": 0}

    def _обёртка(старый):
        def _f(self, input_, *a, **k):
            # ВНУТРИ ЗАХВАТА ГРАФА мерить НЕЛЬЗЯ: и барьер, и синхронизация -- запрещённые операции
            # ("operation not permitted when stream is capturing"), захват падает целиком. А граф у
            # нас захватывается на ДЕКОДЕ, и его свёртки в раскладку префилла всё равно не входят.
            if input_.numel() < 4096 or torch.cuda.is_current_stream_capturing():
                return старый(self, input_, *a, **k)
            e = [torch.cuda.Event(enable_timing=True) for _ in range(3)]
            e[0].record()
            dist.barrier()                      # выравнивание: его время = ПЕРЕКОС рангов
            e[1].record()
            r = старый(self, input_, *a, **k)   # чистая ПЕРЕВОЗКА уже на выровненных рангах
            e[2].record()
            torch.cuda.synchronize()
            С["n"] += 1
            С["перекос"] += e[0].elapsed_time(e[1])
            С["перевозка"] += e[1].elapsed_time(e[2])
            С["байт"] += input_.numel() * input_.element_size()
            if С["n"] % 256 == 0:
                п, в = С["перекос"], С["перевозка"]
                print(f"[fa2_sm70 ОБМЕН] свёрток {С['n']}, {С['байт']/1e9:.1f} ГБ | "
                      f"ПЕРЕКОС {п/1000:.2f} с ({100*п/(п+в):.0f}%)  "
                      f"ПЕРЕВОЗКА {в/1000:.2f} с ({100*в/(п+в):.0f}%)  "
                      f"на свёртку: {п/С['n']:.1f} + {в/С['n']:.1f} мс",
                      file=sys.stderr, flush=True)
            return r
        return _f

    сколько = 0
    for путь, имя in (
        ("vllm.distributed.device_communicators.base_device_communicator", "DeviceCommunicatorBase"),
        ("vllm.distributed.device_communicators.cuda_communicator", "CudaCommunicator"),
    ):
        try:
            мод = __import__(путь, fromlist=[имя])
            кл = getattr(мод, имя)
            if "all_reduce" in кл.__dict__:
                кл.all_reduce = _обёртка(кл.__dict__["all_reduce"])
                сколько += 1
        except Exception:
            pass
    print(f"[fa2_sm70] ИЗМЕРИТЕЛЬ ОБМЕНА включён (классов {сколько}). Прибор МЕНЯЕТ измеряемое: "
          f"читать ОТНОШЕНИЕ перекос/перевозка, не абсолютное время.", file=sys.stderr, flush=True)
