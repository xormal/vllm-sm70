# ЧТО ЗАМЕРЕНО. Опись пути по ядрам декодного шага (45.2 мс): `ncclDevKernel_AllReduce_Sum_f16_RING_LL`
# -- 148 сверток по 44.9 мкс = 6.65 мс, то есть 15 % шага, при полезной нагрузке 40 КиБ на свёртку.
# Это ЧИСТАЯ ЛАТЕНТНОСТЬ: 40 КиБ по PCIe идут около 8 мкс, остальное -- протокол и запуск.
# Настройки NCCL проверены и закрыты отрицательно (NCCL_MAX_NCHANNELS=1 -> 45.6/44.8,
# NCCL_PROTO=LL128 -> 44.3/43.6 против базы 45.5/45.8).
#
# ПОЧЕМУ СВОЙ ALL-REDUCE БЫЛ ЗАПРЕЩЁН И ПОЧЕМУ ЗАПРЕТ СНИМАЕТСЯ. Подъём падал на
# `custom_all_reduce.cuh: 'invalid argument'` -- `cudaIpcGetMemHandle` на буферах ГРАФОВОГО ПУЛА.
# Отсюда был сделан вывод «либо полный граф, либо свой обмен», и граф выиграл.
#
# Вывод оказался ЛОЖНЫМ, и это видно из самого кода vLLM. У `CustomAllreduce` ДВА пути:
#   registered=True  -- вход УЖЕ отдан соседу через IPC; при захвате графа берётся именно он,
#                       и потому в конце захвата зовётся `register_graph_buffers()` -- вот там
#                       и отказывает IPC на графовой памяти;
#   registered=False -- вход КОПИРУЕТСЯ в заранее зарегистрированный буфер, и никакой регистрации
#                       графовых адресов не требуется вовсе.
# Второй путь в графе совершенно законен: адрес буфера постоянен, копия и свёртка -- обычные
# ядра на потоке. Цена -- одна копия 40 КиБ на свёртку (порядка 2-3 мкс, 148 свёрток = 0.4 мс),
# приз -- разница между 44.9 мкс NCCL и однопроходным обменом.
#
# ЧТО ДЕЛАЕТ ЭТОТ МОДУЛЬ: заставляет брать путь `registered=False` ВСЕГДА и отключает регистрацию
# графовых буферов (регистрировать нечего). Включение: FA2SM70_CUSTOM_AR=1 (пускач тогда не
# передаёт --disable-custom-all-reduce).
#
# ГЕЙТ. Обмен -- это ТОЧНОСТЬ СЛОЖЕНИЯ, и порча тут тихая: ответ остаётся связным. Поэтому
# приёмка спекуляции и гейт «17*23» проверяются ОБА: приёмка -- чувствительный детектор
# рассогласования рангов (черновик и цель разъедутся немедленно).
import os
import sys

import torch


def установить() -> None:
    if os.environ.get("FA2SM70_CUSTOM_AR", "0") != "1":
        return
    # FA2SM70_AR_PATCH=0 -- взять ШТАТНЫЙ путь vLLM без нашей правки. Нужен, чтобы
    # отделить дефект нашей правки от дефекта самого механизма: микрозамер показал,
    # что штатное сведение даёт 22 мкс и работает, а наша правка вешает сервер.
    if os.environ.get("FA2SM70_AR_PATCH", "1") != "1":
        print("[fa2_sm70 AR] наша правка ОТКЛЮЧЕНА, идёт штатный путь vLLM",
              file=sys.stderr, flush=True)
        return
    try:
        from vllm.distributed.device_communicators.custom_all_reduce import CustomAllreduce
    except Exception as ex:  # noqa: BLE001
        print(f"[fa2_sm70 AR] свой обмен недоступен: {ex}", file=sys.stderr, flush=True)
        return

    _счёт = [0]
    # КОЛЬЦО УЧАСТКОВ. Причина прежних зависаний найдена: ОДИН буфер переиспользовался всеми 148
    # свёртками шага, а протокол рассчитан на СВОЙ вход у каждой (у vLLM это свежие тензоры
    # графового пула). Сосед ещё читает мой буфер по предыдущей свёртке, когда я пишу вход
    # следующей. Даём каждой свёртке СВОЙ участок: счётчик растёт на вызов, при ЗАХВАТЕ графа
    # значение запекается в место вызова, и на повторе оно то же -- то есть у каждой свёртки
    # шага участок постоянен и одинаков на обоих рангах (код один и тот же).
    _УЧАСТОК = int(os.environ.get("FA2SM70_AR_SLOT_KB", "48")) * 1024

    def _обмен(self, input):
        if self.disabled or not self.should_custom_ar(input):
            return None
        from vllm import _custom_ops as ops
        # [КАЖДОЕ СМЕЩЕНИЕ РЕГИСТРИРУЕТСЯ ОТДЕЛЬНО. ОШИБКА, ПОЙМАННАЯ ПОДЪЁМОМ]
        # `buffer address ... is not registered!` -- поиск идёт по ТОЧНОМУ адресу, и участок
        # внутри зарегистрированного буфера чужой карте неизвестен. Но адреса соседа отображены
        # ЦЕЛИКОМ, значит `base_соседа + смещение` -- законный адрес, и его можно зарегистрировать
        # тем же вызовом. Делаем это ОДИН РАЗ, до захвата графа (первый вызов идёт на прогреве).
        кольцо = getattr(self, "_кольцо", None)
        if кольцо is None:
            колец = max(1, int(self.max_size) // _УЧАСТОК)
            кольцо = []
            for i in range(колец):
                сдв = i * _УЧАСТОК
                ops.register_buffer(self._ptr, [int(p) + сдв for p in self.buffer_ptrs])
                кольцо.append(int(self.buffer_ptrs[self.rank]) + сдв)
            self._кольцо = кольцо
            print(f"[fa2_sm70 AR] кольцо из {колец} участков по {_УЧАСТОК >> 10} КиБ "
                  f"зарегистрировано", file=sys.stderr, flush=True)
        адрес = кольцо[_счёт[0] % len(кольцо)]
        _счёт[0] += 1
        out = torch.empty_like(input)
        ops.all_reduce(self._ptr, input, out, адрес, _УЧАСТОК)
        if _счёт[0] == 1:
            print("[fa2_sm70 AR] СВОЙ ОБМЕН пошёл", file=sys.stderr, flush=True)
        return out

    def _без_регистрации(self):
        # Регистрировать нечего: вход всегда лежит в буфере, зарегистрированном при
        # инициализации, а графовых адресов путь обмена больше не касается.
        return

    # [РЕШЕНИЕ О ПУТИ -- ТОЛЬКО В `should_custom_ar`. ОШИБКА, ПОЙМАННАЯ ПОДЪЁМОМ]
    # Вернуть None из `custom_all_reduce` после того, как `should_custom_ar` сказал «да», нельзя:
    # вызывающий держит `assert out is not None`. Значит ограничение по размеру участка кольца
    # обязано стоять ТАМ ЖЕ, где принимается решение, а не в теле.
    _прежний_годен = CustomAllreduce.should_custom_ar

    def _годен(self, inp):
        if not _прежний_годен(self, inp):
            return False
        return inp.numel() * inp.element_size() <= _УЧАСТОК

    # [СБРОС СЧЁТЧИКА НА КАЖДЫЙ ПРОХОД -- ЛЕЧЕНИЕ ЗАВИСАНИЯ 27.08]
    # Прежде участок выбирался СВОБОДНО БЕГУЩИМ счётчиком. Пока оба ранга делают ровно
    # одинаковую последовательность сведений, их счётчики совпадают; но достаточно ОДНОГО
    # расхождения (прогрев, черновик, нештатная ветка) -- и ранги начинают писать в РАЗНЫЕ
    # участки, каждый ждёт чужой, шаг встаёт намертво. Снаружи это выглядит так: захват графа
    # проходит, «СВОЙ ОБМЕН пошёл» печатается, а первый же запрос вешает воркера и движок
    # падает по таймауту разделяемой очереди.
    # Лечение: участок определяется ПОЗИЦИЕЙ СВЁРТКИ ВНУТРИ ПРОХОДА, а не историей. Счётчик
    # обнуляется на входе в каждый проход (`set_forward_context` зовётся ровно раз на проход),
    # поэтому k-е сведение прохода на обоих рангах берёт участок k ПО ПОСТРОЕНИЮ.
    try:
        import vllm.forward_context as _фк

        _прежний_контекст = _фк.set_forward_context

        def _контекст(*a, **kw):
            _счёт[0] = 0
            return _прежний_контекст(*a, **kw)

        _фк.set_forward_context = _контекст
        print("[fa2_sm70 AR] участок привязан к позиции внутри прохода (счётчик сбрасывается)",
              file=sys.stderr, flush=True)
    except Exception as ex:  # noqa: BLE001
        print(f"[fa2_sm70 AR] сброс счётчика не поставлен: {ex}", file=sys.stderr, flush=True)

    CustomAllreduce.should_custom_ar = _годен
    CustomAllreduce.custom_all_reduce = _обмен
    CustomAllreduce.register_graph_buffers = _без_регистрации
    print("[fa2_sm70] СВОЙ ALL-REDUCE + ПОЛНЫЙ ГРАФ: вход через зарегистрированный буфер",
          file=sys.stderr, flush=True)
