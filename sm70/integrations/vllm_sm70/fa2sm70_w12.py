#
# ЧТО ОБНАРУЖЕНО В СЛЕПКЕ. `quantization_config.modules_to_not_convert` боевого слепка
# Huihui-Qwen3.6-27B-INT8 ЯВНО исключает `self_attn.{q,k,v}_proj` из GPTQ. То есть автор слепка
# сознательно оставил проекции внимания неквантованными -- ровно потому, что они важны для точности.
# Итог: 2.349 ГБ BF16, читаемые КАЖДЫЙ шаг декода, посреди сети, которая вся остальная в int8.
#
# ПОЧЕМУ int12 СНИМАЕТ ЭТО ВОЗРАЖЕНИЕ, А НЕ ОБХОДИТ ЕГО. Замерено на самих этих тензорах:
#   ошибка int12 к хранимому BF16      6.10e-04
#   СОБСТВЕННАЯ зернистость BF16       1.95e-03   (8 разрядов мантиссы)
# То есть int12 представляет эти веса ВТРОЕ ТОЧНЕЕ, чем формат, в котором они сейчас лежат, и при
# 0.75 байт. Размена нет: BF16 держит экспоненту на КАЖДОМ весе, тогда как динамический диапазон уже
# вынесен в масштаб группы из 128. Это не «сжатие с потерей», это снятие дублирования.
#
# ЧТО ЭТО ДАЁТ, ЧЕСТНО. Ядро в отдельности (tools/test_w12a16.py, форма q_proj [12288,5120]):
#   M=1  131 мкс против 204 у плотного fp16  = x1.56     <- декод
#   M=8  197 мкс против 244                  = x1.24
#   M=16 286 мкс против 210                  = x0.73     <- перелом, и он физический
# x1.56 БОЛЬШЕ отношения байт x1.33: плотный путь идёт на 617 ГБ/с, наш упакованный на 720.
#
# СКВОЗЬ СЕРВЕР (пара 0-1, TP=2, парные подъёмы, 15.08.2026) -- И ЗДЕСЬ ПРИЗ МАЛ:
#   декод, 3000 токенов x3, медиана отношений        x1.005   (разрешение прибора ~1 %)
#   префилл 24 тыс. слов, медиана из 3               61.78 с против 62.24 -- НЕ ХУЖЕ
#   байт весов внимания на карту                     1.174 -> 0.890 ГБ  (x1.320, счётчик воркера)
#   -logP/токен на естественном тексте               1.975034 против 1.974582 = +0.023 % ХУЖЕ
#   собственный шум этого прибора                    3e-06 относительных
# Причина малости приза ПОНЯТНА И ПОСЧИТАНА: проекции внимания -- 1.174 ГБ из 14.51 ГБ, читаемых
# картой за шаг, то есть 8.1 %. Срезать у них четверть = 2.0 % байт шага = около 1 % времени.
# ЦЕННОСТЬ ХОДА -- В ПОСТРОЕННОМ ПУТИ, а не в этом проценте: путь int-N для ВЕСОВ строится один раз.
#
# ЧЕГО ЭТОТ ХОД НЕ ДАЁТ. Освобождённые 0.284 ГБ на карту САМИ в ёмкость не превращаются: в боевом
# пускаче объём пула KV задан жёстко (`--kv-cache-memory-bytes`), и профилирование пропускается.
# Чтобы приз стал ёмкостью, это число надо поднять НАМЕРЕННО.
#
# ЧЕМ ПРОВЕРЯТЬ, А ЧЕМ НЕЛЬЗЯ. Критерий «совпал ли текст при T=0» для этого рычага НЕДЕЙСТВИТЕЛЕН:
# замерено, что два ОДИНАКОВЫХ запроса к ОДНОМУ серверу расходятся на символе 482. Эталон сам не
# воспроизводится. Годный прибор -- правдоподобие фиксированного текста (tools/nll_w12.py), у него
# шум ровно ноль на префилле. И текст обязан быть НЕПОВТОРЯЮЩИМСЯ: на повторяющемся 0.5 % позиций
# несут 20.4 % суммы, метрика высокодисперсна и вердикта не выдерживает.
#
# ДВА ПУТИ, И ГРАНИЦА МЕЖДУ НИМИ -- ЗАМЕРЕННАЯ, А НЕ ВЫБРАННАЯ:
#   * ДЕКОД (M мало): вес потребляется УПАКОВАННЫМ, распаковка слита с его же загрузкой. Отдельный
#     проход распаковки здесь ЗАПРЕЩЁН -- замерено на int8-пути, он даёт 0.18x от неквантованного,
#     потому что пишет плотный вес в память и читает обратно.
#   * ПРЕФИЛЛ (M велико): плитка веса переиспользуется тысячами строк, связывает СЧЁТ. Распаковываем
#     в ОДИН общий буфер и отдаём плотному тензорному пути. Отдельный проход здесь законен ровно по
#     той причине, по которой запрещён на декоде: его цена делится на M строк (0.13% префилла).
#
# ВКЛЮЧЕНИЕ: FA2SM70_W12=1. Порог путей: FA2SM70_W12_MMAX (умолчание 12, замеренный перелом).
import os
import sys

_ВКЛ = os.environ.get("FA2SM70_W12", "0") == "1"
_MMAX = int(os.environ.get("FA2SM70_W12_MMAX", "12"))
_ЦЕЛЬ = os.environ.get("FA2SM70_W12_TARGET", "self_attn.qkv_proj")
_G = 128

if _ВКЛ:
    import torch

    _ext = None
    _буфер = None                      # ОДИН распаковочный буфер на процесс, см. шапку
    С = {"тел": 0, "было": 0, "стало": 0, "gemv": 0, "плотн": 0}

    def _расш():
        global _ext
        if _ext is None:
            sys.path.insert(0, os.environ.get("FA2SM70_PATH", "."))
            from fa2_sm70._ext import w12a16_ext
            _ext = w12a16_ext()
        return _ext

    def _упаковать(q):
        """q: [N, K] целые -> [K/8, 3, N] int32. Раскладку задаёт ЧИТАТЕЛЬ (см. w12a16.cu)."""
        N, K = q.shape
        u = (q.to(torch.int64) + 2048) & 0xFFF
        v = u.view(N, K // 8, 8)
        w0 = v[..., 0] | (v[..., 1] << 12) | ((v[..., 2] & 0xFF) << 24)
        w1 = (v[..., 2] >> 8) | (v[..., 3] << 4) | (v[..., 4] << 16) | ((v[..., 5] & 0xF) << 28)
        w2 = (v[..., 5] >> 4) | (v[..., 6] << 8) | (v[..., 7] << 20)
        п = torch.stack([w0, w1, w2], dim=2).permute(1, 2, 0).contiguous()
        return torch.where(п >= (1 << 31), п - (1 << 32), п).to(torch.int32)

    def _квантовать(w):
        """w: [N, K] -> (пак, масштабы [K/G, N], относительная ошибка).

        МАСШТАБ ОКРУГЛЯЕТСЯ ПЕРВЫМ, потом по нему квантуется. Обратный порядок (делить на точный
        максимум, а хранить fp16) даёт целые, оптимальные для делителя, которого на исполнении нет.
        ГРУППА ИДЁТ ПО ОСИ СВЁРТКИ K: масштаб выносится из ЧАСТИЧНОЙ суммы группы, поэтому умножение
        внутри группы остаётся целочисленным. По оси выхода группировать нельзя -- ломает накопление.
        """
        N, K = w.shape
        lvl = 2047
        г = w.float().view(N, K // _G, _G)
        m = г.abs().amax(dim=2, keepdim=True).clamp_min(1e-12)
        масш = (m / lvl).to(torch.float16)
        mf = масш.float().clamp_min(1e-20)
        q = torch.round(г / mf).clamp(-lvl, lvl)
        ош = ((q * mf - г).norm() / г.norm().clamp_min(1e-20)).item()
        return _упаковать(q.view(N, K).to(torch.int32)), масш.squeeze(2).t().contiguous(), ош

    # ОДНА ОПЕРАЦИЯ ДЛЯ DYNAMO, А НЕ НЕПРОЗРАЧНЫЙ ВЫЗОВ. Первая редакция звала расширение прямо из
    # forward и УРОНИЛА ПОДЪЁМ: движок компилирует модель целым графом, а любой разрыв здесь
    # смертелен (упало на os.makedirs -- сборка расширения происходила ВНУТРИ трассировки). Отсюда
    # два правила, оба выполнены ниже:
    #   1. расширение и буфер готовятся В МОМЕНТ ОБРАЩЕНИЯ ВЕСОВ, до всякой компиляции;
    #   2. само умножение регистрируется операцией через штатный direct_register_custom_op -- тогда
    #      Dynamo видит ОДИН узел и трассировать внутрь не пытается.
    def _w12_mm(x: torch.Tensor, qw: torch.Tensor, sc: torch.Tensor, mmax: int) -> torch.Tensor:
        e = _расш()
        N, K = qw.shape[2], qw.shape[0] * 8
        xf = x.reshape(-1, K)
        if xf.shape[0] <= mmax:
            С["gemv"] += 1
            # [FA2/SM70 25.08] ДОПОЛНЕНИЕ M ДО СТЕПЕНИ ДВОЙКИ. Замер на боевых формах
            # (K=5120, N=17408) показал, что тело быстро ТОЛЬКО при M из {1,2,4,8}, а на
            # остальных проваливается в 1.6-2.5 раза:
            #     M   1     2     3     4     5     6     7     8
            #   наше 207   212   398   250   429   435   618   261  мкс
            # Вес читается ЦЕЛИКОМ независимо от M, поэтому посчитать 8 строк вместо 7 почти
            # бесплатно, а вот попасть на «плохое» M -- дорого. Это же объясняло свип по k:
            # q=4 (степень двойки) обгонял q=3 и q=5 при ХУДШЕЙ приёмке.
            _m = xf.shape[0]
            _цель = 1 << (_m - 1).bit_length() if _m > 0 else 0
            if _цель != _m and _цель <= mmax:
                _доп = xf.new_zeros(_цель - _m, xf.shape[1])
                y = e.w12a16_gemv(torch.cat((xf, _доп), 0).half(), qw, sc, _G)[:_m]
            else:
                y = e.w12a16_gemv(xf.half(), qw, sc, _G)
        else:
            С["плотн"] += 1
            need = K * N
            e.w12_dequant_into(qw, sc, _буфер, _G)
            y = torch.matmul(xf.half(), _буфер[:need].view(K, N))
        # СЧЁТЧИК МАРШРУТА -- пишет ВОРКЕР ПО ФАКТУ РАБОТЫ. Без него «включено» доказывается только
        # наличием строки в логе подъёма, а это не доказательство (заявлено != исполняется).
        n = С["gemv"] + С["плотн"]
        if n & (n - 1) == 0 and n >= 64:
            print(f"[fa2_sm70 W12] свёрток {n}: упакованных {С['gemv']}, распакованных "
                  f"{С['плотн']}", file=sys.stderr, flush=True)
        return y.to(x.dtype).view(*x.shape[:-1], N)

    def _w12_mm_fake(x: torch.Tensor, qw: torch.Tensor, sc: torch.Tensor,
                     mmax: int) -> torch.Tensor:
        return x.new_empty((*x.shape[:-1], qw.shape[2]))

    from vllm.utils.torch_utils import direct_register_custom_op
    from fa2sm70_clef_hook import с_поправкой   # FA2SM70_CLEF=0 -> тело как есть
    direct_register_custom_op("fa2sm70_w12_mm", с_поправкой(_w12_mm, (1, 2)), mutates_args=[],
                              fake_impl=_w12_mm_fake)

    def _forward(сам, input_):
        # Повторяет контракт ColumnParallelLinear.forward ДОСЛОВНО: он возвращает ПАРУ, и вызывающий
        # её распаковывает. Вернуть тензор -- тихая порча на распаковке, а не падение.
        y = torch.ops.vllm.fa2sm70_w12_mm(input_, сам.w12_qw, сам.w12_sc, _MMAX)
        if not сам.skip_bias_add and сам.bias is not None:
            y = y + сам.bias
        return y, (сам.bias if сам.skip_bias_add else None)

    # ---------------------------------------------------------------------------------------------
    # СКЛАД ГОТОВЫХ ВЕСОВ. Цель -- чтобы на подъёме int12 ГРУЗИЛСЯ, а не считался заново.
    #
    # ПОЧЕМУ КЛЮЧ ВКЛЮЧАЕТ РАЗРЕЗ, А НЕ ТОЛЬКО ИМЯ. Тензор в слепке лежит целым, а модуль держит уже
    # НАРЕЗАННУЮ по рангу долю. Резать самому значило бы повторить логику разреза движка у себя --
    # то есть завести второй источник истины, который разойдётся с первым молча. Поэтому склад
    # хранит РОВНО то, что отдал движок, а ключом идёт (число рангов, ранг). Файл от другого разреза
    # ОТВЕРГАЕТСЯ, а не подгоняется: подогнанный шард -- это неверный ответ без единого сообщения.
    #
    # Раскладка позволяет так делать без оговорок: группа масштаба идёт по оси СВЁРТКИ, поэтому любая
    # нарезка по оси ВЫХОДА -- это ровно упакованная нарезка того же веса, элемент в элемент.
    def _склад_путь():
        d = os.environ.get("FA2SM70_W12_CACHE", "")
        if not d:
            return None
        # КЛЮЧ ОБЯЗАН ОПИСЫВАТЬ ВЕСЬ РАЗРЕЗ, А НЕ ТОЛЬКО ТЕНЗОРНЫЙ.
        # Здесь стоял ключ tp<мир>r<ранг>, и при КОНВЕЙЕРНОМ разрезе он схлопывался: TP=1 у обоих
        # рангов, значит оба брали файл `tp1r0`, хотя держат РАЗНЫЕ СЛОИ. Ранг 0 записал свою
        # половину, ранг 1 не нашёл в ней слой 35 -- подъём упал. Упал ПРАВИЛЬНО (проверка формы
        # стоит), но причина была в неполном ключе, а не в файле. Правило: ключ склада описывает
        # ВСЕ оси разреза, иначе две разные доли делят одно имя.
        def _ось(имя_р, имя_м):
            try:
                import vllm.distributed as D
                return getattr(D, имя_р)(), getattr(D, имя_м)()
            except Exception:  # noqa: BLE001
                return 0, 1
        тр, тм = _ось("get_tensor_model_parallel_rank", "get_tensor_model_parallel_world_size")
        try:
            from vllm.distributed import get_pp_group
            г = get_pp_group()
            пр, пм = г.rank_in_group, г.world_size
        except Exception:  # noqa: BLE001
            пр, пм = 0, 1
        return os.path.join(d, f"w12_G{_G}_tp{тм}r{тр}_pp{пм}r{пр}.safetensors")

    def _склад_прочесть(путь):
        """ЯВНЫЙ ИНДЕКС КАРТЫ, А НЕ СТРОКА "cuda".

        Здесь стояло device="cuda", и это УРОНИЛО сервер аварийным обращением к памяти. Строка без
        индекса выглядит «на текущую карту», а на деле означает карту НОЛЬ: у воркера ранга 1
        1184 МБ повисли на карте 0, тогда как считает он на карте 1. Подъём при этом ПРОШЁЛ (мост
        PCIe пропускает чужой адрес), и упало на первом же боевом запросе -- то есть отказ отложен
        от причины на несколько минут. Ниже проверка сходства карт стоит рядом: она превращает этот
        класс ошибки из отложенного в немедленный.
        """
        if not путь or not os.path.exists(путь):
            return None
        from safetensors.torch import load_file
        д = load_file(путь, device=f"cuda:{torch.cuda.current_device()}")
        print(f"[fa2_sm70 W12] СКЛАД: читаю готовые веса из {путь}", file=sys.stderr, flush=True)
        return д

    def _склад_записать(путь, д):
        if not путь:
            return
        from safetensors.torch import save_file
        os.makedirs(os.path.dirname(путь), exist_ok=True)
        save_file({k: v.cpu() for k, v in д.items()}, путь)
        print(f"[fa2_sm70 W12] СКЛАД: готовые веса записаны в {путь} "
              f"(следующий подъём их ЗАГРУЗИТ, а не пересчитает)", file=sys.stderr, flush=True)

    def _обратить(model):
        import types
        макс_kn = 0
        путь = _склад_путь()
        склад = _склад_прочесть(путь)
        новое = {} if (путь and склад is None) else None
        # [FA2/SM70 24.08] ЧЕРНОВИК DFlash ПРОПУСКАЕТСЯ ЦЕЛИКОМ. Его слои называются так же, как у
        # целевой модели (`model.layers.N.self_attn.qkv_proj`), поэтому отличить их по ИМЕНИ, как
        # это сделано для MTP, нельзя -- различитель по имени тут ЛОЖНЫЙ. Отличаем по КЛАССУ
        # модели: черновик живёт в bf16 и в складе его слоёв нет, а без пропуска загрузка падала
        # «СКЛАД НЕ ПОДХОДИТ: model.layers.0.self_attn.qkv_proj».
        _кл = type(model).__name__
        _черновик = "DFlash" in _кл or "Eagle" in _кл or "Medusa" in _кл
        if _черновик and os.environ.get("FA2SM70_W12_DRAFT", "0") != "1":
            print(f"[fa2_sm70 W12] ПРОПУСК ВСЕЙ МОДЕЛИ {_кл}: это черновик, он остаётся bf16",
                  file=sys.stderr, flush=True)
            return
        if _черновик:
            # [FA2/SM70 25.08] ЧЕРНОВИК КВАНТУЕТСЯ НА ЛЕТУ, БЕЗ СКЛАДА. Склад собран для ЦЕЛИ и
            # ключуется именами слоёв, а у черновика они те же -- отсюда прежний отказ «СКЛАД НЕ
            # ПОДХОДИТ». Но черновику склад и не нужен: он в 14 раз меньше цели, квантование
            # занимает секунды на подъёме. Приз замерен: тело черновика 4.3 мс из 9.4 мс всего
            # предлагателя, при int8 ожидается вдвое меньше (пол чтения падает с 1.8 до 0.9 ГиБ).
            # Запас точности есть: fp16 даёт 100 % совпадения top-1 с fp32 (замерено на словаре).
            склад = None
            новое = None
            print(f"[fa2_sm70 W12] ЧЕРНОВИК {_кл}: квантуем НА ЛЕТУ (склад не нужен)",
                  file=sys.stderr, flush=True)
        for имя, m in model.named_modules():
            if not имя.endswith(_ЦЕЛЬ):
                continue
            # ЧЕРНОВИК MTP НЕ ОБРАЩАЕТСЯ: он намеренно живёт в bf16 (modules_to_not_convert в
            # слепке), читается только на спекулятивном шаге, и его слоёв НЕТ в складе -- без
            # этого пропуска загрузка черновика падала «СКЛАД НЕ ПОДХОДИТ» (19.08).
            if имя.startswith("mtp.") or ".mtp." in имя:
                print(f"[fa2_sm70 W12] ПРОПУСК {имя}: черновик MTP остаётся bf16",
                      file=sys.stderr, flush=True)
                continue
            w = getattr(m, "weight", None)
            if w is None or w.dim() != 2 or w.numel() == 0:
                continue
            if w.shape[1] % (_G) != 0:
                print(f"[fa2_sm70 W12] ПРОПУСК {имя}: K={w.shape[1]} не кратно {_G}",
                      file=sys.stderr, flush=True)
                continue
            # gather_output=True означал бы, что вывод собирается по рангам ВНУТРИ слоя -- наш
            # forward этого не делает, поэтому отказываемся ЯВНО, а не считаем неверно.
            if getattr(m, "gather_output", False):
                print(f"[fa2_sm70 W12] ОТКАЗ {имя}: gather_output=True не поддержан",
                      file=sys.stderr, flush=True)
                continue
            N, K = w.shape
            if склад is not None:
                пак, масш = склад.get(имя + ".qw"), склад.get(имя + ".sc")
                if (пак is not None and пак.device != w.device):
                    raise RuntimeError(
                        f"СКЛАД НА ЧУЖОЙ КАРТЕ: {имя} лежит на {пак.device}, а вес на {w.device}. "
                        f"Считать так -- либо авария, либо чтение через мост втихую.")
                if (пак is None or масш is None or пак.shape != (K // 8, 3, N)
                        or масш.shape != (K // _G, N)):
                    raise RuntimeError(
                        f"СКЛАД НЕ ПОДХОДИТ: {имя} ждали qw{(K // 8, 3, N)} sc{(K // _G, N)}, "
                        f"в файле {getattr(пак, 'shape', None)}/{getattr(масш, 'shape', None)}. "
                        f"Файл {путь} собран для ДРУГОГО разреза или другой сети -- удалите его.")
                ош = float("nan")
            else:
                пак, масш, ош = _квантовать(w.data)
                if новое is not None:
                    новое[имя + ".qw"], новое[имя + ".sc"] = пак, масш
            m.w12_qw, m.w12_sc, m.w12_N, m.w12_K = пак, масш, N, K
            С["было"] += w.numel() * w.element_size()
            С["стало"] += пак.numel() * 4 + масш.numel() * 2
            # Плотный вес освобождается, но САМ Parameter остаётся: движок обходит parameters() и
            # после загрузки. Пустой буфер держит атрибут живым и отдаёт память профилировщику,
            # который считает объём пула KV ПОСЛЕ загрузки -- то есть экономия достаётся кэшу.
            m.weight.data = torch.empty(0, dtype=w.dtype, device=w.device)
            m.forward = types.MethodType(_forward, m)
            макс_kn = max(макс_kn, K * N)
            С["тел"] += 1
            if С["тел"] == 1:
                # При чтении со склада ошибку считать НЕ ИЗ ЧЕГО (плотного веса мы не разворачивали),
                # и печатать её как nan -- значит выдать отсутствие замера за неудачный замер.
                е = ("не считалась: веса взяты готовыми со склада" if ош != ош
                     else f"ошибка {ош:.2e} (зернистость BF16 1.95e-03)")
                print(f"[fa2_sm70 W12] первое тело {имя}: [{N},{K}] {е}",
                      file=sys.stderr, flush=True)
        # Буфер распаковки -- ОДИН на процесс и выделен ЗАРАНЕЕ: выделение внутри захвата графа
        # или внутри трассировки -- это тот самый класс отказа, из-за которого упала первая редакция.
        global _буфер
        if С["тел"]:
            _расш()
            # БУФЕР ТОЛЬКО РАСТЁТ. Раньше он переоткрывался на КАЖДЫЙ вызов `_обратить`, и когда
            # после цели обращался ЧЕРНОВИК (он меньше), буфер ужимался -- после чего плотный путь
            # ЦЕЛИ падал «w12_dequant: буфер мал». Отказ громкий, но причина неочевидная: виноват
            # не тот, кто упал. Ошибка найдена при включении квантования черновика (25.08).
            _надо = макс_kn if _буфер is None else max(макс_kn, _буфер.numel())
            if _буфер is None or _буфер.numel() < _надо:
                _буфер = torch.empty(_надо, dtype=torch.float16, device="cuda")
            if новое:
                _склад_записать(путь, новое)
        torch.cuda.empty_cache()
        if С["тел"] == 0:
            print(f"[fa2_sm70 W12] НИ ОДНОГО тела по образцу '{_ЦЕЛЬ}' -- ПРИБОР СЛЕП",
                  file=sys.stderr, flush=True)
        else:
            print(f"[fa2_sm70 W12] обращено тел {С['тел']}: {С['было']/1e9:.3f} -> "
                  f"{С['стало']/1e9:.3f} ГБ на карту (x{С['было']/max(1,С['стало']):.3f} меньше)",
                  file=sys.stderr, flush=True)

