# СОСТОЯНИЕ GDN В int16 С МАСШТАБОМ (задача 195, ход владельца 20.08).
#
# ЗАЧЕМ. Рекуррентное состояние обновляется КАЖДЫМ токеном, поэтому ошибка формата не
# рассасывается, а копится. Замер 20.08: на fp16 длинная генерация вырождается (доля
# повторов 0.94 на 20K токенов), на fp32 -- 0.00. Ёмкость, купленная за fp16, была
# оплачена качеством. int16 с равномерной сеткой даёт ТЕ ЖЕ два байта, но точнее:
#
#   гейт 2000 шагов рекуррента, эталон fp32
#   выход:     int16 1.72e-04 против fp16 5.16e-04   (в 3.0 раза точнее)
#   состояние: int16 7.64e-05 против fp16 4.39e-04   (в 5.7 раза точнее)
#
# РАСКЛАДКА МАСШТАБОВ -- НЕ ПРОИЗВОЛЬНАЯ, она повторяет владение внутри ядра. В
# volta_gdn_rec варп w держит строки предпоследней оси vrow = w + 4j, а срез -- 32 строки.
# Поэтому масштаб живёт на (слот, голова, срез, варп), и редукция amax в ядре чисто
# варповая: пять shfl, ни одного барьера. Тот же закон обязан соблюдать и питон, иначе
# ядро и питон разойдутся ТИХО -- ошибкой в разы, но не в порядках (проверено: сверка с
# усреднением по варпам дала 1.85e-01 вместо 7.6e-05, и это врал ПРИБОР, а не ядро).
#
# ГДЕ ЖИВЁТ ТАБЛИЦА. Рядом с пулом, а не внутри него: MambaSpec переварил бы и третий
# тензор (аллокатор идёт по zip(shapes, dtypes)), но это правка спеки, page_size и учёта
# ёмкости. Таблица весит 0.2 % пула (1.5 КиБ против 786 КиБ на блок на слой), а привязка
# идёт по тому же слоту, что и состояние. Приватный формат законен, пока читатели наши.
import os

import torch

BV = 32          # ширина среза по предпоследней оси -- как в ядре
WARPS = 4        # варпов в блоке -- как в ядре
QMAX = 32766.0   # делитель с запасом на округление; насыщения в ядре нет
# Квантование одним ядром вместо семи запусков торча (см. `квант`). Откат -- =0.
_ЯДРОМ = os.environ.get("FA2SM70_GDN_I16_KERNEL", "1") == "1"
_БУФ: dict = {}      # переиспользуемые буферы квантования (см. `квант`)


def включён() -> bool:
    return os.environ.get("FA2SM70_GDN_I16", "0") == "1"


def форма_масштабов(форма_состояния) -> tuple:
    """(блоков, HV, D1, D2) -> (блоков, HV, D1/BV, WARPS)."""
    блоков, hv, d1 = форма_состояния[0], форма_состояния[1], форма_состояния[2]
    assert d1 % BV == 0, f"предпоследняя ось {d1} не кратна срезу {BV}"
    return (блоков, hv, d1 // BV, WARPS)


def таблица(ssm_state: torch.Tensor) -> torch.Tensor:
    """Ленивая приватная таблица масштабов, привязанная К ЭТОМУ тензору состояния."""
    т = getattr(ssm_state, "fa2sm70_scales", None)
    if т is None:
        # [МИНА ГРАФА, 06.09] ЛЕНИВОЕ СОЗДАНИЕ ВНУТРИ ЗАХВАТА -- ЭТО ПАМЯТЬ ПУЛА ГРАФА.
        # Тензор, выделенный во время захвата, принадлежит пулу графа: после захвата эта
        # память переиспользуется, а ЗАПЕЧЁННЫЙ в граф указатель на масштабы продолжает
        # по ней писать. Снаружи -- Xid 13 и смерть воркера, и ровно этой тройкой
        # (спекуляция + полный граф + int16-пул) дефект и опознан бисекцией (§153).
        # Поэтому: создаём ВНЕ захвата, а если захват уже идёт -- громко отказываем,
        # чтобы это было видно на подъёме, а не через сутки в бою.
        if torch.cuda.is_available() and torch.cuda.is_current_stream_capturing():
            raise RuntimeError(
                "[fa2_sm70] таблица масштабов int16 создаётся ВО ВРЕМЯ захвата графа: "
                "её память принадлежит пулу графа и будет переиспользована. "
                "Создайте её до захвата (прогрев) или снимите FA2SM70_GDN_I16.")
        т = torch.ones(форма_масштабов(ssm_state.shape),
                       dtype=torch.float32, device=ssm_state.device)
        ssm_state.fa2sm70_scales = т
    return т


def _амакс(x: torch.Tensor) -> torch.Tensor:
    """amax по владению варпа: (..., HV, D1, D2) -> (..., HV, D1/BV, WARPS).

    D1 разбивается на срезы по BV, а внутри среза строка r принадлежит варпу r % WARPS
    (в ядре: vrow = warp + 4*j). Значит форма разбора -- (срез, j, варп, столбцы), и
    сворачивать надо по j и по столбцам.
    """
    *голова, hv, d1, d2 = x.shape
    y = x.reshape(*голова, hv, d1 // BV, BV // WARPS, WARPS, d2)
    return y.abs().amax(dim=-1).amax(dim=-2)


def квант(x: torch.Tensor, свои_буферы: bool = False) -> tuple:
    """float -> (int16, масштабы). Масштаб = amax/QMAX, поэтому переполнение невозможно.

    [ЯДРОМ, А НЕ ЦЕПОЧКОЙ ТОРЧА -- 31.08] Питонная запись ниже стоит СЕМИ запусков ядер
    (.float, reshape, abs, amax, amax, where, деление, round, .to) и была самой заметной
    нашей строкой в горячем пути: py-spy на воркере под нагрузкой дал 1.18 % снимков на
    `q, s = квант(значение)` плюс ~0.4 % на его частях. Замер ядра против питона:
        (4, 8, 128, 128)   170.5 -> 8.6 мкс   x19.7
        (16, 8, 128, 128)  173.1 -> 39.4      x4.40
        (64, 8, 128, 128)  409.8 -> 136.0     x3.01
    Гейт -- ПОБИТОВОЕ совпадение q и масштабов на шести случаях (fp32 и fp16). Совпадение
    далось не сразу: пришлось взять `rintf` (torch.round округляет половину К ЧЁТНОМУ) и
    `__fdiv_rn` (единица трансляции собрана с --use_fast_math, а он делает деление
    приближённым -- обычное `/` и `__fdividef` расходились на единицу в 0.015 % значений).
    Откат -- FA2SM70_GDN_I16_KERNEL=0.
    """
    if _ЯДРОМ and x.is_cuda and x.dim() >= 3 and x.shape[-2] % BV == 0:
        try:
            from fa2_sm70._ext import gdn_ext
            xc = x.contiguous()
            # [БУФЕРЫ ПЕРЕИСПОЛЬЗУЮТСЯ 31.08] Состояние GDN весит 786 КиБ на блок на слой, и
            # прежде КАЖДЫЙ вызов выделял под q и s новые тензоры. Виду `ssm_state[индекс]`
            # писать напрямую нельзя: индекс -- тензор НА КАРТЕ, а `int()` над ним стоил бы
            # синхронизации с хостом в горячем пути. Поэтому убираем хотя бы выделение:
            # держим буферы по форме и переиспользуем их (запись в пул всё равно копирует).
            # ПЕРЕИСПОЛЬЗОВАНИЕ ТОЛЬКО ПО ЯВНОЙ ПРОСЬБЕ. `квант` -- функция публичная, и
            # если она начнёт отдавать ОДИН И ТОТ ЖЕ буфер, любое сравнение двух её вызовов
            # (в том числе наш собственный побитовый гейт) станет тождественным всегда --
            # прибор согласится сам с собой. Просит буфер только `писать`, где результат
            # немедленно копируется в пул.
            _к = (tuple(xc.shape), xc.device) if свои_буферы else None
            _б = _БУФ.get(_к) if _к is not None else None
            if _б is None:
                q = torch.empty(xc.shape, dtype=torch.int16, device=xc.device)
                s = torch.empty((*xc.shape[:-2], xc.shape[-2] // BV, WARPS),
                                dtype=torch.float32, device=xc.device)
                # В КЭШ -- ТОЛЬКО ВНЕ ЗАХВАТА ГРАФА. Тензор, выделенный во время захвата,
                # принадлежит ПУЛУ ГРАФА: после захвата эта память переиспользуется. Если
                # такой буфер осел в `_БУФ`, то последующие ОБЫЧНЫЕ вызовы (префилл, шаги
                # вне графа) пишут в чужую память, а граф -- в свою; снаружи это Xid 13 и
                # смерть воркера. Тот же класс, что ленивая таблица масштабов (§153).
                # Внутри захвата буфер выделяется каждый раз -- это штатные промежуточные
                # тензоры графа, они и должны жить в его пуле.
                _захват = False
                try:
                    _захват = torch.cuda.is_current_stream_capturing()
                except Exception:
                    _захват = False
                if _к is not None and len(_БУФ) < 8 and not _захват:
                    _БУФ[_к] = (q, s)
            else:
                q, s = _б
            gdn_ext().gdn_state_quant(xc, q, s, QMAX)
            return q, s
        except Exception:
            pass                      # ускорение -- не условие работы: падать оно не вправе
    a = _амакс(x.float())
    s = torch.where(a > 0, a / QMAX, torch.ones_like(a))
    q = torch.round(x.float() / _растянуть(s, x.shape)).to(torch.int16)
    return q, s


def деквант(q: torch.Tensor, s: torch.Tensor, dtype=torch.float32) -> torch.Tensor:
    return (q.to(torch.float32) * _растянуть(s, q.shape)).to(dtype)


def _растянуть(s: torch.Tensor, форма) -> torch.Tensor:
    """(..., HV, D1/BV, WARPS) -> (..., HV, D1, D2) по тому же закону владения."""
    *голова, hv, d1, d2 = форма
    y = s.reshape(*голова, hv, d1 // BV, 1, WARPS, 1)
    y = y.expand(*голова, hv, d1 // BV, BV // WARPS, WARPS, 1)
    return y.reshape(*голова, hv, d1, 1).expand(*голова, hv, d1, d2)


def читать(ssm_state: torch.Tensor, индекс, dtype=torch.float32) -> torch.Tensor:
    """Состояние по индексу слота -- в вещественном виде."""
    if ssm_state.dtype != torch.int16:
        return ssm_state[индекс].to(dtype)
    return деквант(ssm_state[индекс], таблица(ssm_state)[индекс], dtype)


def писать(ssm_state: torch.Tensor, индекс, значение: torch.Tensor) -> None:
    """Записать вещественное состояние по индексу слота."""
    if ssm_state.dtype != torch.int16:
        ssm_state[индекс] = значение.to(ssm_state.dtype)
        return
    q, s = квант(значение, свои_буферы=True)
    ssm_state[индекс] = q
    таблица(ssm_state)[индекс] = s
