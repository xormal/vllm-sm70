# ФАЛЬСИФИКАТОР СНЯТИЕМ ФАЗЫ: обмен TP заменяется тождеством.
#
# Ответ становится ЗАВЕДОМО НЕВЕРНЫМ -- читается ТОЛЬКО ВРЕМЯ. Это единственный способ узнать долю
# фазы: счёт байт даёт верхнюю оценку, а не цену, потому что свёртка на двух картах -- ещё и БАРЬЕР,
# и ожидание отставшего ранга платится здесь же (память: "платим за БАРЬЕР, а не за байты" --
# обмен весил 6.7% по описи и 23% по замеру).
#
# ГДЕ ИМЕННО ПОДМЕНЯТЬ -- НЕ ВСЁ РАВНО. Первая попытка подменяла vllm-уровневую
# `tensor_model_parallel_all_reduce` и функцию в модуле linear: рычаг включался (32 свёртки снято,
# 4.83 ГБ не отправлено), а движок падал в profile_run -- torch.compile строит граф вокруг
# ЗАРЕГИСТРИРОВАННОЙ операции, и подмена питоновского имени рвёт ему граф. Подменять надо НИЖЕ
# регистрации -- в коммуникаторе устройства: тогда весь путь vLLM, включая граф, остаётся дословно
# тем же, а до NCCL дело не доходит.
#
# Включается FA2SM70_GATES='FA2SM70_БЕЗ_ОБМЕНА=1' (bash не умеет кириллические имена переменных
# напрямую -- см. ASCII-ворота в sitecustomize.py). Только на тестовом порту.
import os
import sys

if os.environ.get("FA2SM70_БЕЗ_ОБМЕНА", "0") == "1":
    счёт = {"n": 0, "байт": 0}

    def _тождество(self, input_, *a, **k):
        счёт["n"] += 1
        счёт["байт"] += input_.numel() * input_.element_size()
        if счёт["n"] & (счёт["n"] - 1) == 0:
            print(f"[fa2_sm70 БЕЗ ОБМЕНА] свёрток пропущено {счёт['n']}, "
                  f"байт не отправлено {счёт['байт']/1e9:.2f} ГБ -- ВЫВОД НЕДЕЙСТВИТЕЛЕН",
                  file=sys.stderr, flush=True)
        return input_

    сколько = 0
    for путь, имя in (
        ("vllm.distributed.device_communicators.base_device_communicator",
         "DeviceCommunicatorBase"),
        ("vllm.distributed.device_communicators.cuda_communicator", "CudaCommunicator"),
    ):
        try:
            мод = __import__(путь, fromlist=[имя])
            кл = getattr(мод, имя)
            if "all_reduce" in кл.__dict__:
                кл.all_reduce = _тождество
                сколько += 1
        except Exception:
            pass
    print(f"[fa2_sm70] ОБМЕН TP СНЯТ на уровне КОММУНИКАТОРА (классов подменено {сколько}). "
          f"ОТВЕТЫ НЕВЕРНЫ ПО ПОСТРОЕНИЮ, годно только для замера времени.",
          file=sys.stderr, flush=True)
    if сколько == 0:
        print("[fa2_sm70] ВНИМАНИЕ: ни один класс не подменён -- ПРИБОР СЛЕП, "
              "замер недействителен.", file=sys.stderr, flush=True)
