//
// ГЛАВНОЕ, И ЭТО ИСПРАВЛЯЕТ §4e: 0.784 прочих на 0.392 HMMA = ДВЕ нетензорные инструкции на HMMA
// при 95.4% тензорной пропускной способности. Записанное ранее "HMMA занимает 2 такта -> ровно ОДИН
