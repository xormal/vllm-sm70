// всего 4.6%, отдавая при этом 0.784 инструкций/такт прочей работы. Причина: чем больше НЕЗАВИСИМОЙ
// работы предъявлено планировщику, тем полнее он затыкает дыры. FP64 в набор не входит: он роняет
