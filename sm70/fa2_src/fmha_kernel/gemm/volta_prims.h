// 4p. [ИСПРАВЛЕНО 31.07: ЗАГОЛОВОК БЫЛ НЕВЕРЕН -- ОШИБКА ЕДИНИЦ]
//     Прежняя формулировка "БЮДЖЕТ ВЫДАЧИ БЫЛ ЗАНИЖЕН ВДВОЕ, он не 1, а 2 по конвейерам"
//     ОПРОВЕРГНУТА. Цифра 0.784 "прочих на такт" считалась против PTX-уровня mma.sync, а ОДНА
//     mma.sync это ЧЕТЫРЕ SASS-команды HMMA.884. В пересчёте на SASS выходит 0.5 вспомогательной
//     на HMMA, то есть бюджет ПОДТВЕРЖДАЕТ nu <= 1, а не удваивает его.
//     Независимый различитель, снимающий спор замером: отношение e5m2/int8 = 1.051 (среднее по
//     четырём формам). При "бюджете 2" оба варианта были бы ПОД стеной и отношение равнялось бы
//     РОВНО 1.000. Замер 1.051 отвергает это однозначно.
//     Верно: docs/VOLTA_SM70.md, §3b "Учёт по слотам выдачи" (tau = 2 такта на HMMA.884,
//     бюджет tau-1 = 1.00 вспомогательной выдачи на одну тяжёлую).
//     ПОЧЕМУ ЭТО ВАЖНО ИСПРАВИТЬ, А НЕ ПРОСТО УТОЧНИТЬ: заниженный вдвое потолок приглашает
//     переоткрывать пути, замеренно мёртвые -- ровно та ошибка, ради недопущения которой этот
