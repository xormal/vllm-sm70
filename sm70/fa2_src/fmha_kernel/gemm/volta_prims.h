// ЭТО МЕНЯЕТ ТРАКТОВКУ §4n. Барьер НЕ дорог сам по себе -- дорого ОЖИДАНИЕ. Передача "загрузил в
// один буфер, щёлкнул, забрал в другом" стоит ПРОИЗВОДИТЕЛЮ 2.76 такта; платит только ПРИНИМАЮЩИЙ.
// На архитектуре без cp.async это единственный способ построить асинхронную передачу: producer
// делает bar.arrive и НЕ ОСТАНАВЛИВАЕТСЯ, consumer делает bar.sync и ждёт только когда данные
// действительно нужны.
//
// ПРАКТИЧЕСКОЕ СЛЕДСТВИЕ ДЛЯ ЯДРА: каждый __syncthreads() в мейнлупе -- это ПОЛНЫЙ bar.sync по
// 33.4 такта на ОБЕ стороны. Там, где синхронизация нужна ОДНОСТОРОННЯЯ (производитель закончил ->
// потребителю можно читать), сторона производителя должна ставить bar.arrive (2.76), а ожидание
// оставлять только принимающей стороне. Разделять надо КАЖДЫЙ односторонний __syncthreads.
//
// ЧЕГО ЭТОТ ЗАМЕР НЕ ПОКАЗАЛ (честно): специализация варпов (2 грузят / 6 считают на именованных
// барьерах 1 и 2) дала лишь x1.012 против монолита. Но тест перекошен -- два варпа грузят 2048
// чисел против шести варпов на четырёх MMA, и обе ветки упираются в одни и те же глобальные чтения.
// Это негодный замер ПРИЁМА, а не опровержение приёма. Чистый результат здесь -- цена половинок.

// =================================================================================================
// 4r. ЁМКОСТЬ INT32 ПОД HMMA И СДВИГ ФАЗЫ: теряет ЗАВИСИМОСТЬ, а не занятость
// =================================================================================================
// ЁМКОСТЬ (tools/volta_int32_capacity.cu) -- независимые перестановки байт на фоне HMMA:
//   int32 на 4 HMMA:   0     2     4     6     8    12    16
//   на 1 HMMA:        --   0.5   1.0   1.5   2.0   3.0   4.0
//   от тензорного пика: 1.000 0.985 0.924 0.933 0.923 0.879 0.682
// РАБОЧАЯ ТОЧКА -- ДВЕ целочисленные инструкции на HMMA при 92% пика, и внутри есть ПЛАТО:
// переход с одной на две НЕ СТОИТ НИЧЕГО (0.924 -> 0.923). Заплатив первые 7.6%, вторую получаешь
// даром. Обрыв на четырёх (0.682). Планировать надо на 2/HMMA, а не на 1.
//
// СДВИГ ФАЗЫ (tools/volta_pipelined_expand.cu) -- то же количество работы, разная зависимость:
//   потолок (операнды готовы) ................. 0.428 HMMA/такт   1.000
//   разворот int8 В ЦЕПИ с той же MMA ......... 0.379            0.886   (потеря 11.4%)
//   разворот СДВИНУТ на плитку вперёд ......... 0.398            0.931   (потеря 6.9%)
// x1.052 при ТОМ ЖЕ числе инструкций. Потерю режет вдвое ОДИН приём: разворачивать плитку N+1,
// пока тензор считает плитку N. Тогда перестановки не зависят от текущей MMA и уезжают в свободные
// слоты; в цепи они стоят на критическом пути и слоты не спасают.
