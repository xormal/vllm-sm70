//
// ЧТО ЭТА ВЕДОМОСТЬ ГОВОРИТ КАК ЦЕЛОЕ. Наш мейнлуп построен ФАЗАМИ: загрузить -> посчитать ->
// софтмакс -> посчитать. Замеры же говорят, что фазы должны быть не ПОСЛЕДОВАТЕЛЬНЫ, а СДВИНУТЫ:
// в один и тот же момент тензор на плитке N, INT32 на N+1, FP32 на N-1, LSU на N+1. Это не
// оптимизация ядра, это СМЕНА КООРДИНАТ -- та самая перепараметризация из доктрины: задача
// "ускорить операции" переписана как "разнести зависимости по фазам", и в новых координатах
// ограничение становится чистым.
//
// ПОРЯДОК РАБОТ, вытекающий из ведомости (по убыванию отношения "выигрыш / риск"):
//   1. подсказки .cs/.lu + предвыборка на потоковых K/V -- одна строка, +6% и +5.3%, риск нулевой;
//   2. все обращения к разделяемой памяти шириной 128 бит -- вчетверо меньше MIO при той же полосе;
//   3. разделить односторонние __syncthreads на bar.arrive / bar.sync -- 2.76 вместо 33.4;
//   4. варп-однородные величины (масштабы и нули GPTQ, шаги, длины) -- в параметры ядра, на путь
//      констант, который у нас простаивает ПОЛНОСТЬЮ;
//   5. сдвиг фаз в мейнлупе: разворот и адреса плитки N+1 вперемешку с MMA плитки N;
//   6. подложить fp32-доводку под ex2 софтмакса вместо отдельной фазы.
// Первые четыре -- локальные правки, пятая и шестая -- перестройка мейнлупа.

// =================================================================================================
// 4t. РАЗНЕСЕНИЕ ЦЕЛОЧИСЛЕННОЙ РАБОТЫ ПО ДВУМ КОНВЕЙЕРАМ: 1.45x за 2.7 пункта
// =================================================================================================
// Замерено tools/volta_int_in_fp32.cu. Под HMMA целочисленную работу можно вести НА ДВУХ конвейерах
// сразу: перестановками байт на INT32 и упакованными полями (§1e) на FP32.
//   состав                                  HMMA/такт  от пика  целых/такт/SM
//   потолок (целых нет) ................... 0.434      1.000    --
//   16 int32 (рабочая точка 2/HMMA, §4r) .. 0.380      0.875    0.760
//   8 int32 + 8 fp32x2 .................... 0.368      0.848    1.104   <- x1.45 за 2.7 пункта
//   16 int32 + 16 fp32x2 .................. 0.324      0.747    1.946   <- x2.56 за 12.8 пунктов
//
// ПРАВИЛО: когда INT32 упирается в свои ДВЕ инструкции на HMMA (§4r), переполнение надо уводить в
// FP32 упакованными полями, а не давить дальше на INT32. На инструкцию fp32 при этом ЭФФЕКТИВНЕЕ:
// одна инструкция -- два целых, тогда как prmt -- одно.
//
// ЭТО ЗАМЫКАЕТ ВЕДОМОСТЬ §4s. Полный набор мест, где можно вести целочисленную работу под тензором:
//   INT32 ..... 2 инстр/HMMA при 92% (§4r)          -- перестановки, маски, адреса
//   FP32 ...... +1.45x к этому за 2.7 пункта (§4t)  -- упакованные поля 2x12
//   тензор .... сами HMMA считают int8 точно (§1)   -- если работа выражается умножением
//   fp64 ...... 4 поля, но ломает тензор до 0.843   -- только когда тензор не занят
// Выбирать надо ПО ЗАНЯТОСТИ, а не по "естественности" типа: целое не обязано считаться на INT32.

// =================================================================================================
// 4u. ЧТО ДЕШЕВЛЕ ДЕЛАТЬ В ТЕНЗОРАХ: межполосное -- да, поэлементное -- нет
// =================================================================================================
// Вопрос ставится НЕ "какая инструкция куда положена по паспорту", а "что дешевле выполнить ВНУТРИ
// блока". Тензор считает D = A*B + C, значит он дёшев для всего, что выражается умножением на
// СТРУКТУРНУЮ КОНСТАНТУ: диагональ (масштаб строк), единицы (редукция), одногорячий (выборка),
// перестановка. Замерено (tools/volta_tensor_cheap.cu), тактов на операцию над 8 накопителями:
//   перемасштабирование строк: 8 x mul.f32 .... 0.063 | diag через ОДНУ mma .. 0.061  x1.04 -- НИЧЕГО
//   сумма по строке: 8 слож. + 5 бабочек ...... 0.115 | умножение на единицы .. 0.069  x1.66 -- ДА
//
// ПРИНЦИП: тензор дёшев там, где работа МЕЖПОЛОСНАЯ, и бесполезен там, где ПОЭЛЕМЕНТНАЯ. Причина
// прямая: суммирование по k ВСТРОЕНО в саму MMA -- кроссбар уже внутри блока и не стоит ничего.
// Перемасштабирование поэлементно, полосы не пересекаются, FP32 делает его на полном темпе.
//
// ЭТО ТРЕТИЙ МАРШРУТ ДЛЯ МЕЖПОЛОСНОГО, и по редукции он самый дешёвый из всех:
//   сдвиги .............. половинный темп (§4e), бабочка ~16 тактов
//   разделяемая память .. через MIO (узкое место) + барьер (§4n, §4q)
//   ТЕНЗОР .............. одна инструкция, редукция встроена            <- x1.66 над сдвигами
// У нас в софтмаксе ДВЕ межполосные редукции (максимум и сумма по строке) -- сумма ложится сюда
// напрямую, максимум требует другой структурной константы и отдельной проверки.
//
// ОШИБКА, КОТОРУЮ ЗДЕСЬ ЖЕ НАДО ЗАПОМНИТЬ: сравнивая маршруты для int8 в умножениях-с-накоплением,
// я взял 256 МАС на mma.m8n8k4 и получил, будто dp4a вдвое быстрее тензора. На Volta варп делится
// на ЧЕТЫРЕ квад-пары, и каждая считает свой 8x8x4 -- на инструкцию варпа 1024 МАС, а не 256.
// Проверка размерностью: 0.43 инстр/такт x 80 SM x 1.38 ГГц x 1024 x 2 = 97 TFLOPS при паспортных
// 125 (78%, правдоподобно); с константой 256 вышло бы 24 TFLOPS на цикле из одних MMA, чего быть не
// может. ВЕРНО: тензор 440 МАС/такт/SM, dp4a 217, поля fp32 108 -- и совмещение даёт 442 против 440,
// то есть НИЧЕГО: они не складываются, а перекладывают. ДЛЯ ЧИСТЫХ УМНОЖЕНИЙ ДОЗАГРУЖАТЬ ТЕНЗОР
// ДРУГИМИ МАРШРУТАМИ БЕССМЫСЛЕННО. Разнесение (§4r, §4t) работает только для работы, которую тензор
// НЕ УМЕЕТ: перестановки, маски, адреса, распаковка -- там числа мерились в инструкциях и в силе.

// =================================================================================================
// 4v. ПЕРВОЕ ПРИМЕНЕНИЕ ВЕДОМОСТИ К ЖИВОМУ ЯДРУ: три маршрута, все три мимо
// =================================================================================================
// Применил §4s к рукописному forward (volta_fwd_block.cuh, d=256, частоты зафиксированы, 5 форм).
// Геометрия НЕ трогалась -- менялся только КАНАЛ для той же работы. Результат отрицательный, и
// каждая из трёх причин стоит больше самого замера.
//
//   маршрут                S=4096   S=8192  S=16384  H=16     чанк 16K     вывод
//   база                    1.055    3.565    6.916   3.667    60.36
//   широкая запись V        1.054    3.573    6.911   3.673    60.24       НОЛЬ
//   предвыборка L2          1.037    3.555    6.919   3.694    60.76       +2% только на мелкой
//   подсказка .cs           1.065    3.656    7.054   3.810    61.91       ХУЖЕ ВЕЗДЕ
//
// (1) .cs ПОДТВЕРДИЛ ОПАСЕНИЕ, ВЫСКАЗАННОЕ ДО ЗАМЕРА. Он помечает строку "вытеснять первой", а
//     плитку ключей читают ВСЕ блоки запросов (попадание в L2 97.7%). Подсказка выбрасывает то,
//     что сейчас понадобится соседу. ЗАКОН: .cs законен только там, где переиспользования НЕТ.
//     Замеренные ранее +6% сняты на чистом потоке -- переносить их на кэшируемые данные нельзя.
//
// (2) ШИРОКАЯ ЗАПИСЬ ДАЛА НОЛЬ, И ЭТО МОЯ МЕТОДИЧЕСКАЯ ОШИБКА. Ведомость говорит "широкие
//     обращения режут MIO вчетверо", и я применил это к ПЕРЕКЛАДКЕ V -- а она составляет 32 КБ на
//     плитку против ~780 КБ чтений ФРАГМЕНТОВ операндов. Я расширил ЧЕТЫРЕ ПРОЦЕНТА трафика и
//     получил четыре процента от четырёх процентов. ПРАВИЛО: перед применением рычага посчитать,
//     какую долю ограничителя занимает то, к чему рычаг прикладывается. Это тот же класс ошибки,
//     что "считать свободные слоты без учёта зависимости" (§4r).
//
// (3) НАСТОЯЩИЙ ПОТРЕБИТЕЛЬ -- ЧТЕНИЯ ФРАГМЕНТОВ (LDS.64, 1.5 на MMA). Их расширение до LDS.128
//     существует (accumulate_swzA), но требует XOR-перемешивания, которое СТАТИЧЕСКИ несовместимо
//     с программным конвейером PIPE=3. То есть в текущей схеме подачи рычаг недоступен: это не
//     правка маршрута, а другой мейнлуп. Гипотеза о невыравнивании (LDQ = 260 полуслов = 520 Б,
//     не кратно 16) остаётся НЕПРОВЕРЕННОЙ и требует отдельной сборки.
//
// ЧТО ИЗ ЭТОГО СЛЕДУЕТ ДЛЯ ВЕДОМОСТИ §4s: строки ведомости -- это ЁМКОСТИ, а не выигрыши. Выигрыш
// даёт только рычаг, приложенный к ДОМИНИРУЮЩЕЙ доле ограничителя. Порядок работ надо строить не
// по "сколько обещает рычаг", а по "какую долю ограничителя он трогает".

// =================================================================================================
// 4w. ЯДРО НА int8 ЗАМЕРЕНО: x0.70-0.74 к fp16. ЗАКОН ТРАНСПОРТА ПРИМЕНЁН К НЕ ТОМУ УРОВНЮ
// =================================================================================================
// Ядро volta_fwd_i8.cuh построено ВЫВОДОМ из закона транспорта, корректно на шести формах (relL2
// 3e-4..6e-4), и ЗАМЕРЕНО МЕДЛЕННЕЕ fp16 на 30% на всех формах:
//   форма            наш fp16   наш int8   cutlass   SDPA-eff
//   (1,4,4096)          1.050   1.508 x0.70  1.050     1.834
//   (1,16,4096)         3.641   4.931 x0.74  3.633     6.386
//   (1,4,8192)          3.581   5.060 x0.71  3.562     7.072
//   (1,2,16384)         6.960   9.760 x0.71  6.902    15.313
//   (1,24,8192,32K)   141.527 198.620 x0.71 141.583      --
//
// ПРИЧИНА ПЕРВАЯ, И ЭТО ОШИБКА ВЫВОДА. Закон транспорта я посчитал против HBM: нужно 58 МАС/байт.
// Но трафик до HBM НЕ ДОХОДИТ -- замерено 97.7% попаданий в L2. Эффективное требование
// 58 * 0.023 = 1.3 МАС/байт, и fp16 при своих 32 перекрывает его в 25 раз. Собственный планировщик
// это и показывал -- он называл ограничителем РАЗДЕЛЯЕМУЮ ПАМЯТЬ, а не HBM. Я вывел конструкцию из
// требования к уровню иерархии, который узким местом НЕ ЯВЛЯЕТСЯ.
//   ПРАВИЛО: закон транспорта применять к ТОМУ УРОВНЮ, который ограничивает. Считать надо не
//   "сколько байт нужно из HBM", а "с какого уровня они реально приходят".
//
// ПРИЧИНА ВТОРАЯ, СТРУКТУРНАЯ. Разворот int8 -> fp16 идёт В РАЗДЕЛЯЕМУЮ ПАМЯТЬ, значит она держит
// ТЕ ЖЕ fp16-данные, что и раньше: экономии на ограничителе НОЛЬ, а работа разворота и поправок
// добавлена. Сэкономлено там, где не жмёт; заплачено там, где жмёт. Это тот же класс ошибки, что в
// §4v -- рычаг приложен не к доминирующей доле ограничителя.
//
// КУДА ЭТО ЧИНИТСЯ (не проверено, но направление следует из тех же замеров): держать K/V в int8
// ПРЯМО В РАЗДЕЛЯЕМОЙ ПАМЯТИ и разворачивать ТОЛЬКО ВО ФРАГМЕНТЫ В РЕГИСТРАХ при подаче в MMA.
// Тогда трафик разделяемой памяти падает вдвое -- рычаг прикладывается к настоящему ограничителю,
// -- а разворот уезжает в свободные слоты INT32 (§4r). Операторы для этого уже есть:
// volta_warp_mma.h, load_b_p_i8 / accumulate_bi8.
//
// ЧТО В ЭТОМ ЗАМЕРЕ ПОЛОЖИТЕЛЬНОГО: наш fp16-путь идёт вровень с cutlass и БЫСТРЕЕ SDPA в 1.75-2.2
// раза на всех квадратных формах.
//
// --- ДОДЕЛКА И ОКОНЧАТЕЛЬНЫЙ РАЗБОР (после починки по указанному выше направлению) ---
// Починка сделана: K оставлен БАЙТОВЫМ в разделяемой памяти, разворот перенесён во фрагменты в
// регистрах (accumulate_bi8, сдвиг фазы уже внутри оператора), масштабы квантования подняты из
// разделяемой памяти в регистры. Корректность БИТ В БИТ. Результат: x0.71-0.76 вместо x0.70-0.74,
// то есть ПОЧТИ НИЧЕГО. Два подряд угаданных "виновника" (разворот в smem, чтения масштабов)
// оказались не теми -- и это стоило двух правок вместо одного профиля.
//
// СТАТИЧЕСКИЙ РАЗБОР SASS ОБОИХ ТЕЛ (одна геометрия, инструкций в теле):
//   ядро    всего  HMMA  LDS/STS  FP32  INT/логика
//   fp16     3093  1024      345   439         446
//   int8     4092  1024      368   561         935
//   разница  +999     0      +23  +122        +489
// ЯДРО УПИРАЕТСЯ В ИНСТРУКЦИИ, и int8 добавил 32% инструкций, НЕ УБРАВ НИ ОДНОЙ. Замеренное
// замедление +39% с этим сходится. И решающее: РАЗДЕЛЯЕМАЯ ПАМЯТЬ НЕ РАЗГРУЗИЛАСЬ -- обращений
// стало на 23 БОЛЬШЕ. Рычаг, ради которого всё строилось, не сработал, и причина видна из раскладки
// фрагментов: у k-мажорного операнда K даёт NB/(MB*NB) = 0.5 обращения на MMA против 1.0 у Q, то
// есть лишь треть, а сэкономленное съедено байтовой перекладкой K и по-прежнему fp16-записью V.
//
// ВЕРДИКТ ПО МАРШРУТУ: время НЕ минимально, и маршрут выбран неверно -- не "чуть хуже", а
// структурно. По лестнице §0 это ярус 1 ("больше работы за одну выдачу"), приложенный там, где
// ВЫДАЧА И ЕСТЬ ограничитель. Сжатие формата окупается только если оно снимает БОЛЬШЕ инструкций,
// чем добавляет разворот; здесь баланс -489 против +611 (INT+FP32), то есть заведомо отрицательный,
// и это можно было посчитать ДО постройки.
//
// БАЛАНС НАДО СЧИТАТЬ ВЗВЕШЕННО, А НЕ ШТУКАМИ -- иначе вывод выше ТОЖЕ неверен. Пересчёт по весам
// §4p/§4r (свободные слоты под HMMA: ~1 int32 и ~1 fp32 на HMMA):
//   ядро   int/HMMA  fp/HMMA  доля тензорного пика
//   fp16      0.44     0.43          0.981
//   int8      0.91     0.55          0.927
// Загрузка INT32 растёт с 0.44 до 0.91 на HMMA, а это ЕЩЁ БЕСПЛАТНАЯ ЗОНА (§4r: 0.5 -> 0.985,
// 1.0 -> 0.924). Взвешенный прогноз: int8 должен быть x1.06, то есть ЧУТЬ БЫСТРЕЕ. Замерено x0.72.
// РАСХОЖДЕНИЕ x1.47 -- и значит дело НЕ В ОБЪЁМЕ инструкций, а в том, что добавленная работа НЕ
// ЕДЕТ В СВОБОДНЫЕ СЛОТЫ.
//
// ПРОВЕРКА ЭТОГО ДИАГНОЗА (сделана, результат частичный). Два звена цепи убраны по §4m:
//   * смещение K -- в ЗАТРАВКУ аккумулятора (операнд C бесплатен), примитив §2a seed_rank1;
//   * смещение V -- ПРЕДвычитание, слитое с домножением на corr в один FFMA, примитив §2b rescale_fold.
// Оба легли в библиотеку как примитивы. Корректность бит в бит. Выигрыш: x0.72 -> x0.72..0.77,
// то есть ОКОЛО ПРОЦЕНТА. Значит эти два звена цепи не были главными, и сериализует что-то ещё --
// вопрос ОТКРЫТ и требует динамического профиля (стеки простоев), а не статического счёта.
//
// ПРОФИЛЬ СНЯТ, И ОН ОБЪЯСНЯЕТ ВСЁ -- ВКЛЮЧАЯ ПОЧЕМУ КАЖДАЯ ПРАВКА ДАВАЛА ~1%:
//                              fp16        int8
//   такты                    525 927   722 596  (x1.374)
//   тактов варпа/инструкцию     6.20      5.61   <- у int8 ЛУЧШЕ
//   L1/TEX                     53.3%     41.1%   <- у int8 ЛУЧШЕ
//   вычислительная пропускная  21.2%     22.9%
//   ЗАНЯТОСТЬ                 12.46%    12.47%   <- ВОТ ОНО
//   Block Limit Registers          1         1
//   Block Limit Shared Mem         1         1
//
// ЯДРО НЕ УПИРАЕТСЯ НИ В ОДИН КОНВЕЙЕР -- ОНО УПИРАЕТСЯ В ЗАДЕРЖКИ ПРИ ЗАНЯТОСТИ 12.5%.
// Вычислительная пропускная 21%, память 35%, на планировщик приходится ДВА варпа, инструкция
// выдаётся раз в 6.2 такта. Занять паузу нечем.
//
// И ОТСЮДА ГЛАВНАЯ ПОПРАВКА КО ВСЕМУ РАЗДЕЛУ §4p/§4r: СВОБОДНЫХ СЛОТОВ, КОТОРЫЕ ТАМ ЗАМЕРЕНЫ,
// В ТАКОМ ЯДРЕ НЕТ. Те ёмкости сняты микротестом с ВОСЕМЬЮ независимыми цепочками -- там
// параллелизма по инструкциям вдоволь, и добавленная работа действительно уезжает в паузы. При
// занятости 12.5% и низком ILP добавленная инструкция добавляет время ОДИН К ОДНОМУ. Замер это
// подтверждает: инструкций +32%, времени +37%.
//   ПРАВИЛО: прежде чем применять ёмкости свободных слотов (§4p, §4r, §4t), ПРОВЕРИТЬ, что ядро
//   ТРОПУСКНО-ограничено, а не задержечно. Признак -- Compute Throughput и Memory Throughput ОБА
//   ниже 60% при низкой занятости: это латентность, и там модель свободных слотов НЕ ДЕЙСТВУЕТ.
//
// ЧТО ПРИ ЭТОМ ВЕРНО ПРО int8: по удельным показателям он ЛУЧШЕ fp16 -- 5.61 такта на инструкцию
// против 6.20 и L1 41% против 53%. Он проигрывает ТОЛЬКО количеством инструкций. То есть в
// ядре, которое было бы пропускно-ограничено, тот же маршрут мог бы выиграть.
//
// НАСТОЯЩИЙ РЫЧАГ НАЗЫВАЕТ САМ ПРОФИЛЬ: Block Limit Registers = 1 И Block Limit Shared Mem = 1 --
// резидентен ОДИН блок, и ограничено это ОДНОВРЕМЕННО регистрами и разделяемой памятью. Оценка
// ncu: локальный запас 87.5%. Чтобы получить второй блок, нужно ОДНОВРЕМЕННО <= 48 КБ разделяемой
// и <= 128 регистров на нить. Сейчас 80 КБ и один блок по обоим пределам -- то есть снимать надо
// ОБА, снятие одного не даст ничего. Вот это и есть следующая работа, а не маршруты.
//
// МЕТОДИЧЕСКИЙ ВЫВОД, ПЯТЫЙ РАЗ ЗА СЕССИЮ: не угадывать. И порядок такой -- СНАЧАЛА профиль
// (занятость и природа ограничения), ПОТОМ взвешенный баланс, и только потом правка. Я шёл в
// обратном порядке четыре раза подряд и каждый раз чинил не то.

// =================================================================================================
// 4x. ДВА ПРЕДЕЛА ЗАНЯТОСТИ СНЯТЫ ПО РАЗДЕЛЯЕМОЙ, НО НЕ ПО РЕГИСТРАМ. СЧИТАТЬ САМИМ, ДО КОМПИЛЯТОРА
// =================================================================================================
// Профиль (§4w) назвал рычаг: Block Limit Registers = 1 И Block Limit Shared Mem = 1, снимать надо
// ОБА. Сделано по порядку, каждый шаг с проверкой корректности БИТ В БИТ:
//   80.0 КБ -> 63.0 КБ : V оставлена БАЙТОВОЙ в разделяемой (минус 17 КБ И минус весь проход
//                        разворота V, ~12 тыс. инструкций на плитку -- в задержечном ядре это
//                        прямой выигрыш, а не размен);
//   63.0 КБ -> 39.0 КБ : Q подаётся КУСКАМИ по d, как K. Перечитывание Q идёт из L2 (DRAM по
//                        профилю 2-4%), суммы строк Q для поправки ранга-1 считаются из глобальной.
// Порог двух блоков (48 КБ) ВЗЯТ. По регистрам -- НЕТ, и это доказано с двух сторон.
//
// РУЧНОЙ СЧЁТ ПЛОТНОСТИ (tools/volta_block_planner.py, тот же приём применим к любой геометрии):
// что обязано быть резидентным ОДНОВРЕМЕННО, чтобы расписание метаблока было исполнимо --
//   накопитель O 64, накопитель S 16, состояние софтмакса 36, фрагменты 12, разворот N+1 4,
//   перекладка N+1 8, масштабы и адреса 20  =  160 при доступных 128.
// Упирается НЕ в укладку, а в накопитель O: он равен BQ*d/нитей и НЕСЖИМАЕМ, потому что держится
// через все плитки ключей. Плюс состояние софтмакса, растущее как SMB.
//
// ЗАМЕР ПОДТВЕРДИЛ, И ДВАЖДЫ -- ПРИНУЖДЕНИЕ ЧЕРЕЗ MINB ВСЕГДА КОНЧАЕТСЯ РАЗЛИВОМ:
//   BQ=64 MINB=1: 217 рег, разлив 0   -> 0.600 мс
//   BQ=32 MINB=1: 168 рег, разлив 0   -> 0.627 мс
//   BQ=32 MINB=2: 128 рег, разлив 48Б -> 0.756 мс   (и 216->128 на BQ=64: 0.600 -> 0.991)
// ptxas НЕ перестраивает укладку ради занятости -- он разливает. Это территория, где компилятор
// противник, и полагаться на него в вопросах плотности нельзя.
//
// И ГРАНИЦА ПРИМЕНИМОСТИ РУЧНОГО СЧЁТА, важная: для BQ=32 он дал 98 регистров, ptxas взял 168 --
// разрыв в 70 на состоянии, которого в модели нет. Значит ручной счёт годится, чтобы ГЕОМЕТРИЮ
// ОТВЕРГНУТЬ (не влезает по счёту -- точно не влезет), но НЕ чтобы её утвердить.

// =================================================================================================
// 4y. ПЕРЕРАСПРЕДЕЛЕНИЕ РЕГИСТРОВ: что удалось МИНИМАЛЬНОЙ ЦЕНОЙ, и где счёт не сошёлся
// =================================================================================================
// До накопителя O (несжимаем, §4x) в бюджете лежат три статьи, режущиеся перераспределением:
//
// (1) ЧИСТАЯ ИЗБЫТОЧНОСТЬ. `corr[i][t] = corr2[i][t]` -- побайтовая копия, жившая отдельными
//     регистрами; `vb_run` после поплиточного снятия хранит вклад ОДНОЙ плитки, тратящийся тут же.
//     Оба убраны, оба передаются напрямую. Цена ноль, выигрыш 4 регистра.
// (2) ОТКАТ РЫЧАГА, ДАВШЕГО НОЛЬ. Масштабы квантования я поднимал из разделяемой в регистры --
//     замерено 1.477 -> 1.473, то есть НОЛЬ, а стоило 8*SNB регистров. Возвращены в разделяемую.
//     ПРАВИЛО: рычаг, давший ноль, надо ОТКАТЫВАТЬ, а не оставлять "пусть будет" -- в ядре, где
//     регистры и есть предел занятости, нулевой рычаг это чистый убыток.
// (3) СЕТКА ВАРПОВ ЧЕРЕЗ SMB. Состояние софтмакса это ДЕВЯТЬ массивов по SMB*2 значений, а
//     SMB = (BQ/WM)/16. Переход 2x4 -> 4x2 (те же 8 варпов) роняет SMB с 2 до 1 и вдвое режет это
//     состояние, при ТОМ ЖЕ числе загрузок на MMA (плитки варпа 32x16 и 16x32 обе дают 1.5).
//
// ЗАМЕРЕНО (BQ=64, S=2048, частоты зафиксированы):
//   2x4 база ................ 217 рег, разлив 0 -> 0.6004 мс
//   2x4 минус (1) и (2) ..... 213 рег, разлив 0 -> 0.6047 мс
//   4x2 всё вместе .......... 210 рег, разлив 0 -> 0.5889 мс   <- И ДЕШЕВЛЕ, И БЫСТРЕЕ
//   4x2 при MINB=2 .......... 128 рег, разлив 208 Б -> 0.8665 мс
// Сетка 4x2 закреплена: цена перераспределения ОТРИЦАТЕЛЬНА (x1.02 к базе).
//
// НО СЧЁТ НЕ СОШЁЛСЯ, И ЭТО ГЛАВНОЕ ЗДЕСЬ. Ручная модель предсказывала -26 регистров (18 от SMB,
// 4 от копии, 8 от масштабов), компилятор отдал -7. Он держит ~76 регистров состояния, которого в
// модели НЕТ, -- тот же разрыв, что при BQ=32 (98 против 168). Значит перераспределение по модели
// даёт ВЕРНОЕ НАПРАВЛЕНИЕ, но не величину, и порог занятости им не берётся: 128 регистров остаются
// недостижимы, а принуждение через MINB третий раз подряд кончается разливом и потерей.

// =================================================================================================
// 4z. КУДА УШЛИ РЕГИСТРЫ: не украдены, а потрачены на разворачивание -- и отбирать их НЕЛЬЗЯ
// =================================================================================================
// Гипотеза была "компилятор держит ~76 регистров сверх алгоритма". РАЗБОР ЖИВОСТИ SASS ЕЁ ОПРОВЕРГ:
// из 204 задействованных регистров через весь мейнлуп живут 62 -- и это РОВНО накопитель O
// (при сетке 4x2 это 1*8*8 = 64). Регистров, которые держатся долго и почти НЕ ЧИТАЮТСЯ, НОЛЬ.
// Компилятор ничего не крадёт: остальные ~142 -- КОРОТКОЖИВУЩИЕ временные, и их столько потому, что
// развёрнуты все циклы разом (по d на 4 шага, по SMB/SNB, конвейер внутри accumulate_bi8), а
// диапазоны жизни перекрываются.
//
// РЕГИСТРЫ ОТБИРАЮТСЯ РУКАМИ -- разворот по d задан явно через _Pragma (обычный #pragma unroll
// МАКРОСЫ НЕ РАСКРЫВАЕТ и молча игнорируется, предупреждение #20169):
//   разворот 4 (было) .... 210 рег, разлив 0    -> 0.5887 мс
//   разворот 2 ........... 164 рег, разлив 0    -> 0.6196 мс
//   разворот 1 ........... 161 рег, разлив 0    -> 0.6189 мс
//   разворот 2, 2 блока .. 128 рег, разлив 348Б -> 0.7805 мс
//   разворот 1, 2 блока .. 128 рег, разлив 104Б -> 0.7006 мс
// Сорок девять регистров ОТОБРАНЫ и это подтверждает диагноз. Но КАЖДЫЙ вариант с отъёмом медленнее.
//
// ЗАКОН, КОТОРЫЙ ИЗ ЭТОГО СЛЕДУЕТ: НЕЛЬЗЯ КУПИТЬ ЗАНЯТОСТЬ ЗА СЧЁТ РЕСУРСА, КОТОРЫЙ ЕЁ ЗАМЕНЯЕТ.
// Ядро задержечное (§4w). Разворачивание и занятость -- ДВА СПОСОБА СПРЯТАТЬ ОДНУ И ТУ ЖЕ задержку:
// перекрывающиеся диапазоны жизни означают много независимых операций в полёте. Забирая регистры у
// разворота ради второго блока, забираешь ровно тот механизм, который компенсирует низкую занятость.
// Обмен даёт ноль или минус, и это видно в таблице: 161 регистр вместо 210 стоил 5% времени, а до
// порога 128 всё равно не хватило 33 -- из которых 64 держит несжимаемый накопитель O.
//
// ВЫВОД ПО ВЕТКЕ ЗАНЯТОСТИ: 12.5% при d=256 -- НЕ недоработка укладки, а структурный предел
// алгоритма. Разделяемая память снята до 39 КБ (§4x), регистры разобраны до последнего, оба конца
// сошлись на накопителе O. Дальше -- только менять сам способ накопления O, то есть алгоритм.

// =================================================================================================
// 4aa. ЗАНЯТОСТЬ ПОКУПАЕТСЯ -- НО ЦЕНА ЗАВИСИТ ОТ ФОРМАТА. ЭТО И ЕСТЬ ЦЕННОСТЬ int8
// =================================================================================================
// Два резидентных блока требуют ОДНОВРЕМЕННО <= 48 КБ разделяемой и <= 128 регистров на нить.
// Механизм покупки -- ДРОБЛЕНИЕ ПО ЗАПРОСАМ (BQ=32): каждый блок владеет своими строками, ничего
// не пересчитывается, K/V перечитываются из L2. Разрез по ВЫХОДНОЙ размерности проигрывает, потому
// что заставляет считать S дважды (работа x1.5), а поделиться S срезы не могут -- это разные БЛОКИ.
//
// ЦЕНА У ДВУХ ФОРМАТОВ РАЗНАЯ, И РАЗНИЦА РЕШАЮЩАЯ:
//   int8: байтовые K/V сами вдвое ужимают разделяемую -> 48 КБ достигаются БЕЗ ЖЕРТВ.
//         Замерено в одной обвязке: x1.026 .. x1.116 (S=4096 x1.116, S=8192 x1.088).
//   fp16: 48 КБ достижимы ТОЛЬКО при DC=32 -- при DC=64 выходит 49.5 КБ даже с минимальным
//         дополнением V, не влезает НИ ПРИ КАКОМ. Платить приходится дроблением куска (3.760
//         против 3.663) И перечитыванием Q. Замерено 0.78-0.81x: ПЛАТА ВЫШЕ ВЫИГРЫША.
//         Вывод при этом БИТ В БИТ (расхождение 0.0e+00) -- это чистый размен скорости, не точности.
//
// ОТСЮДА ПЕРЕСМОТР ТОГО, ЗАЧЕМ ВООБЩЕ int8 НА ЭТОМ ЯДРЕ. Не ради меньшего числа инструкций (их
// БОЛЬШЕ на 32%, §4w) и не ради трафика (он идёт из L2, а не из HBM). Ради того, что он делает
// ЗАНЯТОСТЬ ДОСТУПНОЙ: сжатие резидентных данных -- единственный способ уложиться в порог второго
// блока, не жертвуя геометрией подачи. ПРАВИЛО: сжатие окупается там, где оно снимает ПОРОГ, а не
// там, где просто уменьшает объём.
//
// ТЕКУЩЕЕ СОСТОЯНИЕ: у int8 покупка включена по умолчанию (BQ=32, два блока), у fp16 ВЫКЛЮЧЕНА и
// оставлена под FA2SM70_FWD_OCC=1 как след замера. int8-ядро при этом всё ещё позади fp16 в
// абсолюте (1.567 против 1.056 на S=4096): выигрыш занятости не покрывает +32% инструкций.

// =================================================================================================
// 4bb. БОРЬБА С ИНСТРУКЦИЯМИ В БАЙТОВОМ ПУТИ: x0.65 -> x0.89, и виновником был НЕ разворот
// =================================================================================================
// Разбор SASS ПО ОПКОДАМ, нормированный НА ОДНУ HMMA (нормировать обязательно: у ядер разное BQ и
// разный разворот, тела в лоб несравнимы):
//   опкод      fp16    int8(до)   избыток
//   IMAD      0.249     1.381      +1.13   <- ПЕРВЫЙ, и это НЕ разворот
//   PRMT      0.008     0.512      +0.50   <- собственно разворот, лишь второй
//   LOP3      0.050     0.447      +0.40
//   IADD3     0.083     0.488      +0.40
//
// IMAD -- АДРЕСНАЯ АРИФМЕТИКА, и рецепт БЫЛ УЖЕ ЗАПИСАН в шапке fp16-ядра ("считаем базу ОДИН раз
// и двигаем её на константу"). Я не применил его к своим перекладкам, и это стоило 22.6% избытка.
// Шаг там ПОСТОЯНЕН: при i += kWarps*32 и (D/4) элементов в строке номер строки растёт на константу,
// значит адрес сдвигается сложением. Применено ко всем трём перекладкам (Q, K, V).
//
// И ГЛАВНОЕ -- ЭФФЕКТ СЛОЖИЛСЯ САМ С СОБОЙ. Снятие лишних инструкций освободило РЕГИСТРЫ
// (125 -> 110), а на освободившиеся вернулся РАЗВОРОТ, который до того не влезал:
//   до правки:            125 рег, разворот 1 -> 0.5232 мс
//   прямая адресация:     110 рег, разворот 1 -> 0.4382
//   + разворот 2:         117 рег              -> 0.4008
//   + разворот 4:         126 рег, кадр 0      -> 0.3868   (x1.35 к началу, x1.52 к BQ=64)
// ПОРЯДОК ДЕЙСТВИЙ ОТСЮДА: СНАЧАЛА убрать лишние инструкции, ПОТОМ разворачивать. Обратный порядок
// упирается в регистры и заставляет выбирать между разворотом и занятостью, тогда как правильный
// даёт ОБА.
//
// ЧТО НЕ ПОМОГЛО: вынос баз фрагментов из цикла по k внутри accumulate_bi8 -- ноль (0.4629 против
// 0.4634): компилятор это уже делал сам. Проверять, а не предполагать.
//
// ИТОГ ПО БЕНЧМАРКУ (одна обвязка, частоты зафиксированы, d=256, causal):
//   форма            наш fp16    наш int8     cutlass   SDPA-eff
//   (1,4,4096)          1.057   1.190 x0.89     1.059      1.843
//   (1,4,8192)          3.591   4.196 x0.86     3.582      7.026
//   (1,2,16384)         6.933   8.179 x0.85     6.963     15.232
//   (1,24,8192,32K)   141.951 170.195 x0.83   141.907        --
// Байтовый путь прошёл x0.65 -> x0.89; разрыв с fp16 сократился с 35% до 13%. Наш fp16 идёт вровень
// с cutlass и быстрее SDPA в 1.75-2.2 раза.

// =================================================================================================
// 4cc. ОГРАНИЧИТЕЛЬ ПЕРЕЕХАЛ: снятие 12% инструкций дало РОВНО НОЛЬ
// =================================================================================================
// Приём "одна инструкция вместо нескольких" на этой стадии проверен и НЕ СРАБОТАЛ -- и именно этим
// он ценен, потому что называет новую границу.
//
// Ход: XOR в развороте нужен ТОЛЬКО чтобы сделать из знакового байта смещённый. Перенесли это в
// КВАНТОВАТЕЛЬ (он пишет u = v + 128, offset binary), в ядре осталось ДВЕ инструкции вместо трёх,
// смещение -- та же константа 1152, поправка по-прежнему в затравке аккумулятора и стоит ноль.
// ПРАВКА ПОДЕЙСТВОВАЛА, это проверено по SASS: LOP3 361 -> 105, то есть 256 инструкций убрано
// (12% тела), при неизменных PRMT (520) и HMMA (1024).
// ВРЕМЯ: 0.3868 -> 0.3899, то есть НОЛЬ (шум).
//
// ПРОФИЛЬ ОБЪЯСНЯЕТ ПОЧЕМУ. Ядро прошло через ТРИ разных ограничителя:
//                          занятость  вычисл.  L1/TEX   вывод
//   исходное (BQ=64)         12.46%    22.9%   41.0%    ЗАДЕРЖКИ (оба потока < 60%)
//   после покупки занятости  22.42%    40.2%   57.6%    сперва ИНСТРУКЦИИ...
//   после прямой адресации   22.42%    40.2%   57.6%    ...теперь РАЗДЕЛЯЕМАЯ ПАМЯТЬ
//   Block Limit Registers 1 -> 2, Block Limit Shared Mem 1 -> 2.
// Инструкции перестали быть пределом ДО этой правки -- вот почему 12% сняты бесплатно и бесполезно.
//
// ПРАВИЛО, КОТОРОЕ ИЗ ЭТОГО СЛЕДУЕТ: рычаг привязан не к ядру, а к ЕГО ТЕКУЩЕЙ СТАДИИ. Один и тот
// же приём даёт x1.35 (прямая адресация, когда пределом были инструкции) и ноль (снятие XOR, когда
// пределом стала память) -- в ОДНОМ И ТОМ ЖЕ ядре с разницей в один шаг. Поэтому профиль надо
// снимать ПОСЛЕ КАЖДОГО крупного выигрыша, а не один раз в начале: победа СДВИГАЕТ границу.
//
// ЧТО ЭТО ЗНАЧИТ ПРО fp64 (§1d, четыре целых сложения одной инструкцией). Приём настоящий, но к
// оставшейся работе не приложим по ДВУМ причинам: (1) разворот обязан выдать fp16-ОПЕРАНДЫ
// тензорному ядру, а упаковка в мантиссу даёт целые в мантиссе -- другая мишень; (2) даже если бы
// ложился, инструкции больше не предел. Следующий рычаг -- ТРАФИК разделяемой памяти (L1/TEX 57.6%),
// а не число инструкций.
//
// Вариант со смещённым байтом оставлен под FA2_BIASED_U8=1 и ВЫКЛЮЧЕН по умолчанию: он меняет
// ВНЕШНИЙ контракт (формат KV-кэша) при нулевом замеренном выигрыше. Включать имеет смысл, только
// если ограничитель снова станет инструкционным.

// =================================================================================================
// 4dd. ЗАНЯТОСТЬ ДЛЯ fp16: ОБА ПУТИ ПОД 48 КБ ПРОВЕРЕНЫ И ОБА УБЫТОЧНЫ
// =================================================================================================
// Профиль прямо сравнивает два ядра на одной форме:
//                          такты   занятость  вычисл.  L1/TEX   предел рег/smem
//   fp16 (BQ=64, 1 блок)  529663     12.46%    21.1%    53.2%      1 / 1
//   int8 (BQ=32, 2 блока) 540629     22.38%    40.0%    57.5%      2 / 2
// int8 использует машину ВДВОЕ лучше и всё равно проигрывает по секундомеру -- ему нужно больше
// инструкций на ту же математику. А у fp16 этот запас НЕ ТРОНУТ, и вопрос был, нельзя ли его взять.
//
// ПОД 48 КБ У fp16 РОВНО ДВА ПУТИ, ОБА ЗАМЕРЕНЫ:
//   BQ=32 / BK=64 / DC=32 -> 45.0 КБ, 0.78-0.81x. Платим дроблением куска (3.760 против 3.663) и
//                            перезаливкой Q на каждую плитку ключей.
//   BQ=64 / BK=32 / DC=64 -> 34.2 КБ, 0.55-0.63x. Резать BK соблазнительно (sV = BK*(D+PADV) --
//                            САМЫЙ крупный буфер), но BK=32 ВДВОЕ увеличивает число плиток ключей,
//                            а с ним всё ПОПЛИТОЧНОЕ: редукции софтмакса, барьеры и та же
//                            перезаливка Q. Дороже первого пути.
// Вывод исчерпывающий: у fp16 нет дешёвого способа освободить разделяемую память, потому что все
// её крупные буферы пропорциональны либо BK (и тогда растёт число плиток), либо D (и тогда режется
// кусок подачи). У int8 буферы ВДВОЕ меньше ПО ФОРМАТУ -- резать не надо ничего.
//
// ЭТО ОКОНЧАТЕЛЬНО ОТВЕЧАЕТ, ЗАЧЕМ int8 НА ЭТОМ ЯДРЕ: он единственный, кто может позволить себе
// второй резидентный блок, не жертвуя геометрией подачи. Сегодня он всё ещё позади fp16 (x0.83-0.89),
// но по УДЕЛЬНЫМ показателям впереди вдвое -- то есть его отставание в инструкциях, а не в
// использовании машины, и именно там остался запас.

// =================================================================================================
// 4ee. РАСФАЗИРОВКА ДВУХ РЕЗИДЕНТНЫХ БЛОКОВ: эффекта нет, и это говорит о железе
// =================================================================================================
// Замысел: раз на SM теперь ДВА блока (int8, занятость 22.4%), развести их ПО ФАЗЕ рабочего цикла --
// чтобы когда один перекладывает, другой считал, и путь подачи не собирал оба разом.
// Реализуемо, потому что ОНЛАЙН-СОФТМАКС НЕ ЗАВИСИТ ОТ ПОРЯДКА плиток ключей: это сумма с бегущим
// максимумом, любая перестановка даёт тот же ответ. Проверено на корректность -- проходит.
//
//   вариант                        S=2048   Sq=1024/Sk=4096
//   без расфазировки               0.3857        0.6302
//   нечётные блоки НАЗАД           0.3851        0.6256   (+0.15% / +0.7% -- шум)
//   нечётные со сдвигом на половину 0.3965       0.6519   (-2.8% / -3.4% -- ХУЖЕ)
//
// ПОЧЕМУ НЕТ ЭФФЕКТА, и это полезнее самого замера: ФАЗЫ НА УРОВНЕ БЛОКА НЕ СУЩЕСТВУЕТ как
// управляемой величины. Планировщик перемешивает ВСЕ 16 варпов обоих блоков поштучно, и пока варпы
// одного стоят на перекладке, он уже выдаёт варпы другого. Железо делает расфазировку само, на
// зерне ВАРПА, а не блока -- ровно поэтому занятость и работает как рычаг.
// Подтверждающее число из профиля: L1/TEX 57.5%, а не 85-90%. Путь подачи НЕ НАСЫЩЕН, то есть
// разблокировать там пока нечего, и сталкиваться двум блокам особо не на чем.
//
// СДВИГ НА ПОЛОВИНУ ХУЖЕ по отдельной причине: он ломает переиспользование через L2. Соседние блоки
// имеют соседние q0 и в обычном порядке читают ОДНИ И ТЕ ЖЕ плитки ключей почти одновременно
// (попадание 97.7%); разведя их по разным концам потока, мы это сотрудничество разрушаем.
// ЗАКОН: разносить блоки по данным ВРЕДНО, пока они делят кэш. Разносить по ФАЗЕ бессмысленно,
// пока планировщик делает это сам. Оставлено под FA2_STAGGER как след замера, по умолчанию 0.

// =================================================================================================
// 4ff. КАРТА ПРОСТОЕВ: блоки НЕ сталкиваются на MIO, и это закрывает идею взаимодополнения
// =================================================================================================
// Замысел был точный по форме: два резидентных блока развести так, чтобы когда A давит MIO, B давил
// Tensor/ALU, и наоборот -- пути не пересекаются. Проверять это надо НЕ картой темпов (она говорит,
// что конвейер МОЖЕТ), а картой ПРОСТОЕВ (она говорит, на чём мы СТОИМ).
//
//   причина простоя      fp16 (1 блок)   int8 (2 блока)
//   not_selected              0.52            1.02   <- ПЕРВАЯ у int8
//   long_scoreboard           1.14            0.87
//   wait                      0.86            0.86
//   barrier                   0.52            0.74
//   math_pipe_throttle        0.42            0.68
//   mio_throttle              0.66            0.51   <- УПАЛ со вторым блоком
//   lg_throttle               0.26            0.18
//
// БЛОКИ НЕ СТАЛКИВАЮТСЯ НА MIO: с приходом второго блока mio_throttle не вырос, а УПАЛ (0.66 ->
// 0.51). Контенция, которую предполагалось развести, измеренно МЕНЬШЕ, чем была при одном блоке.
// Взаимодополнение целится в ТРЕТИЙ по величине простой, который к тому же сам уменьшился;
// потолок приёма ~11% суммарного стойла при идеальном исполнении.
//
// А ПЕРВЫМ СТАЛ not_selected = 1.02 -- "варп готов, но планировщик выдаёт другой". Это подпись того,
// что ГОТОВЫХ ВАРПОВ БОЛЬШЕ, ЧЕМ СЛОТОВ ВЫДАЧИ: занятость сделала своё дело, и машина упёрлась в
// выдачу, а не в нехватку работы. Заодно math_pipe_throttle вырос 0.42 -> 0.68: тензорный конвейер
// давят сильнее, чего и добивались.
//
// ЧТО КАРТА НАЗЫВАЕТ НАСТОЯЩИМИ ЦЕЛЯМИ и чем каждая лечится:
//   not_selected 1.02     -> МЕНЬШЕ ИНСТРУКЦИЙ (слотов выдачи не хватает на готовые варпы)
//   long_scoreboard 0.87  -> подача РАНЬШЕ (ожидание данных из памяти)
//   wait 0.86             -> разрыв ЦЕПОЧЕК зависимостей
// Ни одно из трёх не лечится расфазировкой блоков.
//
// ОБЩЕЕ ПРАВИЛО: приём, целящийся в контенцию, требует ДОКАЗАТЕЛЬСТВА контенции -- то есть роста
// соответствующего throttle. Карта ТЕМПОВ (§4e) говорит, что конвейеры могут; карта ПРОСТОЕВ
// говорит, на чём мы стоим. Планировать по первой, проверять по второй.

// =================================================================================================
// 4gg. ФАЗЫ БЛОКА: профиль снят, зазор подобран -- НЕ ДЕРЖИТСЯ. Держать может только барьер
// =================================================================================================
// ПРОФИЛЬ ФАЗ (FA2_PHASE=1, отсчёты clock64 по границам; читать ПРОПОРЦИИ, отсчёты сами сдвигают
// время). Тело цикла int8-ядра, S=2048:
//   фаза                              доля    чем давит
//   1  перекладка масштабов и V      27.6%    ЧИСТЫЙ MIO/LSU
//   2  подача Q/K + первое умножение 39.0%    Tensor вперемешку с MIO
//   0  барьер входа                  17.1%    ожидание
//   3-5 софтмакс                     16.4%    ALU + SFU + барьеры
//   6  второе умножение               0.0%    <- MMA АСИНХРОННА: её цена ложится на того, КТО ЖДЁТ,
//                                                то есть уходит в фазу 0. Это свойство замера,
//                                                а не отсутствие работы.
// Фазы РАЗЛИЧИМЫ по конвейерам -- значит замысел развести соседние блоки имеет во что упереться:
// MIO-фаза одного могла бы попадать на счётную фазу другого. И это про ВЫДАЧУ тоже: в одной фазе
// блоки выдают ОДНОТИПНЫЕ инструкции и дерутся за один слот (not_selected 1.02 -- первый простой),
// в дополняющих -- разные, и выдача упаковывается плотно.
//
// ЗАЗОР ПОДОБРАН И НЕ РАБОТАЕТ. Нечётные блоки задерживаются на FA2_GAP тактов перед циклом
// (цена платится ОДИН раз на блок, а не на итерацию):
//   зазор, тактов:      0      200     500    1000    2000    4000
//   S=2048:          0.3868  0.3884  0.3871  0.3866  0.3886  0.3878
//   Sq=1024/Sk=4096: 0.6296  0.6300  0.6293  0.6286  0.6280  0.6281
// Всё в пределах полупроцента на ЛЮБОМ зазоре.
//
// ПРИЧИНА СТРУКТУРНАЯ, А НЕ В ПОДБОРЕ: ОДНОКРАТНЫЙ СДВИГ НЕ УДЕРЖИВАЕТСЯ. Блоки ничем не связаны --
// длительности их итераций различаются (причинная маска даёт разное число плиток, задержки памяти
// пляшут), барьеры у каждого свои, и набранный зазор рассасывается за несколько итераций.
// НАЧАЛЬНОЕ смещение НЕ РАВНО ПОДДЕРЖИВАЕМОМУ. Дешёвой межблочной синхронизации на Volta нет.
//
// ГДЕ ЗАМЫСЕЛ РЕАЛИЗУЕМ ПОЛНОСТЬЮ: внутри ОДНОГО блока. 16 варпов, разделённых на группы, связаны
// ИМЕНОВАННЫМИ БАРЬЕРАМИ, а их цена замерена (§4q): сигнал bar.arrive 2.76 такта против 33.4 у
// ожидания. Тогда фаза каждой группы задаётся ЯВНО и УДЕРЖИВАЕТСЯ защёлкой, а не надеждой на
// планировщик. Плюс у одного блока нет порога 48 КБ -- ему доступны все 96.
// То есть верная форма замысла -- не "два блока с зазором", а "один блок, где одна группа варпов
// ВЕЗЁТ, а другая СЧИТАЕТ", с защёлкой в 2.76 такта между ними.
//
// ПРАВИЛО: фазу можно задать только там, где есть СВЯЗЬ. Между блоками её нет -- значит и фазы нет,
// сколько ни подбирай зазор. Внутри блока связь есть -- значит есть и фаза.

// =================================================================================================
// 4hh. ШАХМАТКА ПО SM: прежний замер зазора был НЕДЕЙСТВИТЕЛЕН. Исправленный даёт монотонный ВРЕД
// =================================================================================================
// МЕТОДИЧЕСКАЯ ОШИБКА, найденная Алексом и стоящая больше самого опыта. Роль блока я брал по
// ЧЁТНОСТИ blockIdx. Но диспетчер раскидывает блоки круговым перебором: блок k идёт на SM k, а
// вторым жильцом SM k становится блок k + 80 (80 -- число SM). ЧИСЛО SM ЧЁТНОЕ, значит k и k+80
// ВСЕГДА одной чётности -- оба резидентных блока получали ОДНУ И ТУ ЖЕ фазу. Опыт не проверял
// ничего, но выглядел как честный нулевой результат.
//
// ТОЧНОЕ НАЗНАЧЕНИЕ РОЛИ: блок читает СВОЙ номер SM (mov.u32 %0, %%smid) и атомарно занимает место
// в счётчике этого SM -- 0 у первого жильца, 1 у второго. Одна атомика на блок, не на итерацию.
//   unsigned smid; asm volatile("mov.u32 %0, %%smid;" : "=r"(smid));
//   role = atomicAdd(sm_role + smid, 1) & 1;
// Это единственный способ узнать соседа по SM: blockIdx о размещении НЕ ГОВОРИТ.
//
// ИСПРАВЛЕННЫЙ ЗАМЕР (зазор -- задержка второго жильца перед циклом):
//   зазор, тактов:      0      300     800    1500    3000    6000
//   S=2048:          0.3871  0.3876  0.3884  0.3888  0.3903  0.3938
//   Sq=1024/Sk=4096: 0.6300  0.6315  0.6311  0.6312  0.6317  0.6329
// МОНОТОННЫЙ ВРЕД: каждый шаг зазора стабильно дороже предыдущего. Задержка НЕ ПОГЛОЩАЕТСЯ
// конвейером -- она просто добавляется ко времени блока, и хвост волны растёт. Прежний "шум"
// был артефактом неверного назначения ролей; при точном назначении сигнал есть, и он отрицательный.
//
// ВЫВОД ПО ВЕТКЕ: развести фазы ДВУХ БЛОКОВ нельзя ни начальным зазором (не удерживается, §4gg),
// ни точной шахматкой (удерживается, но только как чистая потеря). Причина одна: у блоков НЕТ
// СВЯЗИ, а bar.sync/bar.arrive на Volta -- инструкции ОБЛАСТИ CTA, межблочного барьера в железе
// нет. Остальное (глобальные атомики-семафоры, cooperative launch с grid.sync) даёт защёлку в
// сотни тактов против 2.76 у bar.arrive и требует persistent-сетки.
// ЕДИНСТВЕННАЯ РАБОЧАЯ ФОРМА ЗАМЫСЛА -- свести обе группы в ОДИН блок: 16 варпов, 8 везут,
// 8 считают, защёлка именованным барьером. Там связь есть, значит есть и фаза.
//
// И ПРАВИЛО ШИРЕ САМОГО СЛУЧАЯ: если приём различает блоки по их РАЗМЕЩЕНИЮ, брать признак из
// blockIdx НЕЛЬЗЯ -- о размещении он не говорит. Только %smid. Иначе получится опыт, который
// выглядит проведённым, а проверяет пустоту.

// =================================================================================================
// 4ii. РАЗМЕЩЕНИЕ БЛОКОВ ПО SM ЗАМЕРЕНО: диспетчер идёт по TPC, а не подряд
// =================================================================================================
// Оборудование статично, поэтому отображение blockIdx -> smid не угадывают, а ЗАМЕРЯЮТ
// (tools/volta_block_placement.cu: каждый блок пишет свой %smid и держится занятым, чтобы
// резидентность была реальной). Результат воспроизводится между запусками:
//
//   blockIdx:  0  1  2  3  4  5  6  7 ...
//   smid:      0  2  4  6  8 10 12 14 ...
//
// ДИСПЕТЧЕР ЗАПОЛНЯЕТ СНАЧАЛА ЧЁТНЫЕ SM. Это структура TPC: у V100 сорок TPC по ДВА SM, и первая
// волна кладёт по одному блоку в каждый TPC, вторая -- во второй SM того же TPC.
// Наивная гипотеза smid = blockIdx % 80 совпала на 2% -- то есть неверна полностью.
//
// ПАРЫ ПОДТВЕРЖДЕНЫ ТОЧНО: из 80 пар, делящих SM, у ВСЕХ 80 разность ровно 80 и ВСЕ одной чётности.
// Отсюда прежний предикат (blockIdx & 1) был обречён давать обоим соседям одну роль (§4hh).
//
// ДВЕ РАЗНЫЕ ОСИ СОСЕДСТВА, и путать их нельзя:
//   (k, k+80) -- ОДИН SM : делят регистровый файл, разделяемую память и СЛОТЫ ВЫДАЧИ.
//                Предикат: role = (blockIdx.x / nsm) & 1, где nsm -- число SM (одна операция после
//                деления на константу; %smid для этого НЕ ГОДИТСЯ -- он у соседей ОДИНАКОВ).
//   (k, k+40) -- ОДИН TPC: делят путь к памяти на уровне TPC (L1.5 / выход в L2).
//                Предикат: (blockIdx.x / (nsm/2)) & 1, либо по чётности smid: smid & 1 РАЗЛИЧАЕТ
//                два SM внутри TPC -- вот где битовая операция по smid действительно работает.
// Первая ось отвечает за контенцию ПО ВЫДАЧЕ, вторая -- ПО ПАМЯТИ. Приём, целящийся в память,
// должен различать блоки по ВТОРОЙ, а не по первой.
//
// ЧТО ЭТО ЗНАЧИТ ПРО %smid: он говорит, НА КАКОМ SM ты сидишь, но НЕ говорит, кто твой сосед по
// этому же SM -- у обоих соседей smid одинаков. Для роли внутри SM нужен либо атомарный счётчик по
// smid, либо (раз размещение замерено и статично) арифметика по blockIdx. Для роли внутри TPC --
// достаточно smid & 1, одной битовой операции.

// =================================================================================================
// 4jj. БАНКИ МЕЖДУ БЛОКАМИ: наложения НЕ СУЩЕСТВУЕТ -- массив делится по ВРЕМЕНИ, а не в пространстве
// =================================================================================================
// Гипотеза (Алекс): разделяемая память у блоков логически раздельная, но ФИЗИЧЕСКИ это одни и те же
// 32 банка в общем блоке 128 КБ, а планировщиков на SM четыре. Значит смещение аллокации второго
// блока решает, лягут ли его обращения на ТЕ ЖЕ банки.
// Арифметика подтверждала худший случай: наша аллокация 31232 Б, и 31232 % 128 == 0, то есть
// смещение второго блока КРАТНО полному циклу банков (32 банка по 4 Б) -- одинаковый код на
// одинаковых банках.
//
// ПРОВЕРКА: добить аллокацию до смещения в ПОЛЦИКЛА (+64 Б = 16 банков), максимальное разведение.
//   форма              без сдвига   сдвиг 64 Б
//   (1,4,4096)             1.182       1.180
//   (1,16,4096)            4.342       4.347
//   (1,4,8192)             4.167       4.175
//   (1,2,16384)            8.105       8.109
// РОВНО НОЛЬ на всех формах.
//
// ПОЧЕМУ, и это устройство железа, которое стоит помнить: БАНКОВЫЙ МАССИВ ДЕЛИТСЯ ПО ВРЕМЕНИ.
// Блок разделяемой памяти обслуживает ОДНУ ВАРПОВУЮ ИНСТРУКЦИЮ ЗА РАЗ; обращения четырёх
// планировщиков не идут одновременно, они ВСТАЮТ В ОЧЕРЕДЬ. Значит два блока физически НЕ МОГУТ
// столкнуться на банках -- к моменту обслуживания второго первый уже отработал.
// КОНФЛИКТ БАНКОВ СУЩЕСТВУЕТ ТОЛЬКО ВНУТРИ ОДНОЙ ВАРПОВОЙ ИНСТРУКЦИИ (и там он реален -- см. §4a-4d
// и подбор PADV, давший 1.041x).
//
// ЧТО МЕЖДУ БЛОКАМИ ЕСТЬ НА САМОМ ДЕЛЕ: давление на ОЧЕРЕДЬ, видимое как mio_throttle. Замерено:
// 0.66 при одном блоке -> 0.51 при двух, то есть оно ПАДАЕТ, а не растёт.
//
// ЭТИМ ЗАМЫКАЕТСЯ ВСЯ ВЕТКА РАСФАЗИРОВКИ. Между двумя блоками нет:
//   * общей ФАЗЫ  -- нет связи, межблочного барьера в железе нет (§4gg, §4hh);
//   * общих БАНКОВ -- массив делится по времени (§4jj);
// есть только общая ОЧЕРЕДЬ ВЫДАЧИ, и при двух блоках она разгружается. Разводить нечего.
// Единственная форма, где фаза управляема, остаётся прежней: ОДИН блок, группы варпов, именованный
// барьер (сигнал 2.76 такта, §4q).

// =================================================================================================
// 4kk. РУКОТВОРНЫЙ ПЛАНИРОВЩИК: роли варпов + защёлки. x1.23-1.39, и профиль это предсказывал
// =================================================================================================
// ЧТО ПОСТРОЕНО (fa2_sm70/csrc/volta_fwd_ws.cuh). Один блок, 16 варпов:
//   варпы 0..7  ВЕЗУТ  : кладут K и V ЦЕЛИКОМ на плитку в теневой буфер, bar.arrive "готово",
//                        и сразу за следующей; ждут только если считающие отстали на буфер.
//   варпы 8..15 СЧИТАЮТ: bar.sync "готово", оба умножения и софтмакс, bar.arrive "буфер свободен".
// Двойной буфер обязателен. У ОДНОГО блока нет порога 48 КБ -- доступны все 96 (занято 88.5).
//
// ЗАМЕР против двухблочного варианта (частоты зафиксированы, int8 KV, d=256, causal):
//   форма         2 блока x 8в   1 блок 16в (роли)
//   1024x1024        0.1464          0.1054     x1.389
//   2048x2048        0.3884          0.2836     x1.370
//   1024x4096        0.6300          0.5137     x1.226
//   4096x4096        1.2011          0.9789     x1.227
// 96-98 регистров, разлив ноль, 5 барьеров в SASS. relL2 ~3e-4, как у эталонного ядра.
//
// ПРОФИЛЬ ЭТО ПРЕДСКАЗЫВАЛ, и в этом весь метод. Карта простоев (§4ff) давала первым
// not_selected = 1.02 -- "варп готов, но выдают не его". Это ровно подпись того, что ВСЕ варпы в
// одной фазе просят ОДИН конвейер. Лечение отсюда следует однозначно: дать группам РАЗНЫЕ фазы и
// УДЕРЖАТЬ их. Всё остальное было выяснением, ЧЕМ удержать -- и ответ дала не догадка, а перебор:
// зазор между блоками не держится (§4gg), точная шахматка по %smid держит, но как чистая потеря
// (§4hh), поворот обхода по TPC ноль (§4ii), сдвиг банковой базы ноль, потому что банковый массив
// делится по ВРЕМЕНИ (§4jj). Осталась единственная связь -- именованный барьер внутри CTA, 2.76
// такта на сигнал (§4q).
//
// ТРИ ДЕФЕКТА ТАКОГО ПЛАНИРОВЩИКА -- все были НАЗВАНЫ ДО ПОСТРОЙКИ, и это сократило отладку до трёх
// правок. Список стоит держать при себе для любого producer/consumer:
//  1. ПРОИЗВОДИТЕЛЬ ПАДАЕТ В ЭПИЛОГ -> зависание. Ему нужен ранний return сразу после последнего
//     bar.arrive. Иначе он идёт в общий эпилог, где его wm/wn равны нулю, и ПИШЕТ В ВЫХОД поверх
//     счёта -- то есть отказ двойной: и висит, и портит.
//  2. ЧТО-ТО, ЧТО ГОТОВИЛОСЬ ВНУТРИ СВЁРНУТОГО ЦИКЛА, ПЕРЕСТАЁТ ГОТОВИТЬСЯ. У нас Q клалась ВНУТРИ
//     цикла по d; цикл свернули в одно умножение по всему D -- и перекладка уехала вместе с ним.
//     Ядро ВОЗВРАЩАЕТСЯ и считает по мусору (relL2 0.16). Самый коварный: выглядит как численная
//     задача, а не структурная. Правило: сворачивая цикл, перечислить ВСЁ, что в нём делалось.
//  3. ПРЕЖДЕВРЕМЕННОЕ ОСВОБОЖДЕНИЕ БАРЬЕРА -> зависание при числе плиток БОЛЬШЕ ОДНОЙ (одна
//     работает, и это же локализует дефект). При опережении на два буфера производитель делает ДВА
//     bar.arrive подряд, а счётчик барьера равен сумме обеих групп -- значит два прихода
//     ПРОИЗВОДИТЕЛЯ САМИ ПО СЕБЕ освобождают барьер, ещё до того, как потребитель до него дошёл;
//     тот затем ждёт СЛЕДУЮЩЕГО поколения, а приходы уже потрачены.
//     ОБЩЕЕ ПРАВИЛО: ОПЕРЕЖЕНИЕ НА N БУФЕРОВ ТРЕБУЕТ N РАЗНЫХ БАРЬЕРОВ ГОТОВНОСТИ. У нас два --
//     разведены по чётности плитки (барьеры 1 и 4). Иначе приходы производителя схлопываются.
//
// И ЧЕТВЁРТОЕ, ЧТО НАДО ПОМНИТЬ: внутренние синхронизации СЧИТАЮЩИХ нельзя делать __syncthreads --
// он требует ВСЕ нити блока и повесит производителя. Нужен отдельный именованный барьер со счётом
// ТОЛЬКО потребителей (у нас барьер 3 на kConsThr).
//
// ЧТО ЭТО ЗНАЧИТ ШИРЕ: занятость и роли -- РАЗНЫЕ рычаги. Два блока по 8 варпов дают те же 16
// варпов на SM, но БЕЗ управления фазой; один блок из 16 варпов даёт и варпы, и фазу, и выигрывает
// на 23-39%. Разница целиком в том, что во втором случае есть ЧЕМ УДЕРЖАТЬ расписание.

// -------------------------------------------------------------------------------------------------
// 4kk-бис. ПРОФИЛЬ ПОСЛЕ: ВЫИГРЫШ ПРИШЁЛ НЕ ОТТУДА, КУДА ЦЕЛИЛИСЬ
// -------------------------------------------------------------------------------------------------
// Полный набор форм, 9 из 9 верны, x1.22-1.46 -- и НАИБОЛЬШИЙ выигрыш на ЧАНКОВЫХ формах (Sq << Sk),
// то есть ровно там, где он нужен для префилла: 192x2048 x1.461, 320x1024 x1.427, 200x777 x1.410.
//
//   простой              2 блока    роли      что случилось
//   not_selected           1.04     0.74      упал -- КАК И ПРЕДСКАЗЫВАЛОСЬ
//   long_scoreboard        0.80     0.31      упал ВТРОЕ -- вот откуда выигрыш на самом деле
//   math_pipe_throttle     0.69     0.34      упал вдвое
//   mio_throttle           0.49     0.99      ВЫРОС ВДВОЕ
//   barrier                0.69     2.50      ВЫРОС В 3.6 РАЗА
//   занятость            22.36%   24.31%      SM всего 41.1% -> 44.6%, L1/TEX 56.7% -> 58.4%
//
// ЦЕЛИЛИСЬ В not_selected (он и правда упал), А ГЛАВНОЕ ДАЛ long_scoreboard: ожидание данных из
// памяти упало ВТРОЕ, потому что везущая группа подвозит НА ПЛИТКУ ВПЕРЁД -- это скрытие задержки,
// а не разгрузка конвейера. При этом mio_throttle УДВОИЛСЯ (восемь варпов делают только подачу и
// ничего больше -- очередь набивается), а барьеры выросли в 3.6 раза: это прямая цена защёлок.
// И всё равно +36%.
//
// ВЫВОД, КОТОРЫЙ ДОРОЖЕ САМОГО ЗАМЕРА: ЕСЛИ БЫ ОПТИМИЗИРОВАЛИ ПО mio_throttle, ПРАВКУ СОЧЛИ БЫ
// ВРЕДНОЙ. Профиль называет ось, но не говорит, какая из них окупится -- у выигрышной перестройки
// часть показателей УХУДШАЕТСЯ, и это нормально. Судить надо по ВРЕМЕНИ, а профиль читать ПОСЛЕ,
// чтобы понять, откуда выигрыш пришёл на самом деле, и куда целиться дальше.
//
// КУДА ЦЕЛИТЬСЯ ДАЛЬШЕ -- профиль называет прямо:
//   barrier 2.50 -- ПЕРВЫЙ простой с большим отрывом. Лечится БОЛЬШИМ числом буферов (потребитель
//     реже упирается в неготовность) и разделением внутренних барьеров потребителей.
//   mio_throttle 0.99 -- восемь везущих варпов на одну очередь это перебор. Стоит попробовать
//     4 везущих + 12 считающих, если сетка MMA это допустит (у 12 варпов законная сетка не всякая).

// -------------------------------------------------------------------------------------------------
// 4kk-трети. БАРЬЕРЫ: половина оказалась лишней, но выигрыш 1.3% -- профиль снова не договорил
// -------------------------------------------------------------------------------------------------
// Профиль назвал barrier = 2.50 ПЕРВЫМ простоем. Разбор показал ЧЕТЫРЕ внутренних барьера считающих
// на плитку, из которых ДВА избыточны:
//   * первый стоял СРАЗУ ПОСЛЕ барьера готовности плитки, который уже синхронизировал все нити --
//     два барьера подряд, чистая цена без смысла (остаток исходного цикла при переносе);
//   * последний гарантировал видимость sP для второго умножения, но sP пишется РАНЬШЕ редукции
//     сумм, а барьер этой редукции уже прошёл -- видимость обеспечена им.
// Убраны оба. Замер: 0.0278->0.0274, 0.0686->0.0677, 0.1546->0.1526, 0.2843->0.2805, 0.5136->0.5071.
// Устойчивые ~1.3% на всех формах, корректность не тронута.
//
// НО ПОЛОВИНА БАРЬЕРОВ ДАЛА 1.3%, А НЕ ПОЛОВИНУ. Значит основная часть barrier = 2.50 -- это НЕ
// внутренние синхронизации, а ОЖИДАНИЕ СЧИТАЮЩИМИ ГОТОВНОСТИ ПЛИТКИ (барьеры 1 и 4), то есть
// неотъемлемое свойство схемы производитель-потребитель. Оно лечится только БОЛЬШИМ ЧИСЛОМ БУФЕРОВ,
// а третий буфер НЕ ВЛЕЗАЕТ: Q 16640 + P 4352 + 3 x 34816 = 125440 Б = 122.5 КБ при пределе 96.
// Уменьшить буфер можно только уменьшив BK -- но BK=32 вдвое увеличивает число плиток и замерено
// проигрышным. То есть barrier здесь -- ЦЕНА СХЕМЫ, а не дефект реализации.
//
// ТРЕТИЙ РАЗ ЗА ВЕТКУ ОДНО И ТО ЖЕ: счётчик простоя называет ОСЬ, но не говорит, какая ЧАСТЬ этой
// оси поддаётся. Целились в not_selected -- выигрыш дал long_scoreboard; целились в barrier --
// поддалась лишь та его доля, что от избыточных синхронизаций. Профиль -- карта, а не приговор:
// по нему выбирают, ЧТО ПРОБОВАТЬ, а решает ЗАМЕР ВРЕМЕНИ.

// -------------------------------------------------------------------------------------------------
// 4kk-четв. КАРТА ПО УЧАСТКАМ МЕЖДУ БАРЬЕРАМИ: куда бьёт каждая роль и где они сходятся
// -------------------------------------------------------------------------------------------------
// СПОСОБ (годится для любого ядра с ролями): разрезать SASS по барьерам и посчитать инструкции по
// КОНВЕЙЕРАМ на каждом участке. Тогда видно, где две роли бьют в ОДНУ точку инфраструктуры SM.
//   участок          всего  Tensor   MIO   LSU  FP32  INT32
//   2 (счёт, GEMM1)    614     256    86     0    16    220
//   4 (счёт, GEMM2)    598     256    84     0    58    195
//   6 (перекладка)     454       0    78    78     0    249
//
// ТОЧКА СТОЛКНОВЕНИЯ -- MIO, И ТОЛЬКО ОНА. Считающие выдают 84-86 LDS (чтения фрагментов операндов)
// ОДНОВРЕМЕННО с 256 HMMA, везущие -- 78 STS перекладки. Группы работают параллельно, значит эти
// потоки сходятся в ОДНУ очередь MIO. ТЕНЗОРНЫЙ конвейер точкой столкновения НЕ ЯВЛЯЕТСЯ: HMMA есть
// только у считающих, разбавлять их нечем и незачем.
//
// ДОЛИ РОЛЕЙ ПО ВРЕМЕНИ (замер clock64 по границам, FA2_PHASE=1):
//   ВЕЗУЩИЕ: ждут буфер   30.7%      ВЕЗУЩИЕ: везут    20.3%
//   СЧИТАЮЩИЕ: ждут плитку 22.7%     СЧИТАЮЩИЕ: считают 18.8%
// ОБЕ ГРУППЫ ЖДУТ БОЛЬШЕ, ЧЕМ РАБОТАЮТ: 53.4% ожидания против 39.1% работы. При этом сама работа
// сбалансирована почти идеально (20.3 против 18.8) -- то есть дело НЕ в перекосе ролей, а в
// стоимости синхронизации: на плитку приходятся ДВЕ барьерные встречи по 33.4 такта ожидания, и при
// мелких плитках они съедают больше самой работы.
//
// ПРОВЕРКА, ПОДТВЕРДИВШАЯ ЭТО ОТ ПРОТИВНОГО: у везущих 249 целочисленных инструкций на 156 обращений
// к памяти -- вдвое больше, чем нужно на адресацию (причина: четыре указателя, каждый сдвиг
// 64-битный, то есть два IADD3). Два из них ведут в РАЗДЕЛЯЕМУЮ память, чьё адресное пространство
// 32-битное, и перевод их на __cvta_generic_to_shared убирает по четыре инструкции с итерации.
// ЗАМЕРЕНО: 0.2802 -> 0.2788, то есть НИЧЕГО. И это правильно: везущие УЖЕ ждут 30.7% времени,
// у них избыток запаса, и сокращение их инструкций лишь увеличивает простой.
//
// ПРАВИЛО: ОПТИМИЗИРОВАТЬ НАДО НЕ ТОГО, У КОГО МНОГО ИНСТРУКЦИЙ, А ТОГО, КТО НА КРИТИЧЕСКОМ ПУТИ.
// Таблица по участкам говорит, КТО во что бьёт; доли ролей по времени говорят, КТО ЖДЁТ. Первое без
// второго ведёт к правкам, которые ничего не меняют, -- ровно это здесь и вышло.

// -------------------------------------------------------------------------------------------------
// 4kk-пятое. ЧИСЛО ВСТРЕЧ СОКРАЩАЕТСЯ ПЕРЕСТРОЙКОЙ, А НЕ ПАМЯТЬЮ
// -------------------------------------------------------------------------------------------------
// Было ДВЕ встречи на плитку: "плитка готова" (везущие -> считающие) и "буфер свободен" (обратно).
// Третий буфер, который снял бы ожидание, НЕ ВЛЕЗАЕТ (122.5 КБ при пределе 96). Но встречи
// сокращаются БЕЗ роста памяти -- перестройкой:
//   при ДВОЙНОМ буфере обе встречи сводятся в ОДНО РАНДЕВУ. На нём обе группы одновременно узнают,
//   что буфер t полон, а буфер t+1 свободен; дальше везущие наполняют ОДИН, считающие читают
//   ДРУГОЙ -- они не пересекаются ПО ПОСТРОЕНИЮ, и второе подтверждение не нужно.
// Пролог: плитка 0 готовится ДО первого рандеву. Разведение барьеров по чётности (§4kk) при этом
// становится ненужным: производитель больше не может уйти вперёд на два прихода, он ждёт на том же
// рандеву.
//
// ЗАМЕР: 0.0274->0.0274, 0.0676->0.0674, 0.1526->0.1516, 0.2802->0.2789, 0.5070->0.5014.
// Совокупно по всей барьерной ветке (убраны два избыточных внутренних + слиты две встречи в одну):
// 0.2843 -> 0.2789 и 0.5136 -> 0.5014, то есть 1.9-2.4%.
//
// И СНОВА МЕНЬШЕ, ЧЕМ ОБЕЩАЛ СЧЁТЧИК: половина внутренних барьеров дала 1.3%, половина встреч --
// ещё 1%. Значит в barrier = 2.50 сидела НЕ цена самих встреч, а РЕАЛЬНОЕ ОЖИДАНИЕ РАБОТЫ другой
// стороны. Это подтверждается долями ролей: обе группы ждут больше, чем работают (53.4% против
// 39.1%) ПРИ ПОЧТИ РАВНОЙ работе (20.3 против 18.8). Такое сочетание означает не перекос и не
// накладные, а НЕДОСТАТОЧНУЮ ГЛУБИНУ КОНВЕЙЕРА: с двумя буферами любая флуктуация длительности
// сразу останавливает обе стороны, и сгладить её может только третий буфер, которого нет места.
//
// ВЫВОД ПО ВЕТКЕ: барьерная составляющая выбрана до дна теми средствами, что не требуют памяти.
// Дальнейшее упирается в ГЛУБИНУ, то есть в размер буфера, то есть в 96 КБ на блок -- это предел
// машины, а не реализации.

// -------------------------------------------------------------------------------------------------
// 4kk-шестое. РАСКОС ВАРПОВ ПО ТАКТУ: пика, который разглаживали, НЕ СУЩЕСТВУЕТ
// -------------------------------------------------------------------------------------------------
// Замысел: все считающие варпы проходят рандеву РАЗОМ и разом бьют в MIO чтениями фрагментов
// (карта участков даёт 84-86 LDS на участок). Развести их по ОДНОМУ такту: варп cw ждёт cw тактов.
// Инструкция задержки выбрана так, чтобы не трогать НИЧЕГО -- ни регистров, ни флагов, ни памяти.
//
// ПОБОЧНАЯ НАХОДКА ПРО PTX: инструкции "nop" в PTX НЕТ (ptxas: Not a name of any known instruction),
// хотя в SASS NOP есть и компилятор его сам расставляет. Годится pmevent 0 -- она даёт в SASS
// PMTRIG, занимает слот выдачи и ничего не трогает. Это и есть та самая "бессмысленная инструкция
// на один такт", если она понадобится.
//
// ЗАМЕР -- МОНОТОННЫЙ ВРЕД:
//   раскос:      0      x1      x2      x4      x8
//   192/2048   0.1516  0.1526  0.1571  0.1572  0.1580
//   2048x2048  0.2792  0.2809  0.2884  0.2889  0.2910
//   1024/4096  0.5014  0.5062  0.5229  0.5249  0.5285
//
// ПРИЧИНА В УСТРОЙСТВЕ ВЫДАЧИ: планировщик выдаёт ПО ОДНОЙ инструкции варпа за такт НА SMSP. Их
// четыре, варпов двенадцать -- по три на планировщик. Восемь считающих ФИЗИЧЕСКИ НЕ МОГУТ выдать
// LDS в один такт: они уже разнесены аппаратно минимум на два такта, а на деле сильно больше.
// ПИКА, КОТОРЫЙ РАЗГЛАЖИВАЛИ, НЕ СУЩЕСТВУЕТ -- а инструкции задержки ложатся на КРИТИЧЕСКИЙ ПУТЬ
// (считающие и есть критический путь, §4kk-четв), поэтому вред монотонный.
//
// ТО ЖЕ САМОЕ, ЧТО С РАСФАЗИРОВКОЙ БЛОКОВ (§4ee, §4gg, §4hh): ЖЕЛЕЗО УЖЕ РАССЛАИВАЕТ НА ЗЕРНЕ
// ВАРПА. Явное разведение -- хоть блоков, хоть варпов -- избыточно и стоит. Расслаивать имеет смысл
// только то, что железо расслоить НЕ МОЖЕТ: роли (разные ТИПЫ работы), а не экземпляры одной роли.
// Именно поэтому producer/consumer дал x1.37, а раскос внутри группы -- отрицательный результат.

// -------------------------------------------------------------------------------------------------
// 4kk-седьмое. ПЕРЕСТАНОВКА LDG/STS БЕЗ ЕДИНОЙ ИНСТРУКЦИИ: уже сделана компилятором
// -------------------------------------------------------------------------------------------------
// Замысел (Алекс): не добавлять ничего, а ПЕРЕСТАВИТЬ. В перекладке чередуется LDG, LDG, STS, STS,
// и каждый STS ЖДЁТ свой LDG. Развести: сперва ВСЕ чтения из глобальной в регистры, потом ВСЕ
// записи в разделяемую -- тех же инструкций столько же, ожидание собирается в одно место, а поток
// STS в MIO идёт сплошняком.
//
// ЗАМЕР: 0.1517->0.1516, 0.2796->0.2795, 0.5015->0.5014. РОВНО НОЛЬ.
//
// И ЕСТЬ ПРЯМОЕ ДОКАЗАТЕЛЬСТВО ПРИЧИНЫ: РЕГИСТРОВ В ОБОИХ ВАРИАНТАХ 96. Если бы явная версия
// действительно придерживала 32 значения в регистрах между фазами, счёт бы ВЫРОС. Он не вырос --
// значит ptxas УЖЕ ДЕЛАЛ эту перестановку сам (программная конвейеризация выносит загрузки вперёд),
// и мой вариант лишь совпал с тем, что было в SASS.
//
// ПРАВИЛО: прежде чем переставлять руками, проверить, НЕ ПЕРЕСТАВЛЕНО ЛИ УЖЕ. Дешёвый признак --
// число регистров: перестановка, которая реально удлиняет диапазоны жизни, ОБЯЗАНА его поднять.
// Если счёт не изменился, изменения не произошло, каким бы ни был исходный текст.
// Это тот редкий случай, когда компилятор работает НА нас, -- и его тоже надо проверять замером,
// а не считать врагом по умолчанию (§ "компилятор -- противник" про принуждение, а не про всё).

// -------------------------------------------------------------------------------------------------
// 4kk-восьмое. РАЗБОР SASS НАШЁЛ ТО, ЧЕГО НЕ ВИДЕЛ ЗАМЕР: скалярные LDG.E.U16
// -------------------------------------------------------------------------------------------------
// Перестановка LDG/STS дала ноль, и я заключил "компилятор уже сделал" по ЧИСЛУ РЕГИСТРОВ. Проверка
// прямым сравнением SASS это ПОДТВЕРДИЛА: потоки опкодов ПОБИТОВО совпали (2856 инструкций, ноль
// различий, LDG=111 STS=99 LDS=172 HMMA=512 у обоих). Косвенный признак оказался верен -- но сама
// проверка нашла ДРУГОЕ.
//
// В ПОТОКЕ ОКАЗАЛОСЬ МНОЖЕСТВО LDG.E.U16 -- ДВУХБАЙТОВЫХ ГЛОБАЛЬНЫХ ЧТЕНИЙ. Это отдельный проход по
// Q ради сумм строк (поправка ранга-1 разворота), по ОДНОМУ __half за инструкцию: 8192 скалярных
// чтения на блок. В int8-ядре он был оправдан -- там Q подавалась кусками и целиком в разделяемой не
// лежала. Здесь лежит, и ходить в глобальную второй раз незачем.
//
// ТРИ ФОРМЫ, ЗАМЕРЕНЫ:
//   форма                        256^2   192/2048  2048^2  1024/4096
//   проход по ГЛОБАЛЬНОЙ (было) 0.0274    0.1516   0.2796    0.5012
//   атомики в разделяемой       0.0310    0.1548   0.2913    0.5069   <- ХУЖЕ ВСЕХ
//   редукция по РАЗДЕЛЯЕМОЙ     0.0274    0.1513   0.2769    0.5005   <- лучшая
//
// АТОМИКИ Я ПОПРОБОВАЛ, ХОТЯ ПРО НИХ УЖЕ БЫЛО ЗАПИСАНО (§2: контенция дороже отдельного прохода,
// 485 -> 1046 мкс). Повторил собственную зафиксированную ошибку -- признак того, что кукбук надо
// ПЕРЕЧИТЫВАТЬ перед правкой, а не только дописывать после.
//
// ПРАВИЛО: РАЗБОР SASS СТОИТ ДЕЛАТЬ ДАЖЕ КОГДА ГИПОТЕЗА ПОДТВЕРДИЛАСЬ. Здесь он подтвердил вывод
// (потоки совпали) и ЗАОДНО показал статью расхода, которую ни один счётчик простоя не называл:
// скалярные глобальные чтения теряются в сумме, но видны в потоке опкодов как U16.

// -------------------------------------------------------------------------------------------------
// 4kk-девятое. ПОЛНЫЙ РАЗБОР SASS: чек-лист красных флагов и что он нашёл
// -------------------------------------------------------------------------------------------------
// ЧЕК-ЛИСТ (годится для любого рукописного ядра; считается одним проходом по потоку опкодов):
//   локальная память LDL/STL      -- должно быть РОВНО 0, иначе молчаливый разлив
//   узкие обращения .U16/.U8      -- скалярный доступ там, где можно векторный
//   пересылки MOV / IMAD.MOV      -- давление на регистровый файл
//   доля ПОД ПРЕДИКАТОМ           -- ветви, свёрнутые в предикацию: исполняются вхолостую
//   NOP                           -- заполнение расписания компилятором
//   конверсии I2F/F2I/F2F         -- кандидаты на битовые трюки (§1)
//   SHFL                          -- межполосное, половинный темп
//
// ЧТО НАШЛОСЬ в ядре с ролями (2824 инструкции):
//   локальная память        0    -- чисто
//   ПОД ПРЕДИКАТОМ        382 (13.5%)  -- НО это проверки границ на загрузках (LDG 83), а НЕ
//                                свёрнутые ветви ролей. Ключевая проверка: из 512 HMMA под
//                                предикатом НОЛЬ -- значит везущие тензорные не гоняют вхолостую,
//                                разделение ролей РЕАЛЬНО, а не только в исходнике.
//   MOV+IMAD.MOV          139 (4.9%) -- приемлемо
//   NOP                     9    -- компилятор почти не заполняет, расписание плотное
//   .U16                   28    <-- ДЕФЕКТ, см. ниже
//
// ДЕФЕКТ: LDS.U.U16, то есть чтения по ОДНОМУ __half. Это сумма строк Q. Я УЖЕ переносил её из
// глобальной в разделяемую (там были LDG.E.U16), но поменял ПРОСТРАНСТВО и не поменял ШИРИНУ --
// доступ остался скалярным. Правка: читать по ЧЕТЫРЕ значения (uint2).
//   форма       было(скаляр)  стало(по 4)
//   256^2          0.0273       0.0270
//   200x777        0.0672       0.0667
//   192/2048       0.1514       0.1505
//   2048^2         0.2781       0.2747
//
// И ОТДЕЛЬНО ПРО ВЫРАВНИВАНИЕ: шире четырёх значений здесь НЕЛЬЗЯ. Шаг строки LDQ = D + 4 = 260
// полуслов = 520 Б: кратен 8, но НЕ кратен 16, поэтому uint2 законен, а uint4 -- нет. Проверять надо
// ВЫРАВНИВАНИЕ ШАГА, а не только желание читать шире.
//
// ПРАВИЛО: "перенёс в другое пространство памяти" НЕ РАВНО "исправил". Пространство и ШИРИНА --
// две разные оси, и разбор SASS показывает вторую там, где первая уже поправлена.

// -------------------------------------------------------------------------------------------------
// 4kk-итог. ОСЬ ВРЕМЕНИ: задержки закрыты, структурное расщепление открыто. И ЯДРО ОБОГНАЛО fp16
// -------------------------------------------------------------------------------------------------
// ТРИ ОСИ, по которым чинится подача: ПРОСТРАНСТВО (глобальная/разделяемая/регистры), ШИРИНА
// (сколько значений за инструкцию) и ВРЕМЯ (кто когда). Первые две дали конкретные правки (§4bb,
// §4kk-девятое). По ТРЕТЬЕЙ итог такой:
//
// ЗАДЕРЖКИ ЗАКРЫТЫ -- три замера, все отрицательные, причина одна:
//   зазор между блоками (точная шахматка по %smid) -- монотонный вред (§4hh);
//   раскос варпов через pmevent                    -- монотонный вред (§4kk-шестое);
//   поворот обхода по TPC, сдвиг банков            -- ноль (§4ii, §4jj).
// ПРИЧИНА: задержка ложится на КРИТИЧЕСКИЙ ПУТЬ, а расслоение железо делает САМО на зерне варпа
// (планировщик выдаёт по одной инструкции варпа за такт на SMSP).
//
// ОТКРЫТА ровно одна форма -- СТРУКТУРНОЕ РАСЩЕПЛЕНИЕ БЕЗ ЕДИНОЙ ЛИШНЕЙ ИНСТРУКЦИИ: расщепить
// считающих по ЧЁТНОСТИ ПЛИТОК (четыре варпа на чётные, четыре на нечётные, у каждой половины свой
// накопитель, слияние в эпилоге по правилу онлайн-софтмакса). Тогда пока одна половина считает
// плитку N, вторая уже ждёт N+1 -- фазы сдвинуты СТРУКТУРНО, а не задержкой.
// ГЕОМЕТРИЯ ДОПУСКАЕТ: при BQ=32/BK=64 четыре варпа дают WM=2,WN=2, то есть SM=16 и SN=32, оба
// кратны 16. ЦЕНА СЧИТАЕТСЯ НАПЕРЁД И СЕРЬЁЗНАЯ: накопитель O у каждой половины ложится на 128 нитей
// вместо 256, то есть 64 регистра вместо 32; при занятых 96 из 128 это выводит за предел -- либо
// разлив, либо потеря второго буфера. Место отказа известно: слияние состояний (m, l, O).
//
// ИТОГ ПО ЯДРУ (одна обвязка, частоты зафиксированы, d=256, causal, мс):
//   форма            наш fp16   наш int8 (роли)   cutlass   SDPA-eff
//   (1,4,4096)          1.055    0.932  x1.13      1.059      1.842
//   (1,16,4096)         3.655    3.544  x1.03      3.660      6.413
//   (1,4,8192)          3.576    3.425  x1.04      3.580      7.063
//   (1,2,16384)         6.921    6.627  x1.04      6.921     15.246
//   (1,24,8192,32K)   141.957  137.786  x1.03    141.911         --
// БАЙТОВЫЙ ПУТЬ ОБОГНАЛ fp16 НА ВСЕХ ФОРМАХ. Путь за сессию: x0.65 -> x0.83 -> x1.01..1.13.
// Против SDPA: x1.98 на S=4096 и x2.30 на S=16384.
//
// ЧЕМ ЭТО ВЗЯТО, по вкладам: покупка занятости дроблением по запросам (§4aa), прямая адресация плюс
// возвращённый разворот (§4bb, x1.35), РАЗДЕЛЕНИЕ ВАРПОВ ПО РОЛЯМ (§4kk, x1.22-1.46), одна встреча
// на плитку вместо двух, ширина чтений в сумме строк. Ни один из вкладов не пришёл из "ускорения
// операций" -- все из КОМПОНОВКИ.

// -------------------------------------------------------------------------------------------------
// 4ll. ПРЕДЕЛ head_dim У ЯДРА РОЛЕЙ: ограничитель -- ДВОЙНОЙ БУФЕР, и он линеен по d
// -------------------------------------------------------------------------------------------------
// ВОПРОС: до какого head_dim доживает схема "везущие + считающие", и одинаков ли предел у байтового
// и fp16-путей. Считается ТОЧНО, без сборки: раскладка ядра целиком арифметическая.
//   sQ = BQ*(D+4) и sP = BQ*(BK+4) полуслов -- ВСЕГДА fp16, у обоих путей одинаково;
//   двойной буфер K/V = 2*BK*((D+16) + (DV+16)) ЭЛЕМЕНТОВ, элемент 1 Б (int8) либо 2 Б (fp16).
// Отгруженная конфигурация подставляется как проверка: BQ=32,BK=64,D=DV=256,int8 -> 90624 Б = 88.5 КБ,
// что совпадает с замеренным. Перебор: tools/volta_ws_dlimit.py.
//
// ОГРАНИЧЕНИЯ, которые реально режут (все три обязательны):
//   разделяемая <= 96 КБ (один блок, порога 48 КБ нет -- см. §4kk);
//   SM=BQ/WM, SN=BK/WN, ON=DV/WN -- все кратны 16 (шаг фрагмента mma.sync);
//   накопитель O = BQ*DV/(32*nCons) регистров на нить (замерено 32 при 96-98 всего).
//
// ПРЕДЕЛ при >= 4 считающих варпах (меньше -- считающая сторона не покрывает четырёх везущих):
//        d |  int8 KV                      |  fp16 KV
//      256 |  32/64/256  2x4  88КБ  x1     |  32/32/256  2x2  86КБ  x1
//      384 |  32/32/384  2x2  76КБ  x1     |  64/16/192  4x1  89КБ  x2
//      512 |  32/32/256  2x2  84КБ  x2     |  НЕ ВЛЕЗАЕТ
//      640 |  32/32/160  2x2  94КБ  x4     |  НЕ ВЛЕЗАЕТ
//      768 |  НЕ ВЛЕЗАЕТ                   |  НЕ ВЛЕЗАЕТ
// То есть int8 доходит до d=640, fp16 -- до d=384. Отношение НЕ ровно вдвое (1.67), потому что
// удваивается ТОЛЬКО буфер K/V: Q и P в fp16 у обоих путей.
//
// ГЛАВНОЕ ЖЕ НЕ ПРЕДЕЛ, А ГРАНИЦА ОДНОГО ПРОХОДА. DV < D означает, что выход режется на D/DV срезов,
// и S ПЕРЕСЧИТЫВАЕТСЯ на каждый срез -- это ровно та работа, ради экономии которой вся схема и
// строилась. Один проход держится до d=384 (int8) и d=256 (fp16). ОТГРУЖЕННАЯ ТОЧКА d=256/int8 --
// последняя, где один проход достаётся при ВОСЬМИ считающих; это и объясняет, почему x1.36 получен
// именно там, и почему на d=512 повторения ждать НЕ следует: там уже два прохода, то есть x1.5
// работы по нашему же замеру.
//
// И ОТДЕЛЬНО: fp16 отваливается на d=512 НЕ по одной лишь разделяемой. При BK=16 буфер влезает, но
// WN вынужденно 1, и тогда SM=BQ/WM < 16 при четырёх считающих; при BQ=64 распухает sQ. Режет
// СОЧЕТАНИЕ ёмкости и кратности 16, а не ёмкость сама по себе -- поэтому "добавить памяти" тут не
// помогло бы. Опустив планку до ДВУХ считающих, int8 дотягивает до 768, fp16 до 640, но это уже
// вырождение: четыре везущих варпа обслуживают двух считающих.
//
// ПРАВИЛО: у схемы с ролями предел ставит НЕ вычисление, а ДВОЙНОЙ БУФЕР целой плитки -- он линеен
// по d и удваивается буферизацией. Поэтому байтовое KV здесь не просто "быстрее": оно ОТОДВИГАЕТ
// геометрическую границу применимости самой схемы.

// -------------------------------------------------------------------------------------------------
// 4mm. ЯДРО РОЛЕЙ В СЕРВЕРЕ: подключено, замерено -- и вывод НЕ тот, которого ждали
// -------------------------------------------------------------------------------------------------
// ПОСТРОЕНО: байтовый сборщик страничного KV (gather_paged_kv_i8: страницы -> int8 [Hkv,T,d] плюс
// масштаб fp32 на позицию) и маршрут в обвязке vLLM на attn_fwd_volta_i8 (FA2SM70_SHIM_I8=1).
// Сборщик сверен ПОБИТОВО с явным эталоном на четырёх геометриях.
//
// ЗАМЕР СКВОЗНОЙ (Qwen3.6-27B, TP=2, уникальные промпты, частоты 1380, токенов/с префилла):
//     промпт    fp16-путь   байтовый маршрут
//       4119        1396          1394
//      16367        1267          1269
//      32775        1228          1231
//      65448        1124          1132
// То есть РАЗНИЦЫ НЕТ -- она внутри шума 0.7%. И это НЕ провал ядра: ядро своё отработало, время
// внимания в сервере упало 11.68 -> 11.21 с (те самые 4%), просто внимание -- НЕ ТА ДОЛЯ.
//
// ДОЛЯ И ЕСТЬ ОТВЕТ: в этом префилле внимание занимает 36.35 с из 222.47 с стены = 16.3%. Даже
// БЕСКОНЕЧНО быстрое внимание дало бы x1.195, а ядро ролей на серверных формах даёт x1.02-1.05 (не
// x1.36: та цифра с недозагруженной машины при B*H=4, а здесь H=12 на карту и машина полна).
// Отсюда 0.6% сквозняком -- ровно то, что и вышло.
//
// ПРАВИЛО (дороже самого ядра): ПЕРЕД тем как встраивать ядро в систему, замерь ДОЛЮ его работы в
// стене. Ускорение ядра умножается на долю, и доля -- это то, что можно узнать заранее одним
// счётчиком. Здесь счётчик стоил одного прогона, а встраивание -- дня.
//
// И ОТДЕЛЬНО ПРО ТОЧНОСТЬ -- вывод, ради которого стоило всё это построить. Пул vLLM хранит e4m3, а
// ядро ролей ест int8, поэтому маршрут КВАНТУЕТ ДВАЖДЫ. Цена (relMax к деквантованному пулу):
//     Sq/T/H/Hkv      fp16-путь   байтовый маршрут   хуже
//     512/2048/12/2    5.87e-04       7.41e-03       x12.6
//     1024/4096/8/2    4.66e-04       8.32e-03       x17.9
//     256/1024/4/4     4.49e-04       7.53e-03       x16.8
// ПРИЧИНА В ФОРМАТАХ, НЕ В ЯДРЕ: e4m3 держит ОТНОСИТЕЛЬНУЮ точность на всём размахе, int8 с
// масштабом по строке -- АБСОЛЮТНУЮ. Мелкие значения строки с большим максимумом теряют почти все
// разряды, то есть перекантовка выбрасывает ровно то свойство, ради которого e4m3 и берут.
//
// КАК УБРАТЬ ПОТЕРЮ ПОЛНОСТЬЮ (и почему это дёшево). Скорость ядра ролей берётся НЕ из "int8 на
// тензорных ядрах" -- инструкции int8 у Volta нет вообще, счёт в любом случае идёт в fp16. Она
// берётся из ПЕРЕВОЗКИ БАЙТОВ и разворота В РЕГИСТРАХ. А значит формат байта можно менять:
//   * e4m3 ЦЕЛИКОМ ВЛОЖЕН в fp16 -- знак совпадает, порядок сдвигается на +8 (смещения 7 и 15,
//     e in [1,14] -> [9,22] при доступных fp16 [1,30]), мантисса сдвигается влево на 7, поддено-
//     рмальные e4m3 (до 2^-9) у fp16 нормальные. Разворот e4m3 -> fp16 ТОЧЕН ПОБИТОВО.
//   * значит: тот же самый маршрут, но с разворотом e4m3 вместо int8, даёт ошибку РОВНО НОЛЬ
//     относительно пула, не трогает ни формат пула, ни хранение, ни декод;
//   * сборщик при этом становится ЧИСТЫМ КОПИРОВАНИЕМ байтов (ни свёртки максимума, ни деления);
//   * свёртка смещения в ранг-1 ИСЧЕЗАЕТ -- у e4m3 нет постоянного смещения 1024, которое она
//     снимала, то есть часть работы уходит совсем.
// ЦЕНА, которую надо ЗАМЕРИТЬ, а не предполагать: разворот e4m3 длиннее (3-4 операции на значение
// против 0.75 у int8-перестановки байт), и вопрос ровно один -- влезет ли он в свободные слоты
// (§4p: на одну HMMA свободны ОДНА fp32 И ОДНА int32). Примитив уже есть -- e4m3_to_float_fast.
//
// АЛЬТЕРНАТИВА, если формат пула менять можно: хранить СРАЗУ int8 с масштабом на позицию. Тогда
// квантование одно вместо двух, точность -- те самые 4.6e-4..5.4e-4 (ЛУЧШЕ нынешнего e4m3), а
// сборка тоже становится копированием. Дороже по объёму работ: трогает хранение, декод и таблицу
// масштабов, тогда как разворот e4m3 -- правка ОДНОГО места в ядре.

// -------------------------------------------------------------------------------------------------
// 4nn. e4m3 И e5m2 В БАЙТОВОМ ПУТИ: e5m2 ДЕШЕВЛЕ int8, e4m3 -- НЕТ. Решает РАСКЛАДКА, не скорость
// -------------------------------------------------------------------------------------------------
// Замер: tools/volta_fp8_expand.cu. Разворот ставится В ЦЕПЬ подачи операнда рядом с HMMA (не в
// свободный слот -- §4r показал, что это разные вещи), 4 байта -> два регистра по два fp16.
//   разворот в цепи      к базе   инструкций на 4 байта   точность на всех 256 значениях байта
//   без разворота         1.000            0
//   int8 (наш)            1.101            2 (две prmt)     точен по построению
//   e5m2                  1.065            2 (две prmt)     0 РАСХОЖДЕНИЙ
//   e4m3                  1.698            8                0 расхождений (с множителем 256)
//
// e5m2 -- ЗА НОЛЬ, И ДЕШЕВЛЕ НЫНЕШНЕГО int8. Причина чисто структурная: у e5m2 смещение порядка 15,
// ТО ЖЕ САМОЕ, ЧТО У fp16, и порядок полей тот же. Значит e5m2 -- РОВНО СТАРШИЙ БАЙТ fp16:
//   fp16_bits == byte << 8, побитово, включая поддённормальные (E=0: M/4*2^-14 у обоих) и Inf/NaN.
// Одна prmt на два значения -- как у int8, но БЕЗ свёртки смещения в ранг-1 (снимать нечего, нет
// никакого +1024) и без константы 0x64646464 в операнде, отчего и 1.065 против 1.101.
//
// e4m3 -- НЕ ЗА НОЛЬ, и упирается это НЕ в пересчёт порядка. Пересчёт как раз бесплатен: приём
// (b & 0x7F) << 7, прочитанный как fp16, даёт РОВНО значение/256 -- и для нормальных
// (2^(E-15) против 2^(E-7)), и для поддённормальных (2^-14*M/4 против 2^-6*M/8), отношение в обоих
// случаях ровно 256, — а 256 это КОНСТАНТА, и она сворачивается в уже существующее умножение на
// масштаб софтмакса, то есть стоит ноль (§2b).
// Упирается в ПЕРЕКЛАДКУ БИТ: знак едет на 8 позиций, остальные семь бит -- на 7, между полями
// образуется РАЗРЫВ, а перестановка байт разрывов не делает. Минимум -- четыре инструкции на два
// значения: prmt (byte<<8), сдвиг вправо на 1, И МАСКА, и lop3. Маска неустранима: после сдвига
// знак садится в разряд 14, то есть в старший бит порядка, который обязан быть нулём; а одна lop3
// его не обнулит, потому что применяет ОДНУ функцию ко всем разрядам, различая их только по биту
// константы, — разряду же 14 нужно поведение, отличное и от 15 (взять знак), и от 0-13 (взять
// данные), третьего варианта одна константа не даёт.
//
// ОГОВОРКА, зафиксированная а не спрятанная: единственный NaN у e4m3fn (0x7F/0xFF) приём переводит
// в конечное +-480. Для KV-кэша это не отказ (NaN там уже означает сбой), но знать надо.
//
// ЧТО ИЗ ЭТОГО СЛЕДУЕТ ДЕЛАТЬ -- по принципу §1a ("квантователь наш, менять формат хранения нам
// никто не мешает"): не разворачивать дорогой формат в ядре, а ПИСАТЬ ФОРМАТ, который
// разворачивается одной prmt. Таких ровно три, и все проверены:
//   e5m2                 -- одна prmt, точен, диапазон fp16, но всего 2 бита мантиссы;
//   смещённый uint8      -- две prmt (§1a), точен, лучшая относительная точность при малом размахе;
//   int8 со знаком       -- как сейчас, плюс свёртка ранга-1.
// А e4m3 брать в ядро имеет смысл только если пул НЕЛЬЗЯ переписать (случай vLLM, §4mm): тогда
// цена по этому замеру 1.70 в цепи -- это ВЕРХНЯЯ оценка, потому что в цепи прятать разворот не за
// что; в настоящем мейнлупе есть свободные слоты, но по §4bb у байтового ядра их уже занято
// PRMT 0.512 + LOP3 0.447 + IADD3 0.488 + IMAD 1.381 = 2.83 на HMMA при бюджете около 2 (§4p),
// то есть запаса НЕТ и реальная цена окажется ближе к 1.70, чем к нулю. Мерить в ядре, не гадать.
//
// ОТГРУЖЕНО (attn_fwd_volta_e5m2, KVFMT=1 у ядра ролей). Замер на V100, causal, мс:
//   B,H,Sq,Sk         fp16     int8    e5m2   e5m2/int8   ошибка e5m2   ошибка int8
//   1,4,2048,2048     0.411   0.302   0.284     1.062       0.00e+00      5.17e-04
//   1,12,4096,4096    2.978   2.852   2.719     1.049       0.00e+00      4.68e-04
//   1,4,8192,8192     3.477   3.329   3.152     1.056       0.00e+00      5.39e-04
//   1,12,2048,16384   8.987   8.816   8.497     1.038       0.00e+00      1.49e-03
// ОШИБКА РОВНО НОЛЬ -- не "малая", а побитовое совпадение с fp16-ядром на тех же числах, на всех
// шести причинных формах набора (GQA 6:1, рваные Sq/Sk, батч). Иначе и быть не может: разворот
// точен, свёртки смещения нет. При этом e5m2 БЫСТРЕЕ И fp16 (x1.06-1.45), И int8 (x1.04-1.06).
// Правка вышла крошечной, и это следствие структуры, а не везения: kI8Bias=0 заставляет ВСЮ
// машинерию ранга-1 выродиться саму (seed_rank1 сажает накопитель в ноль, rescale_fold оставляет
// только corr2), а масштаб на позицию заменяется единицей. Восемь строк на всё ядро.
// ЛОВУШКА, которую поймал компилятор НЕ поймал бы: новый параметр шаблона я сперва вставил В
// СЕРЕДИНУ списка, где он молча сдвинул позиционный аргумент DV у существующего инстанцирования --
// типы совпадают, ошибки нет, ядро считает не то. Новые параметры -- ТОЛЬКО В КОНЕЦ.
//
// -------------------------------------------------------------------------------------------------
// 4oo. ТЕОРЕМА О ДВУХ СЕМЕЙСТВАХ -- и почему вопрос "как удешевить e4m3" РАСТВОРЯЕТСЯ
// -------------------------------------------------------------------------------------------------
// prmt кладёт ЦЕЛЫЕ БАЙТЫ. Значит развернуть байт в fp16 ОДНОЙ prmt можно ровно двумя способами:
//   (1) байт -> СТАРШИЙ байт fp16  => плавающий формат со смещением fp16 и его же порядком полей.
//       Это ОДНОЗНАЧНО e5m2: знак + 5 порядка + 2 мантиссы, потому что раскладка старшего байта
//       fp16 такая и есть. Больше двух бит мантиссы тут не бывает НИ ПРИ КАКОМ кодировании.
//   (2) байт -> МЛАДШИЙ байт, старший константа => ФИКСИРОВАННАЯ ТОЧКА (наш int8: 0x6400|u=1024+u).
//       Восемь бит мантиссы, порядок общий -- задаётся старшим байтом.
// Третьего не дано. Отсюда: ПОБИТОВЫЙ e4m3 за одну prmt НЕДОСТИЖИМ -- не потому что приём не найден,
// а потому что его не существует (смещение 7 против 15 требует переноса знака на 8 позиций при
// переносе остальных семи на 7, то есть РАЗРЫВА, которого перестановка байт не делает, §4nn).
//
// НО У СЕМЕЙСТВА (2) ЕСТЬ УПУЩЕННАЯ СТЕПЕНЬ СВОБОДЫ: второй источник prmt -- РЕГИСТР, а не
// непосредственный операнд. Значит "константный" старший байт можно менять НА БЛОК за ноль
// инструкций: 0x64 + (D<<2) сдвигает порядок на D, то есть даёт множитель 2^D. Получается int8 с
// ОБЩИМ ПОКАЗАТЕЛЕМ на блок -- ровно семейство microscaling, и на Volta оно бесплатно.
// (У нас эта степень свободы УЖЕ использована сильнее: масштаб на позицию применяется ПОСЛЕ GEMM
// как fp32-умножение, то есть он произвольный, а не степень двойки.)
//
// И ТУТ ВОПРОС РАСТВОРЯЕТСЯ. Замер, ОДНОКРАТНОЕ квантование из fp16, строки d=256 (relMax / relL2):
//   формат                                нормальные строки      строки с выбросами (0.2%, 8-30x)
//   e4m3                                  3.28e-02 / 2.64e-02    4.06e-02 / 2.63e-02
//   e5m2                                  6.56e-02 / 5.25e-02    7.30e-02 / 5.27e-02
//   int8 + масштаб на позицию (НАШ)       3.91e-03 / 6.97e-03    3.94e-03 / 2.35e-02
//   int8 + показатель 2^k на 32           4.10e-03 / 8.04e-03    5.78e-03 / 1.38e-02
// НАШ ФОРМАТ ТОЧНЕЕ e4m3 В 8.4 РАЗА по relMax и в 3.8 по relL2, а на выбросах -- в 10.3 раза по
// relMax. Удешевлять e4m3 незачем: он нам не нужен, он ХУЖЕ того, что уже есть, и при этом дороже
// в развороте.
//
// ЭТИМ ЖЕ ИСПРАВЛЯЕТСЯ МОЙ СОБСТВЕННЫЙ ВЫВОД из §4mm. Замер там верен: перекантовка e4m3 -> int8
// стоит 13-18x. Но ОБЪЯСНЕНИЕ было неверным -- я написал, что int8 выбрасывает то, ради чего берут
// e4m3, и отсюда следовало бы, что e4m3 -- формат лучше. Он не лучше. Вся потеря шла от того, что
// квантование ДВОЙНОЕ, а не от свойств int8: при ОДНОКРАТНОМ квантовании int8 с масштабом на
// позицию бьёт e4m3 почти на порядок. Правило: сравнивать форматы можно только при РАВНОМ ЧИСЛЕ
// квантований; иначе меряешь не формат, а лишний проход.
//
// ЧТО ИЗ ЭТОГО СЛЕДУЕТ ДЛЯ vLLM: не тащить e4m3 в ядро и не удешевлять его, а УБРАТЬ ЕГО ИЗ ПУЛА --
// хранить int8 с масштабом на позицию. Тогда квантование одно, точность выше нынешней e4m3-шной
// почти на порядок, сборка становится перекладкой, а разворот -- две prmt со свёрткой ранга-1.
// e5m2 остаётся вариантом там, где не нужна таблица масштабов вовсе (ценой худшей из трёх точности,
// зато при НУЛЕВОЙ ошибке в ядре -- разворот точен побитово).
//
// И ОТДЕЛЬНО -- ПРО "БЕСПЛАТНЫЕ КОНСТАНТЫ" (§4k), потому что соблазн тут прямой и сильный.
// §4k говорит: константы на ОДНОРОДНОМ адресе идут мимо MIO почти даром (13.27 против 7.27 у LDS,
// в смеси +1.5%), а канал -- ПАРАМЕТРЫ ЯДРА, то есть таблица 256 полуслов (512 Б) в банк констант
// влезает. Отсюда напрашивается: развернуть ЛЮБОЙ байтовый формат ОДНИМ чтением из таблицы, и тогда
// ни раскладка, ни разрывы полей не важны вовсе. ЗАМЕРЕНО НА ЭТОЙ ЖЕ ЗАДАЧЕ (tools/volta_fp8_expand.cu,
// режим "ЛУТ"): 56.04 к базе против 1.102 у int8 и 1.065 у e5m2. То есть в ПЯТЬДЕСЯТ раз хуже.
// ПРИЧИНА -- ровно оговорка §4k: индекс здесь САМ БАЙТ ДАННЫХ, он расходящийся по построению, а на
// расходящемся адресе путь констант сериализует полосы. Записанные там 16 раз -- НИЖНЯЯ оценка: она
// для ОДНОГО обращения, а разворот делает ЧЕТЫРЕ на слово, и потери складываются.
//
// ГДЕ ЖЕ БЕСПЛАТНЫЕ КОНСТАНТЫ РАБОТАЮТ -- И У НАС УЖЕ РАБОТАЮТ: когда константа входит ОПЕРАНДОМ, а
// не адресом. Магия 0x64646464 во втором источнике prmt -- это ровно тот случай: значение однородно
// по варпу, читается не по индексу, и потому стоит НОЛЬ. Туда же §4m.4 (масштаб, свёрнутый в
// операнд, который готовится один раз) и §2a (смещение, свёрнутое в затравку аккумулятора).
// ПРАВИЛО: константа бесплатна, когда она ОПЕРАНД и однородна; и катастрофична, когда она ТАБЛИЦА,
// адресуемая данными. Разница не в объёме и не в кэше -- в том, расходится ли адрес по полосам.
//
// ПРАВИЛО: пригодность формата к тензорным ядрам Volta определяется НЕ его точностью и НЕ скоростью
// конверсии, а тем, СОВПАДАЕТ ЛИ ЕГО РАСКЛАДКА С ПРЕФИКСОМ fp16. Совпадает (e5m2) -- ноль цены;
// не совпадает (e4m3) -- цена тем выше, чем на большее число РАЗНЫХ смещений разъезжаются поля.

// -------------------------------------------------------------------------------------------------
// 4pp. ЧУЖОЙ ПРИЁМ, КОТОРОГО У НАС НЕ БЫЛО: ПРОИЗВЕДЕНИЕ РАНГ-1 ОПЕРАТОРОВ -> БЛОЧНАЯ ФОРМА (WY)
// -------------------------------------------------------------------------------------------------
// Разобрана линейная мешалка Qwen3.5 (gated delta-net, 48 слоёв из 64). Внутри -- НЕ рекуррентность,
// а перепараметризация, и она стоит того, чтобы её унести.
//
// ЗАДАЧА. Дельта-правило обновляет состояние ПОСЛЕДОВАТЕЛЬНО, по одному токену:
//     S <- S * (I - b_t k_t k_t^T) + b_t v_t k_t^T
// То есть за окно из C токенов состояние умножается на ПРОИЗВЕДЕНИЕ C проекторов ранга 1. В лоб это
// цепочка длины C -- ровно тот случай, который убивает параллелизм.
//
// ПРИЁМ. Произведение проекторов ранга 1 имеет ЗАМКНУТУЮ БЛОЧНУЮ ФОРМУ:
//     prod_{i=1..C} (I - b_i k_i k_i^T)  =  I - K^T * A * (bK),   где
//     A = обратная к ЕДИНИЧНОЙ нижнетреугольной матрице  I + tril((bK) K^T, -1)   [C x C]
// Цепочка из C шагов превращается в ДВА умножения матриц плюс ОДНО обращение треугольной матрицы
// размера C. Это множительный аналог нашей свёртки смещения в ранг-1 (§2a): там аддитивная поправка
// выносилась из цикла как внешнее произведение, здесь из цикла выносится МУЛЬТИПЛИКАТИВНЫЙ оператор.
//
// И САМОЕ ЦЕННОЕ -- КАК ОБРАЩАЮТ. Матрица ЕДИНИЧНАЯ нижнетреугольная, то есть на диагонали ровно
// единицы ПО ПОСТРОЕНИЮ. Поэтому обращение не содержит НИ ОДНОГО ДЕЛЕНИЯ: строка i обратной строится
// из уже посчитанных строк одним рангом-1,
//     b_a = -A[i] ;  b_a += sum(b_a[:,None] * b_A) ;  b_A[i] = b_a ;   в конце  b_A += I
// Для нас это прямое попадание в §4g: конверсия и деление -- самые дорогие операции (7.3 против 57
// у prmt), и структурное ИЗБЕГАНИЕ деления ценнее любого быстрого деления. Приём применим везде,
// где строится обратная к треугольной матрице с известной диагональю.
//
// ТРЕТЬЕ -- РАЗМЕР ОКНА КАК РУЧКА РАЗМЕНА. Здесь C=64. Увеличение C сокращает число последовательных
// шагов, но работа треугольной части растёт как C^2..C^3. То есть C -- явная ручка "глубина цепи
// против объёма умножений", и её надо подбирать замером, а не брать из статьи.
//
// ЧТО ЗАМЕРЕНО ПРО САМО ЯДРО (V100, TP=2, чанк 15680 токенов, 24 value-головы на карту):
//   скан 15.93 мс/вызов. Работа ~50 GFLOP -> 3.1 TFLOP/s, то есть 3.4% пика 93.6.
//   Трафик ~930 МБ (главное -- тензор состояний h: 245 чанков x 24 головы x 128x128 fp32 = 385 МБ,
//   записывается и читается) -> 1.1 мс по 841 ГБ/с, то есть 7% полосы.
//   НИ ПО СЧЁТУ, НИ ПО ПОЛОСЕ ядро не упирается -- значит упирается в РАСПИСАНИЕ, а это ровно наш
//   класс задач (§4a-4d, §4p). Запас по обеим меркам примерно 14-30x.
//
// ЗАМЕРЕНО И ОТРИЦАТЕЛЬНОЕ: у этих ядер конфигурации автотюнера для SM70 УРЕЗАНЫ (ступени [2] против
