// Ничего не стало быстрее; изменилось КТО С КЕМ И КОГДА. Поэтому дальше искать надо не приёмы, а
// НЕДОГРУЖЕННЫЕ ресурсы, и ведомость ведётся по ЗАМЕРУ, а не по ощущению.
//
//  (ДОПОЛНЕНО: см. также §4t -- целочисленную работу можно вести и на FP32, +1.45x к ёмкости INT32)
//  ресурс                 замеренная ёмкость            у нас сейчас        недогруз
//  --------------------   ---------------------------   -----------------   -----------------------
//  путь констант          13.27 загр/такт, +1.5% (§4k)   НОЛЬ                100%, полностью простой
//  INT32 под HMMA         2 инстр/HMMA при 92% (§4r)     ~0 в мейнлупе       ~100%
//  тензорный конвейер     86% пика при всех блоках (§4p) ~38% (задача #78)   в 2.3 раза
