// 4a. ШИРОКАЯ ЗАГРУЗКА ЗАКОННА ТОЛЬКО ТАМ, ГДЕ ШАГ ПОЛОСЫ ЕЙ КРАТЕН.
//     Парная 8-байтовая загрузка байтового операнда (одна LDS.64 = 8 значений = ДВА шага по k)
//     законна для k-МАЖОРНОГО операнда и НЕЗАКОННА для n-мажорного: там база полосы шагает по 4
//     (wmma_b_nbase даёт {0,4,8,12}), и чтение 8 байт с неё даёт misaligned address. Это свойство
//     РАСКЛАДКИ ИНСТРУКЦИИ, а не кода.
//
// 4b. ШАГ СТРОКИ БАЙТОВОГО БУФЕРА -- КРАТЕН 16, если по нему пишут uint4.
//     DC+PAD=68 и D+PAD=260 не кратны 16, и широкая запись падала. У fp16-пути та же формула даёт
//     другое выравнивание (шаг в полусловах), поэтому дефект проявляется ТОЛЬКО в байтовом пути.
static constexpr int align_pitch_16(int p) { return (p + 15) / 16 * 16; }
//
// 4c. БАНКОВЫЕ КОНФЛИКТЫ ЗАДАЁТ ШАГ СТРОКИ В 4-БАЙТОВЫХ СЛОВАХ ПО МОДУЛЮ 32.
//     Замерено на отгруженном forward: 158.7 млн конфликтов на 708.8 млн волновых фронтов = 22.4%,
//     и mio_throttle 0.94 -- ПЕРВЫЙ простой. Разбор по раскладке: у k-мажорных Q и K шаг даёт %32=2,
//     и 16 полос ровно кроют 32 банка (чисто). У n-мажорного V адрес складывается как
//     (lane&3)*2 + nbase/2, где ОБА слагаемых пробегают {0,2,4,6} -- суммы накладываются, и 16
//     адресов садятся примерно на 7 банков. Источник -- раскладка V, а не код.
//
// 4d. ИНДЕКС РЕГИСТРОВОГО МАССИВА -- ТОЛЬКО КОНСТАНТА ВРЕМЕНИ КОМПИЛЯЦИИ.
//     Иначе массив уезжает в локальную память при НУЛЕ разливов, и это не лечится освобождением
//     регистров. Признак в ptxas -v: stack frame > 0 при spill == 0.

// =================================================================================================
// 4e. МАТРИЦА ИНСТРУКЦИЙ sm_70: что может, чем грузит, чем грозит, где накладные
// =================================================================================================
// Замерено tools/volta_isa_bench.cu на V100 @1530 МГц, 320 блоков x 256 нитей.
// IPC -- операций НА НИТЬ на такт на SM (потолок 64: столько ядер FP32/INT32 в SM).
// Задержка -- такты зависимой цепочки. Планировать надо по ОБЕИМ: пропускная задаёт бюджет
// выдачи, задержка -- длину критического пути.
//
//  инструкция     IPC    задержка  конвейер   что может                          чем грозит
//  ------------------------------------------------------------------------------------------------
//  IMAD           58.0     17.8    INT32      умножение-сложение, адреса          64-битная адресация
//  PRMT           57.1     18.0    INT32      ПЕРЕСТАНОВКА БАЙТ (наш разворот)    -- полный темп!
//  VABSDIFF4      57.1     18.0    INT32      |a-b| по 4 байтам разом             SIMD, редко нужен
//  DP4A           58.0     17.8    INT32      int8 скаляр. произв. на ALU         0.58x от тензорных
//  FADD/FMUL/FFMA 58.0     17.8    FP32       обычная арифметика                  --
//  HFMA2          57.9     17.7    FP32       ДВА fp16 за инструкцию              вдвое на значение
//  VADD4          35.6     29.1    INT32      4 байта разом                       0.6 темпа
//  SHFL           28.1     44.4    крос-бар   обмен полос, МИМО MIO               ПОЛОВИНА темпа ALU
//  SHFL.XOR       29.0     35.9    крос-бар   обмен по маске                      то же
//  BALLOT         18.9     53.5    крос-бар   голосование по варпу                треть темпа
//  POPC/BREV/FLO  14.5     70.6    SFU        счёт бит, разворот, старший бит     ЧЕТВЕРТЬ темпа
//  EX2 (exp2f)    14.5     70.6    SFU        ЭКСПОНЕНТА СОФТМАКСА                четверть темпа!
//  RCP            8.9     113.2    SFU        обратное                            вшестеро медленнее
//  I2F/F2I        7.3     141.2    конверсия  целое <-> fp32                      ВОСЬМЕРО медленнее
//  LDS.32       1224*        --    MIO/LSU    4 байта                             мелкая, но частая
//  LDS.64        714*        --    MIO/LSU    8 байт                              1.7x дороже за инстр
//  LDS.128       669*        --    MIO/LSU    16 байт                             2.2x ЛУЧШЕ ЗА БАЙТ
//  (* для LDS счёт в операциях на нить; сравнивать между собой, не с ALU)
//
// НЕДЕЙСТВИТЕЛЬНЫ (компилятор свернул константы): IADD, LOP3, SHF показали 15576 / 2832 / 29.7 IPC,
// чего физически быть не может. Их темп следует из IMAD/PRMT: все простые целочисленные идут по
// конвейеру INT32 на ПОЛНОМ темпе ~58.
//
// ЧТО ИЗ ЭТОГО СЛЕДУЕТ ДЛЯ МАКРОСОВ (каждый пункт -- решение, а не наблюдение):
//   1. КОНВЕРСИЯ -- САМАЯ ДОРОГАЯ ОПЕРАЦИЯ (7.3 против 57 у PRMT, ВОСЬМИКРАТНО). Любой формат
//      разворачивать битами, а не cvt. Это и есть §1a/§1b/§3.
//   2. PRMT идёт на ПОЛНОМ темпе -- перестановка байт стоит ровно столько же, сколько FFMA.
//      Поэтому §1a бесплатен относительно арифметики, а cvt -- нет.
//   3. SHFL -- ПОЛОВИНА темпа ALU и задержка 44 такта. Замена одной LDS на один SHFL НЕ ВЫГОДНА;
//      выгодна только замена ДВУХ И БОЛЕЕ LDS или снятие банковых конфликтов.
//   4. EX2 -- четверть темпа. В софтмаксе экспонент BQ*BK на плитку, и это НЕ мелочь: при 64x64
//      это 4096 EX2 на плитку против 8192 HMMA-эквивалентов. Считать экспоненту реже (по блокам,
//      а не поэлементно) -- отдельный рычаг.
//   5. HFMA2 даёт ДВА значения за инструкцию на полном темпе -- эпилог и перемасштабирование
//      выгодно вести парами fp16, а не по одному fp32.
//   6. LDS.128 лучше LDS.32 в 2.2 раза ЗА БАЙТ, но дороже ЗА ИНСТРУКЦИЮ. Поскольку MIO считает
//      инструкции, широкая загрузка выигрывает только когда реально уносит больше данных.
//
// =================================================================================================
// 4f. ЕСТЬ В ЖЕЛЕЗЕ, НЕТ В CUDA C: инструкции, которые компилятор не выдаст никогда
// =================================================================================================
// Пробовано по одной через inline asm, сборка для sm_70 против sm_75 (tools/, probe.sh).
// У всех перечисленных НЕТ обёртки в CUDA C -- значит доступ только через asm, и компилятор
// сам их не поставит ни при какой оптимизации.
//
//  инструкция        sm_70   что даёт                                     где применимо у нас
//  ------------------------------------------------------------------------------------------------
//  lop3.b32 + ЛУТ     ЕСТЬ   ЛЮБАЯ булева функция ТРЁХ входов за 1 инстр.  слияние цепочек масок
//  prmt.rc8           ЕСТЬ   повтор байта восемь раз                       широковещание масштаба
//  prmt.rc16          ЕСТЬ   повтор полуслова                              то же для fp16
//  prmt.ecl / .ecr    ЕСТЬ   зажим краёв (репликация знака)                расширение знака без сдвигов
//  prmt.f4e / .b4e    ЕСТЬ   сдвиг байт с переносом / обратный порядок     перестановки фрагментов
//  bmsk.clamp.b32     ЕСТЬ   создать битовую маску из (база, длина)        маски хвостов плитки
//  fns.b32            ЕСТЬ   найти N-Й УСТАНОВЛЕННЫЙ БИТ                   КОМПАКЦИЯ без префикс-суммы
//  bfe / bfi          ЕСТЬ   извлечь / вставить битовое поле               распаковка форматов
//  dp2a.lo            ЕСТЬ   2-путевое скалярное произведение              16x8 без разворота
//  szext.clamp        ЕСТЬ   расширение знака                             int8 -> int32
//  match.any.sync     ЕСТЬ   найти полосы с равным значением               группировка по ключу
//  redux.sync          НЕТ   варповая редукция одной инструкцией           только sm_80+
//  mma.m8n8k16.s8      НЕТ   IMMA                                          только sm_75+ (см. §1)
//
// ЧТО ИЗ ЭТОГО СТОИТ ВЗЯТЬ ПЕРВЫМ:
//   1. fns.b32 -- компакция выживших элементов сейчас требует ballot + popc + префикс-сумму;
//      fns даёт ОБРАТНОЕ отображение (номер -> позиция) одной инструкцией. Это прямой путь для
//      списков работ и любого отбора.
//   2. prmt.ecl/.ecr -- расширение знака БЕЗ сдвигов, то есть §1a может стать ещё короче на входах,
//      где знак нужен явно.
//   3. lop3 с ЛУТом -- всякая цепочка из двух-трёх логических операций сворачивается в одну.
//      Проверять по SASS: компилятор ИНОГДА сам сливает две в lop3, но не три и не всегда.
//
// И САМОЕ ДЕШЁВОЕ УЛУЧШЕНИЕ §1a, следующее не из ISA, а из постановки: XOR на 0x80808080 нужен
// только потому, что мы храним ЗНАКОВЫЙ int8. Если квантователь пишет смещённое значение (v+128,
// то есть uint8), разворот становится ДВУМЯ инструкциями вместо трёх -- две prmt и ничего больше.
// Квантователь наш, менять формат хранения нам никто не мешает.

// =================================================================================================
// 4g. ВИДЕО-СЕМЕЙСТВО: почти всё ЛОВУШКА, кроме двух
// =================================================================================================
// Гипотеза была: SIMD-инструкции дают "четыре байта по цене одной". Замерено через asm -- держится
// ровно для ДВУХ инструкций из тринадцати. И они НЕ обходят MIO: всё семейство на конвейере INT32.
//
//  vabsdiff4   57.1 IPC / 18 тактов   НАСТОЯЩАЯ, полный темп -- 4 байтовых |a-b| за одну
//  vmad        56.0 / 26.7            НАСТОЯЩАЯ, полный темп
//  vadd2, vshl 27.6 / 28.3            половина темпа
//  vadd4/vsub4 19.2 / 53              треть
//  vmax2        9.6 / 107             шестая часть
//  vset (32b)   8.3 / 124             седьмая
//  vabsdiff2    5.4 / 178             десятая
//  vmin4/vmax4  2.34 / 409            ЭМУЛЯЦИЯ -- в 25 раз хуже обычной арифметики
//  vset4        1.95 / 479            ЭМУЛЯЦИЯ -- убивает идею байтового отбора по порогу
//  vavrg4       1.90 / 520            ЭМУЛЯЦИЯ
//
// ОБРАТНЫЙ СЛУЧАЙ, ЕДИНСТВЕННЫЙ ЗА СЕССИЮ: здесь ИНТРИНСИК БЫСТРЕЕ СЫРОЙ PTX. __vmaxu4() даёт
// 9.6 IPC, а vmax4 через asm -- 2.34: компилятор подменяет интринсик вручную настроенной
// последовательностью, а объявленную инструкцию ptxas разворачивает плохо. То есть правило
// "обходить компилятор" здесь НЕ действует, и это надо помнить.

// =================================================================================================
// 4h. ПЕРЕСТАНОВКА АККУМУЛЯТОРА В ОПЕРАНД: перебор ВСЕХ раскладок
// =================================================================================================
// Вопрос: можно ли скормить результат первого GEMM во второй, минуя разделяемую память (это убрало
// бы STS + LDS с MIO, который и есть лимит). Проверено не одной попыткой, а перебором всех четырёх
// вариантов HMMA:
//
//  вариант                        на месте   XOR-расстояние   ступеней бабочки
//  A k-мажорный (P как есть)        50%           2                  1
//  A m-мажорный (P транспонир.)     50%           1                  1
//  B k-мажорный (O^T = V^T P^T)     25%        1,16,17               2
//  B n-мажорный                     25%        2,16,18               2
//
// НИ ОДНА раскладка не делает перестановку бесплатной: минимум -- одна ступень бабочки. Полсотни
// процентов элементов уже лежат в нужной полосе, остальным нужен обмен на соседнюю (XOR 1) либо
// через одну (XOR 2).
//
// ЦЕНА, И ПОЧЕМУ ВЕРДИКТ НЕ ОКОНЧАТЕЛЬНЫЙ:
//   в лоб  -- 8 регистров fp32: 8 SHFL + 8 выборок = 16 инструкций против ~5 обращений в smem;
//   умно   -- УПАКОВАТЬ В fp16 ДО перестановки (в операнд всё равно идёт fp16): 4 регистра ->
//             4 SHFL + 4 выборки = 8 инструкций против ~5.
// Восемь против пяти -- это уже не приговор. Причём восемь идут по КРОССБАРУ (мимо MIO), а пять --
// по MIO, который и есть узкое место (mio_throttle 0.94, первый простой). Арифметикой вопрос больше
// не решается: нужен замер. Бюджет выдачи при этом занят на 0.928 из 1.000, поэтому чистый прирост
// инструкций должен быть мал -- упаковка в fp16 здесь обязательна, без неё заведомо хуже.

// =================================================================================================
// 4i. FP64 КАК НЕТРОНУТЫЙ РЕСУРС: из трёх идей выжила одна
// =================================================================================================
// Замерено tools/volta_fp64_bench.cu (V100, 80 SM, 80 блоков x 256 нитей):
//   add.f32 темп ..................... 52.35 IPC/SM
//   add.f64 темп ..................... 28.13 IPC/SM  (ровно половина -- соотношение 1:2 у V100)
//   add.f64 задержка ................. 31.6 такта
//   смесь fp32+fp64 .................. 26.60 + 26.60 = 53.2 суммарно
//
// (а) "FP64 -- свободный конвейер, даст мощности сверху" -- ОПРОВЕРГНУТО ДЛЯ FP64. Смесь даёт 53.2
//     против 52.35 у чистого fp32: прирост 1.6%, то есть ноль. Причина -- у fp64 всего 32 блока на
//     SM (темп 1:2), он не столько добавляет, сколько отбирает.
//     ВНИМАНИЕ: обобщение "выдача общая, свободного конвейера НЕТ", которое я отсюда вывел,
//     ОПРОВЕРГНУТО ПОЗЖЕ в §4o. Для пары FP32+INT32 конвейеры СКЛАДЫВАЮТСЯ (+58%). Вывод по fp64
//     верен, вывод "ни один конвейер не складывается" -- был неверен.
// (б) "операция в полёте -- хранилище за ноль регистров" -- ОПРОВЕРГНУТО частично: держать значение
//     в полёте можно 31.6 такта, но double занимает ПАРУ регистров того же единого файла и плотнее
//     двух int32 ничего не хранит. Регистров это не экономит.
// (в) "мантисса 52 бита -- контейнер под несколько целых" -- ПОДТВЕРЖДЕНО и стало примитивом §1d:
//     1.46x над vadd4 при точном результате.
//
// ОБЩЕЕ ПРАВИЛО, которое из этого следует: выигрыш на Volta даёт не поиск НЕЗАНЯТОГО конвейера
// (его нет -- выдача одна), а поиск инструкции, которая на ОДНУ выдачу делает больше полезной
// работы. Оба наших выигрыша именно такие: перестановка байт вместо арифметики и упаковка полей
// вместо SIMD.

// =================================================================================================
// 4j. SFU: ЕДИНСТВЕННЫЙ КОНВЕЙЕР, КОТОРЫЙ ДЕЙСТВИТЕЛЬНО ПЕРЕКРЫВАЕТСЯ С FP32
// =================================================================================================
// Замерено tools/volta_sfu_bench.cu. Всё семейство настоящее (не эмуляция), темп ~1/4 от fp32:
//   ex2   12.66 IPC / задержка 48.0      rcp   10.43 / 59.9  <- самая долгая
//   rsqrt 12.70 / 47.9                   lg2   12.70 / 47.9
//   sin   14.61 / 32.6                   sqrt  12.90 / 47.1
//
// ГЛАВНОЕ, и это ПРОТИВОПОЛОЖНО выводу по fp64 (§4i):
//   чистый add.f32 ........... 51.89 IPC
//   чистый ex2 ............... 12.66 IPC
//   СМЕСЬ .................... 11.70 ex2 + 11.70 fp32 = 23.4 суммарно
// То есть добавление потока fp32 обошлось потоку ex2 всего в 7.6% (12.66 -> 11.70), а взамен дало
// 11.70 IPC арифметики fp32 ПОЧТИ ДАРОМ. FP64 так не умеет: там смесь дала 53.2 против 52.35, ноль.
// ПРИЧИНА: SFU -- медленный блок с длинной задержкой, его инструкция занимает ВЫДАЧУ ненадолго, а
// исполняется 48 тактов, оставляя слоты свободными. FP64 при темпе 1:2 выдачу насыщает.
//
// СЛЕДСТВИЕ ДЛЯ ЯДРА (софтмакс -- единственное место, где мы зовём SFU):
// ex2 в софтмаксе НЕ надо изолировать в отдельную фазу. Наоборот -- под него надо ПОДКЛАДЫВАТЬ
// работу fp32 (перемасштабирование накопителя, коррекция), она уедет почти бесплатно. Это и есть
// тот самый "метаблок" из наброска: разные блоки на разных плитках одновременно. Из всех
// проверенных конвейеров он работает ТОЛЬКО здесь.
//
// ОБХОД ЧЕРЕЗ БИТЫ НЕ ОКУПАЕТСЯ (редкий случай -- железо почти не уступает трюку):
// 2^x через поле экспоненты (ffma + переистолкование) даёт 14.80 IPC против 12.66 у MUFU -- всего
// 1.17x, при максимальной относительной ошибке 3.91% и средней 1.53% на диапазоне софтмакса
// [-16,0]. Для внимания нужно ~1e-3, так что цена неприемлема. MUFU -- НАСТОЯЩЕЕ железо, в отличие
// от vadd4/fns/vset4, и обходить его нечем.

// =================================================================================================
// 4k. ПУТИ ЗАГРУЗКИ: константы на ОДНОРОДНОМ адресе идут МИМО MIO и почти бесплатно
// =================================================================================================
// Замерено tools/volta_load_paths.cu, восемь независимых обращений, загрузок/такт/SM:
//   разделяемая память (LDS) ........ 7.27   <- база, и это тот самый MIO
//   константы, ОДНОРОДНЫЙ адрес ..... 13.27  <- В 1.83 РАЗА БЫСТРЕЕ разделяемой памяти
//   константы, РАСХОДЯЩИЙСЯ адрес ... 0.45   <- В 16 РАЗ ХУЖЕ; обрыв, а не деградация
//   глобальная .nc (__ldg) .......... 6.33
//   текстура (tex1Dfetch) ........... 3.66   <- ВДВОЕ МЕДЛЕННЕЕ LDS, как путь разгрузки бесполезна
//
// СМЕСЬ -- главный вопрос, перекрывается ли путь с MIO:
//   чистая LDS, 8 обращений ............ 0.209 мс   (значит 4 обращения = 0.105)
//   смесь 4 LDS + 4 константы .......... 0.106 мс   <- ЧЕТЫРЕ КОНСТАНТНЫХ ОБРАЩЕНИЯ ДАЛИСЬ ЗА +1.5%
//   смесь 4 LDS + 4 текстуры ........... 0.212 мс   <- прироста нет, упирается в саму текстуру
// То есть путь констант НЕ идёт через порт разделяемой памяти и добавляет мощность практически
// даром. Текстура -- нет: она просто медленнее того, что разгружает.
//
// КАК ЭТИМ ПОЛЬЗОВАТЬСЯ (ограничение жёсткое): данные должны быть (а) ОДНОРОДНЫ по варпу и
// (б) только для чтения, и попасть в постоянную память можно лишь до запуска -- из ядра туда не
// записать. Практический канал -- ПАРАМЕТРЫ ЯДРА: они и так лежат в банке констант (~4 КБ на
// Volta), поэтому небольшая таблица, переданная по значению, едет по бесплатному пути.
// Наши кандидаты: масштабы и нули GPTQ на уровне группы (они варп-однородны!), константы софтмакса,
// шаги и длины. Всё, что сейчас читается из разделяемой памяти и однородно, стоит перевести сюда --
// это прямой съём нагрузки с MIO, который у нас узкое место (mio_throttle 0.94).
//
// ЛОВУШКА, ОБЯЗАТЕЛЬНАЯ К ПАМЯТИ: на РАСХОДЯЩЕМСЯ адресе путь констант рушится в 16 раз
// (0.45 против 7.27) -- он сериализует полосы. Прежняя оценка "2.7x потери" была СИЛЬНО мягче
// действительности. Индекс, зависящий от threadIdx, в постоянной памяти -- запрещён.

// =================================================================================================
// 4l. РЕГИСТРОВЫЙ ФАЙЛ И ШИНА: кэш повторного использования пуст, подсказка потока даёт +6%
// =================================================================================================
// Замерено tools/volta_regfile_bus.cu.
//
// КЭШ ПОВТОРНОГО ИСПОЛЬЗОВАНИЯ ОПЕРАНДОВ (флаг .reuse: соседние инструкции берут один регистр в
// ТОЙ ЖЕ позиции -> чтение из файла не выполняется):
//   оба операнда общие ...... 51.17 IPC, в SASS 6 флагов .reuse из 8
//   общий ОДИН операнд ...... 47.41 IPC, флагов 0     <- ХУЖЕ НА 7.3%
//   все операнды разные ..... 51.17 IPC, флагов 0
// Механизм РЕАЛЕН (флаги видны), но выигрыша НЕ ДАЁТ: fp32 упирается в число исполнительных блоков
// (51 из 64), а не в пропускную способность файла. Гнаться за .reuse смысла нет.
//
// ЗАТО СРЕДНЯЯ СТРОКА -- ПРЕДУПРЕЖДЕНИЕ, и оно про наш мейнлуп. Схема "общий A, разные B" -- ровно
// то, как устроена подача операндов у нас -- потеряла 7.3% при НУЛЕ флагов. Это подпись КОНФЛИКТА
// БАНКОВ регистрового файла (банк = номер регистра по модулю 4): два операнда одной инструкции из
// одного банка стоят лишний такт. Лечится только раскладкой регистров, то есть через SASS, и
// проверять это надо ЗАМЕРОМ, а не глазами -- ptxas распределение не показывает.
//
// УПРАВЛЕНИЕ ШИНОЙ, потоковое чтение 256 МБ (L2 всего 6 МБ):
//   ld.global.ca .... 508.2 ГБ/с      ld.global.cg .... 507.0      ld.global.cv .... 506.9
//   ld.global.cs .... 537.6 ГБ/с      ld.global.lu .... 538.5      <- ОБЕ ДАЮТ +6%
// .cs (потоковая, вытеснять первой) и .lu (последнее использование) помечают строку как ненужную
// в кэше, и она не вытесняет полезное. K и V во внимании читаются ИМЕННО так: один раз на блок
// запросов, при большом S в L2 не помещаются. Правка -- одна подсказка в загрузке, выигрыш бесплатный.
//
// ТЕКСТУРНОЙ ПАМЯТИ НЕ СУЩЕСТВУЕТ (частый и естественный вопрос): с Maxwell текстурный кэш СЛИТ с
// L1, на Volta это единый блок 128 КБ, делимый между разделяемой памятью и L1. Отдельного яруса
// хранения у текстурных блоков нет. Для нас даже хуже нейтрального: ядро берёт 85 КБ разделяемой из
// 96, значит на L1 остаётся ~32 КБ, за которые текстурные чтения будут конкурировать. Своё у текстур
// только адресная арифметика (интерполяция, зажим, свёртка координат) -- это вычисление, не память.
// Ярусы на SM исчерпываются: регистры 256 КБ, разделяемая до 96 КБ, L1 из остатка, L2 6 МБ, HBM.

// =================================================================================================
// 4m. ЧТО В ТЕНЗОРНОЙ ИНСТРУКЦИИ ДАРОМ (самое крупное, потому что УЖЕ ОПЛАЧЕНО)
// =================================================================================================
// Инструкция считает D = A*B + C. Отсюда четыре бесплатных вещи, и их надо искать ПЕРВЫМИ, до
// всякой охоты за конвейерами: тут цена не "низкая", а РОВНО НОЛЬ.
//
// 1. СЛОЖЕНИЕ. Операнд C бесплатен. Мы уже пользуемся им на накоплении P*V, но там же даром едет
//    ЛЮБОЕ аддитивное слагаемое: ALiBi, позиционное смещение, ограничение логита, поправка.
//    Правило: если слагаемое можно записать в аккумулятор ДО умножения -- оно ничего не стоит.
//
// 2. ПЕРЕСТАНОВКА ПРИ ЗАГРУЗКЕ ФРАГМЕНТА. Адреса LDS для операнда выбираем мы, поэтому любая
//    перестановка, ВЫРАЗИМАЯ АДРЕСОМ, бесплатна. Это и есть настоящий смысл закона раскладки
//    (§4a-4d): граница проходит не между "быстро/медленно", а между "вписывается в адрес" (ноль) и
//    "не вписывается" (ступень бабочки, §4h). Проверять принадлежность к первой категории НАДО
//    ДО того, как считать стоимость перестановки.
//
// 3. ПЕРЕСТАНОВКА ЧЕРЕЗ ЗАРАНЕЕ ПЕРЕСТАВЛЕННЫЙ ОПЕРАНД. Если операнд готовится один раз (веса,
//    V^T, таблица), переставить его при подготовке -- бесплатно в момент использования. Умножение
//    на матрицу перестановки (§ "странные маршруты") нужно только там, где операнд построить
//    заранее НЕЛЬЗЯ.
//
// 4. МАСШТАБ, СВЁРНУТЫЙ В СТРОЯЩИЙСЯ ОПЕРАНД. Делается у нас: Q домножен на scale*log2(e) заранее,
//    поэтому ни масштаб, ни перевод основания не стоят ни одной инструкции в цикле. Тот же приём --
//    свёртка смещения в ранг-1 (§2).
//
// А ВОТ ЧЕГО ТУДА НЕ КЛАДЁТСЯ, хотя очень хочется: ПРИЧИННАЯ МАСКА. Технически работает
// (-inf + A*B = -inf, аккумулятор можно затравить), но это РАЗМЕН, а не выигрыш: затравка потребует
// сравнения со select вместо дешёвого обнуления и ровно съест тот select, который убирается после
// MMA. Ноль. Настоящий рычаг по маске -- НЕ тензорный: проверка на уровне ПЛИТКИ, потому что
// внутренние плитки не замаскированы целиком и предикат в них можно не считать вовсе.
// (Сейчас маска стоит поэлементно: volta_fwd_block.cuh, ветка CAUSAL после мейнлупа.)

