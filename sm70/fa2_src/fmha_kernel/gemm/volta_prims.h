//   Складывать их в один счётчик нельзя -- именно эта ошибка закрыла несколько путей раньше срока.
//
// ЧТО ЭТО ПЕРЕСМАТРИВАЕТ. Вердикт по перестановке P (§4h) звучал как "16 инструкций кроссбара против
// 5 MIO -- перебор бюджета". Бюджет вдвое больше, чем я считал, барьер стоит 33.7 такта (§4n), а
