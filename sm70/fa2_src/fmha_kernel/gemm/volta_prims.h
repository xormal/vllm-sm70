//
// 4p (прежний текст, читать с поправкой выше). МЕТАБЛОК: Tensor + FP32 + INT32 почти даром.
// =================================================================================================
// Замерено tools/volta_metablock.cu, HMMA-инструкций варпа на такт на SM:
//   только HMMA .......................... 0.410   (база)
//   HMMA + FP32 .......................... 0.389   = 0.948 от базы, прочих 0.389/такт
//   HMMA + INT32 ......................... 0.385   = 0.937 от базы, прочих 0.385/такт
//   HMMA + FP32 + INT32 .................. 0.392   = 0.954 от базы, прочих 0.784/такт  <- ЛУЧШЕ ОБОИХ
