// 4q. БАРЬЕР КАК ПЕРЕДАЧА: сигнал стоит 2.76 такта, ожидание -- 33.40. РАЗНИЦА В 12 РАЗ
// =================================================================================================
// Замерено tools/volta_bar_pipeline.cu (чистая цена сверх базы, 8 варпов в блоке):
