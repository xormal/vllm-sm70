    def load_model(self, target_model: torch.nn.Module) -> None:
        from vllm.model_executor.models.qwen3_dflash import (
            dflash_target_rope_is_neox_style,
        )

        конф = self.speculative_config.draft_model_config
        assert конф is not None
        # Черновик обязан вращать Q/K ТАК ЖЕ, как его цель: иначе позиции разойдутся тихо, и это
        # проявится не падением, а падением приёмки -- худший вид дефекта.
        neox = dflash_target_rope_is_neox_style(target_model)
        if neox is not None:
            конф.hf_config.is_neox_style = neox
        super().load_model(target_model)
        # [int8-СЛОВАРЬ СТРОИТСЯ ЗДЕСЬ, А НЕ ЛЕНИВО -- записка 25 §113d]
        # Ленивая сборка «при первом вызове вне захвата» падала OOM: к тому моменту KV-пул уже
        # выделен, свободно 237 МиБ, а раскладке нужно 1.19 ГиБ. Запас при max_model_len=262144
        # структурно меньше нужного (8.59 пула против минимума 7.68 -> 0.82 ГиБ), поэтому
        # «ужать пул» не помогает: движок отвергает пул меньше 7.68.
        # Здесь голова цели УЖЕ подключена (super().load_model разделил её с черновиком), а
        # KV-пул ЕЩЁ не выделен -- значит 1.19 ГиБ уйдут в замер занятой памяти, и пул
        # посчитается уже с ними. Это единственная точка, где верны оба условия.
        if getattr(self.model, "_словарь_int8", False):
            try:
                self.model._собрать_словарь_int8()
                print("[dflash2] int8-словарь черновика собран ДО выделения KV-пула", flush=True)
            except Exception as _e:  # noqa: BLE001
                print(f"[dflash2] int8-словарь не собран ({type(_e).__name__}: {str(_e)[:80]}), "
                      f"верхушка пойдёт полной головой", flush=True)

