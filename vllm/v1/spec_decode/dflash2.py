    # 2-5. Один проход + отбор связного пути
    def _учесть_priyomku(self, ib, батч: int) -> None:
        """Приписать приёмку ТОМУ источнику, что дал черновик на прошлом шаге.

        СИГНАЛ БЕРЁТСЯ ГОТОВЫЙ: `input_batch.num_accepted_tokens_cpu` -- движок сам
        заполняет его после приёмки (gpu_model_runner.py:1184), на процессоре, без
        сверки с картой.
        ПЕРВАЯ РЕДАКЦИЯ СЧИТАЛА ПРИРОСТ `num_tokens_no_spec` -- и он оказался ВЫРОЖДЕН:
        186 замеров дали РОВНО 1.00 при любой приёмке, потому что это число растёт на
        один токен за шаг независимо от того, сколько черновых приняли. Метрика, которая
        не двигается от того, что ОБЯЗАНО её двигать, недействительна -- и калибровщик на
        ней молча выбирал не тот источник.
        """
        if self._прошлый_ист is None:
            return
        try:
            прин = ib.num_accepted_tokens_cpu
        except AttributeError:
            return
        сумма = 0.0
        учтено = 0
        for i in range(батч):
            a = int(прин[i])
            if 1 <= a <= self.num_speculative_tokens + 1:
                сумма += a
                учтено += 1
        if учтено:
            и = self._прошлый_ист
            self._сум[и] += сумма / учтено
            self._проб[и] += 1
            if self._проб[и] >= self._проб_предел:      # забывание: половиним обе чаши
                for к in self._сум:
                    self._сум[к] *= 0.5
                    self._проб[к] = self._проб[к] // 2

    def _средняя(self, и: str) -> float:
        return self._сум[и] / self._проб[и] if self._проб[и] else 0.0

    def _выбрать_источник(self) -> bool:
        """True -- пробовать n-граммы.

        Пока у источника нет 8 замеров приёмки, его надо ОПРОБОВАТЬ, и опробовать
        ВПЕРЕМЕЖКУ: восемь проб подряд одного источника попадут в один участок текста
        и измерят участок, а не источник.
        """
        if self._проб["нг"] < 8 or self._проб["мод"] < 8:
            return (self._проб["нг"] <= self._проб["мод"])
        # Изредка проверяем отвергнутый: текст по ходу диалога меняется.
        if self._нграм_шаг % self._нграм_иссл == 0:
            return self._средняя("нг") <= self._нграм_цена * self._средняя("мод")
        return self._средняя("нг") > self._нграм_цена * self._средняя("мод")

    @staticmethod
    def _свежие_на_хост(t):
        """Последние принятые токены на процессор. Отдельной функцией, чтобы место
        переноса с карты было ОДНО и было видно: это единственная синхронизация,
        которую добавляют n-граммы."""
        return None if t is None else t.view(-1).tolist()

    def _накопить_ряд(self, i: int):
        """Накопленные ПРИНЯТЫЕ токены строки i, как список.

        Раннер кладёт `_fa2_принятые` -- принятые токены ТЕКУЩЕГО шага ([батч, k+1] с -1 на
        отвергнутых, либо список списков). Дописываем их в свой список на запрос: propose
        зовётся ровно раз за шаг, поэтому ряд получается полным и без пропусков.
        """
        рн = getattr(self, "runner", None)
        прин = getattr(рн, "_fa2_принятые", None)
        if прин is None:
            return None
        ib = getattr(рн, "input_batch", None)
        рид = None
        _ри = getattr(ib, "req_ids", None) if ib is not None else None
        if _ри is not None and i < len(_ри):
            рид = _ри[i]
        ключ = рид if рид is not None else i
        ряд = self._ряд_вых.get(ключ)
        if ряд is None:
            ряд = self._ряд_вых[ключ] = []
        # Новые токены этого шага. Тензор переносим на хост целиком -- это единицы чисел.
        try:
            if hasattr(прин, "tolist"):
                if прин.shape[0] <= i:
                    return ряд
                новые = прин[i].tolist()
            else:
                if len(прин) <= i:
                    return ряд
                новые = list(прин[i])
        except (IndexError, RuntimeError, AttributeError):
            return ряд
        for т in новые:
            т = int(т)
            if т < 0:                       # заполнитель отвергнутой позиции -- ряд кончился
                break
            ряд.append(т)
        # Ограничитель памяти: держим хвост, длиннее которого n-грамма всё равно не смотрит.
        if len(ряд) > self._ряд_предел:
            del ряд[: len(ряд) - self._ряд_предел]
        return ряд

    def _поиск_нграмм(self, батч: int, k: int, свежие=None):
        """Черновик из САМОГО КОНТЕКСТА: чем кончается последовательность, тем она уже
        кончалась раньше -- берём продолжение оттуда.

        Отдаём тензор [батч, k] ТОЛЬКО если продолжение полной длины нашлось ДЛЯ ВСЕХ
        строк батча, иначе None и работает обычный черновик. Так длина черновика остаётся
        РОВНО k, и ни однородный декод, ни метаданные GDN не трогаются (штатный метод
        "ngram" отдаёт списки переменной длины и роняет наш форк).

        Качество не при чём ПО ПОСТРОЕНИЮ: приёмка сверяет каждый токен целью точным
        совпадением. Проверено побайтово -- отпечатки трёх проб совпали с прогоном без
        n-грамм (28.08).
        """
        ib = getattr(getattr(self, "runner", None), "input_batch", None)
        if ib is None:
            return None
        try:
            токены = ib.token_ids_cpu          # [макс_запросов, макс_длина], numpy
            длины = ib.num_tokens_no_spec      # [макс_запросов], numpy
        except AttributeError:
            return None
        import numpy as _np
        out = _np.zeros((батч, k), dtype=_np.int32)
        _рид = getattr(ib, "req_ids", None)
        _выхи = getattr(ib, "req_output_token_ids", None)
        _нпр = getattr(ib, "num_prompt_tokens", None)
        self._нграм_всего += 1
        for i in range(батч):
            L = int(длины[i])
            _L0 = L                      # длина ДО отката по -1: видно, съедает ли откат генерацию
            # [ЖИВОЙ РЯД 31.08 -- БЕЗ ЭТОГО n-ГРАММЫ НЕ РАБОТАЛИ НИ РАЗУ]
            # ЧТО БЫЛО. `token_ids_cpu` заполняется движком ТОЛЬКО при добавлении запроса
            # (`add_request`) и при записи спекулятивных позиций; ПРИНЯТЫЕ токены туда не
            # пишутся. Поэтому весь диапазон после промпта -- это -1, откат по -1 съедал
            # генерацию целиком, и поиск шёл по ОДНОМУ ПРОМПТУ. Прибор назвал это числом:
            #     L0=9031  L=8885  за_границей=[-1,-1,-1,0,0,0]  длины совпадения: n=1:149
            # то есть после 149 шагов ряд стоял на длине промпта, а самое длинное совпадение
            # было равно ЕДИНИЦЕ на каждом шаге -- случайное попадание частого токена.
            # Отказ выглядел как «текст неподходящий» (`нет совпадения=149 из 149`), и прежняя
            # правка лечила симптом откатом границы, то есть ровно ту же болезнь с другой
            # стороны. Живой ряд лежит в `req_output_token_ids[i]` -- это ССЫЛКА на список
            # запроса, который движок дополняет по мере выдачи.
            # ЦЕНА: дописываем только НОВЫЙ хвост (единицы токенов на шаг), а не копируем ряд.
            _склеен = None
            # ИСТОЧНИК -- ПРИНЯТЫЕ ТОКЕНЫ ШАГА (их кладёт раннер), а не `req_output_token_ids`:
            # последний держит заполнители -1, пока реальные значения не потребуются штрафам,
            # и склейка по нему давала ряд из одних -1 (прибор: `посл=-1`, откат съедал всё).
            if _нпр is not None:
                _в = self._накопить_ряд(i)
                if _в:
                    _нп = int(_нпр[i])
                    _к = self._ряд_кэш.get(_рид[i] if _рид is not None and i < len(_рид) else i)
                    if _к is None or _к[1] != _нп:
                        _б = _np.empty(_нп + max(1024, len(_в) * 2), dtype=_np.int32)
                        _б[:_нп] = токены[i, :_нп]
                        _к = [_б, _нп, 0]
                        self._ряд_кэш[_рид[i] if _рид is not None and i < len(_рид) else i] = _к
                    _н = len(_в)
                    # Ряд мог быть обрезан слева по пределу памяти -- тогда индексы кэша
                    # больше не соответствуют списку, и дописывание склеило бы разные места.
                    if _н < _к[2]:
                        _к[2] = 0
                    if _н > _к[2]:
                        if _нп + _н > _к[0].size:
                            _нов = _np.empty(_нп + _н * 2, dtype=_np.int32)
                            _нов[:_нп + _к[2]] = _к[0][:_нп + _к[2]]
                            _к[0] = _нов
                        _к[0][_нп + _к[2]:_нп + _н] = _в[_к[2]:_н]
                        _к[2] = _н
                    _склеен = (_к[0], _нп + _н)
            # ХВОСТ РЯДА МОЖЕТ БЫТЬ НЕ ЗАПОЛНЕН. `num_tokens_no_spec` считает и слоты
            # отвергнутых спекулятивных позиций, а в них лежит -1. Диагностика 29.08:
            #   L=2003 ... хвост=[..., 189756, 220, -1]  канд=0
            # то есть якорь брался с ДЫРЫ, любое совпадение назад упиралось в -1, и поиск
            # отказывал в 199 случаях из 199 -- на ПЕРИОДИЧЕСКОМ тексте, где совпадений
            # заведомо много. Счётчик причин отказа назвал это одним прогоном; без него
            # я бы правил правило отбора, а виновата была ГРАНИЦА РЯДА.
            while L > 0 and int(токены[i, L - 1]) < 0:
                L -= 1
            if (max(L, _склеен[1] if _склеен is not None else 0)
                    < self._нграм_мин + k + 2):
                self._отказ["коротко"] += 1
                return None
            if _склеен is not None and _склеен[1] > L:
                ряд, L = _склеен[0], _склеен[1]
                # ХВОСТ СКЛЕЕННОГО РЯДА ТОЖЕ ЧИСТИМ. `output_token_ids` держит заполнители -1
                # на местах отвергнутых спекулятивных позиций (прибор показал `посл=-1`), и
                # якорь, взятый с такого места, снова упирался бы в дыру -- ровно та ошибка,
                # ради которой откат вводился для `token_ids_cpu`.
                while L > 0 and int(ряд[L - 1]) < 0:
                    L -= 1
                ряд = ряд[:L]
            else:
                ряд = токены[i, :L]
            # ХВОСТ ОБЯЗАН КОНЧАТЬСЯ ПОСЛЕДНИМ ПРИНЯТЫМ ТОКЕНОМ. Он ещё НЕ записан в
            # token_ids_cpu: первая редакция искала от сдвинутой точки -- n-граммы брались
            # в 93 % шагов, а приёмка падала до 1.1. Приклеивать его к ряду нельзя (копия
            # 250 000 элементов за шаг), поэтому сверяем его отдельной первой ступенью.
            свеж = int(свежие[i]) if (свежие is not None and i < len(свежие)) else None
            if свеж is None or (L and int(ряд[-1]) == свеж):
                свеж, сдвиг = None, 0          # свежий уже в ряду
            else:
                сдвиг = 1
            # ПОИСК САМОГО ДЛИННОГО СОВПАДЕНИЯ, ВЕКТОРНО И ЗА ОДИН ПРОХОД ПО РЯДУ.
            # Две тупиковые редакции записаны, чтобы не повторять:
            #  1) отдельный проход на каждое n -- до 6 проходов по 250 000 за шаг (питон в пути);
            #  2) якорь по последнему токену с отсечкой 48 свежайших кандидатов -- приёмка
            #     1.94 -> 1.65, «слова» 68.2 -> 34.8 ток/с: в повторяющемся тексте длинные
            #     совпадения лежат ДАЛЕКО НАЗАД, а отсечка с конца их не видит.
            # Здесь набор кандидатов ЗАСЕВАЕТСЯ один раз и потом только СУЖАЕТСЯ сравнением
            # следующего токена назад -- каждый шаг дешевеет, а найденное n заведомо
            # максимально. Цикл по питону идёт по n (<= 8), а не по кандидатам.
            хвостL = L - 1 + сдвиг            # индекс "как если бы свежий стоял в ряду"
            цель = свеж if свеж is not None else int(ряд[-1])
            канд = _np.nonzero(ряд[:L - k - сдвиг] == цель)[0]
            лучш_n, лучш = 0, канд
            n = 1
            while n <= self._нграм_макс and канд.size:
                лучш_n, лучш = n, канд
                канд = канд[канд >= n]
                if not канд.size:
                    break
                канд = канд[ряд[канд - n] == ряд[хвостL - n]]
                n += 1
            # [ПРИБОР 31.08] ДВЕ ПЕЧАТИ В НАЧАЛЕ ПРОГОНА -- НЕ ПРИБОР, А АНЕКДОТ: они попадают
            # на первые шаги, когда сгенерированного ещё нет, и любой отказ выглядит законным.
            # Считаем ГИСТОГРАММУ найденной длины: она отличает «якорь не найден вовсе»
            # (лучш_n=0) от «совпадение короче порога» -- это разные дефекты с разным лечением.
            _г = getattr(self, "_гист_n", None)
            if _г is None:
                _г = self._гист_n = {}
            _г[лучш_n] = _г.get(лучш_n, 0) + 1
            # ДЛИНА РЯДА И ХВОСТ -- проверка того, что ряд ВООБЩЕ РАСТЁТ с генерацией.
            # Если L стоит на месте, значит мы ищем в одном промпте, и совпадение длиннее
            # единицы взяться не может ни на каком тексте.
            _за = токены[i, _L0:_L0 + 6].tolist() if _L0 + 6 <= токены.shape[1] else []
            self._диаг_L = (f"L0={_L0}", f"L={L}", f"посл={int(ряд[-1])}",
                            f"цель={цель}", f"сдвиг={сдвиг}", f"за_границей={_за}")
            if лучш_n < self._нграм_мин:
                self._отказ["нет совпадения"] += 1
                if self._отказ["нет совпадения"] <= 2:
                    print(f"[dflash2 n-ГРАММЫ ДИАГ] L={L} свеж={свеж} сдвиг={сдвиг} цель={цель} "
                          f"канд={канд.size} хвост={ряд[-8:].tolist()} "
                          f"начало={ряд[:8].tolist()} ненулевых={int((ряд != 0).sum())}",
                          flush=True)
                return None
            # СОГЛАСИЕ ВХОЖДЕНИЙ, А НЕ ДЛИНА СОВПАДЕНИЯ.
            # Фальсификатор (28.08) развёл два слагаемых: поиск вхолостую стоит x1.034
            # (то есть НИЧЕГО), а поиск с черновиком -- x0.875. Значит убыток целиком в
            # КАЧЕСТВЕ черновика, и порог по длине его не лечит: x0.879 / x0.826 / x0.790
            # при n>=3 / 8 / 16 -- длиннее совпадение, не лучше предсказание.
            # Причина: длинное совпадение говорит, что контекст УЖЕ БЫЛ, но не говорит,
            # что продолжение было ТЕМ ЖЕ. На границе предложения одна и та же концовка
            # продолжается по-разному, и n-грамма уверенно выдаёт одно из продолжений.
            # Признак надёжности лежал рядом и выбрасывался: ВСЕ вхождения самой длинной
            # n-граммы. Согласны -- предсказание однозначно; расходятся -- отдаём ход
            # обычному черновику, который умеет выбирать.
            _вх = лучш[-self._нграм_свид:] if self._нграм_свид > 0 else лучш
            _вх = _вх[_вх + 1 + k <= L]
            if _вх.size == 0:
                self._отказ["нет совпадения"] += 1
                return None
            _конт = ряд[_вх[:, None] + 1 + _np.arange(k)]      # [вхождений, k]
            # [ГОЛОСОВАНИЕ ВМЕСТО ЕДИНОГЛАСИЯ 31.08]
            # Прежнее правило требовало, чтобы ВСЕ вхождения продолжались одинаково, и это
            # отвергало почти половину находок: замер после починки ряда дал `разошлись=120`
            # при `выдано=147`. Между тем приёмка самих n-грамм 3.89 против 2.01 у тела --
            # то есть отвергается вдвое лучший источник. Единогласие -- частный случай
            # голосования с порогом 1.0; выносим порог рычагом и берём МОДУ продолжений.
            # Тождество выхода не затрагивается: цель проверяет каждый токен точным
            # совпадением, ошибка черновика стоит приёмки, а не правильности.
            if _вх.size > 1:
                if self._нграм_голос >= 1.0:
                    if not bool((_конт == _конт[-1]).all()):
                        self._отказ["разошлись"] += 1
                        return None
                    out[i] = _конт[-1]
                else:
                    _u, _обр, _сч = _np.unique(_конт, axis=0, return_inverse=True,
                                               return_counts=True)
                    _лид = int(_сч.argmax())
                    if _сч[_лид] < self._нграм_голос * _вх.size:
                        self._отказ["разошлись"] += 1
                        return None
                    out[i] = _u[_лид]
            else:
                out[i] = _конт[-1]
        self._нграм_взято += 1
        self._отказ["выдано"] += 1
        if self._нграм_всего % 500 == 0:
            print(f"[dflash2 n-ГРАММЫ] взято {self._нграм_взято}/{self._нграм_всего} = "
                  f"{100 * self._нграм_взято / self._нграм_всего:.1f} % шагов", flush=True)
        import torch as _t
        return _t.from_numpy(out).to(self.device, non_blocking=True)

    # ---------------------------------------------------------------------------------------
    @torch.inference_mode()
    def _собрать_пару(self, признаки, якоря, позиции=None, токены=None):
        """Кладёт пару «признаки цели -> её токен» на процессор и сбрасывает срезами.

        Признаки -- ровно тот тензор, что получает черновик, поэтому обучение пойдёт на тех же
        входах, что и вывод: никакого расхождения между тем, на чём учили, и тем, на чём
        считают. Копия идёт на ПРОЦЕССОР сразу, иначе срез удержит память карты.
        """
        try:
            import torch as _t
            # Метка -- либо токены (тензор), либо ЛОГИТЫ цели (кортеж значения+индексы для
            # дистилляции). Оба вида кладём одинаково: тензоры на процессор, кортеж как есть
            # (он уже на процессоре -- раннер снял его там же).
            if isinstance(якоря, tuple):
                метка = tuple(т.detach().to("cpu") if hasattr(т, "detach") else т for т in якоря)
            else:
                метка = якоря.detach().to("cpu", _t.int32)
            # [ЧИСЛО ПРИНЯТЫХ -- 02.09] Без него корпус НЕГОДЕН, и это стоило трёх заходов
            # обучения (§95, §96). Цель считает логиты для позиций [якорь, ч1..чk], но позиции
            # после первого отказа посчитаны по ОТВЕРГНУТОМУ префиксу -- там мусор, а выглядит
            # он как обычная метка. Истинны ровно позиции 0..m-1, где m -- принятые. С m
            # цепочка склеивается точно: concat(топ1_i[0:m_i]) даёт связный текст.
            _m = 1
            try:
                _рб = getattr(self, "runner", None)
                if _рб is not None:
                    _m = int(_рб.input_batch.num_accepted_tokens_cpu[0])
            except Exception:
                _m = 1
            # [ПОЗИЦИИ В ПАРУ -- 08.09] Цепочка склеивается из пар подряд, но границу между
            # ЗАПРОСАМИ по одним признакам не видно: у нового запроса счёт позиций начинается
            # сначала, и склейка через границу даёт черновику чужой контекст. Позиции режут
            # цепочку точно (разрыв там, где позиция не равна предыдущей+1).
            _п = (позиции.detach().to("cpu", _t.int32)
                  if hasattr(позиции, "detach") else None)
            # [НАСТОЯЩИЕ ТОКЕНЫ ПОЗИЦИЙ -- 08.09] Метка top-1 -- это ЖАДНЫЙ токен цели, а сбор
            # идёт при температуре 0.7: в части позиций сеть выбрала другой. Цепочка, склеенная
            # из жадных токенов, расходится с той, из которой взяты ПРИЗНАКИ, и черновику на
            # вход подаётся бонусный токен, которого в тексте не было. Настоящие токены позиций
            # лежат прямо здесь -- это вход цели на этом шаге.
            _тк = (токены.detach().to("cpu", _t.int32)
                   if hasattr(токены, "detach") else None)
            self._дамп_буфер.append((признаки.detach().to("cpu", _t.float16), метка, _m, _п, _тк))
            self._дамп_счёт += 1
            if len(self._дамп_буфер) >= self._дамп_порция:
                import os as _o
                _o.makedirs(self._дамп_путь, exist_ok=True)
                _имя = f"{self._дамп_путь}/pary_{_o.getpid()}_{self._дамп_счёт:08d}.pt"
                _t.save(self._дамп_буфер, _имя)
                self._дамп_буфер = []
                print(f"[dflash2 СБОР] срез сохранён: {_имя} (пар всего {self._дамп_счёт})",
                      file=__import__("sys").stderr, flush=True)
        except Exception as _e:
            print(f"[dflash2 СБОР] отказ: {_e}", file=__import__("sys").stderr, flush=True)
            self._дамп_путь = ""      # один отказ -- и ветка замолкает, вывод не трогаем

    def propose(
        self,
        target_token_ids: torch.Tensor,
        target_positions: torch.Tensor,
        target_hidden_states: torch.Tensor,
        next_token_ids: torch.Tensor,
        last_token_indices: torch.Tensor | None,
        common_attn_metadata: CommonAttentionMetadata,
        sampling_metadata=None,
        mm_embed_inputs=None,
        num_rejected_tokens_gpu: torch.Tensor | None = None,
        slot_mappings=None,
    ) -> torch.Tensor:
        батч = common_attn_metadata.batch_size()
        k = self.num_speculative_tokens
        if self._авто > 0:
            _АВТО_ШАГ[0] += 1
            _проба = (_АВТО_ШАГ[0] % max(self._авто_проба, 2)) == 0
            if ПРИЁМКА_СРЕДН[0] > 0 and ПРИЁМКА_СРЕДН[0] < self._авто and not _проба:
                # НЕ ОКУПАЕТСЯ: отдаём пустой черновик -- движок пойдёт обычным декодом
                return torch.zeros((батч, 0), dtype=torch.int32, device=self.device)
        if self._нграм_файл:
            # У ОПРОСА ПЕРЕКЛЮЧАТЕЛЯ СВОЙ СЧЁТЧИК. Здесь стоял общий счётчик шагов, а он
            # двигается только когда n-граммы УЖЕ включены -- то есть включение зависело от
            # счётчика, который без включения стоит. Замок на себя: два свипа подряд мерили
            # выключённую ветвь и дали ровные x0.97-1.01, которые я чуть не принял за работу
            # калибровщика. Признак был в приборе: печать состояния не появилась НИ РАЗУ.
            self._нграм_опрос += 1
            if self._нграм_опрос % 16 == 1:
                # Содержимое файла: 0 = выключено, N>0 = включено с порогом длины N.
                # Порог в том же файле, чтобы свип шёл БЕЗ перезапусков: сравнение
                # "перезапуск А против перезапуска Б" на общей машине недействительно.
                try:
                    with open(self._нграм_файл) as _f:
                        _v = int(_f.read(8).strip() or "0")
                    # ФАЛЬСИФИКАТОР СНЯТИЕМ ФАЗЫ: ОТРИЦАТЕЛЬНОЕ значение = поиск идёт,
                    # но результат ВЫБРАСЫВАЕТСЯ. Разность с выключенным даёт цену САМОГО
                    # ПОИСКА, разность с включённым -- вклад КАЧЕСТВА черновика. Иначе эти
                    # два слагаемых неразделимы, и "стало хуже" не указывает ни на одно.
                    self._нграм = _v != 0
                    self._нграм_вхолостую = _v < 0
                    if _v != 0:
                        self._нграм_мин = abs(_v)
                except (OSError, ValueError):
                    pass
        if self._пустышка:
            return torch.zeros(батч, k, dtype=torch.int32, device=self.device)
        if self._фазы:
            import time as _t

            def _от():
                torch.cuda.synchronize()
                return _t.perf_counter()

            def _до(имя, т0):
                torch.cuda.synchronize()
                self._фаза_сумма[имя] = self._фаза_сумма.get(имя, 0.0) + (_t.perf_counter() - т0) * 1e3
            _т_всё = _от()
        else:
            _от = lambda: 0.0
            _до = lambda имя, т0: None
            _т_всё = 0.0

        # ШАГ 1. Слияние признаков ПЯТИ слоёв цели -> [T, hidden]. Без него `fc` не выполнен, и
        # впрыск пойдёт от неверной размерности -- проверяем ЯВНО, а не полагаемся на форму.
        # Приведение типа НА НАШЕМ СТЫКЕ: у цели остаток (residual) живёт в fp32 -- это её право
        # и её точность, но веса черновика fp16, и `fc` падает на разнотипном умножении. Кастуем
        # ЗДЕСЬ, а не у цели: менять точность чужого пути ради своего черновика -- значит тихо
        # тронуть качество боевой сети. Потери нет: признаки всё равно уходят в fp16-умножение.
        if target_hidden_states.dtype != self.dtype:
            target_hidden_states = target_hidden_states.to(self.dtype)
        # [СБОР ОБУЧАЮЩИХ ПАР ДЛЯ ДООБУЧЕНИЯ ЧЕРНОВИКА -- 01.09]
        # Черновик обучен для БАЗОВОЙ Qwen3.8-27B, а боевая сеть -- ABLITERATED. Отсюда его
        # приёмка 1.79-1.88 против 3.0, нужных для 70 ток/с: это НЕ предел конструкции, а
        # несоответствие модели (на базовой тот же черновик давал 1.08 на блок против 0.90).
        # Дообучение требует пар «признаки цели -> её же следующие токены», и оба конца есть
        # ровно здесь: признаки на входе, принятые токены приходят якорем следующего шага.
        # Пишем в файл ТОЛЬКО при FA2SM70_DFLASH2_DUMP -- в бою ветка мертва.
        if self._дамп_путь:
            self._дамп_отложен = (target_hidden_states, next_token_ids, target_positions,
                                  target_token_ids)
        _т = _от()
        состояния = self.model.combine_hidden_states(target_hidden_states)
        if self._дамп_путь and self._дамп_отложен is not None:
            # [ПОПРАВКИ СБОРА -- по замеру первого среза: 1.42 МБ на пару]
            # 1. Пишем состояния ПОСЛЕ `fc` (одно hidden вместо пяти слоёв цели) -- впятеро меньше.
            # 2. Берём только ДЕКОДНЫЕ формы: у префилльной плитки T в сотни раз больше, и она
            #    забивает корпус тем, на чём черновик и так не работает.
            _т_, _як_, _поз_, _ток_ = self._дамп_отложен
            self._дамп_отложен = None
            if состояния.shape[0] <= self._дамп_maxT:
                # Логиты цели прошлого шага кладёт раннер (`_fa2_логиты`). Если они есть --
                # корпус пишется для ДИСТИЛЛЯЦИИ (KL по распределению), если нет -- по токенам,
                # как раньше. Обучение по токенам вышло на плато, см. записку 25 §94d.
                _лог = getattr(self.runner, "_fa2_логиты", None) if hasattr(self, "runner") else None
                self._собрать_пару(_т_ if self._дамп_сырьё else состояния,
                                   _як_ if _лог is None else _лог, _поз_, _ток_)
        if self._дозор:
            def _оп(имя, t):
                if t is None: return f"{имя}=нет"
                ф = torch.isfinite(t)
                return (f"{имя}[{tuple(t.shape)} {str(t.dtype).split('.')[-1]}]"
                        f" max={t[ф].abs().max().item() if ф.any() else float('nan'):.4g}"
                        f" неконечных={int((~ф).sum())}")
            print(f"[dflash2 СТАДИИ] {_оп('признаки_цели', target_hidden_states)} | "
                  f"{_оп('после_fc', состояния)}", flush=True)
            # ВЕСА: `base_kernel` и кодбуки заведены как nn.Parameter(torch.empty(...)). Если
            # загрузчик их не заполнил, там НЕИНИЦИАЛИЗИРОВАННАЯ память -- и это даёт ровно NaN,
            # причём молча. Проверяем ЧИСЛОМ, а не наличием имени в дереве.
            сл = self.model.model.layers[0]
            for имя, т in (("attention_conv.base_kernel", сл.attention_conv.base_kernel),
                           ("attention_conv.kernel_projection", сл.attention_conv.kernel_projection.weight),
                           ("mlp_conv.base_kernel", сл.mlp_conv.base_kernel),
                           ("q_proj", сл.self_attn.qkv_proj.weight if hasattr(сл.self_attn, "qkv_proj") else сл.self_attn.q_proj.weight),
                           ("codebook_пред", self.model.model.candidate_selector.predecessor_codebook),
                           ("selector.hidden_projection", self.model.model.candidate_selector.hidden_projection.weight),
                           ("fc", self.model.model.fc.weight)):
                ф = т.isfinite()
                print(f"    ВЕС {имя}: {tuple(т.shape)} max={т[ф].abs().max().item() if ф.any() else float('nan'):.4g}"
                      f" среднее|.|={т[ф].abs().float().mean().item() if ф.any() else float('nan'):.4g}"
                      f" неконечных={int((~ф).sum())}", flush=True)
        _до("слияние fc", _т)
        assert состояния.shape[-1] == self.hidden_size, (
            f"DFlash2: после fc ждали {self.hidden_size}, получили {состояния.shape[-1]}"
        )

        _т = _от()
        запросных, контекста, индексы_выборки, cad = self._разложить_вход(
            target_token_ids, next_token_ids, target_positions,
            common_attn_metadata, num_rejected_tokens_gpu,
        )

        _т = _от()
        _до("раскладка входа", _т)
        строитель = self.attn_metadata_builder or self._get_attention_metadata_builder()
        мета = строитель.build_for_drafting(common_attn_metadata=cad, draft_index=0)
        по_слоям = {имя: мета for имя in self.attn_layer_names}

        _до("метаданные", _т)
        _, поперёк_dp = self._pad_batch_across_dp(
            num_tokens_unpadded=запросных, num_tokens_padded=запросных
        )
        режим_графа, опись = self.cudagraph_dispatcher.dispatch(запросных)
        входных = опись.num_tokens
        if self._фазы:
            self._гр_печать = getattr(self, "_гр_печать", 0) + 1
            if self._гр_печать % 500 == 1:
                import sys as _sg
                print(f"[dflash2 ГРАФ] запросных={запросных} входных={входных} "
                      f"режим={режим_графа}", file=_sg.stderr, flush=True)
        if поперёк_dp is not None:
            поперёк_dp[self.dp_rank] = входных

        # ШАГ 2. ВПРЫСК: признаки цели -> K/V всех слоёв -> кэш черновика. Идёт ВНЕ графа: форма
        # контекста меняется от шага к шагу, а запросная часть -- нет, потому граф ей и достаётся.
        _т = _от()
        self.model.model.precompute_and_store_context_kv(
            состояния,
            self._позиции_контекста[:контекста],
            self._слоты_контекста[:контекста],
        )

        if self._дозор:
            # ПОСТРОЧНО: NaN уже во вложениях или родился в теле? Вызов симметричен на всех рангах
            # (внутри вложения идёт коллектив TP), поэтому лишнего барьера не создаёт.
            _вл = self.model.embed_input_ids(self.input_ids[:запросных])
            _ф = _вл.isfinite().all(dim=-1)
            print(f"[dflash2 ВХОД] вложения по строкам конечны={_ф.tolist()} "
                  f"ids={self.input_ids[:запросных].tolist()} "
                  f"max={_вл[_вл.isfinite()].abs().max().item():.4g}", flush=True)

        _до("ВПРЫСК KV", _т)

        # [n-ГРАММЫ] МЕСТО ПРОВЕРКИ -- ЗДЕСЬ, А НЕ В НАЧАЛЕ propose.
        # Сперва ранний возврат стоял первой строкой -- и пропускал ВПРЫСК KV, то есть
        # оставлял в кэше черновика дыру на каждом шаге, где взята n-грамма. Замер:
        # проза x0.875 (порог 8) и x0.90-0.92 даже с правилом согласия, при том что поиск
        # ВХОЛОСТУЮ стоит x1.034 -- то есть убыток шёл не от поиска и не от качества
        # n-граммы, а от РАЗРУШЕННОГО СОСТОЯНИЯ ЧЕРНОВИКА на следующих шагах.
        # Здесь состояние черновика уже обновлено, и пропускается ровно дорогое:
        # проход тела + верхушка словаря + отбор пути.
        if self._нграм:
            _иб = getattr(getattr(self, "runner", None), "input_batch", None)
            if _иб is not None:
                self._нграм_шаг += 1
                try:
                    self._учесть_priyomku(_иб, батч)
                except (AttributeError, IndexError):
                    pass
            self._прошлый_ист = "мод"
            # Печатать надо НЕЗАВИСИМО от того, какая ветвь выбрана: прошлая редакция
            # печатала только внутри взятой n-граммы, и когда её переставали брать,
            # прибор ослеп ровно в том случае, который надо было разобрать.
            if self._нграм_шаг % self._нграм_печать == 0:
                print(f"[dflash2 n-ГРАММЫ] приёмка: n-грамма {self._средняя('нг'):.2f}"
                      f" ({self._проб['нг']} проб) против тела {self._средняя('мод'):.2f}"
                      f" ({self._проб['мод']} проб, порог x{self._нграм_цена}); отказы: "
                      + ", ".join(f"{к}={в}" for к, в in self._отказ.items())
                      + " | длины совпадения: "
                      + ", ".join(f"n={к}:{в}" for к, в in
                                  sorted(getattr(self, "_гист_n", {}).items())[:12])
                      + f" | ряд(L, посл, предпосл, цель, сдвиг)={getattr(self, '_диаг_L', None)}",
                      flush=True)
            if self._выбрать_источник():
                _нг = self._поиск_нграмм(батч, k, свежие=self._свежие_на_хост(next_token_ids))
                if _нг is not None and not self._нграм_вхолостую:
                    self._прошлый_ист = "нг"
                    if self._фазы:
                        _до("ВЕСЬ propose", _т_всё)
                    return _нг

        # ШАГ 3. ОДИН проход. Никакого цикла по k -- в этом весь метод.
        _т = _от()
        выход = None
        if self._гр_тела_вкл and поперёк_dp is None:
            выход = self._тело_графом(мета, запросных, входных, cad)
        if выход is None:
            with set_forward_context(
                по_слоям,
                self.vllm_config,
                num_tokens=входных,
                num_tokens_across_dp=поперёк_dp,
                cudagraph_runtime_mode=режим_графа,
                slot_mapping=self._get_slot_mapping(входных, cad.slot_mapping),
                additional_kwargs=self._get_forward_context_additional_kwargs(),
            ):
                выход = self.model(
                    input_ids=self.input_ids[:входных],
                    positions=self._get_positions(входных),
                    inputs_embeds=None,
                )
        _до("ПРОХОД тела", _т)
        скрытое = выход[0] if isinstance(выход, tuple) else выход
        if self._дозор:
            ф = torch.isfinite(скрытое)
            print(f"[dflash2 ВЫХОД] строки конечны={скрытое.isfinite().all(dim=-1).tolist()}", flush=True)
            print(f"[dflash2 СТАДИИ] причинность_меты={getattr(мета, 'causal', 'НЕТ ПОЛЯ')} "
                  f"скрытое_черновика[{tuple(скрытое.shape)}] "
                  f"max={скрытое[ф].abs().max().item() if ф.any() else float('nan'):.4g} "
                  f"неконечных={int((~ф).sum())} из {скрытое.numel()}", flush=True)

        # ШАГ 4. Верхушка словаря на k позициях маски (бонусный токен пропущен -- он уже принят).
        _т = _от()
        выбранные = скрытое[индексы_выборки]                      # [B*k, H]
        унарные, кандидаты = self.model.compute_candidates(выбранные)
        _до("верхушка словаря", _т)

        # [ВТОРОЙ ПРОХОД БЛОКА -- РЕШЁТЧАТЫЙ ЧЕРНОВИК, 08.09; записка 25 §205]
        # Блок предсказывает k позиций ПАРАЛЛЕЛЬНО: строка j не знает, что выпало строке j-1,
        # отсюда падение точности 65 / 37 / 23 % по позициям. Здесь тело гоняется ВТОРОЙ раз,
        # и во входе первая маска заменена токеном, который черновик сам же и выбрал. Дорогая
        # часть шага (слияние `fc` и впрыск K/V) НЕ повторяется -- она уже посчитана; цена --
        # только тело на k+1 строке, то есть тот же CUDA-граф ещё одним replay.
        # Замер (L=1024, 500 проб): префикс из двух позиций 32.8 -> 37.6 %, верхняя оценка
        # приёмки 2.134 -> 2.186. Раскрывать сразу ДВЕ позиции ХУЖЕ (2.120), третий проход не
        # добавляет ничего (2.188) -- потому раскрытие ровно одно.
        # ВАЖНО: черновик должен быть ОБУЧЕН частично раскрытому блоку. На необученных весах
        # второй проход РУШИТ ответ (tau 2.04 -> 1.44): строка с настоящим токеном у блочной
        # модели не предсказывает ничего. Рычаг по умолчанию ВЫКЛЮЧЕН.
        if self._второй_проход and k > 1:
            try:
                _к = кандидаты.view(батч, k, self.top_k)
                _у = унарные.view(батч, k, self.top_k)
                # догадка позиции 0 -> вход строки 1 (строка 0 -- бонусный токен)
                _строка1 = (self.arange[:батч] * self.позиций_на_запрос + 1).long()
                self.input_ids[_строка1] = _к[:, 0, 0].to(self.input_ids.dtype)
                _вых2 = None
                if self._гр_тела_вкл and поперёк_dp is None:
                    _вых2 = self._тело_графом(мета, запросных, входных, cad)
                if _вых2 is None:
                    with set_forward_context(
                        по_слоям, self.vllm_config, num_tokens=входных,
                        num_tokens_across_dp=поперёк_dp,
                        cudagraph_runtime_mode=режим_графа,
                        slot_mapping=self._get_slot_mapping(входных, cad.slot_mapping),
                        additional_kwargs=self._get_forward_context_additional_kwargs(),
                    ):
                        _вых2 = self.model(
                            input_ids=self.input_ids[:входных],
                            positions=self._get_positions(входных),
                            inputs_embeds=None,
                        )
                _скр2 = _вых2[0] if isinstance(_вых2, tuple) else _вых2
                _у2, _к2 = self.model.compute_candidates(_скр2[индексы_выборки])
                # Позиция 0 остаётся от ПЕРВОГО прохода: её ответ уже принят и подан на вход,
                # переспрашивать его вторым проходом бессмысленно (и вредно -- см. §205).
                кандидаты = torch.cat(
                    (_к[:, :1], _к2.view(батч, k, self.top_k)[:, 1:]), dim=1
                ).reshape(батч * k, self.top_k)
                унарные = torch.cat(
                    (_у[:, :1], _у2.view(батч, k, self.top_k)[:, 1:]), dim=1
                ).reshape(батч * k, self.top_k)
                скрытое = _скр2
            except Exception as _е2:
                self._второй_проход = False
                print(f"[dflash2 ВТОРОЙ ПРОХОД] отказ ({type(_е2).__name__}: {_е2}) -- "
                      f"навсегда одним проходом", file=__import__("sys").stderr, flush=True)
        if унарные is None:  # не последний ранг TP: токенов не отдаём
            return torch.zeros(батч, k, dtype=torch.int32, device=self.device)

        if self._покрытие:
            # ФАЛЬСИФИКАТОР ДЕРЕВА. Вопрос: НАСКОЛЬКО чаще цель попадает в top-2/4/8 черновика,
            # чем в top-1. Это ПРИЗ ветвления, и его надо знать ДО реализации дерева.
            # Сравниваем кандидатов ПРОШЛОГО шага (позиция 0) с тем, что цель выбрала на самом
            # деле -- она приезжает якорем СЛЕДУЮЩЕГО шага.
            _к = кандидаты.view(батч, k, self.top_k)
            _пр = getattr(self, "_прошлые_канд", None)
            if _пр is not None and _пр.shape[0] == батч:
                _факт = next_token_ids.view(батч, 1)
                for _n in (1, 2, 4, 8, 16):
                    _есть = (_пр[:, :_n] == _факт).any(dim=1).sum().item()
                    self._покр_сумма[_n] = self._покр_сумма.get(_n, 0) + _есть
                self._покр_счёт += батч
                if self._покр_счёт % self._покрытие == 0:
                    н = self._покр_счёт
                    стр = "  ".join(
                        f"top-{_n}={self._покр_сумма.get(_n, 0) / н * 100:.1f}%"
                        for _n in (1, 2, 4, 8, 16)
                    )
                    # ПЕЧАТЬ В STDERR: stdout воркеров не проксируется в журнал, и проба
                    # молчала целый прогон, хотя считала. Признак был -- НИ ОДНОЙ строки.
                    print(f"[dflash2 ПОКРЫТИЕ, {н} шагов] {стр}",
                          file=__import__("sys").stderr, flush=True)
            self._прошлые_канд = _к[:, 0].clone()

        # [ПРОБА ПОКРЫТИЯ, ИСПРАВЛЕННАЯ 25.08] Кандидаты позиции 0 сохраняются, а сверяются В ТОМ ЖЕ
        # ШАГЕ -- в runner'е, после выборки, против токена, который цель реально выдала на этой
        # позиции (`sampled_token_ids[:, 0]`). Прежняя проба сверяла их с БОНУСНЫМ токеном
        # СЛЕДУЮЩЕГО шага, а тот сдвинут на число принятых: рассогласование почти всегда, отсюда
        # «top-1 = 5.3 %» при истинной приёмке 0.65. Единица сравнения должна совпадать.
        if self._покрытие:
            self.канд0 = кандидаты.view(батч, k, self.top_k)[:, 0].clone()
        # [СБОР ВЫБОРКИ ДЛЯ ПЕРЕРАНЖИРОВЩИКА, 07.09] Замерено: верный токен лежит в
        # top-16 черновика в 86 % случаев, а первым он стоит лишь в 54 %. Значит слабое
        # место -- ранжирование. Учить голову на 16 выходов можно ДАРОМ: и кандидаты,
        # и скрытое состояние уже посчитаны, а метка (argmax цели) приходит следующим
        # шагом. Здесь сохраняется вход головы; метку и запись на диск делает runner.
        if self._выборка:
            self.скрыт0 = выбранные.view(батч, k, -1)[:, 0].detach().clone()
            # [ПРИЗНАКИ ЦЕЛИ, 08.09] Переранжировщик на признаках ЧЕРНОВИКА не обобщился
            # (§185-186): его ранжирование уже исчерпало то, что в них есть. Здесь
            # сохраняются признаки ЦЕЛИ -- те самые "другие признаки", которых не
            # хватало: они богаче (пять слоёв цели против одного состояния черновика)
            # и приходят в propose даром, до всякого слияния.
            try:
                _ц = target_hidden_states
                if last_token_indices is not None:
                    _ц = _ц[last_token_indices]
                self.цель0 = _ц[:батч].detach().to(torch.float16).clone()
                if not hasattr(self, "_цель_форма_напечатана"):
                    self._цель_форма_напечатана = True
                    print(f"[ВЫБОРКА] признаки цели: {tuple(self.цель0.shape)}",
                          file=__import__("sys").stderr, flush=True)
            except Exception as _e:
                self.цель0 = None
            self._канд_для_выборки = кандидаты.view(батч, k, self.top_k)[:, 0].clone()
            self.унар0 = унарные.view(батч, k, self.top_k)[:, 0].detach().clone()

        # ШАГ 5. Связный путь. Якорь -- принятый токен: путь пришит к реальности, а не к догадке.
        _т = _от()
        if self._поточечно:
            токены = кандидаты.view(батч, k, self.top_k)[:, :, 0].to(torch.int32)
        else:
            токены = self.model.выбрать_путь(
                выбранные.view(батч, k, -1),
                кандидаты.view(батч, k, self.top_k),
                унарные.view(батч, k, self.top_k),
                next_token_ids.view(батч),
            )
        # [ДЕРЕВО, ШАГ 2] ВТОРАЯ ВЕТВЬ ВМЕСТО ХВОСТА ЦЕПИ.
        # Движок идёт с num_speculative_tokens = 2W; мы отдаём тот же тензор [B, 2W], но
        # трактуем его как ДВЕ ветви по W: 0..W-1 -- путь селектора, W..2W-1 -- ветвь от
        # ВТОРОГО кандидата позиции 0. Приз ровно там: покрытие позиции 0 у top-1 56.7 %,
        # у top-2 69.3 % (записка 25 §60), то есть вторая ветвь добавляет 12.6 пункта.
        # Продолжение ветви B берётся жадным top-1 -- кандидаты считаны блоком и для B
        # формально не пересчитаны; это приближение, и оно измеряется приёмкой, а не спорится.
        if self._дерево_W > 0 and k == 2 * self._дерево_W and not self._дерево_черн_выкл:
            W = self._дерево_W
            _к = кандидаты.view(батч, k, self.top_k)
            _b = _к[:, :W, 0].clone()          # жадный путь по позициям 0..W-1
            # ГЕЙТ ТОЖДЕСТВА ВЕТВЕЙ (FA2SM70_TREE_GATE=1): b0 берётся ТЕМ ЖЕ токеном,
            # что и a0. Тогда строки 1 и W+1 несут один токен на одной позиции и с
            # одним контекстом -- их скрытые состояния ОБЯЗАНЫ совпасть побайтово.
            # Расхождение означает, что маска ветви или позиции не доехали до ядра,
            # и тогда все выводы о ветви B делались на испорченных строках.
            _b[:, 0] = _к[:, 0, 0] if _ГЕЙТ_ВЕТВЕЙ else _к[:, 0, 1]
            токены = torch.cat([токены[:, :W], _b], dim=1)
        if self._дозор:
            # ДОЗОР: печатаем ПЕРВЫЕ несколько ходов и умолкаем. Печать в горячем цикле уже вешала
            # у нас сервер (1.3 млн строк за 40 минут), поэтому счётчик, а не флаг.
            self._дозор -= 1
            with torch.no_grad():
                поточечный = кандидаты.view(батч, k, self.top_k)[:, :, 0]
                print(
                    f"[dflash2 ДОЗОР] якорь={next_token_ids.view(-1)[:2].tolist()} "
                    f"путь={токены[0].tolist()} "
                    f"поточечный={поточечный[0].tolist()} "
                    f"унар0={унарные.view(батч, k, self.top_k)[0, 0, :3].tolist()} "
                    f"контекста={контекста} запросных={запросных} "
                    f"вход={self.input_ids[:min(запросных, 10)].tolist()} "
                    f"позиции={self._get_positions(запросных)[:min(запросных, 10)].tolist()}",
                    flush=True,
                )
        _до("ОТБОР пути", _т)
        if self._фазы:
            _до("ВЕСЬ propose", _т_всё)
            self._фаза_счёт += 1
            if self._фаза_счёт % self._фазы == 0:
                н = self._фаза_счёт
                стр = "  ".join(f"{и}={в/н:.2f}" for и, в in sorted(
                    self._фаза_сумма.items(), key=lambda x: -x[1]))
                print(f"[dflash2 ФАЗЫ, мс/вызов, {н} вызовов] {стр}", flush=True)
        return токены.to(torch.int32)

    # [ГРАФ ТЕЛА ЧЕРНОВИКА, 05.09] --------------------------------------------------------
    _ГР_ПОЛЯ = ("query_start_loc", "seq_lens", "block_table", "slot_mapping")

    def _тело_графом(self, мета, запросных, входных, cad):
        """Проход тела одним CUDA-графом; None означает «иди обычным путём».

        Захват НЕ ИСПОЛНЯЕТ ядра, поэтому сразу за ним стоит replay -- шаг получает свой
        результат. Тензоры меты, снятые при захвате, становятся буферами графа: держим их
        и каждый шаг копируем в них свежие значения. Инты запечены -- они входят в ключ.
        Любое исключение хоронит ключ навсегда: путь возвращается к piecewise без порчи.
        """
        from vllm.config.compilation import CUDAGraphMode as _CGM
        # [ЧЕРЕДОВАНИЕ БЕЗ ПЕРЕЗАПУСКА -- 08.09, записка 25 §212] Рычаг стоит ~1 мс, а разброс
        # между экземплярами ~1.2 мс: сравнивать перезапусками нельзя. Файл-переключатель даёт
        # обе ветви на ОДНОМ экземпляре. Граф уже захвачен -- выключение просто не зовёт replay.
        if _ГРАФ_ФАЙЛ:
            self._гр_черед = getattr(self, "_гр_черед", 0) + 1
            if self._гр_черед % 64 == 1:
                try:
                    with open(_ГРАФ_ФАЙЛ) as _ф:
                        self._гр_вкл_файл = _ф.read(1) == "1"
                except OSError:
                    self._гр_вкл_файл = True
            if not getattr(self, "_гр_вкл_файл", True):
                return None
        ключ = (int(входных), int(мета.num_reqs), int(мета.max_query_len), bool(мета.causal))
        з = self._гр_тела.setdefault(ключ, {"счёт": 0, "мёртв": False})
        if з["мёртв"]:
            return None
        if "граф" not in з:
            з["счёт"] += 1
            if з["счёт"] < 4:
                return None                      # прогрев обычным путём
            try:
                слоты = self._get_slot_mapping(входных, cad.slot_mapping)
                по_слоям_пост = {имя: мета for имя in self.attn_layer_names}
                if self._гр_пул is None:
                    self._гр_пул = torch.cuda.graph_pool_handle()
                г = torch.cuda.CUDAGraph()
                with set_forward_context(
                    по_слоям_пост, self.vllm_config,
                    num_tokens=входных, num_tokens_across_dp=None,
                    cudagraph_runtime_mode=_CGM.NONE,
                    slot_mapping=слоты,
                    additional_kwargs=self._get_forward_context_additional_kwargs(),
                ):
                    with torch.cuda.graph(г, pool=self._гр_пул):
                        вых = self.model(
                            input_ids=self.input_ids[:входных],
                            positions=self._get_positions(входных),
                            inputs_embeds=None,
                        )
                з.update(граф=г, мета=мета, выход=вых,
                         буферы=[(и, getattr(мета, и)) for и in self._ГР_ПОЛЯ])
                г.replay()                        # захват ядра не исполнял -- шаг получает своё
                import sys as _sg
                print(f"[dflash2 ГРАФ ТЕЛА] захвачен: ключ={ключ}",
                      file=_sg.stderr, flush=True)
                return вых
            except Exception as _e:
                з["мёртв"] = True
                import sys as _sg
                print(f"[dflash2 ГРАФ ТЕЛА] отказ захвата ({type(_e).__name__}: {_e}) -- "
                      f"навсегда прежним путём для ключа {ключ}", file=_sg.stderr, flush=True)
                return None
        # повтор: обновить буферы и переиграть
        for и, буф in з["буферы"]:
            нов = getattr(мета, и)
            if нов is None or нов.shape != буф.shape:
                return None
            if нов.data_ptr() != буф.data_ptr():
                буф.copy_(нов, non_blocking=True)
        self._get_slot_mapping(входных, cad.slot_mapping)   # копия в постоянный буфер слотов
        з["граф"].replay()
        return з["выход"]

    @torch.inference_mode()
    def dummy_run(
        self,
        num_tokens: int,
        use_cudagraphs: bool = True,
        is_graph_capturing: bool = False,
        slot_mappings=None,
    ) -> None:
        """Прогрев/профиль: ОДИН проход, как в бою (иначе профиль соврёт в свою пользу)."""
        from vllm.config.compilation import CUDAGraphMode

        запросных = min(num_tokens, self.max_query_tokens)
        if use_cudagraphs:
            размеры = getattr(self.compilation_config, "cudagraph_capture_sizes", None)
            подходящие = [x for x in sorted(размеры or []) if x >= запросных]
            входных = подходящие[0] if подходящие else запросных
            режим = CUDAGraphMode.PIECEWISE
        else:
            входных, режим = запросных, CUDAGraphMode.NONE

        if (
            self.attn_layer_names
            and slot_mappings is not None
            and next(iter(self.attn_layer_names)) in slot_mappings
        ):
            слоты = self._get_slot_mapping(входных)
        else:
            слоты = slot_mappings or {}

        self.model.model.precompute_and_store_context_kv(
            self.hidden_states[:num_tokens], self._позиции_контекста[:num_tokens]
        )
        with set_forward_context(
            None,
            self.vllm_config,
            num_tokens=входных,
            num_tokens_across_dp=None,
            cudagraph_runtime_mode=режим,
            slot_mapping=слоты,
        ):
            self.model(
                input_ids=self.input_ids[:входных],
                positions=self._get_positions(входных),
                inputs_embeds=None,
            )
