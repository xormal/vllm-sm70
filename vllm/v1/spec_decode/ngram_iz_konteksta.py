    def _учесть_приёмку(self, ib, батч: int) -> None:
        """Приписать приёмку ТОМУ источнику, что дал черновик на прошлом шаге.

        СИГНАЛ БЕРЁТСЯ ГОТОВЫЙ: `input_batch.num_accepted_tokens_cpu` -- движок сам
        заполняет его после приёмки (gpu_model_runner.py:1184), на процессоре, без
        сверки с картой.
        ПЕРВАЯ РЕДАКЦИЯ СЧИТАЛА ПРИРОСТ `num_tokens_no_spec` -- и он оказался ВЫРОЖДЕН:
        186 замеров дали РОВНО 1.00 при любой приёмке, потому что это число растёт на
        один токен за шаг независимо от того, сколько черновых приняли. Метрика, которая
        не двигается от того, что ОБЯЗАНО её двигать, недействительна -- и калибровщик на
        ней молча выбирал не тот источник.
        """
        if self._прошлый_ист is None:
            return
        try:
            прин = ib.num_accepted_tokens_cpu
        except AttributeError:
            return
        сумма = 0.0
        учтено = 0
        for i in range(батч):
            a = int(прин[i])
            if 1 <= a <= self.k + 1:
                сумма += a
                учтено += 1
        if учтено:
            и = self._прошлый_ист
            if self._испр:
                # СВОЁ забывание у каждой чаши: редкая больше не обнуляется активностью частой
                λ = 1.0 - 1.0 / max(2, self._проб_предел)
                self._сум[и] = self._сум[и] * λ + сумма / учтено
                self._проб[и] = self._проб[и] * λ + 1.0
                return
            self._сум[и] += сумма / учтено
            self._проб[и] += 1
            if self._проб[и] >= self._проб_предел:      # забывание: половиним обе чаши
                for к in self._сум:
                    self._сум[к] *= 0.5
                    self._проб[к] = self._проб[к] // 2
